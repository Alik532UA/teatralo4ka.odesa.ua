/**
 * Пороги Lighthouse.
 *
 * ## Чому SEO перевіряється НЕ на всіх адресах
 *
 * `staticDistDir` знаходить сторінки сам, і серед них є `/admin/` та
 * `/admin/login/`. Ці сторінки навмисно закриті від індексації — у
 * `static/robots.txt` стоїть `Disallow: /admin/`, і так має бути: панель
 * керування в пошуку не потрібна нікому.
 *
 * Аудит `is-crawlable` бачить саме це й ставить нуль, тягнучи категорію SEO до
 * 0.69 проти порога 0.9. Тобто гейт вимагав зробити адмінку індексованою: він
 * позеленів би ЛИШЕ від справжньої регресії — знятого `Disallow`. Заміряно на
 * прогоні `d98e8ff`: обидві адреси 0.69, і єдина причина — `is-crawlable`.
 *
 * Такий гейт гірший за відсутній: він тисне в бік помилки. Тому SEO
 * стверджується лише там, де індексація потрібна.
 *
 * Доступність і найкращі практики на адмінці лишаються під порогом: це живий
 * інтерфейс, яким користуються, і до пошуку він відношення не має.
 */

/**
 * Те, що вимагається від КОЖНОЇ сторінки.
 *
 * ## Чому окремо CLS, коли є оцінка «performance»
 *
 * Оцінка категорії — це зважена сума пʼяти метрик, і зсув розкладки важить у ній
 * чверть. Тобто сторінка може помітно стрибати й лишатися вище порога за рахунок
 * швидкого LCP — саме той випадок, коли гейт зелений, а дефект видно оком.
 * PERFORMANCE-v8 § 10.2 просить пороги на самі метрики, і CLS тут перший:
 * інваріант `src/image-dimensions.test.ts` доводить, що місце під зображення
 * ВІДВЕДЕНО, але не те, що воно відведено правильно — це видно лише в браузері.
 *
 * 0.1 — межа «good» за Core Web Vitals, і рівень `error`, бо це не смак:
 * зсув розкладки промахує повз кнопку, у яку людина вже цілилася.
 */
const EVERY_PAGE = {
	'categories:performance': ['warn', { minScore: 0.8 }],
	'categories:accessibility': ['error', { minScore: 0.95 }],
	'categories:best-practices': ['error', { minScore: 0.9 }],
	'cumulative-layout-shift': ['error', { maxNumericValue: 0.1 }]
};

/**
 * Адмінка — будь-яка адреса з сегментом `admin`.
 *
 * Дужка `(/|$)` обов'язкова: без неї шаблон збігся б і з умовною
 * `/administration-news/`, тобто мовчки зняв би перевірку SEO зі звичайної
 * сторінки. Патерни взаємно виключні — LHCI застосовує КОЖЕН, чий шаблон
 * підійшов, тож перекриття дало б дві різні вимоги до тієї самої адреси.
 */
const ADMIN = '/admin(/|$)';

/**
 * Адреси беруться з ПЕРЕЛІКУ, складеного з маршрутів, а не з автовиявлення
 * (OBSERVABILITY-v9 § 2.2.1, `OBS-LHCI-REAL-PAGES`).
 *
 * Перелік пише `scripts/lighthouse-urls.ts` у `postbuild` — там же розбір,
 * що саме автовиявлення не бачило (галактику, анкети, вистави: усе, що
 * глибше за два каталоги) і чому ключ `maxAutodiscoverIsolate`, який тут
 * стояв, не робив нічого: такої опції в LHCI немає.
 *
 * Відсутній файл — це помилка, а не привід тихо повернутися до
 * автовиявлення: мовчазний відкат означав би, що аудит знову міряє не те,
 * і нічого про це не скаже.
 *
 * Разом зі `staticDistDir` це працює саме так, як тут використано: коли
 * `url` не порожній, LHCI піднімає свій сервер над каталогом збірки й
 * підставляє в кожну адресу його порт (перевірено у джерелі
 * `@lhci/cli@0.15.1`, `src/collect/collect.js`).
 */
const URLS_FILE = './.lighthouse-urls.json';
let urls;
try {
	urls = require(URLS_FILE);
} catch {
	throw new Error(
		`Lighthouse: немає ${URLS_FILE} — його пише postbuild (scripts/lighthouse-urls.ts). ` +
			'Спершу `npm run build`.'
	);
}
if (!Array.isArray(urls) || urls.length < 10) {
	throw new Error(`Lighthouse: у ${URLS_FILE} замало адрес (${urls && urls.length}) — перелік зламався`);
}

module.exports = {
	ci: {
		collect: {
			staticDistDir: './build',
			url: urls
		},
		assert: {
			assertMatrix: [
				{
					matchingUrlPattern: ADMIN,
					assertions: { ...EVERY_PAGE }
				},
				{
					matchingUrlPattern: `^(?!.*${ADMIN}).*$`,
					assertions: {
						...EVERY_PAGE,
						'categories:seo': ['error', { minScore: 0.9 }]
					}
				}
			]
		},
		upload: {
			target: 'temporary-public-storage'
		}
	}
};

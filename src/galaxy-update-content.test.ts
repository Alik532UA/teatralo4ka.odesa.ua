// @vitest-environment node
// Перевірка читає json зі `static/` і джерела компонентів — DOM їй не потрібен.
import { describe, expect, it } from 'vitest';
import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';

/**
 * Вітальне вікно: текст, ілюстрації й демонстрація галереї не розійшлися.
 *
 * ## Навіщо
 *
 * Вміст вікна живе в ДВОХ файлах `static/galaxy/update-uk.json` і
 * `update-en.json`, а малюється третім — `GalaxyUpdateIllustration.svelte`.
 * Жоден із трьох про інші не знає, і кожне розходження тихе:
 *
 *   пункт лише в uk ............ англійський читач просто не бачить розділу, і
 *                               ніде про це не сказано
 *   інший порядок .............. два тексти розповідають про нову версію в
 *                               різній послідовності
 *   id без ілюстрації .......... пункт малюється, `{#if}` не знаходить гілки,
 *                               поруч порожнє місце — збірка зелена
 *   зайвий запис у переліку
 *   «навмисно без картинки» .... ілюстрацію додали, а виняток лишився
 *                               пам'ятником
 *
 * ## Демонстрація галерей
 *
 * Пункт `gallery` показує по два кадри від КОЖНОГО, у кого галерея вже є, —
 * мініатюрами з `static/galaxy/`. Це НЕ самі знімки галерей: ті по 1280 px і
 * 27…155 КБ, і возити чотирнадцять таких у рамку 108 px означало б понад
 * мегабайт на кожного, хто відкрив вікно (докблок `GalaxyUpdateGallery.svelte`).
 *
 * Мініатюри — похідні, зроблені руками, тож зв'язок із джерелом тримає лише
 * перелік у компоненті. Розійтися він може з обох боків, і обидва тихі: кадр
 * прибрали з галереї — вікно обіцяє те, чого на сторінці немає; з'явилася
 * восьма галерея — «від кожного» тихо стало «від сімох».
 *
 * ## Зворотний експеримент (`PIT-REVERSE-EXPERIMENT`)
 *
 * Прибрати пункт `theatres` з `update-en.json` — перевірка називає саме його.
 * Прибрати `institutions` із `CHIPS` — називає його ж як пункт без ілюстрації.
 * Прибрати рядок із переліку кадрів — називає і власника без кадрів, і
 * невідповідність кількості мініатюр.
 */

interface Пункт {
	id: string;
	title: string;
	text: string;
}

const вміст = (мова: 'uk' | 'en'): { features: Пункт[] } =>
	JSON.parse(readFileSync(join('static', 'galaxy', `update-${мова}.json`), 'utf8'));

const uk = вміст('uk');
const en = вміст('en');

const ІЛЮСТРАЦІЇ = join('src', 'lib', 'components', 'GalaxyUpdateIllustration.svelte');
const джерело = readFileSync(ІЛЮСТРАЦІЇ, 'utf8');

/**
 * Пункти, у яких власної ілюстрації немає НАВМИСНО, і хто малює замість неї.
 *
 * Перелік лише скорочується: щойно в пункту з'явиться гілка в ілюстрації,
 * рядок звідси має піти тим самим комітом — про це кричить перевірка нижче.
 *
 * `teachers` тут НЕМАЄ навмисно: у нього гілка є, лише порожня, і причина
 * записана прямо в ній. Порожня гілка — це вже сказане вголос «тут нічого не
 * малюється», і дублювати його переліком означало б мати дві відповіді на одне
 * питання.
 */
const БЕЗ_ІЛЮСТРАЦІЇ: Record<string, string> = {
	galaxy: 'GalaxyUpdateStars — зоряний шар малює сам пункт, зсередини картинки до країв не дотягтися',
	order: 'GalaxyUpdateTeacherRow — ряд значків стоїть у потоці тексту, під ним',
	together: 'картинки немає: пункт — прохання заповнити анкету за друга, а не можливість сайту'
};

/** Чи вміє ілюстрація малювати цей пункт: окрема гілка або ключ у `CHIPS`. */
const малюється = (id: string): boolean =>
	джерело.includes(`id === '${id}'`) || new RegExp(`^\\t\\t${id}: \\{$`, 'm').test(джерело);

describe('вітальне вікно: вміст і ілюстрації', () => {
	it('перевірка жива: обидва тексти прочитано, і в них є пункти', () => {
		expect(uk.features.length, 'український текст без пунктів').toBeGreaterThan(8);
		expect(джерело.length, 'джерело ілюстрацій не прочитано').toBeGreaterThan(0);
	});

	it('uk і en описують ті самі пункти в тому самому порядку', () => {
		expect(
			en.features.map((f) => f.id),
			'перелік пунктів розійшовся між мовами — англійський читач бачить інше вікно'
		).toEqual(uk.features.map((f) => f.id));
	});

	it('у жодного пункту немає порожнього заголовка чи тексту', () => {
		const порожні = [...uk.features, ...en.features]
			.filter((f) => !f.title?.trim() || !f.text?.trim())
			.map((f) => f.id);
		expect(порожні, `пункт без тексту:\n${порожні.join('\n')}`).toEqual([]);
	});

	it('кожен пункт або має ілюстрацію, або названий у переліку винятків', () => {
		const німі = uk.features
			.map((f) => f.id)
			.filter((id) => !малюється(id) && !(id in БЕЗ_ІЛЮСТРАЦІЇ));
		expect(
			німі,
			`пункт малюється, а ілюстрація його не знає — поруч буде порожньо:\n${німі.join('\n')}`
		).toEqual([]);
	});

	it('перелік винятків не пережив ані своїх пунктів, ані своєї причини', () => {
		const id = new Set(uk.features.map((f) => f.id));
		const зайві = Object.keys(БЕЗ_ІЛЮСТРАЦІЇ)
			.map((ключ) => {
				if (!id.has(ключ)) return `${ключ}: такого пункту в тексті вже немає`;
				if (малюється(ключ)) return `${ключ}: ілюстрація з'явилася — прибрати рядок`;
				return null;
			})
			.filter(Boolean);
		expect(зайві, `перелік винятків застарів:\n${зайві.join('\n')}`).toEqual([]);
	});
});

const КОМПОНЕНТ = join('src', 'lib', 'components', 'GalaxyUpdateGallery.svelte');
const компонент = readFileSync(КОМПОНЕНТ, 'utf8');

/** Перелік кадрів, як він записаний у самому компоненті. */
const КАДРИ = [...компонент.matchAll(/\{ slug: '([^']+)', file: '([^']+)' \}/g)].map((m) => ({
	slug: m[1],
	file: m[2]
}));

/** Скільки кадрів беремо від кожного — теж записано в компоненті. */
const ПО_СКІЛЬКИ = 2;

/** Разом мініатюри важать ~85 КБ. Стеля з запасом — і лише вниз. */
const СТЕЛЯ_КБ = 90;

/** Анкети з непорожньою галереєю: адреса теки → список кадрів (щонайменше ПО_СКІЛЬКИ для двох кіл демонстрації). */
const галереї = (() => {
	const корінь = join('static', 'graduates', 'profiles');
	const мапа = new Map<string, string[]>();
	for (const файл of readdirSync(корінь)) {
		const анкета = JSON.parse(readFileSync(join(корінь, файл), 'utf8')) as {
			slug: string;
			gallery?: string[];
		};
		if (анкета.gallery && анкета.gallery.length >= ПО_СКІЛЬКИ)
			мапа.set(анкета.slug, анкета.gallery);
	}
	return мапа;
})();

describe('вітальне вікно: демонстрація галерей', () => {
	const мініатюри = readdirSync(join('static', 'galaxy'))
		.filter((f) => /^update-gallery-\d+\.webp$/.test(f))
		.sort();

	it('перевірка жива: перелік кадрів і анкети з галереями знайдено', () => {
		expect(КАДРИ.length, 'у компоненті не розібрано жодного кадру').toBeGreaterThan(0);
		expect(галереї.size, 'жодної анкети з галереєю').toBeGreaterThan(0);
	});

	it('мініатюр рівно стільки, скільки кадрів у переліку', () => {
		expect(
			мініатюри.length,
			`у переліку ${КАДРИ.length} кадрів, а мініатюр у static/galaxy/ ${мініатюри.length}: ` +
				'зайвий файл нікому не показується, якого бракує — дасть порожню рамку'
		).toBe(КАДРИ.length);
	});

	it('показано по два кадри від КОЖНОГО, у кого галерея є', () => {
		/*
		 * Не «від когось», а саме від кожного: пункт стверджує, що галерею має
		 * не одна людина, і восьма галерея без свого кадру тихо зробила б це
		 * твердження вужчим. Червоне тут означає «перегенеруй мініатюри»,
		 * а не помилку в даних.
		 */
		const показані = new Map<string, number>();
		for (const к of КАДРИ) показані.set(к.slug, (показані.get(к.slug) ?? 0) + 1);

		const біда: string[] = [];
		for (const slug of галереї.keys())
			if (!показані.has(slug)) біда.push(`${slug}: галерея є, а кадрів у вікні немає`);
		for (const [slug, скільки] of показані) {
			if (!галереї.has(slug)) біда.push(`${slug}: кадри у вікні є, а галереї в анкеті вже немає`);
			else if (скільки !== ПО_СКІЛЬКИ)
				біда.push(`${slug}: кадрів ${скільки}, а правило — ${ПО_СКІЛЬКИ}`);
		}
		expect(біда, `демонстрація розійшлася з галереями:\n${біда.join('\n')}`).toEqual([]);
	});

	it('кожен кадр-джерело досі лежить у галереї свого власника', () => {
		// Мініатюри — похідні, і самі про джерело нічого не знають. Коли кадр із
		// галереї прибрали чи перенумерували, вікно й далі показує його — тобто
		// обіцяє те, чого на сторінці вже немає, і відкриває на весь екран файл,
		// якого може не бути на диску.
		const зниклі = КАДРИ.filter(
			(к) => !(галереї.get(к.slug) ?? []).includes(`/graduates/gallery/${к.slug}/${к.file}`)
		).map((к) => `${к.slug}/${к.file}`);
		expect(
			зниклі,
			`кадр, з якого зроблено мініатюру, зник із галереї:\n${зниклі.join('\n')}`
		).toEqual([]);
	});

	it('повнорозмірні кадри, які відкриває лайтбокс, є на диску', () => {
		const немає = КАДРИ.filter(
			(к) => !existsSync(join('static', 'graduates', 'gallery', к.slug, к.file))
		).map((к) => `${к.slug}/${к.file}`);
		expect(немає, `натискання відкриє порожнечу:\n${немає.join('\n')}`).toEqual([]);
	});

	it('мініатюри лишаються мініатюрами', () => {
		const кб =
			мініатюри.reduce((сума, f) => сума + statSync(join('static', 'galaxy', f)).size, 0) / 1024;
		expect(
			кб,
			`мініатюри важать ${кб.toFixed(1)} КБ при стелі ${СТЕЛЯ_КБ} — ` +
				'заради економії їх і робили, інакше простіше було б показувати самі знімки'
		).toBeLessThan(СТЕЛЯ_КБ);
	});
});

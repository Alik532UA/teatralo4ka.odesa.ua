// @vitest-environment node
import { describe, expect, it } from 'vitest';
import { зібрати, лишеАвтор } from '../scripts/audit-play-naming';

/**
 * Виставу звуть однаково в анкеті й у реєстрі.
 *
 * ## Звідки взявся гейт
 *
 * Автор побачив те саме двома написаннями: в анкеті «Уривки з класики: Той, що
 * отримує ляпаса», у реєстрі — «Л. Андреєв „Той, хто отримує ляпаси“». Звірка
 * всіх анкет знайшла 109 таких розходжень у 53 випадках; автор вирішив просто:
 * «реєстр вважаємо джерелом правди, виправляємо все».
 *
 * Після виправлення розходжень лишилося НУЛЬ — і саме тому гейт з'явився аж
 * тепер. Поки їх була сотня, він був би червоним назавжди, а червоний назавжди
 * — те саме, що вимкнений.
 *
 * ## Чого гейт не бачить
 *
 * Того самого, чого не бачив звіт: анкета може ДОПИСУВАТИ автора («Антігона;
 * Софокл»), а реєстр тримає його окремим полем. Це різні способи запису, і
 * автор сказав, що виправляти там нема чого (`лишеАвтор` у скрипті).
 *
 * ## Зворотний експеримент (AI-AGENT-PITFALLS-v8 § 1.1)
 *
 * Змінити в будь-якій анкеті назву вистави на іншу — перевірка падає й називає
 * людину, рік, обидва написання й ключ вистави.
 */

const { розбіжності, перевірено } = зібрати();
const справжні = розбіжності.filter((р) => !лишеАвтор(р));

describe('назви вистав в анкетах збігаються з реєстром', () => {
	it('перевірка жива: рядки анкет із посиланням на виставу знайдено', () => {
		// Без цього гейт був би зеленим і на порожній вибірці — тобто нічого не
		// стверджував би.
		expect(перевірено, 'жодного рядка з `playId` — звіряти нема чого').toBeGreaterThan(500);
	});

	it('жодна анкета не зве виставу інакше, ніж реєстр (CRITICAL)', () => {
		const bad = справжні.map(
			(р) =>
				`${р.хто} (${р.рік ?? '—'}) ${р.вид}: анкета «${р.вАнкеті}» ≠ реєстр «${р.уРеєстрі}» [${р.вистава}]`
		);
		expect(
			bad,
			'те саме на двох сторінках зветься по-різному. Джерело правди — реєстр вистав: ' +
				'або виправити рядок анкети, або, якщо помилка в реєстрі, виправити реєстр і ' +
				`анкети разом:\n  ${bad.join('\n  ')}`
		).toEqual([]);
	});
});

import type { Reroute } from '@sveltejs/kit';
import { stripLocale } from '$lib/i18n/routing';

/**
 * Мовний префікс в адресі без дублювання маршрутів (I18N-v8 § 3.1).
 *
 * `reroute` віддає шлях, за яким SvelteKit ШУКАЄ маршрут, не змінюючи адреси в
 * рядку браузера. Тобто `/en/about` рендериться маршрутом `/about`, а
 * `page.url.pathname` лишається `/en/about` — саме з нього далі беруться мова,
 * canonical і hreflang.
 *
 * ## Чому так, а не групою маршрутів `[[lang=lang]]`
 *
 * Група — очевидніший спосіб, і спершу планувався саме він. Ціна: усі 25
 * каталогів маршрутів переїжджають на рівень глибше. Це не лише великий дифф,
 * а й ризик, якого не видно в коді: `resolve()` у цьому проєкті типізований
 * проти списку реальних маршрутів, і 72 місця з ним мали б бути переписані
 * одним комітом разом із переїздом. Саме такий масовий рух — «перейменування
 * без оновлення того, що на нього посилається» — AI-AGENT-PITFALLS-v8 § 4
 * називає окремим класом помилок.
 *
 * `reroute` натомість не чіпає ані структуру, ані `resolve()`: маршрути
 * лишаються там, де були, і лишаються тими самими для обох мов.
 *
 * ## Обмеження, про які треба знати
 *
 * Хук ОБОВ'ЯЗКОВО синхронний і виконується на кожну навігацію, зокрема на
 * клієнті перед завантаженням модуля маршруту. Тому тут не може бути ні
 * запитів, ні читання сховища — лише розбір рядка.
 */
export const reroute: Reroute = ({ url }) => stripLocale(url.pathname);

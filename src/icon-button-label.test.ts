import { describe, expect, it } from 'vitest';
import { readFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';

/**
 * Кнопка й посилання зі самого значка мусять мати імʼя
 * (ACCESSIBILITY-v9 § 10.2, `A11Y-STATIC-ICON-LABEL`, HIGH).
 *
 * ## Чому статично, коли є axe
 *
 * axe ходить сторінками — і бачить рівно те, що на них НАМАЛЬОВАНО в момент
 * обходу. Кнопка в модальному вікні, у гілці `{#if}`, у меню, яке
 * розкривається дією, або на сторінці, куди `page.goto()` не заходить,
 * лишається поза оглядом. Саме такі місця й забувають підписати: значок
 * виглядає зрозумілим тому, хто його ставив.
 *
 * Тут перевіряється розмітка, тож гілки не мають значення — файл прочитано
 * цілком.
 *
 * ## Що вважається імʼям
 *
 * Будь-що з переліченого: `aria-label`, `aria-labelledby`, `title`, видимий
 * текст (зокрема через `{$t(...)}` чи будь-який інший вираз), клас
 * прихованого тексту для читалки або `<title>` усередині значка.
 *
 * ## Чого перевірка НЕ судить
 *
 * Двох випадків, і обидва — тому, що з тексту правди не видно:
 *
 * 1. **Розгортання атрибутів** (`{...щось}`): що саме там лежить, невідомо, і
 *    вимога перетворилася б на шум. Таких одиниці, і вони під окремим
 *    наглядом — розгортання на елементі коштує CSP
 *    (`scripts/check-inline-handlers.ts`).
 * 2. **Чужий компонент усередині**, який не є значком. `GraduatePlayRow`
 *    показав це першим: посилання складається з `RichTextWithFlags`, тобто
 *    саме з тексту, — а сканер, який знімає розмітку, бачив порожнє тіло й
 *    оголошував посилання безіменним. Значки відрізняються не назвою, а
 *    ПОХОДЖЕННЯМ: усі вони приходять із `lucide-svelte`, і перелік береться з
 *    імпортів того самого файлу. Компонент іншого походження вважається
 *    можливим текстом.
 *
 * ## Стан на 2026-09-10
 *
 * Порушень нуль — і саме тому перевірка зʼявилася зараз. Правило трималося
 * памʼяттю автора: зробити наступну кнопку-значок без підпису ніщо не заважало.
 *
 * Зворотний експеримент (AI-AGENT-PITFALLS-v9 § 1.1): додати в будь-який
 * компонент кнопку зі самим значком і без підпису — перевірка називає файл,
 * рядок і розмітку. Зроблено.
 */

const КОРІНЬ = 'src';

/** Атрибути, що дають імʼя. */
const ІМЕНУВАЛЬНІ = /\b(aria-label|aria-labelledby|title)\s*=/;

/** Класи прихованого тексту, які проєкт уживає для читалок. */
const ПРИХОВАНИЙ_ТЕКСТ = /\b(sr-only|visually-hidden|screen-reader|visuallyhidden)\b/;

/** Розгортання атрибутів: вміст із тексту не видно, судити нема про що. */
const РОЗГОРТАННЯ = /\{\s*\.\.\./;

function усіКомпоненти(dir: string, out: string[] = []): string[] {
	for (const entry of readdirSync(dir)) {
		const full = join(dir, entry).replace(/\\/g, '/');
		if (statSync(full).isDirectory()) усіКомпоненти(full, out);
		else if (full.endsWith('.svelte')) out.push(full);
	}
	return out;
}

/**
 * Кінець відкривального тега.
 *
 * Простим `[^>]*` тут не обійтися: у значенні атрибута легко трапляється `>` —
 * `onclick={() => close()}` є в кожному другому компоненті. Тому рахуються
 * лапки й фігурні дужки, і `>` поза ними вважається кінцем тега.
 */
function кінецьТега(src: string, from: number): number {
	let depth = 0;
	let quote: string | null = null;
	for (let i = from; i < src.length; i++) {
		const c = src[i];
		if (quote) {
			if (c === quote) quote = null;
			continue;
		}
		if (c === '"' || c === "'") quote = c;
		else if (c === '{') depth++;
		else if (c === '}') depth--;
		else if (c === '>' && depth === 0) return i;
	}
	return -1;
}

type Знахідка = { файл: string; рядок: number; розмітка: string };

/**
 * Значки, імпортовані у файл із `lucide-svelte`.
 *
 * Саме походження, а не назва: `<X />` — значок, `<RichTextWithFlags />` —
 * текст, і відрізнити їх можна лише за рядком імпорту.
 */
function значкиФайлу(src: string): Set<string> {
	const out = new Set<string>();
	for (const m of src.matchAll(/import\s*\{([^}]*)\}\s*from\s*['"]lucide-svelte['"]/g)) {
		for (const name of m[1].split(',')) {
			const clean = name.split(' as ').pop()?.trim();
			if (clean) out.add(clean);
		}
	}
	for (const m of src.matchAll(/import\s+(\w+)\s+from\s+['"]lucide-svelte\/icons\//g)) out.add(m[1]);
	return out;
}

function безІмені(файл: string, тег: 'button' | 'a'): Знахідка[] {
	const src = readFileSync(файл, 'utf8');
	const значки = значкиФайлу(src);
	const out: Знахідка[] = [];
	const відкриття = new RegExp(`<${тег}(?=[\\s>])`, 'g');
	for (const m of src.matchAll(відкриття)) {
		const кінець = кінецьТега(src, m.index + 1);
		if (кінець < 0) continue;
		const атрибути = src.slice(m.index + тег.length + 1, кінець);
		if (src[кінець - 1] === '/') continue; // самозакритий — тіла немає
		const закриття = src.indexOf(`</${тег}>`, кінець);
		if (закриття < 0) continue;
		const тіло = src.slice(кінець + 1, закриття);

		if (РОЗГОРТАННЯ.test(атрибути)) continue;
		if (ІМЕНУВАЛЬНІ.test(атрибути)) continue;
		if (ПРИХОВАНИЙ_ТЕКСТ.test(тіло)) continue;
		// `<title>` усередині значка — теж імʼя.
		if (/<title[\s>]/.test(тіло)) continue;

		// Текст поза розміткою: літерали, вирази `{…}`, блоки `{#if}` — усе,
		// що може стати видимим словом.
		const текст = тіло.replace(/<[^>]*>/g, '').replace(/\s+/g, '').trim();
		if (текст.length > 0) continue;

		// Чужий компонент усередині може малювати текст — судити нема про що.
		const компоненти = [...тіло.matchAll(/<([A-Z]\w*)[\s/>]/g)].map((c) => c[1]);
		if (компоненти.some((c) => !значки.has(c))) continue;

		out.push({
			файл,
			рядок: src.slice(0, m.index).split('\n').length,
			розмітка: src.slice(m.index, Math.min(закриття + тег.length + 3, m.index + 100)).replace(/\s+/g, ' ')
		});
	}
	return out;
}

const компоненти = усіКомпоненти(КОРІНЬ);

describe('кнопка-значок має імʼя', () => {
	it('перевірка жива: компоненти знайдено й кнопки в них розібрано', () => {
		expect(компоненти.length, 'жодного .svelte — сканер зламався').toBeGreaterThan(100);
		const усіКнопки = компоненти.reduce(
			(n, f) => n + (readFileSync(f, 'utf8').match(/<button(?=[\s>])/g)?.length ?? 0),
			0
		);
		expect(усіКнопки, 'у проєкті не знайдено жодної кнопки — розбір зламався').toBeGreaterThan(
			100
		);
	});

	it('жодна кнопка не складається зі самого значка без підпису', () => {
		const знайдені = компоненти.flatMap((f) => безІмені(f, 'button'));
		expect(
			знайдені.map((з) => `${з.файл}:${з.рядок} — ${з.розмітка}`),
			'кнопка без видимого тексту й без aria-label: читалка озвучить її як «кнопка»'
		).toEqual([]);
	});

	it('жодне посилання не складається зі самого значка без підпису', () => {
		const знайдені = компоненти.flatMap((f) => безІмені(f, 'a'));
		expect(
			знайдені.map((з) => `${з.файл}:${з.рядок} — ${з.розмітка}`),
			'посилання без видимого тексту й без aria-label: у переліку посилань сторінки ' +
				'воно буде безіменним'
		).toEqual([]);
	});
});

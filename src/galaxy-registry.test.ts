import { describe, it, expect } from 'vitest';
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';

/**
 * Кожна сторінка-перелік галактики має пошук, режими показу й обличчя.
 *
 * ## Дефект, через який ця перевірка з'явилася
 *
 * Автор порівняв п'ять переліків і виписав різницю сам: у вистав, груп і
 * фестивалів є пошук, три режими показу (хронологія, список, плитка) і
 * мініатюри випускників; у навчальних закладів і театрів немає нічого з цього.
 *
 * І назвав те, що потрібно виправити НАСПРАВДІ: «але ремонтували костилем, а по
 * ремонтувати так щоб при створенні наступних подібних сторінок ці відсутні
 * елементи були, бо кожен раз створюється сторінка на подобі існуючої і саме ці
 * елементи чомусь не створюються».
 *
 * Причина була не в недбалості. Обидві нові сторінки писалися, дивлячись на
 * сусідню, — а пошук і режими жили не в ній, а в ста п'ятдесяти рядках
 * однакового зв'язування, розкиданого по трьох файлах. Те, що переписують
 * руками, копіюють не повністю: перше, що губиться при копії, — саме дрібне
 * зв'язування.
 *
 * Тому виправлення двоскладове, і ця перевірка — його друга половина.
 * Перша — `components/galaxy/GalaxyRegistry.svelte`, який тримає все
 * зв'язування; друга — вимога тут, щоб перелік його ВЖИВАВ. Без неї наступна
 * сторінка знову народиться копією.
 *
 * ## Чому перевіряється саме ІМПОРТ, а не згадка імені
 *
 * Пошук і перемикач — це не рядок HTML, який можна знайти регуляркою: вони
 * приходять компонентами, і саме імпорт є тим, що забувають. Три наявні
 * сторінки зв'язують усе руками (у них є свої `SearchField`, `MasterViewToggle`
 * і `GalaxyRows`), і переписувати їх «за компанію» тут ніхто не просив — тому
 * перевірка приймає обидва способи: або `GalaxyRegistry`, або всі три частини
 * окремо. Вимагати саме `GalaxyRegistry` означало б валити гейт на трьох
 * робочих сторінках.
 *
 * Шукається РЯДОК ІМПОРТУ (`from '…/GalaxyRegistry.svelte'`), а не входження
 * імені, і це виправлення першої редакції. Вона питала `includes('…')` — і
 * зворотний експеримент її не зламав: перейменований `GalaxyRegistryZZZ`
 * усередині МІСТИТЬ `GalaxyRegistry`, тож перевірка бачила його й зеленіла.
 * Заразом та сама дірка пропускала б згадку в коментарі. Тобто перший дослід
 * зламав не код, а мою перевірку — і добре, що зламав.
 *
 * ## Зворотний експеримент (AI-AGENT-PITFALLS-v8 § 1.1)
 *
 * ПРИБРАТИ рядок імпорту (а не перейменувати компонент — див. вище): без
 * `GalaxyRegistry` на сторінці театрів перевірка падає й називає саме її та
 * саме те, чого не стало; без `MasterViewToggle` на сторінці груп, яка
 * зв'язує руками, — так само. Третій дослід: лишити `GalaxyRegistry`, але
 * викинути `memberIds` із рядків — падає окрема перевірка про обличчя.
 */
const КОРІНЬ = 'src/routes/projects/galaxy-graduates';

/**
 * Сторінки, які переліком НЕ є, — з причиною в кожної.
 *
 * Список короткий навмисно: щойно в ньому з'явиться десяток записів, перевірка
 * перетвориться на декорацію.
 */
const НЕ_ПЕРЕЛІКИ: Record<string, string> = {
	// Сама галактика: там імена літають по полотну, а не стоять переліком.
	'.': 'полотно галактики, а не перелік',
	// Дві адреси заради прев'ю в месенджері: ведуть далі, вмісту не мають.
	update: 'сторінка-прев’ю оголошення',
	form: 'сторінка-прев’ю анкети',
	// Наповнення архіву: числа й графіки, жодного переліку сутностей.
	stats: 'показники наповнення, а не перелік сутностей'
};

/** Частини зв'язування, які перелік мусить мати — сам або через `GalaxyRegistry`. */
const ЧАСТИНИ = ['SearchField', 'MasterViewToggle', 'GalaxyRows'] as const;

/**
 * Чи сторінка справді ІМПОРТУЄ цей компонент.
 *
 * Збіг — хвіст шляху разом із лапкою: `/GalaxyRegistry.svelte'`. Згадка імені в
 * коментарі так не зійде, і перейменований `…ZZZ` не влізе — розбір у докблоці
 * вище.
 *
 * Просте входження рядка, а не регулярка, і це друга спроба: у першій регулярка
 * складалася в шаблонному рядку, `\s` і `\.` з'їдалися ним, і вираз ставав
 * `froms+…`, який не збігається ні з чим. Перевірка тоді оголосила, що ЖОДНА
 * сторінка нічого не імпортує — і саме ця брехня її й виказала.
 */
const імпортує = (джерело: string, назва: string) =>
	джерело.includes(`/${назва}.svelte'`);

/**
 * Джерело БЕЗ коментарів — і без цього перевірка обманює себе.
 *
 * Третій зворотний дослід був такий: викинути `memberIds` із рядків сторінки
 * театрів. Перевірка не впала — бо слово `memberIds` лишилося в докблоці над
 * тим самим місцем, де я пояснював, що воно й дає обличчя. Тобто моє власне
 * пояснення й задовольнило перевірку.
 *
 * Це та сама пастка, на якій уже спіймався гейт стилів компонентів у цьому
 * проєкті: перевірки по джерелах читають файл ТЕКСТОМ і не відрізняють код від
 * коментаря. Тому тут коментарі знімаються — і `//`, і блокові, і розміткові.
 */
const безКоментарів = (джерело: string) =>
	джерело
		.replace(/<!--[\s\S]*?-->/g, '')
		.replace(/\/\*[\s\S]*?\*\//g, '')
		.replace(/^\s*\/\/.*$/gm, '');

function переліки(): { назва: string; файл: string; джерело: string }[] {
	const out: { назва: string; файл: string; джерело: string }[] = [];
	for (const entry of readdirSync(КОРІНЬ)) {
		const шлях = join(КОРІНЬ, entry).replace(/\\/g, '/');
		if (!statSync(шлях).isDirectory()) continue;
		if (entry.startsWith('[')) continue; // сторінка однієї сутності, не перелік
		if (entry in НЕ_ПЕРЕЛІКИ) continue;
		const файл = `${шлях}/+page.svelte`;
		let джерело: string;
		try {
			джерело = readFileSync(файл, 'utf8');
		} catch {
			continue; // тека без своєї сторінки — лише вкладені маршрути
		}
		out.push({ назва: entry, файл, джерело: безКоментарів(джерело) });
	}
	return out;
}

const ПЕРЕЛІКИ = переліки();

describe('сторінки-переліки галактики', () => {
	it('перевірка жива: переліки знайдено', () => {
		// Без цього рядка все нижче зеленіє на порожньому переліку тек.
		expect(ПЕРЕЛІКИ.length, 'жодного переліку не знайдено').toBeGreaterThan(4);
		expect(ПЕРЕЛІКИ.map((p) => p.назва)).toContain('theatres');
		expect(ПЕРЕЛІКИ.map((p) => p.назва)).toContain('institutions');
	});

	it('у кожному переліку є пошук, режими показу й рядки з обличчями', () => {
		const bad: string[] = [];
		for (const { назва, файл, джерело } of ПЕРЕЛІКИ) {
			if (імпортує(джерело, 'GalaxyRegistry')) continue;
			const бракує = ЧАСТИНИ.filter((частина) => !імпортує(джерело, частина));
			if (бракує.length)
				bad.push(
					`${назва} (${файл}): немає ${бракує.join(', ')} — ` +
						'візьміть `galaxy/GalaxyRegistry.svelte`, він дає все це разом'
				);
		}
		expect(
			bad,
			'перелік без пошуку або без режимів показу. Це не косметика: саме ці\n' +
				'частини губляться, коли сторінку роблять копією сусідньої:\n  ' +
				bad.join('\n  ')
		).toEqual([]);
	});

	/*
	 * Обличчя перевіряються окремо від решти, бо ламаються інакше: `GalaxyRows`
	 * малює їх ЛИШЕ коли рядок несе `memberIds`. Сторінка може взяти
	 * `GalaxyRegistry` і не покласти ключів — тоді пошук і режими є, а облич
	 * немає, і виглядає це як задум.
	 */
	it('рядки переліку несуть ключі людей — інакше облич не буде', () => {
		const bad: string[] = [];
		for (const { назва, файл, джерело } of ПЕРЕЛІКИ) {
			if (!імпортує(джерело, 'GalaxyRegistry') && !імпортує(джерело, 'GalaxyRows')) continue;
			if (!джерело.includes('memberIds'))
				bad.push(`${назва} (${файл}): у рядках немає memberIds`);
		}
		expect(bad, `перелік без облич випускників:\n  ${bad.join('\n  ')}`).toEqual([]);
	});

	it('кожен виняток зі списку «не переліки» справді існує', () => {
		// Інакше список переживе саму сторінку й тихо звільнить від перевірки те,
		// що з'явиться під тим самим іменем.
		const bad = Object.keys(НЕ_ПЕРЕЛІКИ)
			.filter((назва) => назва !== '.')
			.filter((назва) => {
				try {
					return !statSync(join(КОРІНЬ, назва)).isDirectory();
				} catch {
					return true;
				}
			});
		expect(bad, `виняток без сторінки:\n  ${bad.join('\n  ')}`).toEqual([]);
	});
});

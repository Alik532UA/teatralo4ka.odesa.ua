import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';
import { ОБОВʼЯЗКОВІ_СЕКРЕТИ, відсутніСекрети } from '../scripts/firebase-env';

/**
 * Охорона секретів Firebase на збірці — і те, що вона стереже правильний
 * перелік.
 *
 * ## Чому це окрема перевірка, а не «і так видно»
 *
 * Перелік обовʼязкових ключів і код, який їх читає, — два місця з тією самою
 * правдою. Розходження тихе в обидва боки:
 *
 * - ключ зʼявився в `firebaseConfig`, але не в переліку — збірка без нього
 *   пройде зеленою, а сайт поїде з `undefined` у цьому полі;
 * - ключ лишився в переліку, а з конфігу зник — збірка вимагає секрет, якого
 *   код більше не читає, і його доведеться вигадувати при кожному переносі.
 *
 * ## Що НЕ перевіряється тут
 *
 * Наявність самих значень: `.env.local` у репозиторії немає й не буде, а в CI
 * секрети приходять із `secrets`. Тут доводиться лише те, що охорона на місці,
 * увімкнена саме на збірці, стереже правильний перелік і не друкує значень.
 *
 * Зворотний експеримент (AI-AGENT-PITFALLS-v9 § 1.1): прибрати рядок із
 * переліку в `scripts/firebase-env.ts` — падає звірка множин і називає саме
 * цей ключ; замінити `apply: 'build'` на `apply: 'serve'` — падає перевірка
 * моменту. Зроблено обидва.
 */

const VITE_CONFIG = readFileSync('vite.config.ts', 'utf8');
const FIREBASE_CONFIG = readFileSync('src/lib/firebase/config.ts', 'utf8');

/**
 * Ключі, які читає сам конфіг Firebase.
 *
 * Береться лише обʼєкт `firebaseConfig` — саме без нього SDK непрацездатний.
 * Решта читань у файлі (`VITE_APPCHECK_*`) навмисно необовʼязкові: без App
 * Check сайт працює, і сам модуль це передбачає.
 */
function перелікКоду(): string[] {
	const block = /const firebaseConfig\s*=\s*\{([\s\S]*?)\n\};/.exec(FIREBASE_CONFIG);
	if (!block) {
		throw new Error('у firebase/config.ts не знайдено обʼєкта конфігурації — його переписали');
	}
	return [...block[1].matchAll(/import\.meta\.env\.([A-Z0-9_]+)/g)].map((m) => m[1]).sort();
}

describe('секрети Firebase під охороною збірки', () => {
	it('перевірка жива: обидва переліки не порожні', () => {
		expect(ОБОВʼЯЗКОВІ_СЕКРЕТИ.length).toBeGreaterThan(3);
		expect(перелікКоду().length).toBeGreaterThan(3);
	});

	it('охорона вимагає рівно ті ключі, які читає конфіг Firebase', () => {
		expect([...ОБОВʼЯЗКОВІ_СЕКРЕТИ].sort()).toEqual(перелікКоду());
	});

	it('повне оточення проходить, а порожнє називає всі ключі', () => {
		const повне = Object.fromEntries(ОБОВʼЯЗКОВІ_СЕКРЕТИ.map((k) => [k, 'x']));
		expect(відсутніСекрети(повне)).toEqual([]);
		expect(відсутніСекрети({})).toEqual([...ОБОВʼЯЗКОВІ_СЕКРЕТИ]);
	});

	it('порожній рядок і пробіли — це відсутність, а не значення', () => {
		const [перший, ...решта] = ОБОВʼЯЗКОВІ_СЕКРЕТИ;
		const майже = Object.fromEntries(решта.map((k) => [k, 'x']));
		expect(
			відсутніСекрети({ ...майже, [перший]: '   ' }),
			'змінна, оголошена в CI без значення, приїжджає порожнім рядком — ' +
				'він мовчки їде в бандл, тоді як undefined принаймні видно'
		).toEqual([перший]);
	});

	it('охорона вмикається саме на збірці й не друкує значень', () => {
		expect(VITE_CONFIG, 'плагін охорони зник із конфігу Vite').toContain('firebase-env-gate');
		expect(VITE_CONFIG, 'охорона мусить стосуватися збірки, а не dev-сервера').toMatch(
			/name:\s*'firebase-env-gate'[\s\S]{0,120}apply:\s*'build'/
		);
		const повідомлення = /збірка зупинена[\s\S]*?\);/.exec(VITE_CONFIG)?.[0] ?? '';
		expect(повідомлення, 'охорона не називає відсутніх ключів').toContain('порожні.join');
		expect(
			/env\[[^\]]+\]/.test(повідомлення),
			'у повідомлення підставляється ЗНАЧЕННЯ ключа — це витік секрету в лог CI'
		).toBe(false);
	});
});

// @vitest-environment node
import { describe, expect, it } from 'vitest';
import { зібрати, записи, адреса } from '../scripts/build-address-aliases';
import ЗГЕНЕРОВАНО from './lib/data/address-aliases.data.json';
import { GRADUATE_ALIASES, RENAMED_GRADUATE_ADDRESSES } from './lib/config/renamedAddresses';

/**
 * Стандартна адреса випускника веде на його особисту — і перелік не відстає.
 *
 * ## Навіщо
 *
 * Адреса сторінки це `code ?? slug`, тож у 27 людей очікувана адреса
 * (ім'я-прізвище) не веде нікуди: `/projects/galaxy-graduates/alik-zapolnov/`
 * давала 404, хоч сторінка Аліка існує за адресою `Alik`. Перелік заглушок
 * генерується з реєстру (`npm run build:address-aliases`) і лежить у
 * репозиторії, щоб `npm run dev` і перевірки працювали без збірки — а отже може
 * відстати рівно так, як відставав покажчик карток новин.
 *
 * Те, що кожна заглушка справді пререндериться, стоїть у реєстрі й не забирає
 * чужу сторінку, перевіряє `src/renamed-addresses.test.ts`: аліаси лежать у
 * тому самому `RENAMED_PATHS`, тож усі його вісім перевірок стосуються і їх.
 * Тут — лише те, що стосується самого виведення.
 *
 * ## Найважливіша перевірка тут — остання
 *
 * Виведення точне тільки для тих, у кого адреса це `code`: стандартна адреса
 * лежить поруч у `slug`. Для особистого `slug` (`margotcine`, `reverenciel`)
 * виводити нема з чого, і поле `aliases` пишеться руками — тобто про нього
 * можна забути. Тому остання перевірка шукає слаг, НЕ схожий на ім'я людини, і
 * вимагає для нього або `code`, або `aliases`.
 *
 * Схожість тут — саме детектор, а не джерело істини: транслітерація в реєстрі
 * не одна (`anton-babich` проти `anton-babych`, `dar-ia-hurevych`), тож поріг
 * підібраний так, щоб різні написання проходили, а `al_bryn` — ні.
 *
 * ## Зворотний експеримент (AI-AGENT-PITFALLS-v8 § 1.1)
 *
 * Проведено: з файлу прибрано один запис — упала перевірка збігу й назвала
 * адресу; слаг Маргарити Жовненко змінено на `margotcine` без `aliases` — упала
 * перевірка «слаг, не схожий на людину» й назвала саме її; аліасом зроблено
 * чинну адресу іншої людини — виведення відкинуло його, і впала перевірка «без
 * зіткнень».
 *
 * Перша спроба другого досліду взяла Марію Куліш — і НЕ впала, бо в неї є
 * `code`. Це не хиба перевірки, а той самий поділ: кому адресу дає код, тому
 * стандартну виводить скрипт, хоч би як змінився слаг.
 */

const УСІ = записи();

/**
 * Кого вже прикриває ПЕРЕЙМЕНУВАННЯ, а не аліас.
 *
 * Двоє (Роман Арабаджі, Алла Бринза) отримали особисту адресу тоді, коли стара
 * вже існувала, тож їхня стандартна адреса живе в `RENAMED_GRADUATE_ADDRESSES`.
 * Без цього переліку перевірка нижче вимагала б від них ще й `aliases` — тобто
 * ту саму адресу двома записами з різними цілями.
 */
const ЧЕРЕЗ_ПЕРЕЙМЕНУВАННЯ = new Set(Object.values(RENAMED_GRADUATE_ADDRESSES));

/** Наскільки слаг далекий від імені. 0 — збігається, 1 — нічого спільного. */
function несхожість(slug: string, імʼя: string): number {
	const варіанти = транслітерації(імʼя);
	return Math.min(...варіанти.map((в) => відстань(slug, в) / Math.max(slug.length, в.length, 1)));
}

/** Кілька написань того самого імені: `є` буває `ye` і `ie`, `я` — `ya` і `ia`. */
function транслітерації(імʼя: string): string[] {
	const ОДНОЗНАЧНІ: Record<string, string> = {
		а: 'a', б: 'b', в: 'v', г: 'h', ґ: 'g', д: 'd', е: 'e', ж: 'zh', з: 'z', и: 'y',
		і: 'i', к: 'k', л: 'l', м: 'm', н: 'n', о: 'o', п: 'p', р: 'r', с: 's', т: 't',
		у: 'u', ф: 'f', х: 'kh', ц: 'ts', ч: 'ch', ш: 'sh', щ: 'shch', ь: '', ' ': '-'
	};
	const ДВОЯКІ: Record<string, [string, string]> = {
		є: ['ye', 'ie'], ї: ['yi', 'i'], й: ['y', 'i'], ю: ['yu', 'iu'], я: ['ya', 'ia']
	};
	const джерела = [імʼя, імʼя.replace(/\(.*?\)/g, '')];
	const результат: string[] = [];
	for (const джерело of джерела) {
		for (const другий of [false, true]) {
			const літери = [...джерело.toLowerCase()].map((с) => {
				if (ДВОЯКІ[с]) return ДВОЯКІ[с][другий ? 1 : 0];
				if (с in ОДНОЗНАЧНІ) return ОДНОЗНАЧНІ[с];
				return /[a-z0-9]/.test(с) ? с : '-';
			});
			результат.push(літери.join('').replace(/-+/g, '-').replace(/^-|-$/g, ''));
		}
	}
	return результат;
}

function відстань(a: string, b: string): number {
	let попередній = Array.from({ length: b.length + 1 }, (_, i) => i);
	for (let i = 1; i <= a.length; i++) {
		const поточний = [i];
		for (let j = 1; j <= b.length; j++) {
			поточний.push(
				Math.min(
					попередній[j] + 1,
					поточний[j - 1] + 1,
					попередній[j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1)
				)
			);
		}
		попередній = поточний;
	}
	return попередній[b.length];
}

/** Вище цього слаг уже не читається як ім'я людини. Підібрано на реєстрі. */
const МЕЖА = 0.4;

describe('стандартні адреси випускників', () => {
	it('перевірка жива: реєстр і перелік не порожні', () => {
		expect(УСІ.length, 'реєстр порожній').toBeGreaterThan(500);
		expect(Object.keys(ЗГЕНЕРОВАНО).length, 'жодного аліаса').toBeGreaterThan(20);
	});

	it('перелік збігається з реєстром ЗАРАЗ', () => {
		expect(
			ЗГЕНЕРОВАНО,
			'перелік відстав від реєстру. Перезібрати: npm run build:address-aliases'
		).toEqual(зібрати(УСІ).aliases);
	});

	it('модуль реєстру віддає той самий перелік', () => {
		// Без цього рядка перелік міг би бути правильним, а сторінки — ні:
		// заглушки збирає саме `GRADUATE_ALIASES` через `RENAMED_PATHS`.
		expect(GRADUATE_ALIASES).toEqual(ЗГЕНЕРОВАНО);
	});

	it('без зіткнень: жодну адресу не відкинуто мовчки', () => {
		const { конфлікти } = зібрати(УСІ);
		expect(
			конфлікти,
			'аліас не потрапив у перелік — вирішити руками, а не лишати як є:\n  ' +
				конфлікти.join('\n  ')
		).toEqual([]);
	});

	it('адрес, що різняться лише регістром, рівно троє — і жодна з них не аліас', () => {
		/*
		 * На Windows дві такі сторінки претендують на ОДНУ теку в `build/`, і
		 * заглушка затирає справжню: збірка падає на битих посиланнях, а в CI
		 * (Linux) те саме зелене. Тому аліас для них не робиться, і поява
		 * четвертої адреси з великими літерами мусить зупинити збірку — тоді
		 * рішення (привести адресу до нижнього регістру) ухвалює автор.
		 */
		expect(зібрати(УСІ).регістр).toEqual([
			'kateryna-muntian → Kateryna-Muntian',
			'nadiia-hasynets → Nadiia-Hasynets',
			'sofia-chernova → Sofia-Chernova'
		]);
	});

	it('аліас і перейменування не сперечаються за ту саму адресу', () => {
		// Двоє (`roman-arabadzhi`, `alla-brynza`) — саме перейменування: адресу
		// міняли. Якби вони потрапили ще й у виведення, редирект став би
		// подвійним записом реєстру з різними цілями.
		const обидва = Object.keys(GRADUATE_ALIASES).filter(
			(alias) => alias in RENAMED_GRADUATE_ADDRESSES
		);
		expect(обидва, 'адреса є і перейменуванням, і аліасом').toEqual([]);
	});

	it('слаг, не схожий на людину, має код або назване поле `aliases`', () => {
		const bad = УСІ.filter((g) => {
			if (g.code || (g.aliases?.length ?? 0) > 0) return false;
			if (ЧЕРЕЗ_ПЕРЕЙМЕНУВАННЯ.has(адреса(g))) return false;
			return несхожість(g.slug, g.name) > МЕЖА;
		}).map((g) => `${g.name}: slug «${g.slug}» — стандартна адреса нікуди не веде`);
		expect(
			bad,
			'особиста адреса без запасної. Дописати `aliases` у запис реєстру:\n  ' + bad.join('\n  ')
		).toEqual([]);
	});

	it('детектор живий: він упізнає особисті адреси, які вже названі', () => {
		// Без цього рядка перевірка вище зеленіла б і з поламаним детектором.
		expect(несхожість('al_bryn', 'Алла Бринза')).toBeGreaterThan(МЕЖА);
		expect(несхожість('reverenciel', 'Роман Арабаджі')).toBeGreaterThan(МЕЖА);
		// А різні написання того самого імені — не особисті адреси.
		expect(несхожість('anton-babich', 'Антон Бабич')).toBeLessThan(МЕЖА);
		expect(несхожість('yulia-bulhakova', 'Юля Булгакова')).toBeLessThan(МЕЖА);
	});
});

// @vitest-environment node
import { describe, expect, it } from 'vitest';
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, basename } from 'node:path';

/**
 * Сироти в `static/` — борг із числом, що лише скорочується
 * (PROJECT-STRUCTURE-v9, `PS-STATIC-ORPHANS`).
 *
 * `adapter-static` копіює вміст `static/` на хостинг МОВЧКИ й повністю: файл,
 * на який ніхто не посилається, однаково їде в збірку, лежить на сервері й
 * віддається за прямою адресою. Наслідки різні за вагою — від зайвих
 * мегабайтів у деплої до знімка, який автор вважав видаленим, а він
 * відкривається за вгаданою адресою. Ані `svelte-check`, ані бюджет бандла
 * цього не бачать: бюджет міряє JS, а тут картинки й документи.
 *
 * ## Дві тéки різної природи, і плутати їх не можна
 *
 * Частину `static/` код адресує ШАБЛОНОМ: `asset(\`/graduates/${slug}-96.webp\`)`,
 * `asset(\`/galaxy/update-${lang}.json\`)`. Імені файлу в джерелах немає й бути
 * не може — воно збирається з даних у рантаймі. Наївна перевірка «чи згадано
 * ім'я» оголошує такі теки сиротами цілком: тут це 409 світлин випускників із
 * 427 «знахідок» першого прогону. Гейт, який щоразу показує 409 хибних
 * спрацювань, вимикають того ж дня.
 *
 * Тому теки за шаблоном перелічені явно й із причиною. Це свідома сліпа зона,
 * а не випадкова: усередині такої теки сироту цей інваріант не побачить, і
 * ловить її інший — `galaxy-registry` та інваріанти реєстрів, які звіряють
 * `hasPhoto` з файлами на диску. Перевірка живості нижче стежить, щоб запис у
 * переліку не пережив свій шаблон.
 *
 * ## Чому борг переліком, а не числом
 *
 * Число сказало б «сиріт шістнадцять» і мовчало б про те, що одну прибрали, а другу
 * додали. Перелік називає кожну поіменно: нова сирота — червоне, зникла —
 * теж червоне (запис треба прибрати тим самим комітом). Це той самий храповик,
 * що й у стелях розміру в `structure.test.ts`.
 *
 * ## Зворотний експеримент (`PIT-REVERSE-EXPERIMENT`)
 *
 * У `static/documents/` покладено `ПІДСТАВНИЙ.txt`, на який не посилається
 * ніхто — перевірка назвала його. Прибрано рядок про `static/png/News1.png` —
 * перевірка назвала і його. Після відкоту обох — зелено.
 */

const КОРІНЬ = 'static';

/** Де шукати згадки: код, скрипти збірки, E2E і текстові файли самого `static/`. */
const СПОЖИВАЧІ = ['src', 'scripts', 'e2e', 'vitest'];

/**
 * Теки, які код адресує шаблоном. Ім'я файлу збирається з даних, тож шукати
 * його в джерелах немає сенсу. Значення — де саме будується шлях.
 */
const ТЕКИ_ЗА_ШАБЛОНОМ = new Map([
	['/graduates/', 'GraduateAvatarRow.svelte: asset(`/graduates/${slug}-96.webp`)'],
	['/miniIcon/svg/', 'MiniIconsEngine.ts: asset(`/miniIcon/svg/${file}`)'],
	['/galaxy/', 'GalaxyUpdateModal.svelte: asset(`/galaxy/update-${lang}.json`)']
]);

/**
 * Відомі сироти. Перелік ЛИШЕ СКОРОЧУЄТЬСЯ: файл або видаляють, або на нього
 * починають посилатися, і тоді рядок звідси йде тим самим комітом.
 *
 * Заміряно 2026-09-10, шістнадцять файлів. Жодна не є втратою даних — це
 * залишки чотирьох різних заходів, і рішення, видаляти чи використати, за
 * автором:
 */
const ВІДОМІ_СИРОТИ = new Set([
	// Растрова копія набору значків, зроблена до переходу на svg. Двигун
	// (`MiniIconsEngine.ts`) бере лише `/miniIcon/svg/`, і `/miniIcon/png/` не
	// згадується в джерелах жодного разу. Тека спершу стояла в переліку
	// «за шаблоном» — і перевірка нижче цю здогадку відкинула.
	...Array.from(
		{ length: 11 },
		(_, i) => `static/miniIcon/png/MTS-miniIcon-${String(i + 1).padStart(2, '0')}.png`
	),
	// Варіант логотипа з часів добору анімації часток; у макеті лишився інший.
	'static/logo/svg/t4_logo_IndividualParticles_MasksTwo_2026.svg',
	// Три знімки, завантажені разом із рештою галереї й не вставлені в жодну
	// сторінку; решта того ж заходу перелічена в `config/localImages.ts`.
	'static/photo/IMG_7270.jpg',
	'static/photo/IMG_7487.jpg',
	'static/photo/photo_16_2025-09-04_12-38-24.jpg',
	// Растр із першої версії блоку новин; новини давно беруть картинки з Firestore.
	'static/png/News1.png'
]);

const шлях = (p: string) => p.split('\\').join('/');

function обійти(dir: string, out: string[] = []): string[] {
	for (const entry of readdirSync(dir)) {
		const p = join(dir, entry);
		if (statSync(p).isDirectory()) обійти(p, out);
		else out.push(шлях(p));
	}
	return out;
}

const файлиStatic = обійти(КОРІНЬ);

/** Веб-адреса файлу: `static/fonts/x.woff2` → `/fonts/x.woff2`. */
const вебШлях = (f: string) => f.replace(/^static/, '');

const текстСпоживачів = (() => {
	let текст = '';
	for (const f of СПОЖИВАЧІ.flatMap((d) => обійти(d))) {
		if (!/\.(ts|js|mjs|svelte|json|css|html|txt|md)$/.test(f)) continue;
		// Файли перевірок споживачами НЕ рахуються, і перший же прогін показав,
		// чому це не формальність: перелік боргу нижче називає всі шляхи
		// ДОСЛІВНО, лежить у `src/` — і сам зробив їх усі «згаданими». Гейт
		// став зеленим від власного тексту. Той самий клас, що й у
		// `orphan-modules`: файл, на який посилається лише перевірка, з погляду
		// сайту не існує.
		if (/\.(test|spec)\.ts$/.test(f)) continue;
		текст += readFileSync(f, 'utf8') + '\n';
	}
	// Самі статичні текстові файли теж посилаються одне на одного: `llms.txt`,
	// `robots.txt`, маніфест, svg зі вкладеними `<use>`.
	for (const f of файлиStatic) {
		if (!/\.(txt|json|md|css|svg|webmanifest)$/.test(f)) continue;
		текст += readFileSync(f, 'utf8') + '\n';
	}
	return текст;
})();

function згадано(f: string): boolean {
	const база = basename(f);
	return (
		текстСпоживачів.includes(вебШлях(f)) ||
		текстСпоживачів.includes(база) ||
		текстСпоживачів.includes(база.replace(/\.[^.]+$/, ''))
	);
}

const сироти = файлиStatic
	.filter((f) => ![...ТЕКИ_ЗА_ШАБЛОНОМ.keys()].some((d) => вебШлях(f).startsWith(d)))
	.filter((f) => !згадано(f))
	.sort();

describe('сироти в static/ (PROJECT-STRUCTURE-v9, PS-STATIC-ORPHANS)', () => {
	it('перевірка жива: файли й згадки прочитано', () => {
		expect(файлиStatic.length, 'обхід static/ нічого не знайшов').toBeGreaterThan(1000);
		expect(текстСпоживачів.length, 'жодного споживача не прочитано').toBeGreaterThan(100_000);
		// Файл, згаданий у джерелах дослівно, мусить розпізнаватися — інакше
		// «сиротами» стане півсховища, і перелік боргу нічого не означатиме.
		expect(згадано('static/fonts/e-Ukraine-Regular.woff2'), 'шрифт із app.html не розпізнано').toBe(
			true
		);
	});

	it('кожна тека за шаблоном справді адресується шаблоном', () => {
		// Запис, який пережив свій шаблон, ховає цілу теку. Ознака — префікс
		// теки більше не зустрічається в жодному джерелі.
		const мертві = [...ТЕКИ_ЗА_ШАБЛОНОМ.keys()].filter((d) => !текстСпоживачів.includes(d));
		expect(
			мертві,
			`ці теки вилучені з перевірки, а шаблону, що їх будує, у джерелах немає:\n${мертві.join('\n')}`
		).toEqual([]);
	});

	it('нових сиріт немає', () => {
		const нові = сироти.filter((f) => !ВІДОМІ_СИРОТИ.has(f));
		expect(
			нові,
			'на ці файли не посилається ніхто, а adapter-static однаково скопіює ' +
				`їх на хостинг — видалити або підключити:\n${нові.join('\n')}`
		).toEqual([]);
	});

	it('перелік боргу не містить зайвого', () => {
		const зниклі = [...ВІДОМІ_СИРОТИ].filter((f) => !сироти.includes(f)).sort();
		expect(
			зниклі,
			'ці записи більше не сироти — прибрати з переліку тим самим комітом, ' +
				`інакше борг перестане скорочуватися:\n${зниклі.join('\n')}`
		).toEqual([]);
	});
});

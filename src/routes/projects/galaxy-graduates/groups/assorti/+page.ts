import { redirect } from '@sveltejs/kit';
import { resolve } from '$app/paths';
import type { PageLoad } from './$types';

/**
 * Стара адреса групи «Асорті» — курс мав ДВІ картки.
 *
 * В одній лежав склад і репертуар, у другій — знімки; автор попросив звести їх
 * у `asorti`. Адреса `assorti` встигла побувати в мапі сайту, тож просто зникнути
 * не може.
 *
 * ## Чому окрема сторінка, а не рядок у завантажувачі `[slug]`
 *
 * Спершу я зробив саме так — мапу `RENAMED_SLUGS` у `groups/[slug]/+page.ts`,
 * копіюючи прийом зі сторінок фестивалів. І ПЕРЕВІРИВ у справжньому браузері:
 * не працює. Стара адреса не пререндериться, статика віддає `404.html`, і той
 * файл — не порожня оболонка, а готова сторінка «404»: він гідратується як
 * помилка й маршрут заново не розвʼязує.
 *
 * Заміряно на обох: `/groups/assorti/` і `/festivals/slavianskyi-venok/` — обидві
 * лишаються на своїй адресі й показують «Сторінку не знайдено». Тобто прийом на
 * сторінках фестивалів не працює теж, а його докблок стверджує протилежне.
 *
 * Працює те, чим у проєкті вже зроблені `/fest-odesa-teatr-pro` та її двійник:
 * СПРАВЖНІЙ маршрут із `prerender`, у якому `redirect()` перетворюється
 * адаптером на сторінку з `meta http-equiv="refresh"`. Її статика віддає з
 * кодом 200, і браузер іде далі.
 *
 * Запис у `config/redirects.ts` обовʼязковий: без нього `generate-sitemap`
 * покладе цю заглушку в індекс як звичайну сторінку — з порожнім тілом.
 */
export const prerender = true;

export const load: PageLoad = () => {
	throw redirect(301, `${resolve('/projects/galaxy-graduates/groups/asorti')}/`);
};

import { castIdsOf, loadPlayCast } from '$lib/data/playCast';

/**
 * Перелік показів дістає склад ЗВІДСИ, а не імпортом.
 *
 * Зріз складу переїхав із бандла в `static/galaxy/play-cast.json` — розбір і
 * замір у докблоці `data/playCast.ts`; коротко: 7 КБ, які їхали до кожного
 * відвідувача сайту заради двох сторінок галактики. `load` бере його `fetch`ем,
 * тож на пререндері він лягає в готовий HTML, а мережею не їде взагалі.
 *
 * Сторінці досить КЛЮЧІВ людей: вона малює ряд облич і показує, скільки людей
 * назвали виставу своєю. Ролі й уривки потрібні лише на сторінці самого показу,
 * і туди вони й приходять — повним зрізом.
 */
export async function load({ fetch }) {
	return { castIds: castIdsOf(await loadPlayCast(fetch)) };
}

// @vitest-environment node
import { describe, expect, it } from 'vitest';
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync } from 'node:fs';

/**
 * Кінці рядків однакові в індексі й у робочому дереві (`PIT-EOL-GATE`, HIGH).
 *
 * ## Чому це гейт, а не просто файл `.gitattributes`
 *
 * `.gitattributes` у цьому репозиторії лежить із 27 серпня і сам по собі
 * пояснює ціну питання: два дефекти (`33d296f`, `d98e8ff`) коштували вечора
 * саме через CRLF. Але файл — це намір, а не стан. Правило `eol=lf` діє на
 * ЧЕКАУТ; уже наявні в дереві файли з CRLF воно не чіпає, і `core.autocrlf` у
 * чужому `~/.gitconfig` теж не скасовує. Тобто дерево може розійтися з
 * індексом при абсолютно правильному `.gitattributes`, і жодна червона лампа
 * не спалахне.
 *
 * `AI-AGENT-PITFALLS-v9` (`PIT-EOL-GATE`) саме про це й каже: перевіряється
 * розходження, а не наявність файлу. Тут таких перевірок дві, і друга —
 * головна.
 *
 * ## Чим це відрізняється від `csp-hash` і `ci`
 *
 * Обидва сусідні гейти ловлять НАСЛІДОК на своїй ділянці: перший — хеш
 * інлайн-скрипта, обчислений над CRLF, другий — розбір workflow, що бачить нуль
 * кроків. Цей ловить ПРИЧИНУ, і тому він один на весь репозиторій: гейтів, які
 * читають власні джерела текстом, тут більшість, і писати кожному свою
 * перевірку кінців рядків означало б стільки ж копій того самого.
 *
 * Найгірший прояв — не червоний тест. Регулярка з `$` без прапорця `m`
 * перестає збігатися через `\r`, гейт звітує «нічого не знайдено» і виглядає
 * зеленим. Тобто мовчазний нуль знахідок, тобто перевірка, якої фактично
 * немає.
 *
 * ## Зворотний експеримент (`PIT-REVERSE-EXPERIMENT`)
 *
 * `git update-index --cacheinfo` з файлом, що містить CRLF, або локальне
 * `git config core.autocrlf true` + `git checkout -- .` — перевірка мусить
 * назвати конкретні шляхи. Зроблено підстановкою рядка `i/crlf w/crlf ...` у
 * розбір: тест падає й перелічує файл. На чистому дереві — зелений.
 *
 * ## Чому `git ls-files --eol`, а не читання файлів із диска
 *
 * Читання з диска покаже лише робоче дерево. Розходження ж живе МІЖ деревом і
 * індексом: у CI (Linux) checkout дає LF, локально (Windows) — те, що
 * налаштоване, і саме ця пара визначає, чи гейти читають однаковий текст у
 * двох місцях. `--eol` — єдине джерело, яке показує обидві колонки одразу.
 */

/** Рядок виводу `git ls-files --eol`: `i/lf    w/lf    attr/…   	шлях`. */
type Запис = { index: string; worktree: string; path: string };

function прочитатиEol(): Запис[] {
	const вивід = execFileSync('git', ['ls-files', '--eol'], {
		encoding: 'utf8',
		maxBuffer: 32 * 1024 * 1024
	});
	const записи: Запис[] = [];
	for (const рядок of вивід.split('\n')) {
		// `i/<eol> w/<eol> attr/<атрибути><TAB><шлях>` — шлях відділений табуляцією,
		// і саме тому розбір не по пробілах: пробіли бувають і в назвах файлів, і
		// в самому полі атрибутів (`attr/text=auto eol=lf `).
		const m = /^i\/(\S+)\s+w\/(\S+)\s+attr\/[^\t]*\t(.+)$/.exec(рядок);
		if (m) записи.push({ index: m[1], worktree: m[2], path: m[3] });
	}
	return записи;
}

describe('кінці рядків (AI-AGENT-PITFALLS-v9, PIT-EOL-GATE)', () => {
	const записи = прочитатиEol();

	it('перевірка жива: `git ls-files --eol` прочитано і розібрано', () => {
		// Без цього тест нижче був би зелений на порожньому масиві — тобто саме
		// той мовчазний нуль, проти якого весь цей файл і стоїть.
		expect(записи.length, 'розбір виводу `git ls-files --eol` дав порожній перелік').toBeGreaterThan(
			500
		);
		expect(
			записи.some((з) => з.path === 'package.json'),
			'у розібраному переліку немає навіть package.json — формат виводу змінився'
		).toBe(true);
	});

	it('`.gitattributes` фіксує `text=auto eol=lf`', () => {
		expect(existsSync('.gitattributes'), 'немає .gitattributes').toBe(true);
		const текст = readFileSync('.gitattributes', 'utf8');
		expect(
			/^\*\s+text=auto\s+eol=lf\s*$/m.test(текст),
			'у .gitattributes немає рядка `* text=auto eol=lf`'
		).toBe(true);
	});

	it('в індексі немає CRLF', () => {
		const винні = записи.filter((з) => з.index === 'crlf' || з.index === 'mixed');
		expect(
			винні.map((з) => `${з.path} (i/${з.index})`),
			'файли лежать у репозиторії з CRLF — у CI гейти прочитають інший текст, ніж бачить автор'
		).toEqual([]);
	});

	it('робоче дерево не розійшлося з індексом', () => {
		// `-text` — двійкові, `none` — порожні: у них кінців рядків немає взагалі,
		// і порівнювати колонки нема з чим.
		const текстові = записи.filter((з) => з.index !== '-text' && з.index !== 'none');
		const розбіжні = текстові.filter((з) => з.worktree !== з.index && з.worktree !== 'none');
		expect(
			розбіжні.map((з) => `${з.path} (i/${з.index} w/${з.worktree})`),
			'робоче дерево й індекс мають різні кінці рядків: локальний прогін і CI ' +
				'читають РІЗНИЙ текст, і розбіжність показується як мовчазний нуль знахідок. ' +
				'Полагодити: `git add --renormalize .` або перечекаутити файли'
		).toEqual([]);
	});
});

// @vitest-environment node
import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';
import { ФАЙЛ_ПОКАЖЧИКА, зібратиПокажчик } from '../scripts/build-search-index';

/**
 * Покажчик пошуку по анкетах — файл, який легко застаріває мовчки.
 *
 * ## Чому це вартувало окремого гейта
 *
 * `static/search/profiles.json` збирається скриптом і лежить у репозиторії.
 * Тобто рівно той клас артефакту, який у цьому проєкті вже підводив: анкету
 * правлять руками, покажчик лишається старим, і пошук перестає знаходити те, що
 * в базі є. Помітити це оком не можна — пошук не каже «мій покажчик застарів»,
 * він просто показує на один рядок менше.
 *
 * Тому перевірка перебудовує покажчик У ПАМ'ЯТІ тим самим кодом, що й скрипт, і
 * порівнює з файлом. Розходження — червоний прогін і команда, якою лікується.
 *
 * ## Друга половина: прихованих у файлі бути не може
 *
 * Файл роздається статикою, тобто його можна відкрити прямо в браузері. Текст
 * людини з рівнем `direct` («таємний агент») у ньому означав би, що приховану
 * людину видає один запит — без пошуку, без переліків, без нічого.
 *
 * ## Зворотний експеримент (AI-AGENT-PITFALLS-v8 § 1.1)
 *
 * Дописати рядок у будь-яку анкету `static/graduates/profiles/*.json` і не
 * перезібрати покажчик — перевірка падає й називає ключ. Поставити комусь
 * `visibility: 'direct'` без перезбирання — падає та сама перевірка; перезібрати
 * — і людина зникає з файлу.
 */

const файл = () => readFileSync(ФАЙЛ_ПОКАЖЧИКА, 'utf8');

describe('покажчик пошуку по анкетах', () => {
	it('файл на місці й не порожній', () => {
		const покажчик = JSON.parse(файл()) as Record<string, string>;
		const ключів = Object.keys(покажчик).length;
		expect(ключів, 'покажчик порожній — пошук по анкетах мовчки нічого не знайде').toBeGreaterThan(
			200
		);
	});

	it('файл збігається з тим, що дають анкети зараз', () => {
		const очікуваний = зібратиПокажчик();
		const фактичний = JSON.parse(файл()) as Record<string, string>;

		const зайві = Object.keys(фактичний).filter((k) => !(k in очікуваний));
		const бракує = Object.keys(очікуваний).filter((k) => !(k in фактичний));
		const розійшлися = Object.keys(очікуваний).filter(
			(k) => k in фактичний && фактичний[k] !== очікуваний[k]
		);

		expect(
			{ зайві, бракує, розійшлися },
			'покажчик застарів — перезібрати: npm run build:search-index'
		).toEqual({ зайві: [], бракує: [], розійшлися: [] });
	});

	it('у покажчику немає жодного, кого приховали навмисно', () => {
		const покажчик = JSON.parse(файл()) as Record<string, string>;
		const люди = JSON.parse(readFileSync('src/lib/data/graduates.index.json', 'utf8')) as {
			slug: string;
			visibility?: string;
			kind?: string;
		}[];

		const приховані = люди
			.filter((g) => {
				const рівень = g.visibility ?? 'listed';
				if (рівень === 'listed') return false;
				// Учні — `linked`, але в пошуку вони є навмисно.
				return !(рівень === 'linked' && g.kind === 'student');
			})
			.map((g) => `person:${g.slug}`)
			.filter((ключ) => ключ in покажчик);

		expect(
			приховані,
			'текст прихованої людини лежить у файлі, який роздається статикою'
		).toEqual([]);
	});

	it('перевірка жива: приховані в реєстрі справді є', () => {
		// Без цього попередня перевірка була б зеленою й на реєстрі, де ховати
		// нікого — тобто нічого не стверджувала б.
		const люди = JSON.parse(readFileSync('src/lib/data/graduates.index.json', 'utf8')) as {
			visibility?: string;
		}[];
		const прихованих = люди.filter((g) => (g.visibility ?? 'listed') !== 'listed').length;
		expect(прихованих, 'у реєстрі немає прихованих — перевірка нічого не стереже').toBeGreaterThan(
			0
		);
	});

	it('те, що автор шукав, у покажчику є', () => {
		/*
		 * Три запити з шести, які 2026-09-05 давали нуль. Тут перевіряється не
		 * пошук (він у `utils/siteSearch.test.ts`), а те, що ТЕКСТ для нього
		 * зібраний: без цих рядків у файлі жодне ранжування не помогло б.
		 */
		const текст = файл();
		/*
		 * «отримує ляпаси», а не «ляпаса»: 2026-09-05 анкету виправили під
		 * реєстр вистав — там уривок Андреєва зветься «Той, хто отримує ляпаси»,
		 * і в анкеті стояло інше написання. Рядок тут оновлений разом із даними,
		 * бо він і є доказ, що покажчик бере СВІЖИЙ текст.
		 */
		for (const фрагмент of ['отримує ляпаси', 'Пекельна Хоругва', 'Риськіна']) {
			expect(текст.includes(фрагмент), `у покажчику немає «${фрагмент}»`).toBe(true);
		}
	});
});

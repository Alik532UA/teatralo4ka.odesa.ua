/**
 * Знімки героя головної: який файл для слота, який — для повного екрана.
 *
 * ## Навіщо два розміри, коли доти був один
 *
 * Заміряно 2026-09-10: герой тягнув 1107 КБ двома JPEG без жодного `srcset` —
 * 259 КБ (1280×804) і 848 КБ (4068×3070). Слот же має щонайбільше 544 CSS px
 * (заміряно в браузері на 1440 і 1920 — однаково 544; 500 на планшеті, 311 на
 * телефоні), тобто другий знімок приходив увосьмеро більшим, ніж є куди його
 * покласти. Та сама вага давала й другий дефект: baseline JPEG браузер малює
 * ЗГОРИ ВНИЗ, тож на екрані була смужка фото над суцільним блоком.
 *
 * Чому одного файлу не досить: клік по герою відкриває `PhotoLightbox`, і той
 * брав ТОЙ САМИЙ `src`. Тобто важкий знімок працював за двох, і «зменшити до
 * слота» зламало б перегляд на весь екран. Тепер роль кожного файлу названа.
 *
 * Стало: 26 + 32 = 58 КБ на завантаження сторінки (DPR 1) замість 1107, а
 * повний розмір — 299 і 120 КБ, і платить за них лише той, хто натиснув.
 *
 * ## Чому окремим файлом, а не в компоненті
 *
 * Спочатку все це стояло в `HeroSection.svelte` — і гейт розміру запропонував
 * вибір «розділити або підняти стелю». Поділ тут природний: перелік файлів із
 * ширинами це конфігурація, а не розкладка, і в проєкті для такого вже є
 * `config/` (`localImages`, `redirects`, `seoPages`). Компонент лишається про
 * слайдшоу й розкладку, а «який файл якої ширини» живе поруч із мапою
 * розмірів, з якої той самий базовий варіант і бере пропорцію.
 *
 * ## Кадрування немає
 *
 * Рішення автора, і воно зберігає нинішній вигляд точно: слот має
 * `aspect-ratio: 4 / 3` і `object-fit: cover`, тобто обрізає БРАУЗЕР і робить
 * це з повного кадру. Файли — просто зменшені повні кадри, тож видиме в слоті
 * не змінилося.
 *
 * Оригінали лежать у `design-source/hero/` і на хостинг більше не їдуть;
 * перегенерувати варіанти — `npx tsx scripts/convert-hero-photos.ts`.
 */

/**
 * `srcset` виписаний ДОСЛІВНО, а не складений із шаблону.
 *
 * Шаблон (`hero-${base}-${w}.webp`) був би коротшим і зробив би всі вісім
 * файлів невидимими для `static-orphans.test.ts`: той гейт шукає згадку імені,
 * а шаблон жодного імені не містить — тобто вісім знімків опинилися б у
 * переліку сиріт або, гірше, тихо поїхали б на хостинг без жодного власника.
 * Дослівний перелік лишає гейт правдивим і заразом показує, які ширини є.
 *
 * Ширини — із заміру слота: 320 (телефон DPR 1), 544 (десктоп DPR 1), 768
 * (телефон DPR 2 і десктоп DPR 1.5), 1088 (десктоп DPR 2). Ширшого немає, бо
 * слот не росте.
 */

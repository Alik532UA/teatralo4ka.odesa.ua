/**
 * `sizes` — із заміру слота, а не зі стелі.
 *
 * До 768 px розкладка мобільна: слот це вся ширина мінус 4rem відступів, але не
 * більше 500 px (заміряно: 311 на 375, 500 на 768). Вище — рівно 544 px.
 */
export const HERO_SIZES = '(max-width: 768px) min(100vw - 4rem, 500px), 544px';

/** Абсолютний `srcset`: кожен шлях крізь `asset()`, як і одиночний `src`. */
export function heroSrcset(набір: string): string {
	return набір
		.split(', ')
		.map((запис) => {
			const [шлях, дескриптор] = запис.split(' ');
			return `${asset(шлях)} ${дескриптор}`;
		})
		.join(', ');
}

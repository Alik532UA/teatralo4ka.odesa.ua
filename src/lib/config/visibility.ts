/**
 * Три рівні видимості людини на сайті — спільні для випускників і працівників.
 *
 * ## Звідки взялися саме три
 *
 * Автор 2026-09-02 описав види людей трьома рядками на кожного: «Хто» ·
 * «Відображаємо в переліку (галактика або сторінка дорослих): так/ні» ·
 * «Відображаємо, якщо є зв'язок (вистави, групи, фестивалі, анкети): так/ні».
 * Дві відповіді «так/ні» дають чотири комбінації, з яких одна безглузда — «у
 * переліку так, за зв'язком ні», — тож замість двох булевих одне поле з трьома
 * значеннями:
 *
 *   `listed` — усюди: у переліку, за зв'язками; сторінка індексується.
 *   `linked` — не в переліку, але скрізь, де на людину є зв'язок: у складі
 *              вистави, у групі, на фестивалі, в анкеті учня чи в потоці учнів
 *              майстра; сторінка жива, але з `noindex` і не в мапі сайту.
 *   `direct` — нікуди: зв'язки в даних збираються, але не показуються; сторінка
 *              жива лише за прямим посиланням («таємний агент»).
 *
 * ## Чому поле, а не обчислення
 *
 * Доти відповідь «чи показуємо» доводилося виводити з коду: у випускників
 * прапорець звався `hidden` і означав «нікуди», у працівників — `visible: false`
 * і означав «лише за зв'язками», а статус «ще навчається» ховали тим самим
 * `hidden`. Автор попросив, щоб при аналізі бази було видно, кого показуємо,
 * без читання логіки. Тому одне ім'я й одні значення в обох реєстрах; поля немає
 * — `listed`, бо переважна більшість записів саме такі, і розмічати їх словом
 * «так» означало б платити за це в кожному з півтисячі записів.
 *
 * Причина невидимості в полі не зберігається — вона в коміті, що поставив
 * рівень, або в DATA-QUESTIONS. Невідоме значення читається як `listed`, а не
 * як прихований рівень: описка в даних не має ховати людину мовчки, і її ловить
 * гейт `narrowed-fields.test.ts` ще на збірці.
 *
 * Модуль без залежностей і з відносними імпортами звідусіль: його читають і
 * SvelteKit, і `scripts/generate-sitemap.ts` через tsx, де аліасів немає.
 */
export const VISIBILITY_LEVELS = ['listed', 'linked', 'direct'] as const;
export type Visibility = (typeof VISIBILITY_LEVELS)[number];

/** Рівень запису; поля немає або воно невідоме — `listed`. */
export function visibilityOf(record: { visibility?: string }): Visibility {
	const value = record.visibility;
	return value && (VISIBILITY_LEVELS as readonly string[]).includes(value)
		? (value as Visibility)
		: 'listed';
}

/** У переліку: галактика й реєстр випускників, сторінка дорослих. */
export function isListed(record: { visibility?: string }): boolean {
	return visibilityOf(record) === 'listed';
}

/** Показуємо там, де є зв'язок: рівні `listed` і `linked`. */
export function isLinked(record: { visibility?: string }): boolean {
	return visibilityOf(record) !== 'direct';
}

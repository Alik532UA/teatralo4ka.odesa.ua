// Відносний імпорт, а не `$lib`: цей модуль читає ще й `scripts/generate-sitemap.ts`,
// який виконується в Node через tsx, де аліасів SvelteKit не існує. Так само
// зроблено в `redirects.ts` — і з тієї самої причини.
import { stripLocale } from '../i18n/routing';

/**
 * Службові сторінки: адреса працює завжди, але поза індексом.
 *
 * BETA-CHECKLIST-v8 § 4.1 і SEO-v8: політика адрес живе в ОДНОМУ модулі, а не
 * трьома окремими правками в layout, у мапі сайту й у `robots.txt`. Причина не в
 * елегантності — три правки розходяться. Рівно так у цьому проєкті шість
 * сторінок-заглушок лежали в `sitemap.xml` із порожнім `<body>`, доки їхній
 * перелік жив у тестах: тестовий шар знав про продакшн те, чого не знала збірка
 * (див. `redirects.ts`).
 *
 * Одне рішення тут дає всі чотири вимоги:
 *   • layout не малює `canonical` і `hreflang`, зате малює `noindex` (§ 4);
 *   • `generate-sitemap.ts` не кладе сторінку в мапу й перевіряє ПРОТИЛЕЖНЕ:
 *     що `noindex` є, а `canonical` немає (§ 5.5);
 *   • `e2e/pages.ts` не перевіряє її нарівні з публічними — інакше перевірка
 *     canonical падала б на сторінці, у якої його немає навмисно;
 *   • `robots.txt` тримає `Disallow` тим самим рядком, що й для адмінки.
 *
 * ЦЕ НЕ ТАЄМНИЦЯ, і краще сказати це тут, ніж повірити в протилежне. Сайт
 * статичний, репозиторій відкритий, довжина шляху не додає до захисту нічого.
 * Сторінка просто не потрапляє в пошук і в меню; посилання на неї дають руками
 * тому, хто погодився допомогти.
 */
export const HIDDEN_ROUTES = ['/beta-test-checklists'] as const;

export type HiddenRoute = (typeof HIDDEN_ROUTES)[number];

/**
 * Чи ця адреса — службова, з урахуванням мовного префікса.
 *
 * `/en/beta-test-checklists/` — та сама сторінка, що й `/beta-test-checklists/`,
 * і забути про це означало б віддати англійському дзеркалу `canonical`, якого в
 * українського немає. Хвостова коса риска знімається: `trailingSlash: 'always'`
 * дає її в адресі, а обхід `build/` — ні.
 */
export function isHiddenRoute(pathname: string): boolean {
	const bare = stripLocale(pathname).replace(/\/+$/, '') || '/';
	return (HIDDEN_ROUTES as readonly string[]).includes(bare);
}

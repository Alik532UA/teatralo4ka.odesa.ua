/**
 * Варіанти динамічного фону з ключами перекладу.
 *
 * Той самий перелік потрібен у двох місцях: у debug-випадайці, де фон вибирає
 * відвідувач, і в адмінці, де задають типове значення. Дві копії розійшлися б
 * при додаванні варіанта, і в одному з місць його просто забули б — так уже
 * сталося з режимами смуги прокрутки.
 *
 * `0` — це не окремий тип фону, а «немає»: динамічний фон вимкнено. Саме тому
 * вибір фону завжди зачіпає два поля стану, а не одне.
 */

export type BackgroundType = 0 | 1 | 2 | 3 | 4;

/**
 * Дійсні значення одним кортежем — для `z.literal` у схемі налаштувань.
 *
 * `z.number().min(0).max(4)` теж не пропустив би зайвого, але віддавав би тип
 * `number`, і кожне місце довелося б приводити вручну. Тут тип виходить рівно
 * `BackgroundType`.
 */
export const BACKGROUND_TYPE_IDS = [0, 1, 2, 3, 4] as const;

export const BACKGROUND_OPTIONS: { id: BackgroundType; key: string }[] = [
	{ id: 0, key: 'settings.bgNone' },
	{ id: 1, key: 'settings.bgParticles' },
	{ id: 2, key: 'settings.bgWaves' },
	{ id: 3, key: 'settings.bgShapes' },
	{ id: 4, key: 'settings.bgMiniIcon' }
];

/**
 * Новини, які живуть У КОДІ, а не в базі.
 *
 * ## Чому обидва джерела, а не одне
 *
 * Досі новини приходили ЛИШЕ з Firestore: `getArticles` для переліку,
 * `getArticleById` для сторінки, `prerender = false` на маршруті. Це добре для
 * того, що автор пише з адмінки, і погано для того, що належить репозиторію:
 * такий текст не переживає збірку в HTML, не має мета-тегів для прев'ю, не
 * потрапляє в пошук по сайту й не перевіряється жодним гейтом.
 *
 * Місце для другого джерела в архітектурі вже було: `pageMetadataSchema` має в
 * перерахунку `category` значення `'news'` — тобто markdown-новина в
 * `i18n/pages/` передбачалася з самого початку, просто нею ніхто не
 * скористався. Ця новина — перша, і саме вона це й перевіряє.
 *
 * ## Що звідки береться
 *
 *   текст, назва, дата, SEO ... `i18n/pages/{uk,en}/<slug>.md`, той самий
 *                               завантажувач і та сама схема, що в сторінок
 *   знімки ................... тут, бо frontmatter у цьому проєкті розбирається
 *                               власним парсером без масивів (`i18n/loader.ts`)
 *   адреса ................... `/news/<id>`, поряд із новинами з бази
 *
 * ## ЧОМУ `id` — НАЗВА З РОКОМ, А НЕ ДАТА
 *
 * Перша редакція мала `id: '2026-09-04'`, тобто адресу `/news/2026-09-04/`.
 * Автор попросив інакше: «треба slug не просто дата, а притомна назва та рік».
 * Це не смак — адреса новини це те, що люди пересилають одне одному, і з дати
 * не видно, про що вона. Тепер ключ читається як заголовок:
 * `/news/30-y-sezon-i-17-studentiv-2026/`, а потім — на прохання автора — на
 * `/news/2026-year-30th-season-18-students/`: транслітерація читалася гірше за
 * англійську, а число в адресі збрехало, щойно знайшовся вісімнадцятий
 * студент. Обидві старі адреси лишилися сторінками перенаправлення
 * (`config/newsAliases.ts`) — посилання вже роздавали в соцмережах.
 *
 * Рік у кінці — той самий порядок, що в реєстрі вистав (`posviata-2022`,
 * `novyi-rik-2014`): спершу про що, потім коли.
 *
 * А от ТЕКА ЗНІМКІВ лишилася датою (`static/news/2026-09-04/`), і це навмисно:
 * там файли складають, а не читають адресу, і дата — природний ключ
 * упорядкування. Зв'язок між нею й ключем новини задано тут явно, тож шукати
 * його ніде не треба.
 *
 * ## Чому перелік ЯВНИЙ, а не з імен файлів
 *
 * Та сама причина, що записана в `SEARCHABLE_PAGES`: відповідність не
 * механічна. `id` — це те, що стоїть в адресі й що читає людина, `slug` — ім'я
 * файлу поруч із двома десятками сторінок, і префікс `news-` там потрібен, щоб
 * новина не читалася як ще один розділ сайту. Виводити одне з іншого можна, але
 * тоді перше ж відхилення від правила стане невидимим.
 */
export interface CodeNewsItem {
	/** Сегмент адреси: `/news/<id>`. Дата, бо новину шукають саме за нею. */
	id: string;
	/** Ім'я файлу в `i18n/pages/{uk,en}` без розширення. */
	slug: string;
	/** `object-position` обкладинки в картці переліку й на головній. */
	coverPosition?: string;
	/**
	 * Медіа новини в порядку показу: знімки й записи одним переліком.
	 *
	 * Доти тут були `photos` і окреме `videoUrl` — тобто «друге відео» не мало
	 * куди подітися, а порядок «спершу запис, потім знімки» задати було нічим.
	 * Тепер порядок задає автор, а вид кожного елемента названий явно
	 * (`utils/articleMedia`, спільний із новинами з бази).
	 */
	media: readonly ArticleMediaItem[];
	/**
	 * Пропорція плиток НА СТОРІНЦІ. Немає — вертикальна.
	 *
	 * У переліку новин картка лишається вертикальною завжди: там пропорція
	 * належить сітці переліку, а не новині.
	 */
	mediaShape?: MediaShape;
	/** Стовпець плиток збоку від тексту (типово) або все одне за одним. */
	mediaLayout?: MediaLayout;
	/**
	 * `id` статті в базі, яку ця новина ЗАМІНЯЄ.
	 *
	 * Ставиться, коли новину перенесли з Firestore у код: перелік новин після
	 * цього не показує статтю з бази, навіть якщо її забули приховати в
	 * адмінці. Без цього поля одна новина стояла б у переліку двічі — і саме
	 * так і сталося б, бо порядок дій автора («опублікувати в коді, потім
	 * приховати в базі») лишає між кроками проміжок.
	 *
	 * Пишеться конвертером `scripts/news-from-firestore.ts` разом із самою
	 * новиною, тож руками про нього думати не треба.
	 */
	replacesArticleId?: string;
}

/**
 * Помічник знімків новини: шлях від кореня `static/` плюс власні розміри.
 *
 * Тека задається один раз (`зТеки`), бо в кожної новини вона своя й дорівнює
 * даті — а рядки знімків від того не довшають.
 *
 * Розміри справжні, а не спільні 1200×900, як у галереї «Про школу»: серед цих
 * знімків є і 1280×960, і 960×1280, і 187×554, тож одне число не могло б бути
 * правильним. Числа звіряються із заголовками файлів у
 * `src/lib/config/localImages.test.ts` — тобто заміна знімка валить прогін, а не
 * лишає неправильну пропорцію.
 */
function зТеки(тека: string) {
	return (
		файл: string,
		width: number,
		height: number,
		alt: string,
		position?: string
	): ArticleMediaItem => ({
		kind: 'photo',
		url: `/news/${тека}/${файл}`,
		alt,
		width,
		height,
		position
	});
}

/** Запис події: YouTube, Vimeo, Instagram або Facebook — розбирає `utils/videoEmbed`. */
function відео(url: string, alt: string): ArticleMediaItem {
	return { kind: 'video', url, alt };
}


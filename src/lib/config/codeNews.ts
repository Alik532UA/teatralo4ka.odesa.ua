/** Новина з коду за сегментом адреси, або `undefined` — тоді її шукають у базі. */
export function codeNewsById(id: string): CodeNewsItem | undefined {
	return CODE_NEWS.find((item) => item.id === id);
}

/**
 * Новини з коду у формі картки переліку — щоб `/news` показував обидва джерела.
 *
 * ## Чому чернетка НЕ повертається
 *
 * `status: 'draft'` у frontmatter — те саме, що `isPublished: false` у статті з
 * бази, і поводитися з ним треба так само: сторінка існує (автор має її
 * подивитися), а в переліку її немає. Перша новина в коді якийсь час саме так і
 * стояла — доки автор не надіслав текст.
 *
 * ## Чому дата з frontmatter, а не з файлової системи
 *
 * `date` у frontmatter — заявлена дата ПОДІЇ, і саме за нею новини стоять у
 * переліку. Час зміни файлу означав би «коли я цей текст правив», тобто нову
 * новину щоразу, коли виправили кому.
 */
export function codeNewsCards(lang: 'uk' | 'en'): ContentCardItem[] {
	const cards: ContentCardItem[] = [];
	for (const item of CODE_NEWS) {
		const meta = loadPageMetadata(lang, item.slug);
		if (!meta || meta.status !== 'published') continue;
		const дата = new Date(meta.date);
		cards.push({
			id: item.id,
			title: meta.title,
			date: дата.toLocaleDateString(lang === 'uk' ? 'uk-UA' : 'en-US', {
				day: 'numeric',
				month: 'short',
				year: 'numeric'
			}),
			/* Той самий помічник, що й для статей із бази: без нього картка
			   показувала сиру `news` великими літерами замість «Новина» —
			   заміряно на цій сторінці. */
			category: getCategoryLabel(meta.category, lang),
			excerpt: meta.excerpt ?? meta.seo.description,
			color: '',
			/* Перший знімок галереї — обкладинка картки: окремого поля для неї в
			   frontmatter немає, а вибирати з одинадцяти знімків «найкращий»
			   машина не вміє. */
			coverUrl: item.photos[0] ? asset(item.photos[0].src as `/${string}`) : '',
			/* Кадрування обкладинки — своє, а не те, що в мозаїці: там у плитки
			   інша пропорція. Розбір і замір — у полі `coverPosition`
			   `ContentCard`. */
			coverPosition: item.coverPosition
		});
	}
	return cards;
}

/** Дата новини з коду у вигляді, придатному для сортування разом із базою. */
export function codeNewsTime(lang: 'uk' | 'en', id: string): number {
	const item = codeNewsById(id);
	const meta = item ? loadPageMetadata(lang, item.slug) : null;
	return meta ? new Date(meta.date).getTime() : 0;
}

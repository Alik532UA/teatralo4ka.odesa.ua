// Відносний імпорт, як у `hiddenRoutes.ts` і `redirects.ts`: цей перелік читає
// ще й `e2e/pages.ts`, який виконується поза аліасами SvelteKit.
import { stripLocale } from '../i18n/routing';

/**
 * Адреси, що існують заради ПРЕВ'Ю: везуть мета-теги й одразу ведуть далі.
 *
 * ## Навіщо вони
 *
 * Посилання на оголошення й на анкету роздають руками, а `?update=open` /
 * `?form=open` власного підпису мати не можуть: query-рядок у мета-теги не
 * потрапляє (сторінка пререндериться в один файл, а краулер не виконує JS).
 * Власна адреса — єдиний спосіб дати такому посиланню власний опис.
 *
 * ## Чому вони НЕ перевіряються нарівні з рештою
 *
 * Причина та сама, що вже записана для заглушок у `e2e/pages.ts`: браузер іде
 * за перенаправленням, і далі всі перевірки — заголовки, canonical, дублікати
 * `data-testid`, axe, переповнення екрана — стосуються вже ІНШОЇ сторінки.
 *
 * Заміряно: без цього переліку повний прогін Playwright дав 11 падінь на двох
 * адресах — `csp`, `smoke` («не порожня» і canonical), `testid` (дублікати) і
 * `viewport-overflow`. Жодне з них не про ці сторінки: усі про галактику, куди
 * браузер уже переїхав.
 *
 * ## Чому окремий реєстр, а не `redirects.ts` чи `hiddenRoutes.ts`
 *
 * `redirects.ts` — заглушки на `meta refresh`, які `generate-sitemap` навмисно
 * НЕ кладе в мапу й у яких немає жодного мета-тега (заміряно: 122 байти). Тут
 * протилежне: мета-теги і є сенсом сторінки.
 *
 * `hiddenRoutes.ts` дав би `noindex` і виключення з мапи, але тим самим рядком
 * додає `Disallow` у `robots.txt` — а краулер прев'ю Telegram його поважає.
 * Тобто штатний інструмент для службових сторінок вимкнув би саме те, заради
 * чого ці адреси й створені.
 *
 * ## Чому перелік в застосунку, а не в тестах
 *
 * Той самий урок, що записаний у `redirects.ts`: доки перелік заглушок жив у
 * тестах, збірка про нього не знала, і `generate-sitemap` клав усі шість у мапу
 * сайту з порожнім `<body>`. Тестовий шар не має знати про продакшн те, чого не
 * знає продакшн.
 */
export const PREVIEW_HOPS = [
	'/projects/galaxy-graduates/update',
	'/projects/galaxy-graduates/form'
] as const;

/** Чи це адреса-прев'ю. Приймає шлях із мовним префіксом або без, із рискою або без. */
export function isPreviewHop(pathname: string): boolean {
	const bare = stripLocale(pathname);
	const normalized = bare !== '/' ? bare.replace(/\/+$/, '') : bare;
	return (PREVIEW_HOPS as readonly string[]).includes(normalized);
}

/**
 * Стелі для запитів до Firestore — в одному місці й поіменно.
 *
 * CLOUD-DATABASE-v8 § 7.1 (`CDB-QUERY-LIMIT`, HIGH): кожен запит колекції має
 * `limit()`. Причина не в швидкості, а в рахунку: Firestore тарифікує КОЖЕН
 * прочитаний документ, тож ціна запиту без межі росте лінійно з наповненням
 * бази й помножена на розмір документа. Ані типи, ані тести, ані ручна
 * перевірка на десятку статей цього не показують — перший сигнал приходить
 * рахунком або повільною сторінкою в живих відвідувачів.
 *
 * Чому окремий модуль, а не число на місці виклику. Стеля — це рішення про
 * поведінку продукту («більше цієї кількості новин у списку не буде»), і його
 * треба бачити цілим. Розкидані по восьми файлах числа розходяться: два роки
 * тому саме так у сусідньому проєкті два списки того самого вмісту показували
 * різну кількість, і причину шукали в правилах доступу.
 *
 * Числа обрані з запасом до реального наповнення (на 2026-08 у базі десятки
 * статей), але скінченні: досягнення стелі означає «список обрізано», а не
 * «сайт зламався». Кожне число — окрема константа, щоб зміна однієї стелі не
 * чіпала решту.
 *
 * Інваріант `src/firestore-queries.test.ts` тримає правило: `query(` над
 * колекцією без `limit(` у джерелах — падіння.
 */


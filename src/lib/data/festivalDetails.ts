/**
 * Подробиці фестивалю — те, що показує ЛИШЕ його власна сторінка.
 *
 * ## ЧОМУ `fetch` ІЗ `static/`, А НЕ ПОЛЯ РЕЄСТРУ — і що це коштувало
 *
 * Доти ці п'ять полів лежали в `festivals.data.json` і приходили звичайним
 * імпортом, тобто ЇХАЛИ В КЛІЄНТСЬКИЙ БАНДЛ — до кожного відвідувача сайту,
 * включно з тими, хто жодної сторінки фестивалю не відкриє.
 *
 * Заміряно 16 вересня 2026, коли деплой упав на `check-bundle-budget`: усі дані
 * бандла важили 84 КБ brotli при стелі 82. Поштучно:
 *
 *   plays 34.37 · graduates 15.99 · festivals 10.20 · masters 9.93 ·
 *   groups 7.79 · institutions 3.83 · theatres 1.52
 *
 * Реєстр фестивалів виріс із 7.03 до 10.20 КБ за один коміт даних — склади й
 * матеріали 2020–2021. Усередині нього самі поля важили так:
 *
 *   bio 4.45 · memberIds 2.17 · playIds 0.54 · outsideMembers 0.52 ·
 *   masterIds 0.37 · nameEn 0.34 · name 0.34 · slug 0.30 · photos 0.30 …
 *
 * Тобто 44 % реєстру — це `bio`, проза, яку читають на одній сторінці.
 *
 * ## ЧОМУ САМЕ ЦІ П'ЯТЬ ПОЛІВ
 *
 * Не «найбільші», а ті, чий ЄДИНИЙ споживач — сторінка фестивалю; перевірено
 * пошуком по `src/`. `videoUrl` лишився в реєстрі саме тому, що його читає ще
 * й `GalaxyPlaysTiles.svelte`, хоч він і невеликий: критерій тут не розмір, а
 * хто дивиться.
 *
 * Пошук галактики (`matchesFestivalQuery`) жодного з цих полів не читає, тож
 * винос не змінює ані момент готовності пошуку, ані його результати — саме
 * цього боялися, відмовляючись виносити `theatres` та `institutions` у
 * докблоці `DATA_CEILING_KB`.
 *
 * Після виносу: реєстр 10.01 → 4.70 КБ, сума даних бандла 83.62 → 78.26 КБ при
 * стелі 82.
 *
 * ## ЧОМУ НЕ ЧЕРГОВЕ ПІДНЯТТЯ СТЕЛІ
 *
 * Бо `check-bundle-budget.ts` записав це наперед, піднімаючи 80 → 82:
 * «Запас 2 КБ — рівно на те, щоб цей коміт був зелений, і не більше. Наступне
 * поповнення даних його вичерпає, і тоді вибору вже не буде: доведеться робити
 * саме винос, а не чергове підняття.» Наступне поповнення сталося наступним же
 * комітом даних.
 *
 * Зразок виносу — `playCast.ts`: той самий `fetch` із `load`, той самий кеш на
 * сеанс, та сама причина.
 *
 * ## ДЕ ЦЕ РЕДАГУЮТЬ
 *
 * У `static/galaxy/festival-details.json`, ключем є `slug` фестивалю. Це
 * ДЖЕРЕЛО, а не зріз: на відміну від `play-cast.json`, який рахується з анкет,
 * тут дані авторські й нізвідки не виводяться. Тому за розходженням ключів із
 * реєстром стежить гейт `festival-details.test.ts` — інакше подробиці тихо
 * осиротіли б при перейменуванні адреси.
 */

/**
 * Учасник, для якого в реєстрах картки немає, — запис цілком.
 *
 * Спершу поле називалося «з інших шкіл», і це було НЕПРАВДОЮ про половину
 * випадків: у списках «Одеса.Театр.PRO» частина учасників поза реєстром
 * підписана «Одеса, ДТШ», тобто наші.
 *
 * ПОТІМ ВИЯВИЛОСЯ, ЩО ПОЛОВИНА «НАШИХ БЕЗ КАРТКИ» КАРТКУ МАЛА. Звірка з
 * реєстром за прізвищем знайшла чотирьох, яких я до того розводив руками й
 * не впізнав через написання імені: Сиванич/Сіванич, Крістіна/Христина,
 * Даніїл/Данило, Дар'я/Дар'я з різними апострофами. Кожного підтвердив сам
 * буклет — названий у програмці педагог збігся з майстром курсу в анкеті
 * (Риськіна, Імас, Ткач, Шевчук). Тобто помилка була не в даних, а в тому,
 * що збіг шукали очима.
 *
 * Тому ознака тут не «чий», а «ЧИ Є КОМУ ПОКАЗАТИ КАРТКУ», і саме тому людина
 * з Херсона чи з театру «Лімпопо» спокійно лежить у `memberIds`: перелік каже
 * не «вона з нашої школи», а «в неї є сторінка». Зворотне так само в силі —
 * заводити людину в реєстр випускників заради рядка у фестивалі не можна:
 * реєстр стверджує, що вона в нас училася, а програмка цього не доводить.
 * Питання стоїть у `DATA-QUESTIONS.md`.
 *
 * Зараз без картки лишилося 17 записів на три випуски, і ЖОДЕН із них у
 * програмці не підписаний ДТШ.
 *
 * Поля рівно ті, які справді розрізняють людей у списку: звідки приїхав і від
 * якого закладу. Ім'я педагога, що підготував, тут НЕ зберігається — для наших
 * цей зв'язок живе в їхніх анкетах, а заводити його лише для решти означало б
 * мати дві різні відповіді на одне питання.
 */
export interface OutsideMember {
	name: string;
	/** Місто або село, як у програмці: «Херсон», «с. Усатове, Одеська обл.». */
	city?: string;
	/** Заклад чи театральний колектив: «ДМШ №1», «театр «Лімпопо»». */
	school?: string;
}

export interface FestivalDetail {
	/** Опис поїздки абзацами — найважче поле реєстру, 44 % його ваги. */
	bio?: string[];
	/**
	 * Учасники БЕЗ КАРТКИ — ті, кого немає в реєстрі випускників.
	 *
	 * «Одеса.Театр.PRO» — фестиваль абітурієнтів з усієї країни, тож частина
	 * учасників чужа за визначенням. Але не вся: розбір — у докблоці
	 * `OutsideMember` вище. Розділ показує рядки з містом і закладом, бо ні
	 * фотографії, ні сторінки в цих людей немає.
	 */
	outsideMembers?: OutsideMember[];
	photos?: string[];
	/**
	 * Дипломи й грамоти — ОКРЕМИМ полем, а не наприкінці `photos`.
	 *
	 * Прохання автора дослівне: «думаю основні зображення та дипломи мають бути
	 * в різних блоках». Причина за ним змістовна, а не про розкладку: знімок
	 * поїздки й скан аркуша — різні речі за призначенням. На перший дивляться
	 * (хто поїхав, як виступали), другий читають (кому, за що, від кого).
	 * Зведені в одну стопку, вони перемішуються: гортаючи фотографії, людина
	 * несподівано впирається в документ, а шукаючи документ — гортає крізь
	 * фотографії.
	 *
	 * Наслідок для файлів теж є, і він у `localImages`: аркуші конвертуються з
	 * вищою межею, бо їхній дрібний текст при банерних 720 px зникає.
	 */
	diplomas?: string[];
	/**
	 * СКАНИ ПРОГРАМКИ — третє поле для зображень, і теж не заради симетрії.
	 *
	 * Буклет не фотографія і не диплом. Дивитися на нього нема на що: це
	 * розворот зі списком учасників, їхніми педагогами й складом Експертної
	 * Ради — аркуш, який ЧИТАЮТЬ. У `photos` він перемішався б із поїздковими
	 * знімками, тобто відтворив би рівно ту біду, заради якої вище відділені
	 * дипломи.
	 *
	 * Але й дипломом він не є: розділ зветься «Дипломи», а програмка нікого не
	 * нагороджує — підпис сказав би неправду про те, що людина зараз відкриє.
	 *
	 * Практичний наслідок той самий, що в дипломів, і він у конвертації: межа
	 * висока (1800 px по ширині проти банерних 1280), бо на розвороті А4 два
	 * стовпці імен дрібним шрифтом. Заміряно на буклеті 2018: 4110×2835 →
	 * 1800×1242, 3.4 МБ → 251 КБ, імена читаються; при банерних 1280×720 той
	 * самий аркуш стискається до 1045×720 і не читається.
	 *
	 * Ці розвороти — ще й ПЕРШОДЖЕРЕЛО половини даних сторінки: склади 2018 і
	 * 2026 знято саме з них. Тому вони тут не ілюстрація, а те, за чим читач
	 * може перевірити список власними очима.
	 */
	booklets?: string[];
	/**
	 * Відеозаписи фестивалю (зум-консультації, трансляції, круглі столи).
	 *
	 * Коли записів кілька, вони винесені сюди з назвами, щоб не перевантажувати
	 * реєстр `festivals.data.json` і показувати повноцінний перелік на сторінці.
	 */
	videos?: FestivalVideo[];
}

export interface FestivalVideo {
	url: string;
	title?: string;
}

export type FestivalDetails = Record<string, FestivalDetail>;

/** Адреса зрізу в `static/`. Одна на проєкт — щоб не розійшлася з гейтом. */
export const FESTIVAL_DETAILS_URL = '/galaxy/festival-details.json';

/**
 * Кеш на сеанс сторінки.
 *
 * Кешується САМА ОБІЦЯНКА, а не результат: два `load` можуть початися
 * одночасно (перехід і попереднє завантаження посилання), і на результаті вони
 * зробили б два запити. Те саме рішення, з тієї самої причини, що в `playCast`.
 */
let кеш: Promise<FestivalDetails> | null = null;

/**
 * Подробиці — з `static/`, через `fetch` із `load`.
 *
 * Помилка мережі не валить сторінку: фестиваль без опису — це те саме, що
 * фестиваль, опису якого ми ще не написали, і сторінка вже вміє це показати
 * (усі поля необов'язкові). Валитися тут означало б віддати 500 замість
 * сторінки зі списком учасників.
 */
export async function loadFestivalDetails(fetchFn: typeof fetch): Promise<FestivalDetails> {
	кеш ??= fetchFn(FESTIVAL_DETAILS_URL)
		.then((response) => (response.ok ? (response.json() as Promise<FestivalDetails>) : {}))
		.catch(() => ({}) as FestivalDetails);
	return кеш;
}

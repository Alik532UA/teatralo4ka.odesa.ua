/**
 * Учасник, для якого в реєстрах картки немає, — запис цілком.
 *
 * Спершу поле називалося «з інших шкіл», і це було НЕПРАВДОЮ про половину
 * випадків: у списках «Одеса.Театр.PRO» частина учасників поза реєстром
 * підписана «Одеса, ДТШ», тобто наші.
 *
 * ПОТІМ ВИЯВИЛОСЯ, ЩО ПОЛОВИНА «НАШИХ БЕЗ КАРТКИ» КАРТКУ МАЛА. Звірка з
 * реєстром за прізвищем знайшла чотирьох, яких я до того розводив руками й
 * не впізнав через написання імені: Сиванич/Сіванич, Крістіна/Христина,
 * Даніїл/Данило, Дар'я/Дар'я з різними апострофами. Кожного підтвердив сам
 * буклет — названий у програмці педагог збігся з майстром курсу в анкеті
 * (Риськіна, Імас, Ткач, Шевчук). Тобто помилка була не в даних, а в тому,
 * що збіг шукали очима.
 *
 * Тому ознака тут не «чий», а «ЧИ Є КОМУ ПОКАЗАТИ КАРТКУ», і саме тому людина
 * з Херсона чи з театру «Лімпопо» спокійно лежить у `memberIds`: перелік каже
 * не «вона з нашої школи», а «в неї є сторінка». Зворотне так само в силі —
 * заводити людину в реєстр випускників заради рядка у фестивалі не можна:
 * реєстр стверджує, що вона в нас училася, а програмка цього не доводить.
 * Питання стоїть у `DATA-QUESTIONS.md`.
 *
 * Зараз без картки лишилося 17 записів на три випуски, і ЖОДЕН із них у
 * програмці не підписаний ДТШ.
 *
 * Поля рівно ті, які справді розрізняють людей у списку: звідки приїхав і від
 * якого закладу. Ім'я педагога, що підготував, тут НЕ зберігається — для наших
 * цей зв'язок живе в їхніх анкетах, а заводити його лише для решти означало б
 * мати дві різні відповіді на одне питання.
 */
export interface OutsideMember {
	name: string;
	/** Місто або село, як у програмці: «Херсон», «с. Усатове, Одеська обл.». */
	city?: string;
	/** Заклад чи театральний колектив: «ДМШ №1», «театр «Лімпопо»». */
	school?: string;
}

export interface Festival {
	slug: string;
	name: string;
	nameEn?: string;
	verificationStatus?: VerificationStatusProp;
	/**
	 * Роки участі — СПИСОК, хоча зазвичай у ньому один рік.
	 *
	 * Кожна поїздка — окремий запис, і це рішення з даних: «Мрій-Дім» їздили
	 * 2012-го і 2013-го РІЗНИМ складом. Спершу тут стояв один запис на два роки —
	 * так це записано в анкеті, — але тоді сторінка звела б у купу дві різні
	 * групи людей і сказала б неправду про обидві.
	 *
	 * Список лишається на випадок, коли поїздка справді одна, а тривала два роки
	 * поспіль тим самим складом. Назва тоді не розрізняє записи, тож пару
	 * «назва + рік» стереже гейт.
	 */
	years: number[];
	/**
	 * Країни кодами ISO 3166-1 alpha-2, а не назвами.
	 *
	 * Назва країни залежить від мови сторінки, а код — ні. За тим самим кодом
	 * малює прапор `CountryFlag` — інлайновим SVG, бо в системних шрифтах
	 * Windows прапорців немає й емодзі 🇺🇦 показувалося б як «UA».
	 */
	countries: string[];
	/** Місто, коли воно й є місцем: «Прилуки». Немає поля — вистачає країни. */
	city?: string;
	/**
	 * Коротка примітка про сам захід: «Онлайн».
	 *
	 * НЕ місто, хоча стоїть поруч із ним. Чотири випуски Театр.PRO 2022–2025
	 * пройшли онлайн, і записати це містом означало б сказати, що така місцина
	 * є: плашка виглядала б так само, як «Одеса», а `city` у цьому реєстрі
	 * скрізь означає «де саме це відбувалося». Онлайн — це відповідь на інше
	 * питання, тому й поле інше, а місто в таких записів просто порожнє.
	 */
	note?: string;
	/** Хто з випускників їздив — за СТІЙКИМ ключем, як і склад групи. */
	memberIds: string[];
	/**
	 * УЧАСНИКИ З РЕЄСТРУ ПРАЦІВНИКІВ — ті, хто поїхав виступати, а не вести.
	 *
	 * Третій перелік з'явився 2026-09-08 і не заради симетрії. Автор попросив
	 * показати Анастасію Ніколаєву серед учасників Art Like Fest, «але не треба
	 * перероблювати профіль в учня чи в випускника». Тобто питання не в тому, у
	 * якому вона реєстрі, а в тому, ЩО ВОНА РОБИЛА на поїздці.
	 *
	 * Доти модель відповідала на це реєстром: `memberIds` — випускники, отже
	 * учасники; `masterIds` — працівники, отже викладачі. Збіг тримався, поки не
	 * трапився перший працівник-учасник, і тоді довелося б або переписувати
	 * людину в чужий реєстр, або підписувати її не тим, ким вона була.
	 *
	 * Тому реєстр і роль тепер розділені: два перших переліки — це РОЗДІЛ
	 * СТОРІНКИ («учасники»), третій — теж учасники, просто їхні картки
	 * розгортаються з іншого реєстру. Окремим полем, а не мішаними ключами в
	 * `memberIds`: слаг може збігтися в обох реєстрах у РІЗНИХ людей — саме для
	 * цього випадку в проєкті живе `dual-role.test.ts`, — і пошук «спершу тут,
	 * потім там» одного дня мовчки взяв би не ту людину.
	 */
	memberMasterIds?: string[];
	/**
	 * Хто з працівників школи ВІВ поїздку — за `id` реєстру майстрів.
	 *
	 * Тільки ключі: ім'я живе в самому реєстрі, і копія тут розійшлася б із ним
	 * при першому ж виправленні. Так само вже зроблено на ребрах випускників.
	 */
	masterIds: string[];
	/**
	 * ВИПУСКНИКИ, які приїхали на фестиваль уже випускниками.
	 *
	 * Окремо від `memberIds`, і це поділ самого автора: у списках «Одеса.Театр.PRO»
	 * він розводить «Учні ДТШ», «Випускники ДТШ» і «Не ДТШ». Різниця змістовна —
	 * учень приїхав від школи, випускник приїхав сам, уже студентом або актором.
	 *
	 * Реєстр той самий, що в `memberIds`: різниця не в тому, де лежить картка, а
	 * в тому, ким людина була НА ЦЬОМУ фестивалі. Тому й поле фестивалю, а не
	 * ознака в реєстрі: 2021-го та сама людина могла бути ученицею, а 2026-го —
	 * випускницею.
	 *
	 * Немає поля — немає й розділу: решта 27 фестивалів такого поділу не мають, і
	 * вигадувати його для них нічим.
	 */
	alumniIds?: string[];
	/**
	 * Учасники БЕЗ КАРТКИ — ті, кого немає в реєстрі випускників.
	 *
	 * «Одеса.Театр.PRO» — фестиваль абітурієнтів з усієї країни, тож частина
	 * учасників чужа за визначенням. Але не вся: розбір — у докблоці
	 * `OutsideMember` вище. Розділ показує рядки з містом і закладом, бо ні
	 * фотографії, ні сторінки в цих людей немає.
	 */
	outsideMembers?: OutsideMember[];
	/**
	 * ЕКСПЕРТНА РАДА — запрошені фахівці, які дивилися покази.
	 *
	 * Два переліки на одну роль із тієї самої причини, що в учасників: більшість
	 * експертів зовнішні (`data/experts`), але в Раді 2018 сидів Олег Шевчук —
	 * наш колишній педагог, і його картка мусить розгортатися з реєстру
	 * працівників, а не дублюватися серед зовнішніх.
	 */
	expertIds?: string[];
	expertMasterIds?: string[];
	/** Коучі фестивалю — ті, хто ВІВ заняття, а не оцінював. Реєстр той самий. */
	coachIds?: string[];
	/**
	 * ПОЧЕСНІ ГОСТІ.
	 *
	 * У програмці 2021 Лєна Лягушонкова названа «спеціальною гостею» — це та сама
	 * роль: людина приїхала не оцінювати й не вчити, а бути присутньою.
	 */
	guestIds?: string[];
	/** Вистави, показані на фестивалі, — посилання на реєстр, а не копії назв. */
	playIds: string[];
	bio?: string[];
	photos?: string[];
	/**
	 * Дипломи й грамоти — ОКРЕМИМ полем, а не наприкінці `photos`.
	 *
	 * Прохання автора дослівне: «думаю основні зображення та дипломи мають бути
	 * в різних блоках». Причина за ним змістовна, а не про розкладку: знімок
	 * поїздки й скан аркуша — різні речі за призначенням. На перший дивляться
	 * (хто поїхав, як виступали), другий читають (кому, за що, від кого).
	 * Зведені в одну стопку, вони перемішуються: гортаючи фотографії, людина
	 * несподівано впирається в документ, а шукаючи документ — гортає крізь
	 * фотографії.
	 *
	 * Наслідок для файлів теж є, і він у `localImages`: аркуші конвертуються з
	 * вищою межею, бо їхній дрібний текст при банерних 720 px зникає.
	 */
	diplomas?: string[];
	/**
	 * СКАНИ ПРОГРАМКИ — третє поле для зображень, і теж не заради симетрії.
	 *
	 * Буклет не фотографія і не диплом. Дивитися на нього нема на що: це
	 * розворот зі списком учасників, їхніми педагогами й складом Експертної
	 * Ради — аркуш, який ЧИТАЮТЬ. У `photos` він перемішався б із поїздковими
	 * знімками, тобто відтворив би рівно ту біду, заради якої вище відділені
	 * дипломи.
	 *
	 * Але й дипломом він не є: розділ зветься «Дипломи», а програмка нікого не
	 * нагороджує — підпис сказав би неправду про те, що людина зараз відкриє.
	 *
	 * Практичний наслідок той самий, що в дипломів, і він у конвертації: межа
	 * висока (1800 px по ширині проти банерних 1280), бо на розвороті А4 два
	 * стовпці імен дрібним шрифтом. Заміряно на буклеті 2018: 4110×2835 →
	 * 1800×1242, 3.4 МБ → 251 КБ, імена читаються; при банерних 1280×720 той
	 * самий аркуш стискається до 1045×720 і не читається.
	 *
	 * Ці розвороти — ще й ПЕРШОДЖЕРЕЛО половини даних сторінки: склади 2018 і
	 * 2026 знято саме з них. Тому вони тут не ілюстрація, а те, за чим читач
	 * може перевірити список власними очима.
	 */
	booklets?: string[];
	/**
	 * Запис САМОЇ ПОЇЗДКИ — не вистави, яку на ній показали.
	 *
	 * Доти записи жили лише на виставах, і на сторінці фестивалю кнопка
	 * «Дивитися запис» стояла в розділі «Показані вистави» — тобто внизу й про
	 * інше. Автор попросив рівно це: «відео може відноситися і до "Показані
	 * вистави", і до самого фестивалю як такого, але за замовчуванням робити
	 * відношення відео до фестивалю».
	 *
	 * Тому поле тут, а не на виставі, і кнопка стоїть біля назви. Обидва місця
	 * лишаються можливими: у вистави своє `videoUrl`, і якщо запис справді про
	 * показ, він живе там. Але коли автор надсилає посилання РАЗОМ із поїздкою —
	 * як із «Зимовою казкою» й «Дружбою-2008», — воно поїздки й стосується.
	 */
	videoUrl?: string;
}

/*
 * Реєстр у JSON, а не масивом у коді, — з тієї самої причини, що й групи: він
 * росте з кожним фестивалем, а `structure.test.ts` рахує рядки коду, не даних.
 *
 * `satisfies`, а не приведення: форму звіряє компілятор на збірці й нічого не
 * важить у бандлі. Цілісність — що кожен `memberId` існує, що `playId`
 * знаходиться, що код країни справжній — тримає `festivals.test.ts`.
 */
export const FESTIVALS: readonly Festival[] = festivalsData satisfies readonly Festival[];

/**
 * Країни, від яких на сторінці лишається ЛИШЕ ПРАПОР, без назви.
 *
 * Рішення автора, і воно точне: «країну не писати, хоча нехай в пошуку
 * шукається». Дві половини цього прохання тягнуть у різні боки, бо назва
 * країни живе в одному місці — `galaxy.country.<КОД>` — і звідти її бере і
 * розмітка, і пошук (`matchesFestivalQuery` нижче). Прибрати назву зі словника
 * означало б прибрати її й з пошуку; лишити в розмітці означало б написати те,
 * чого писати не просили.
 *
 * Тому розділено не джерело, а ВЖИВАННЯ: назва лишається в словнику й далі
 * шукається, а сторінка для цих кодів її не малює. Прапор при цьому свій —
 * біло-синьо-білий, а не триколор (див. `CountryFlag.svelte`).
 *
 * Перелік, а не прапорець на записі фестивалю: правило стосується КРАЇНИ, а не
 * поїздки, і другий фестиваль там само не мусив би повторювати рішення.
 */
/**
 * Власний фестиваль школи — і всі його випуски.
 *
 * Театр.PRO відрізняється від решти реєстру тим, що школа на нього не ЇЗДИТЬ,
 * а ПРОВОДИТЬ його. Через це в нього є ще й загальна сторінка
 * (`/projects/teatr-pro`), якій потрібен перелік самих лише його випусків, а
 * не весь реєстр поїздок.
 *
 * Відбір за назвою, а не окремим полем у даних: назва в усіх випусків одна й
 * та сама за визначенням — саме пара «назва + рік» і розрізняє записи
 * (див. гейт «назва разом із роком не трапляється двічі»). Зайве поле довелося
 * б проставляти руками кожному новому випуску, і забути його було б нічим не
 * помітно.
 *
 * Порожній перелік тут означав би, що назву в даних перейменували, а це
 * прибрало б список зі сторінки мовчки — тому непорожність стереже гейт.
 *
 * ## Чому 2026-й — «ІV-й», хоча випусків вісім
 *
 * Нумерація рахує лише ОФЛАЙНОВІ: 2018, 2019, 2021 і 2026. Онлайнові
 * 2022–2025 (ті, що з приміткою) повноцінними фестивалями не були — це
 * відповідь автора на пряме питання, і записана вона тут, щоб наступного разу
 * розбіжність «вісім записів, а номер четвертий» не виправляли як помилку.
 */
export const TEATR_PRO_NAME = 'Театр.PRO';

/** Випуски Театр.PRO, найновіші згори. */
export const TEATR_PRO_FESTIVALS: readonly Festival[] = FESTIVALS.filter(
	(f) => f.name === TEATR_PRO_NAME
).sort((a, b) => Math.max(...b.years) - Math.max(...a.years));

export const FLAG_ONLY_COUNTRIES: readonly string[] = ['RU'];

/** Чи показувати назву країни поруч із прапором. */
export function showsCountryName(code: string): boolean {
	return !FLAG_ONLY_COUNTRIES.includes(code.toUpperCase());
}

/** Фестиваль за адресою. */
export function getFestivalBySlug(slug: string): Festival | undefined {
	return FESTIVALS.find((f) => f.slug === slug);
}

/**
 * Фестивалі, на яких був цей випускник, — УСІ, а не перший.
 *
 * Так само, як із групами: людина їздила не раз, і котра з поїздок «головна»,
 * дані не кажуть.
 */
/**
 * Новіші згори.
 *
 * Порядок у реєстрі — від найдавнішого, бо так його й вносили. Доти обидва ці
 * переліки віддавали саме його, а сторінка-перелік фестивалів сортувала сама, і
 * та сама людина бачила поїздки в різному порядку залежно від того, звідки
 * дивиться. Сортування ТУТ, а не в показі: порядок — властивість відповіді на
 * питання «на яких фестивалях ця людина була», а не одного місця показу.
 *
 * Тай-брейк назвою — щоб дві поїздки того самого року не мінялися місцями між
 * збірками (у реєстрі є два «Мрій-Дім» поспіль).
 */
function newestFirst(list: Festival[]): Festival[] {
	return [...list].sort((a, b) => latestYear(b) - latestYear(a) || a.name.localeCompare(b.name, 'uk'));
}

export function getFestivalsByMember(memberId: string): Festival[] {
	return newestFirst(FESTIVALS.filter((f) => f.memberIds.includes(memberId)));
}

/**
 * Фестивалі, на які їздив цей ПРАЦІВНИК.
 *
 * Окремою функцією, а не тим самим `getFestivalsByMember` з іншим ключем:
 * `memberIds` і `masterIds` — два різні поля, і людина в них означає різне.
 * Випускник у складі й викладач, що вів групу, обидва «були на фестивалі», але
 * шукати їх треба в різних списках; спроба зіставити одним полем знайшла б
 * викладача лише тоді, коли він ще й випускник цієї школи.
 *
 * Заміряно на реєстрі: у чотирьох фестивалях `masterIds` заповнені в усіх
 * чотирьох (по 2–5 людей), а в `memberIds` жоден із цих п'ятьох викладачів не
 * значиться.
 */
export function getFestivalsByMaster(masterId: string): Festival[] {
	return newestFirst(
		FESTIVALS.filter(
			(f) => f.masterIds.includes(masterId) || (f.memberMasterIds ?? []).includes(masterId)
		)
	);
}

/** Найпізніший рік — за ним перелік упорядковується, новіші перші. */
export function latestYear(festival: Festival): number {
	return Math.max(...festival.years);
}

/** Шлях сторінки фестивалю БЕЗ мовного префікса — його додає `localizedPath`. */
export function festivalPath(slug: string): Pathname {
	return `/projects/galaxy-graduates/festivals/${slug}` as Pathname;
}

/**
 * Чи підходить фестиваль під запит пошуку.
 *
 * Правила збігу — у `utils/searchQuery`, як і в групах та майстрах; тут лише
 * ЯКІ поля шукаються.
 *
 * Країни в переліку не випадково: фестиваль частіше згадують саме так
 * («той, що в Чехії»), ніж власною назвою. Роки — окремими словами, бо на
 * фестиваль їздять не раз, і в записі їх список.
 *
 * ## Чому назва країни приходить ЗВЕРХУ, а не береться тут
 *
 * У записі країна лежить кодом (`UA`), а поле пошуку обіцяє шукати «за
 * назвою, містом, країною або роком» — і автор перевірив цю обіцянку першим:
 * «Україна» давала нуль, «Прилуки» теж. Перше — бо в полях були лише КОДИ,
 * друге — бо міста в переліку не було взагалі.
 *
 * Назва країни залежить від мови сторінки й живе в `galaxy.country.*`, а цей
 * модуль — дані: тягнути сюди i18n означало б зв'язати реєстр із мовою
 * інтерфейсу. Тому сторінка передає перекладач, як і в решті місць, де дані
 * потребують слова людською мовою (`getCategoryLabel`, `masterLabel`).
 *
 * Код країни лишається в переліку: «UA» набирають рідко, але той, хто набрав,
 * має щось знайти.
 */
export function matchesFestivalQuery(
	festival: Festival,
	query: string,
	countryName?: (code: string) => string
): boolean {
	const назвиКраїн = countryName ? festival.countries.map(countryName) : [];
	return matchesQuery(
		[
			festival.name,
			festival.nameEn,
			festival.city,
			...festival.countries,
			...назвиКраїн,
			...festival.years
		],
		query
	);
}

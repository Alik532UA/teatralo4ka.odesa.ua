/**
 * Випускники «Галактики» — дані в репозиторії, не у Firestore.
 *
 * Рішення записане в PROJECT-CONTEXT: перелік майже не змінюється, а найдорожче
 * тут — потрапити в індекс пошуку. Дані з репозиторію проходять prerender і
 * опиняються в HTML; дані з Firestore приходять уже в браузері, і сторінка їде в
 * індекс порожньою — саме тому `/news` має записане відхилення.
 *
 * ## Два види записів, і різниця між ними принципова
 *
 * Заміряно на джерелі: випускників **482** за 1998–2025, і лише **80** із них
 * заповнили анкету — тобто мають власну сторінку, портрет і подробиці. Решта 402
 * присутні на сторінці-індексі просто іменем.
 *
 * Спершу тут лежали тільки ті 80 — бо краулер ходив за посиланнями, а на решту
 * посилань немає. Це давало не «менше даних», а НЕПРАВДУ: сторінка казала
 * «вісімдесят випускників», хоча їх понад чотириста.
 *
 * `hasPhoto` і є ця різниця. Запис без нього летить у галактиці зіркою без
 * обличчя, і це не заглушка: людина в переліку є, просто анкету ще не заповнила.
 *
 * ## Чому поля опційні
 *
 * У 402 записів немає нічого, крім імені, року й відділення. Тримати для них
 * порожні масиви означає платити за них розміром у кожного відвідувача: стислий
 * файл — 80 КБ проти 154 з порожніми полями.
 */

/** Відділення. Ключі збігаються з емодзі-маркерами джерела (див. парсер). */
/**
 * Відділення ЗНАЧЕННЯМ, а не лише типом: із цього ж списку перевірка бере
 * перелік дозволених. Тримати союз у типі, а перелік — окремо в тесті
 * означало б, що додане відділення мовчки лишиться поза наглядом.
 */
export const DEPARTMENTS = [
	'theatre',
	'intensive',
	'music',
	'vocal',
	'art',
	'piano',
	'guitar'
] as const;

export type Department = (typeof DEPARTMENTS)[number];

/**
 * ХТО це для школи. Значенням, а не лише типом: звідси гейт бере перелік
 * дозволених, і додане значення не лишається поза наглядом.
 *
 *   `graduate` (поля немає) — свідоцтво про закінчення є;
 *   `attended` — навчався й не закінчив («навчався до N»);
 *   `student` — ще вчиться; у `graduationYear` очікуваний рік випуску.
 *
 * Статус не залежить від видимості (`visibility`): той, хто не закінчив,
 * буває і в галактиці (Ігор Розводюк), і лише за зв'язками (Ірина Тимофієнко),
 * і лише за прямим посиланням (Володимир Захарченко).
 */
export const GRADUATE_KINDS = ['graduate', 'attended', 'student'] as const;
export type GraduateKind = (typeof GRADUATE_KINDS)[number];

/**
 * Ребро «випускник → майстер».
 *
 * Несе `id` і більше нічого: ім'я та відділення — властивості самого майстра,
 * і копіювати їх у кожен зв'язок означало платити вагою й ризикувати
 * розходженням. Заміряно перед прибиранням: 535 копій на 25 КБ індексу, і
 * жодна з них не була потрібна — усі 332 зв'язки знаходили майстра за `id`.
 *
 * `name` лишається запасним підписом на випадок, коли працівника ще немає в
 * реєстрі. Гейт стежить, щоб таких не з'являлося мовчки.
 */
export interface GraduateMaster {
	id?: string;
	name?: string;
	department?: Department | string | null;
}

/**
 * Викладач предмета в записі КОНКРЕТНОГО випускника.
 *
 * ## Чому предметів тут два поля, і яке з них правильне
 *
 * У майстра є власний перелік — `MasterIndexEntry.subjects`, тобто «що ця людина
 * викладає взагалі». Тут же йдеться про інше: «що вона викладала САМЕ ЦЬОМУ
 * випускникові». Це різні величини, і різниця не теоретична: Самуїл Імас
 * викладає риторику й акторську майстерність, а конкретний випускник міг мати
 * лише риторику.
 *
 * `subjects` — правильне поле: перелік, як і в майстра, тож обидві сторони
 * зв'язку описані однаково і зіставні автоматично (див. інваріант
 * `src/faculty-relations.test.ts`).
 *
 * `subject` — стара форма, вільний рядок. Лишається для сумісності, але нових
 * записів у ній робити не варто, і причина конкретна: у ньому вже стояло
 * `"Риторика та поетика, акторська майстерність"` — рукописна копія ПОВНОГО
 * переліку майстра, зліплена комою. Зіставити такий рядок із переліком майстра
 * не може ні код, ні перевірка: «акторська майстерність» тут з малої літери,
 * тобто це навіть не той сим, що в майстра.
 */
export interface GraduateTeacher {
	id?: string;
	/** Запасний підпис — див. `GraduateMaster.name`. */
	name?: string;
	department?: Department | string | null;
	/** Предмети саме цього зв'язку. Перелік, як `subjects` у майстра. */
	subjects?: string[];
	/** @deprecated Вільний рядок, стара форма. Читається, але не пишеться. */
	subject?: string;
}

export interface GraduateSocial {
	network: string;
	url: string;
}

export interface GraduateIndexEntry {
	/**
	 * Ключ, який НЕ МІНЯЄТЬСЯ. На нього посилаються всі зв'язки.
	 *
	 * `slug` — це адреса, і вона законно змінюється: ім'я виправили, порядок
	 * «прізвище-ім'я» привели до ладу. Доти таке виправлення мовчки рвало склад
	 * груп, бо `memberIds` посилалися саме на адресу; рятував лише гейт
	 * `groups.test.ts`, який червонів постфактум.
	 *
	 * Значення — теперішній `slug`, заморожений назавжди: у файлі, який правлять
	 * руками, читабельний ключ вартий більше за непрозорий номер. Так само
	 * влаштовані майстри — у всіх 140 `id === slug`.
	 */
	id: string;
	slug: string;
	name: string;
	/** `null` буває: у джерелі рік вказаний не завжди. */
	graduationYear: number | null;
	/**
	 * Хто це для школи — див. `GRADUATE_KINDS`. Поля немає — випускник.
	 *
	 * Підпис під іменем виводиться звідси (`graduationCaption`): «випуск 2014»,
	 * «навчався до 2009», «навчається». Доти статус проходив через ключ перекладу
	 * `graduationLabelKey` — поле оформлення грало роль статусу, і з бази не
	 * було видно, хто перед тобою. Учень тримає в `graduationYear` ОЧІКУВАНИЙ рік
	 * випуску (рішення автора 2026-09-02); у переліку за роком він став би поруч
	 * зі своїм майбутнім випуском — але учнів у переліку не буває, і це стереже
	 * гейт `narrowed-fields.test.ts`.
	 */
	kind?: GraduateKind;
	departments: Department[];
	/** Є портрет і подробиці — тобто анкету заповнено. Інакше поля нижче порожні. */
	hasPhoto?: true;
	/**
	 * Кількість фото: 1 за замовчуванням (основне), >1 якщо є додаткові.
	 * Відсутнє поле = 1 фото (зворотна сумісність).
	 * Додаткові фото лежать як `{slug}-2-{size}.webp`, `{slug}-3-{size}.webp` тощо.
	 */
	photoCount?: number;
	/**
	 * Код сторінки на старому сайті: `15K`, `18A_1`, `odessitkavmonreale`.
	 *
	 * Це не внутрішній ідентифікатор, а САМА АДРЕСА, за якою людину знали:
	 * `sites.google.com/view/ats-ua/GG/2015/15K` → `/projects/galaxy-graduates/15K`.
	 * Тому код не перегенеровується й не «покращується» — інакше всі посилання,
	 * які випускники роздавали роками, поїхали б у нікуди.
	 *
	 * Є у 80 із 482: решта на старому сайті власної сторінки не мали.
	 */
	code?: string;
	/** Список, а не число: вступати можна двічі (у джерелі є «2003, 2007»). */
	enrollmentYears?: number[];
	masters?: (string | GraduateMaster)[];
	teachers?: (string | GraduateTeacher)[];
	/**
	 * Скільки важить профіль, який доведеться довантажити. Саме тому решта
	 * важкого сюди й не потрапляє: індекс імпортується модулем і їде в бандл
	 * ЦІЛКОМ, на кожну сторінку сайту.
	 *
	 * `socials` і `sourceUrl` тут БУЛИ й переїхали в профіль. Заміряно перед
	 * переносом: 84 набори посилань і 82 адреси джерела — 16 КБ зі 109, і всі до
	 * єдиного вже лежали в профілі тими самими значеннями. У браузері їх читала
	 * одна сторінка — картка випускника, яка профіль і так завантажує.
	 */
	profileSize?: number;
	/**
	 * Скільки вистав у профілі. Показується в переліку випускників, тож живе в
	 * індексі — інакше довелося б тягнути профіль кожного, щоб намалювати рядок.
	 *
	 * Свіжість тримає гейт `profileSize і playCount в індексі збігаються з
	 * анкетами`: заміряно, що після переносу 52 рядків зі списків школи це число
	 * відстало у 25 записах.
	 */
	playCount?: number;
	/**
	 * Три рівні видимості — `config/visibility.ts`. Поля немає — `listed`.
	 *
	 * Поле, а не обчислення: автор просив, щоб при аналізі бази було видно, кого
	 * показуємо, без читання логіки. Причина невидимості тут не зберігається —
	 * вона в коміті, що поставив рівень, або в DATA-QUESTIONS. Статус «ще
	 * навчається» — це `kind`, а не рівень видимости: доти учнів ховали тим самим
	 * `hidden`, і два різних питання виглядали одним.
	 */
	visibility?: Visibility;
}

/**
 * Вистава в анкеті випускника — це РЕБРО, а не запис про виставу.
 *
 * `text` лишається дослівно тим, що людина написала про себе: назва разом із
 * роллю. Це і є те, що правдиве лише для пари «ця людина — ця вистава», і воно
 * не переїде в реєстр, як не переїхав туди предмет викладача.
 *
 * `playId` — посилання на сам запис вистави. Його немає там, де зв'язати
 * однозначно не вийшло: у записах без року й у складених («Уривки з класики»:
 * три уривки одним рядком). Розрізати їх машинально означало б вигадати за
 * дані, тож такі лишаються просто текстом. Заміряно: зв'язано 386 із 520.
 *
 * `playId` — це ще й ЄДИНЕ джерело складу вистави: заява «я в цьому грав»
 * робиться тут і більше ніде. Виводити склад із групи заборонено — пояснення
 * й заміри в докблоці `src/lib/data/plays.ts`.
 *
 * `role` — та сама роль, витягнена з `text` окремим полем. Навіщо, якщо вона
 * вже є в тексті: у тексті вона злита з назвою («Маленький принц», Лис), і
 * розібрати їх машинально не виходить — рядки надто різні, від «осінь, донька»
 * до «Лизль фон Трапп (старшая дочь), наставница (монашка)». Поле заповнюється
 * поступово й лише руками; `text` лишається тим, що бачить читач, і запасним
 * джерелом там, де `role` ще немає.
 */
export interface GraduatePlay {
	year: number | null;
	text: string;
	playId?: string;
	role?: string;
	/**
	 * `true` — рядок узято зі СПИСКУ ШКОЛИ, а не зі слів самої людини.
	 *
	 * Це не дрібниця. Уся сторінка вистави тримається на тому, що `playId` в
	 * анкеті — заява «я в цьому грав», зроблена самою людиною (докблок
	 * `GraduatePlay` вище). Склад показу з паперів школи такою заявою не є: там
	 * бувають успадковані навмання імена — саме так Анісія Стасевич, що
	 * випустилася 2011-го, потрапила у виставу 2012 року.
	 *
	 * Тому такі рядки позначені. Без позначки напис під «Хто грав» — «тут ті, хто
	 * САМ назвав цю виставу своєю» — став би неправдою, і жодна перевірка цього
	 * не побачила б.
	 *
	 * Заміряно 2026-09-01: у складах показів 372 імені, з них 283 зіставилися з
	 * випускником, 12 уже були в анкетах, 52 стали такими рядками, а 219 —
	 * люди, у яких анкети немає взагалі.
	 */
	fromRegistry?: boolean;

	/**
	 * Ключі НОМЕРІВ програми — коли людина назвала не вечір, а конкретні уривки.
	 *
	 * «Уривки з класики: Незнайома; О. Блок», Поет» — це заява «я грав у ЦЬОМУ
	 * уривку». Доти такий рядок ставав окремою «виставою» з одним учасником;
	 * тепер він веде на сам вечір, а `items` кажуть, у яких саме номерах.
	 *
	 * ПЕРЕЛІК, а не один ключ: в одному вечорі людина буває в кількох уривках —
	 * Анастасія Іванес 2012 року грала і в «Рафаелі» Вампілова, і в «Коли мине 5
	 * років» Лорки. Коли ж у кожному уривку своя роль, рядків стає кілька — по
	 * одному на уривок, бо роль живе в рядку: Алік Запольнов 2015 року — «Ася»,
	 * М. М., і окремо «Принижені та зневажені». Гейт дозволяє повтор вистави в
	 * анкеті лише заради РІЗНИХ уривків.
	 *
	 * Пояснення рівня — у докблоці `PlayProgrammeItem`.
	 */
	items?: string[];
	/**
	 * Прибирає плашку «разом з» саме з ЦЬОГО рядка.
	 *
	 * Плашка обчислюється сама (`coGroupsForPlay`), і в переважній більшості
	 * випадків це правильно. Але рядок буває складеним — «Уривки з класики»
	 * трьома уривками одразу, — і тоді групи різних уривків зливаються в одну
	 * купу; буває й так, що зв'язок групи з виставою в реєстрі ширший за те, що
	 * робила ця конкретна людина. Тому потрібен вимикач на один рядок, а не
	 * правка спільних даних, яка зіпсувала б плашку всім іншим.
	 */
	hideCoGroups?: boolean;
}

/**
 * Повний профіль — те, що лежало на власній сторінці випускника.
 *
 * Окремо від індексу і НЕ в бандлі: разом усі 80 профілів — 96 КБ, і тягнути їх
 * на сторінку галактики заради однієї відкритої картки безглуздо. Кожен лежить
 * у `static/graduates/profiles/<code>.json` (найбільший — 3 КБ) і читається на
 * вимогу: сторінкою профілю під час prerender, карткою в галактиці — на кліку.
 */
export interface GraduateProfile {
	code: string;
	slug: string;
	name: string;
	graduationYear: number | null;
	enrollmentYears: number[];
	departments: Department[];
	hasPhoto: boolean;
	photoCount?: number;
	/**
	 * Назви груп, які людина вписала, але сторінки в них ще немає.
	 *
	 * Сам зв'язок «людина — група» живе в `memberIds` самої групи й лише там:
	 * доти він дублювався тут рядком, в індексі — об'єктом, і з 83 таких згадок
	 * на наявну групу вели 54. Рядок при цьому завжди «валідний», тож жоден
	 * гейт розриву не бачив.
	 *
	 * Тут лишається те, чого зв'язком не заміниш: 20 назв на кшталт «Кеди»,
	 * «Дівочі драми», «Пріколісти» — курси, у яких анкету заповнила одна
	 * людина, тож сторінки вони не мають. Викинути їх означало б забути факт;
	 * вигадати під них групу — створити сторінку без складу й репертуару.
	 *
	 * Двадцять першою була «Йорики», і вона показує, чим цей список
	 * закривається: коли склад стає відомий (2026-09-01 автор назвав шістьох),
	 * назва перестає бути рядком і стає групою зі складом. Тоді згадку ЗВІДСИ
	 * прибирають — інакше той самий факт лежав би у двох виглядах, а саме від
	 * цього поле й чистили.
	 */
	unlinkedGroups?: string[];
	masters: (string | GraduateMaster)[];
	teachers?: (string | GraduateTeacher)[];
	socials: GraduateSocial[];
	/**
	 * Запис випускника — уривок, показ, візитівка. Саме ПОСИЛАННЯ, а не голий
	 * ідентифікатор: розбирає його `parseVideoUrl` — той самий, що для новин і
	 * репертуару груп, — і він же вирішує, чи можна показати плеєр на сторінці.
	 */
	videoUrl?: string;
	plays: GraduatePlay[];
	/** Абзаци «про себе»: навчання після школи, робота, власні слова. */
	bio: string[];
	festivals: string[];
	duringStudies: string | null;
	afterGraduation: string | null;
	/** Сторінка-джерело на старому сайті — походження даних видиме. */
	sourceUrl: string;
}

/**
 * Адреса файлу профілю.
 *
 * Параметр — АДРЕСА (`graduateAddress`), а не `code`, і це не косметика імені:
 * файли трьох профілів названі слагом, бо коду в тих людей немає. Поки параметр
 * звався `code`, викликачі щиро передавали туди `graduate.code` — і для тих
 * трьох виходило `undefined.json`.
 */
export function graduateProfileJson(address: string): string {
	return asset(`/graduates/profiles/${address}.json`);
}

/**
 * Шлях сторінки профілю БЕЗ мовного префікса — його додає `localizedPath`.
 *
 * Саме рядок, а не `resolve()` з `$app/paths`, і це перевірено збіркою, а не
 * вирішено: під SSR `resolve()` віддає ВІДНОСНИЙ шлях
 * (`../../../projects/galaxy-graduates/15K`), і мовний префікс поверх нього дав
 * `/en../../../projects/…`. Наслідок був тихий і дорогий: сторінки в збірці
 * лишилися, але краулер prerender не знайшов англійських — у мапі сайту стало
 * 100 uk і 20 en замість 100 і 100. Про цю саму пастку попереджає коментар до
 * `base` в `+layout.svelte`.
 *
 * Тип повернення — `Pathname` із `$app/types`, тобто згенерований список
 * реальних шляхів проєкту. Це те, що `resolve()` давав і що втрачалося разом із
 * ним: описка в шляху знову стала помилкою компіляції, без відносних шляхів під
 * prerender. Далі `localizedPath` перетворює це на `ResolvedPathname` — тип, за
 * яким `svelte/no-navigation-without-resolve` визнає адресу перевіреною.
 */
/**
 * Підпис під іменем — з `kind`: «випуск 2014», «навчався до 2009», «навчається».
 *
 * Тут, а не в кожному компоненті: підпис показують і картка, і склад групи, і
 * розійшовшись вони дали б ту саму людину з різними роками в різних місцях.
 * `translate` приходить ззовні, бо `svelte-i18n` живе лише в компоненті.
 *
 * Учень підписується без року навмисно: рік у нього ОЧІКУВАНИЙ, і показувати
 * його як факт означало б обіцяти випуск. Той, хто не закінчив, без року
 * лишається без підпису — форма «навчався до» ще й чоловіча, і борг жіночої
 * форми записаний у PROJECT-CONTEXT.
 */
export function graduationCaption(
	graduate: { graduationYear: number | null; kind?: GraduateKind },
	translate: (key: string, options?: { values?: Record<string, string | number> }) => string
): string | null {
	if (graduate.kind === 'student') return translate('galaxy.studying');
	const year = graduate.graduationYear;
	if (!year) return null;
	return graduate.kind === 'attended'
		? translate('galaxy.studiedUntil', { values: { year } })
		: `${translate('galaxy.graduated')} ${year}`;
}

/**
 * Чи є в людини файл подробиць у `static/graduates/profiles`.
 *
 * Ознака — `profileSize`: його проставляє генератор рівно тим, кому написав
 * файл. Перевірено на всій базі: 93 записи з полем, 93 файли на диску, жодного
 * розходження в обидва боки.
 *
 * Потрібна саме ознака, а не спроба прочитати файл: сторінка тепер є в КОЖНОГО,
 * і 437 разів отримати 404 замість подробиць — це не «немає даних», а шум у
 * журналі й зайвий запит.
 */
export function hasProfile(graduate: { profileSize?: number }): boolean {
	return graduate.profileSize !== undefined;
}

/**
 * Адреса сторінки цієї людини.
 *
 * `code` — стара адреса з Google-сайту, вона є у 90 із 530. У решти адресою стає
 * `slug`. Перевірено: усі 530 значень унікальні, жоден слаг не збігається з чужим
 * кодом, і в жодному немає символів, які довелося б кодувати.
 *
 * Старий код лишається головним не з ліні: за ним у мережі стоять посилання
 * дев'яти років, і міняти адресу тим, у кого вона вже є, означало б рвати їх
 * заради однорідності, якої ніхто не побачить.
 */
export function graduateAddress(graduate: { code?: string; slug: string }): string {
	return graduate.code ?? graduate.slug;
}

export function graduateProfilePath(address: string): Pathname {
	return `/projects/galaxy-graduates/${address}`;
}

/**
 * Адреса, за якою відкривається КАРТКА цієї людини.
 *
 * Тепер це просто адреса сторінки — така сама, як у всіх. Раніше було інакше, і
 * варто пам'ятати чому: власну сторінку мали 90 із 530, а решті 440 картка
 * відкривалася параметром `?g=<slug>` на сторінці галактики. Параметр з'явився
 * не від доброго життя — кнопці «сторінка випускника» на сторінці працівника
 * потрібна була адреса, а в шести з одинадцяти подвійних людей коду немає.
 *
 * Відколи сторінка є в кожного, ця розвилка зникла. `?g=` галактика й далі
 * розуміє — за дев'ять років на нього могли зіслатися ззовні, — але жодне місце
 * в коді його більше не породжує.
 */
export function graduateCardHref(
	graduate: { code?: string; slug: string },
	locale: Locale
): ResolvedPathname {
	return localizedPath(graduateProfilePath(graduateAddress(graduate)), locale);
}

/**
 * Форму реєстру звіряє КОМПІЛЯТОР, а не приведення типу.
 *
 * Доти тут стояло `as GraduateIndexEntry[]` — воно мовчки погоджувалося з
 * будь-яким вмістом файлу. `satisfies` натомість звіряє кожне поле на
 * збірці й нічого не важить у бандлі.
 *
 * Виняток один: в імпортованому JSON TypeScript бачить `departments:
 * string[]` і звузити рядок до союзу не вміє. Тому нагляд ділиться надвоє —
 * решту форми тримає `satisfies`, а самі значення відділень тримає гейт
 * «реєстри знають лише відомі відділення». Саме його бракувало: значень
 * відділень не перевіряв ніхто.
 */
type IndexEntryJson = Omit<GraduateIndexEntry, 'departments' | 'hasPhoto' | 'kind' | 'visibility'> & {
	departments: string[];
	hasPhoto?: boolean;
	/* Так само рядком: значення тримає гейт `narrowed-fields.test.ts`. */
	kind?: string;
	visibility?: string;
};
const INDEX_JSON = indexData satisfies readonly IndexEntryJson[];

/**
 * У ПЕРЕЛІКУ: зірки галактики, рядки реєстру, роки випуску, лічильники.
 * Лише рівень `listed` (`config/visibility.ts`).
 */
export const GRADUATES: readonly GraduateIndexEntry[] = (
	INDEX_JSON as GraduateIndexEntry[]
).filter(isGraduateListed);

/**
 * ЗА ЗВ'ЯЗКАМИ: кого показуємо там, де на людину є посилання — склад вистави,
 * група, фестиваль, потік учнів майстра, кнопка «також працівник», картка з
 * адреси. Рівні `listed` і `linked`.
 *
 * Окремий перелік, а не `GRADUATES`: людина рівня `linked` у галактиці не
 * летить, але в складі «Уривків з класики» стоїть — і саме за цим переліком
 * склад її знаходить. Доти такої межі не було: `hidden` викидав людину
 * звідусіль одразу, і Тимофієнко, яка грала чотири ролі, не мала запису взагалі.
 */
export const LINKED_GRADUATES: readonly GraduateIndexEntry[] = (
	INDEX_JSON as GraduateIndexEntry[]
).filter(isGraduateLinked);

/**
 * ЛИШЕ ЗА ПРЯМИМ ПОСИЛАННЯМ — і саме тому їх видно окремо.
 *
 * Такої людини немає ні в `GRADUATES`, ні в `LINKED_GRADUATES`. Але в паперових
 * списках школи її ім'я лишається вільним текстом, і без цього переліку показ
 * малював би її звичайною карткою: не як випускницю (у реєстрі її «немає»), а як
 * сторонню людину без сторінки — тобто рівно там, де її й просили не показувати.
 *
 * Тому рівень `direct` доступний окремо: щоб показ міг ЗІСТАВИТИ ім'я й промовчати.
 */
export const DIRECT_GRADUATES: readonly GraduateIndexEntry[] = (
	INDEX_JSON as GraduateIndexEntry[]
).filter((g) => !isGraduateLinked(g));

/**
 * Ті, у кого є портрет і анкета.
 * Впорядковані за точним розміром файлу профайлу (у байтах) від меншого до більшого,
 * щоб у польоті галактики випускники з довшими/багатшими профайлами летіли поверх.
 */
export const WITH_PHOTO: readonly GraduateIndexEntry[] = GRADUATES
	.filter((g) => g.hasPhoto)
	.sort((a, b) => (a.profileSize ?? 0) - (b.profileSize ?? 0));

/** Ті, хто ще не заповнив анкету: летять зірками без обличчя, з іменем на наведенні. */
export const WITHOUT_PHOTO: readonly GraduateIndexEntry[] = GRADUATES.filter((g) => !g.hasPhoto);

/**
 * Розміри портретів, які справді існують у `static/graduates/`.
 *
 * Числа не декоративні: вони йдуть у `srcset` дескрипторами `w`, а дескриптор
 * мусить бути правдивим. Тому `fetch-graduate-photos.ts` і робить сторону файлу
 * рівно такою, як в його імені.
 */
export const PHOTO_SIZES = [96, 192, 480] as const;

/** Адреса портрета потрібного розміру. */
export function graduatePhoto(slug: string, size: (typeof PHOTO_SIZES)[number]): string {
	return asset(`/graduates/${slug}-${size}.webp`);
}

/** `srcset` на всі наявні розміри — браузер обирає під щільність екрана сам. */
export function graduatePhotoSrcset(slug: string): string {
	return PHOTO_SIZES.map((size) => `${graduatePhoto(slug, size)} ${size}w`).join(', ');
}

/** Адреса додаткового портрета (index ≥ 2). */
export function graduateExtraPhoto(slug: string, index: number, size: (typeof PHOTO_SIZES)[number]): string {
	return asset(`/graduates/${slug}-${index}-${size}.webp`);
}

/** `srcset` для додаткового портрета. */
export function graduateExtraPhotoSrcset(slug: string, index: number): string {
	return PHOTO_SIZES.map((size) => `${graduateExtraPhoto(slug, index, size)} ${size}w`).join(', ');
}

/**
 * Повний список фото випускника з src/srcset, впорядкований від наймолодшого
 * до найстаршого (основне фото — останнє).
 *
 * Додаткові фото (index 2, 3, …) йдуть першими (молодші),
 * основне фото (без індекса) — останнє (найстарше/поточне).
 */
export function allGraduatePhotos(
	slug: string,
	photoCount: number,
	size: (typeof PHOTO_SIZES)[number] = 96
): { src: string; srcset: string }[] {
	const photos: { src: string; srcset: string }[] = [];
	// Додаткові фото (молодші) — index 2, 3, ..., photoCount
	for (let i = 2; i <= photoCount; i++) {
		photos.push({
			src: graduateExtraPhoto(slug, i, size),
			srcset: graduateExtraPhotoSrcset(slug, i),
		});
	}
	// Основне фото (найстарше/поточне) — останнє
	photos.push({
		src: graduatePhoto(slug, size),
		srcset: graduatePhotoSrcset(slug),
	});
	return photos;
}

/** Роки випуску, які є в даних — для фільтра. Новіші перші. */
export const GRADUATION_YEARS: readonly number[] = [
	...new Set(GRADUATES.map((g) => g.graduationYear).filter((y): y is number => y !== null))
].sort((a, b) => b - a);

/**
 * Ті, у кого є власна сторінка, — тепер це ВСІ.
 *
 * Доти тут стояв фільтр `g.code`, тобто сторінку отримував той, хто був на
 * старому Google-сайті. Правило звучало як «має подробиці», а означало «має
 * стару адресу», і збігалося з наповненням лише випадково: усі 89 фото — у тих
 * самих 90 записів.
 *
 * Наслідки були не косметичні. У 440 людей не було адреси взагалі, тож картка
 * відкривалася параметром, вікно вибору для випускника-працівника мусило вести
 * в модалку, а пошуковик тих людей не бачив зовсім.
 *
 * Те саме рішення для вистав ухвалене раніше й записане в
 * `plays/[id]/+page.ts`: сторінка є в кожної, «навіть якщо про неї відомий
 * сам лише рік», бо «посилання, що веде в 404, гірше за скупу сторінку». Тут
 * скупа сторінка теж не порожня: ім'я, рік випуску, відділення, а часто ще
 * група, майстер курсу й вистави.
 *
 * Константа лишилася під тією самою назвою навмисно: вона й далі відповідає на
 * питання «кому будувати сторінку», просто відповідь тепер «усім».
 *
 * І «всім» тут означає ВСІМ, зокрема рівням `linked` і `direct`: видимість ховає
 * людину з переліків, а не з сайту. Тому `WITH_PAGE` і `GRADUATES` — уже різні переліки,
 * і плутати їх не можна: перший будує сторінки, другий малює списки. Розбір — у
 * докблоці `config/graduatesVisibility.ts`.
 */
export const WITH_PAGE: readonly GraduateIndexEntry[] = INDEX_JSON as GraduateIndexEntry[];

/**
 * Пошук за АДРЕСОЮ — серед усіх, зокрема прихованих.
 *
 * `GRADUATES` містить лише рівень `listed`, і сторінка шукала людину саме там:
 * адреса приходила, запис не знаходився, і маршрут віддавав 404. Тобто
 * видимість ховала людину не з переліків, а з сайту зовсім.
 *
 * Ховати треба з ПЕРЕЛІКІВ, а сторінка мусить лишатися живою: адреса випускника
 * це ідентифікатор, який роздають роками. Повний розбір — у докблоці
 * `config/graduatesVisibility.ts`.
 */
export function findByAddress(address: string): GraduateIndexEntry | undefined {
	return WITH_PAGE.find((candidate) => graduateAddress(candidate) === address);
}

import friendsData from './friends.data.json';

/**
 * ДРУЗІ ШКОЛИ — люди театру, які лишили школі підписану картку.
 *
 * ## Що це за сутність і чим вона НЕ є
 *
 * Це не реєстр людей, а реєстр КАРТОК. Сама картка — цілий артефакт: портрет,
 * рукописне побажання, підпис і дата, зроблені для школи й більше ніде не
 * існують. Тому в записі немає ні міста, ні посад за роками, ні фестивалів:
 * усе, що про людину відомо з картки, на ній і написано.
 *
 * Дев'ятеро з двадцяти двох мають ще й сторінку фахівця — вони приїздили до нас
 * у журі або на майстер-класи. Зв'язок записаний `expertSlug`, і саме з цього
 * боку: картка знає про сторінку, сторінка про картку — ні. Другого поля в
 * реєстрі фахівців немає навмисно, бо воно розійшлося б із цим тихо.
 *
 * ## Дві серії, і це не оформлення
 *
 * `stars` — «Зіркові друзі "Театрало4ки"»: жовта картка з чорно-білим
 * портретом, фах підписаний друком. `heart` — старша серія «Я ♥ ДТШ»:
 * помаранчева, фах друком НЕ підписаний, тож у цих чотирьох він переписаний
 * сюди з окремих підписів, що йшли разом зі знімками.
 *
 * Розрізняти серії треба саме в даних: у них різна пропорція (8910×6300 проти
 * 2560×1600), а розмітка мусить знати висоту зображення наперед — інакше
 * сторінка стрибає, поки картки вантажаться.
 */
export interface Friend {
	/** Адреса картки в `static/friends/`: `<slug>.webp` і `<slug>-480.webp`. */
	slug: string;
	name: string;
	nameEn: string;
	/** Фах — так, як він підписаний на самій картці. */
	role: { uk: string; en: string };
	/**
	 * `'stars'` або `'heart'` — але тип ШИРШИЙ навмисно.
	 *
	 * В імпортованому JSON TypeScript бачить `series: string`, а не союз із двох
	 * значень; звузити тут означало б приведення, яке мовчки погоджується з
	 * будь-яким вмістом файлу. Звужує це `narrowed-fields.test.ts` — той самий
	 * спосіб, що для `departments` випускника й `category` майстра.
	 */
	series: string;
	/** Сторінка фахівця, якщо ця людина приїздила до нас на фестиваль. */
	expertSlug?: string;
	/** Розмір МАЛОЇ картки. Не виводиться із серії: числа мусять бути звірені з диском. */
	thumb: { w: number; h: number };
}

export const FRIENDS: readonly Friend[] = friendsData satisfies readonly Friend[];

/** Тека карток у `static/`. Одна на проєкт — щоб не розійшлася зі скриптом. */
export const FRIENDS_DIR = '/friends';

/** Чи згадує картка щось із запиту: ім'я обома мовами й фах. */
export function matchesFriendQuery(friend: Friend, query: string): boolean {
	const q = query.trim().toLowerCase();
	if (!q) return true;
	return [friend.name, friend.nameEn, friend.role.uk, friend.role.en]
		.join(' ')
		.toLowerCase()
		.includes(q);
}

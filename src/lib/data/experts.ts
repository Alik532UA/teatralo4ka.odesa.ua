import type { Pathname } from '$app/types';
import { matchesQuery } from '$lib/utils/searchQuery';
import expertsData from './experts.data.json';

/**
 * Запрошені фахівці фестивалів — Експертна Рада, коучі, почесні гості.
 *
 * ## Чому ОКРЕМИЙ реєстр, а не реєстр працівників
 *
 * Це люди з інших закладів: голова НСТДУ, режисери київських і львівських
 * театрів, викладачі харківських і дніпровських вишів. Заміряно на трьох
 * списках, які надіслав автор: із дванадцяти названих експертів у реєстрі
 * працівників не знайшовся ЖОДЕН, а серед випускників — теж жоден.
 *
 * Записати їх працівниками означало б сказати неправду про школу: сторінка
 * «Дорослі» перелічує тих, хто в ній працює.
 *
 * ## А свої там теж бувають
 *
 * В Експертній Раді 2018 сидів Олег Шевчук — НАШ колишній педагог
 * (`oleh-shevchuk` у реєстрі працівників), і в тому самому буклеті він же
 * стоїть педагогом кількох учасників. Тому роль і реєстр розділені так само, як
 * це вже зроблено для учасників (`memberIds` + `memberMasterIds` у
 * `data/festivals`): у фестивалю два переліки на одну роль, і картка кожного
 * розгортається зі свого реєстру.
 *
 * ## ЧОМУ ПОСАДА — ПЕРЕЛІК ЗА РОКАМИ, А НЕ ОДИН РЯДОК
 *
 * Посада змінюється, і в наших даних це видно прямо. Станіслав Жирков 2018-го
 * був художнім керівником театру «Золоті ворота», а 2021-го — директором
 * театру драми і комедії на лівому березі Дніпра. Володимир Саган і Дмитро
 * Захоженко теж названі по-різному у 2021 і 2026.
 *
 * Один рядок на людину змусив би вибирати між двома неправдами: показати
 * теперішню посаду на сторінці фестивалю 2018 року або показати тодішню як
 * теперішню. Перелік за роками не змушує ні до чого — сторінка фестивалю бере
 * запис свого року, а сторінка людини показує всі, і виходить маленька
 * хронологія замість одного застиглого рядка.
 *
 * Поле лежить у ЛЮДИНІ, а не в фестивалі, бо це властивість людини в часі. У
 * фестивалю лишаються самі ключі — так само, як у решти його переліків.
 */
export interface ExpertTitle {
	/** Рік фестивалю, на якому посада була названа саме так. */
	year: number;
	/** Посада дослівно з програмки того року. */
	text: string;
}

export interface Expert {
	/** Стійкий ключ і сегмент адреси. */
	slug: string;
	name: string;
	nameEn?: string;
	/** Місто, з якого фахівець приїхав. Показується під іменем. */
	city?: string;
	/** Портрет із `static/`. Немає — картка покаже ініціали. */
	photo?: string;
	titles: ExpertTitle[];
}

/*
 * Реєстр у JSON, а не масивом у коді, — з тієї самої причини, що фестивалі й
 * групи: він росте з кожним фестивалем, а `structure.test.ts` рахує рядки коду,
 * не даних.
 */
export const EXPERTS: readonly Expert[] = expertsData satisfies readonly Expert[];

export function getExpertBySlug(slug: string): Expert | undefined {
	return EXPERTS.find((e) => e.slug === slug);
}

/** Адреса сторінки фахівця. Типізована, як решта адрес проєкту. */
export function expertPath(slug: string): Pathname {
	return `/projects/galaxy-graduates/experts/${slug}` as Pathname;
}

/**
 * Посада, названа на фестивалі ЦЬОГО року, або найсвіжіша з відомих.
 *
 * Запасний варіант потрібен не «про всяк випадок»: фестиваль може додатися
 * раніше, ніж програмка того року знайдеться, і тоді картка без підпису
 * виглядала б як помилка даних. Найсвіжіша посада в такому разі — найменша
 * неправда з можливих, і вона принаймні каже, хто ця людина.
 */
export function expertTitle(expert: Expert, year?: number): string {
	const exact = year === undefined ? undefined : expert.titles.find((t) => t.year === year);
	if (exact) return exact.text;
	const latest = [...expert.titles].sort((a, b) => b.year - a.year)[0];
	return latest?.text ?? '';
}

/** Пошук по імені та місту — той самий механізм, що в решти реєстрів. */
export function expertMatches(expert: Expert, query: string): boolean {
	return matchesQuery([expert.name, expert.nameEn, expert.city], query);
}

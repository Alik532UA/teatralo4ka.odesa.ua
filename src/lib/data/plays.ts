import playsData from './plays.data.json';

/**
 * Реєстр вистав.
 *
 * ## Навіщо окрема сутність
 *
 * Доти вистава не була об'єктом: вона існувала трьома незалежними записами —
 * у анкеті випускника, у профілі майстра й у групі, — і жоден не знав про
 * решту. Заміряно перед зведенням: 807 записів на 363 справді різні вистави.
 * Наслідок було видно на сторінках: та сама вистава йшла двома написаннями, бо
 * кожен вписував її по-своєму.
 *
 * ## Що лежить тут, а що на ребрі
 *
 * Тут — те, що правдиве про саму виставу: назва, рік, автор, запис, нагороди.
 * На ребрі — те, що правдиве лише про пару: роль випускника лишається в його
 * анкеті, бо це його роль, а не властивість вистави.
 *
 * ## Чому JSON, а не масив у коді
 *
 * З тієї ж причини, що й групи: реєстр росте, а типова межа файлу — ні.
 * Цілісність тримає `plays.test.ts` на збірці.
 */
export interface Play {
	/** Ключ, на який посилаються групи, анкети й профілі майстрів. */
	id: string;
	title: string;
	year: number;
	/** «за казками Оскара Вайльда», «поетична вистава» — як записано в джерелі. */
	author?: string;
	/** Посилання на запис. Розбирає його `parseVideoUrl`, як і всюди на сайті. */
	videoUrl?: string;
	awards?: string[];
	/** Заклад, де показували. */
	institution?: string;
	/**
	 * Група, що грала. Разом із назвою й роком вона й РОЗРІЗНЯЄ подію.
	 *
	 * Це не дрібниця: «Уривки з класики» 2015 йшли двома різними групами в
	 * різних закладах, «Показ етюдів» 2024 — двома групами під номерами 57 і 58.
	 * Ключем «назва + рік» вони склеїлися б в один запис, і половина даних
	 * (учасники однієї, номер другої) зникла б мовчки.
	 */
	theatreGroup?: string;
	/** Номер вистави в ДТШ — наскрізна нумерація школи. */
	number?: number;
	/** «22 травня», «два покази» — уточнення дати, як записано в джерелі. */
	dateNote?: string;
	/** `false` — показ був не в ДТШ. Немає поля — був. */
	isDtsh?: boolean;
	/** Склад — поки вільним текстом, як його вписали. Зіставляє `participantMatch`. */
	participants?: string[];
	/** Майстри, у чиїх профілях ця вистава значиться. */
	masters?: string[];
}

/*
 * Приведення тут не потрібне: реєстр вистав збігається з типом ТОЧНО, і це
 * перевіряє компілятор, а не довіра. `as` мовчки погодилося б і з файлом,
 * у якому поля роз'їхалися.
 */
export const PLAYS: readonly Play[] = playsData satisfies readonly Play[];

const BY_ID = new Map(PLAYS.map((p) => [p.id, p]));

/** Вистава за ключем, або `undefined` — гейт стежить, щоб такого не траплялося. */
export function getPlayById(id: string): Play | undefined {
	return BY_ID.get(id);
}

/**
 * Розгортає перелік ключів у вистави, найновіші згори.
 *
 * Ключі, яких немає, мовчки відкидаються: сторінка має показати те, що є, а не
 * впасти. Про саме́ розходження кричить гейт, і кричить на збірці.
 */
export function playsByIds(ids: readonly string[]): Play[] {
	return ids
		.map((id) => BY_ID.get(id))
		.filter((p): p is Play => Boolean(p))
		.sort((a, b) => b.year - a.year || a.title.localeCompare(b.title, 'uk'));
}

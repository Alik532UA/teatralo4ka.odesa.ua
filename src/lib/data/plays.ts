/**
 * Реєстр вистав.
 *
 * ## Навіщо окрема сутність
 *
 * Доти вистава не була об'єктом: вона існувала трьома незалежними записами —
 * у анкеті випускника, у профілі майстра й у групі, — і жоден не знав про
 * решту. Заміряно перед зведенням: 807 записів на 363 справді різні вистави.
 * Наслідок було видно на сторінках: та сама вистава йшла двома написаннями, бо
 * кожен вписував її по-своєму.
 *
 * ## Що лежить тут, а що на ребрі
 *
 * Тут — те, що правдиве про саму виставу: назва, рік, автор, запис, нагороди.
 * На ребрі — те, що правдиве лише про пару: роль випускника лишається в його
 * анкеті, бо це його роль, а не властивість вистави.
 *
 * ## ХТО ГРАВ У ВИСТАВІ — тільки те, що людина сказала про себе
 *
 * Склад вистави береться ВИКЛЮЧНО з анкет: із тих записів, де випускник сам
 * поставив `playId` у своєму рядку. Виводити склад із групи — «усі учасники
 * групи × усі вистави групи» — ЗАБОРОНЕНО, і це не педантизм, а два заміри:
 *
 *   • «Дядюшка Кролик против дядюшки Ягуара» (2007) числиться за групою ЗТК, і
 *     Алік Запольнов числиться в ЗТК. Але своєю цю виставу назвали п'ятеро, і
 *     його серед них немає: він прийшов у групу пізніше. Прямий добуток
 *     приписав би йому виставу, якої він не грав.
 *
 *   • «Мнимый больной» (2011) назвали своєю СЕМЕРО — більше, ніж учасників у
 *     ЗТК, і сама вистава числиться за двома групами. Тобто у виставі грали
 *     люди з різних груп, і межа групи тут не збігається зі складом.
 *
 * Те саме в зворотний бік: рядок «разом з групою ЗТК» в анкеті означає, що
 * грали ЧАСТИНА тієї групи й частина цієї, а не дві групи цілком.
 *
 * Правило одне: зв'язок «людина ↔ вистава» авторський і поштучний. Ніяка
 * машинна добудова його не замінює. Заміряно станом на 2026-08-31: 386 із 520
 * рядків анкет мають `playId`, і 274 з 363 вистав мають бодай одного, хто
 * назвав її своєю.
 *
 * ## Чому JSON, а не масив у коді
 *
 * З тієї ж причини, що й групи: реєстр росте, а типова межа файлу — ні.
 * Цілісність тримає `plays.test.ts` на збірці.
 */
/**
 * Один НОМЕР програми: уривок вечора «Уривки з класики», етюд показу.
 *
 * ## Навіщо рівень між виставою і складом
 *
 * «Уривки з класики» — не вистава, а вечір із кількох уривків, і в кожному
 * грали різні люди. Доти цього рівня не було, тож уривок ставав окремою
 * «виставою»: `uryvky-z-klasyky-neznaiomka-o-bloka-2013` — сторінка з одним
 * учасником поруч зі сторінкою самого вечора, де той самий уривок уже стояв у
 * переліку творів. Заміряно: таких записів-уривків 5, а рядків анкет, що
 * називають конкретний уривок, — 24, і прив'язати їх було ні до чого.
 *
 * ## Звідки беруться номери
 *
 * З того самого поля `author`, де перелік творів вечора й лежав прозою:
 * «Софокл «Антігона», А. Чехов «Дядя Ваня», … О. Блок «Незнайомка», …». Поле
 * лишається — воно джерело, а `programme` його розібраний вигляд.
 */
export interface PlayProgrammeItem {
	/** Ключ, на який посилається рядок анкети. З назви твору, не з порядку. */
	id: string;
	/** Як номер названо: «О. Блок «Незнайомка»». */
	title: string;
	/**
	 * `true` — номера немає в переліку школи, він відомий лише зі слів
	 * випускника. Це не дрібниця: такий номер може бути й помилкою пам'яті, і
	 * пропуском у переліку, тож показувати його врівні з рештою було б
	 * перебільшенням.
	 *
	 * Прапорець, а не `source: 'registry' | 'profile'`: реєстр приходить із JSON
	 * через `satisfies`, а звідти літеральний союз не виводиться — тип рядка
	 * ширший за союз, і перевірка падає. Приведення `as` тут заборонене
	 * (докблок нижче), тож поле мусить бути таким, яке JSON виражає точно.
	 */
	fromProfile?: boolean;
	/**
	 * Запис САМЕ ЦЬОГО номера. Вечір буває записаний цілком (`Play.videoUrl`),
	 * а буває — окремими уривками, і трапляється обидва разом; тому поле є на
	 * обох рівнях, а не на одному. Розбирає той самий `parseVideoUrl`.
	 */
	videoUrl?: string;
	/**
	 * Ролі номера в порядку АФІШІ: головні спершу, «Хор — усі» наприкінці.
	 *
	 * Це не склад — хто грав, кажуть анкети, — а порядок, у якому програмка
	 * називає ролі. Саме він задає порядок карток під фільтром номера: хто грав
	 * першу названу роль, стоїть першим. Абетка ставила Аліка Запольнова першим
	 * у кожному номері, хоч у «Незнайомці» він третій.
	 *
	 * Роль пишеться ТАК САМО, як у рядку анкети («Тінь», а не «Тіні»): збіг
	 * точний, і гейт у `play-cast.test.ts` стежить, щоб кожна роль звідси мала
	 * виконавця у складі, а кожна роль зі складу була названа тут.
	 */
	roles?: string[];
}

/**
 * Різновид події — не вистава курсу, а щорічний захід школи.
 *
 * ## Чому це поле, а не окремий реєстр
 *
 * Заходи мають усе те саме, що вистава: рік, назву, запис, склад із анкет,
 * сторінку. Окремий реєстр означав би другу копію `plays.test.ts`, другий
 * маршрут і другий зріз складу — а розрізняє їх РІВНО одне: чиї вони.
 *
 * ## ЧОМУ «У РЕПЕРТУАРІ ГРУП» ТУТ БУЛА БРЕХНЯ
 *
 * `posviata` — «Посвята в Мистецтво», яку для учнів готують ВИПУСКНИКИ, і
 * приходять вони з різних років і різних груп. Це не гіпотеза, це титри:
 * «Енеїда» 2022 — випускники 2005, 2012, 2018, 2018, 2020 і 2022 років;
 * «Ken & Barbi team» 2023 — 2005, 2010, 2012, 2018, 2020, 2020, 2021, 2022 і
 * ще двоє 2022-го; Посвята 2021 — випускники 2021-го плюс випускниці 2018 і
 * 2013 років.
 *
 * Тому підрахунок груп за складом (`classifyPlayGroups`) для них не просто
 * марний, а активно шкідливий: він оголошував «Енеїду» частиною репертуару
 * «Шевчужок», а «Театральне королівство» — репертуаром «Карандашів». Група
 * такої вистави не ставила й до її історії не має відношення; єдине, що
 * правда, — що хтось із її випускників у ній грав.
 *
 * `new-year` — новорічний показ, і тут навпаки: за традицією його готують
 * групи, які ЦЬОГО року випускаються. Тобто репертуар групи для нього —
 * доречний підпис, і саме тому одного прапорця «це не вистава» було б мало:
 * два заходи, і поводитися з ними треба по-різному.
 *
 * Немає поля — звичайна вистава курсу, як і всі 692 записи до появи цього
 * поділу.
 */
export type PlayKind = 'posviata' | 'new-year';

/**
 * Те саме, розширене рядком, — саме такий тип бере поле.
 *
 * Причина точно та сама, що вже записана для `VerificationStatusProp` і для
 * `PlayProgrammeItem.fromProfile`: реєстр приходить із JSON через `satisfies`, а
 * звідти літеральний союз не виводиться — TypeScript бачить `string`, і зріз
 * перестає приводитися до власного типу (`svelte-check` падає рівно на цьому).
 * Порівняння `kind === 'posviata'` при цьому лишається точним.
 */
export type PlayKindProp = PlayKind | (string & {});

export interface Play {
	/** Ключ, на який посилаються групи, анкети й профілі майстрів. */
	id: string;
	title: string;
	year: number;
	/**
	 * Різновид події. Розбір — у докблоці `PlayKind`; коротко: `posviata`
	 * НЕ належить репертуару жодної групи, `new-year` належить.
	 */
	kind?: PlayKindProp;
	verificationStatus?: VerificationStatusProp;
	/** «за казками Оскара Вайльда», «поетична вистава» — як записано в джерелі. */
	author?: string;
	/** Посилання на запис. Розбирає його `parseVideoUrl`, як і всюди на сайті. */
	videoUrl?: string;
	/**
	 * Той самий показ, викладений КІЛЬКОМА частинами.
	 *
	 * Не `programme`: там номери програми — окремі твори вечора, у кожного свій
	 * склад і свій фільтр на сторінці. Тут же одна подія, розрізана на серії
	 * просто тому, що так її виклали. Посвята 2021 має запис цілком і ще чотири
	 * серії; злиття цих двох понять дало б чотири «номери» без жодного твору й
	 * без жодного виконавця.
	 */
	videoParts?: string[];
	/**
	 * Афіша чи знімки показу — для того самого банера, що в групи й фестивалю
	 * (`GroupPhotoBanner`). Шляхи від кореня `static/`; розмір кожного файлу
	 * мусить стояти в `localImages.ts`, інакше банер упаде на `imageSize` уже в
	 * браузері — гейт у `plays.test.ts` перевіряє це наперед.
	 */
	photos?: string[];
	awards?: string[];
	/** Заклад, де показували. */
	institution?: string;
	/**
	 * Група, що грала. Разом із назвою й роком вона й РОЗРІЗНЯЄ подію.
	 *
	 * Це не дрібниця: «Уривки з класики» 2015 йшли двома різними групами в
	 * різних закладах, «Показ етюдів» 2024 — двома групами під номерами 57 і 58.
	 * Ключем «назва + рік» вони склеїлися б в один запис, і половина даних
	 * (учасники однієї, номер другої) зникла б мовчки.
	 */
	theatreGroup?: string;
	/**
	 * Друга назва того самого курсу — з розкладу.
	 *
	 * Один і той самий курс у репертуарі майстра зветься «ТУ-154», а в розкладі
	 * «6Т-16»: номер міняється щороку, назва ні. Доти ці два імені жили в двох
	 * записах про один показ, і саме через них здавалося, що показів два. Після
	 * злиття друге ім'я лишається тут — воно єдиний наявний зв'язок між
	 * позивним курсу й його номером на конкретний рік.
	 */
	theatreGroupAlt?: string;

	/** Номер вистави в ДТШ — наскрізна нумерація школи. */
	number?: number;
	/** «22 травня», «два покази» — уточнення дати, як записано в джерелі. */
	dateNote?: string;
	/** `false` — показ був не в ДТШ. Немає поля — був. */
	isDtsh?: boolean;
	/** Склад — поки вільним текстом, як його вписали. Зіставляє `participantMatch`. */
	participants?: string[];
	/**
	 * Ті, кого в джерелі позначено знаком «+» — додатково поверх складу.
	 *
	 * У «ФФ ПОКАЗИ» осередок «Учасники» має чотири різні значення, і колишній
	 * розбір злив їх в один перелік:
	 *
	 *   повний перелік імен ....... склад цього показу
	 *   `-//-` .................... той самий склад, що рядком вище
	 *   `+Ім'я` ................... ДОДАТКОВО поверх складу групи
	 *   `Ім'я+Ім'я` без пробілу ... пара на одну роль, а не додаток
	 *
	 * Через це «Уривки з класики» 2013 показували шістьох поспіль, хоч у джерелі
	 * стоїть «+Макс Пономаренко»: п'ятеро — основа групи «Freedom», а Максим
	 * прийшов на цей показ. Заміряно: знак «+» стоїть у 19 рядках джерела — 13
	 * осередків із нього починаються, в 11 він усередині переліку, і ще п'ять
	 * разів це пара, а не додаток.
	 *
	 * Тому поле окреме, а не приписка в тексті: інакше «основа» й «прийшли на
	 * один показ» знову злилися б, і жодна перевірка цього не побачила б.
	 */
	extraParticipants?: string[];
	/**
	 * Запрошені професійні актори — окреме поле, а не частина складу.
	 *
	 * Різниця не косметична: `participants` проходять через `participantMatch`
	 * і стають посиланнями на випускників. Гості школи не закінчували, тож
	 * зіставляти їх нема з чим — а спроба призвела б рівно до тієї помилки,
	 * якої тут бояться: «І. Давлятян (Шинкаренко)» знайшла б випускницю
	 * Наталію Шинкаренко, і картка повела б читача не до тієї людини.
	 *
	 * Заміряно на семи гостях «Зони турбулентності»: жоден не збігається з
	 * нашими людьми. «Ф. Азаренко» — не Оксана АЗАРЕНКО з реєстру майстрів,
	 * «І. Макаренко» — не випускник Віталій Макаренко; ініціали інші.
	 */
	guests?: string[];
	/** Номери програми — уривки, етюди. Порожньо: вечір із номерів не складався. */
	programme?: PlayProgrammeItem[];
	/** Майстри, у чиїх профілях ця вистава значиться. */
	masters?: string[];
	/**
	 * Працівники школи, які в показі ГРАЛИ, — з роллю в конкретному номері.
	 *
	 * Окреме поле, а не `masters` і не `participants`, бо це третій різновид
	 * зв'язку, і плутати його з двома наявними означало б втратити рівно те, що
	 * тут важливо.
	 *
	 * `masters` відповідає на «хто цю виставу вчив»: сторінка малює їх під
	 * підписом «Майстри», без ролей, і та сама людина може стояти там, ні разу
	 * не вийшовши на сцену. `participants` — паперовий склад показу вільним
	 * текстом; він теж зіставляється з реєстром працівників, але роль у ньому
	 * сказати нічим, тож картка підписується предметами («Хореографія»). Саме
	 * так «Заручини» 2015 і показували Н. Домбровську та В. Ємцову-Дацюк: вони
	 * стояли окремим переліком «Склад показу» з предметами, хоч на афіші в них
	 * ролі — «Біла фігура» й «Фея».
	 *
	 * Тепер вони йдуть у той самий перелік «Хто грав», що й випускники, і в тому
	 * самому порядку афіші: `roles[].item` вказує номер програми, тож фільтр
	 * уривка й сортування `byBilling` працюють для них без жодного винятку.
	 *
	 * Поле НЕ дублює `participants`: паперовий склад лишається як є, а показ
	 * прибирає з нього тих, кого вже намалював карткою, — тим самим механізмом,
	 * яким випускник зникає з паперу, щойно в нього з'явилася анкета.
	 */
	staff?: PlayStaffRole[];
}

/** Один працівник школи в складі показу: `id` з реєстру плюс роль у номері. */
export interface PlayStaffRole {
	/** `id` із `masters.index.json`. */
	id: string;
	/** Роль у кожному номері окремо — та сама пара, що в складі випускника. */
	roles: CastRole[];
}

/*
 * Приведення тут не потрібне: реєстр вистав збігається з типом ТОЧНО, і це
 * перевіряє компілятор, а не довіра. `as` мовчки погодилося б і з файлом,
 * у якому поля роз'їхалися.
 */
export const PLAYS: readonly Play[] = playsData satisfies readonly Play[];

const BY_ID = new Map(PLAYS.map((p) => [p.id, p]));

/** Вистава за ключем, або `undefined` — гейт стежить, щоб такого не траплялося. */
export function getPlayById(id: string): Play | undefined {
	return BY_ID.get(id);
}

/**
 * Розгортає перелік ключів у вистави, найновіші згори.
 *
 * Ключі, яких немає, мовчки відкидаються: сторінка має показати те, що є, а не
 * впасти. Про саме́ розходження кричить гейт, і кричить на збірці.
 */
export function playsByIds(ids: readonly string[]): Play[] {
	return ids
		.map((id) => BY_ID.get(id))
		.filter((p): p is Play => Boolean(p))
		.sort((a, b) => b.year - a.year || a.title.localeCompare(b.title, 'uk'));
}

/**
 * Адреса сторінки вистави.
 *
 * Типізована як `Pathname` з тієї ж причини, що й шлях майстра: за цим типом
 * `svelte/no-navigation-without-resolve` визнає адресу перевіреною, і описка
 * ловиться компіляцією, а не читачем.
 */
export function playPath(id: string): Pathname {
	return `/projects/galaxy-graduates/plays/${id}` as Pathname;
}

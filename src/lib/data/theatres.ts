import theatresData from './theatres.data.json';
import type { Pathname } from '$app/types';
import type { VerificationStatusProp } from './groups';

/**
 * Театри, у яких працюють (або працювали) наші випускники.
 *
 * ## Навіщо окрема сутність
 *
 * Прохання автора: «по прикладу як у нас є університети варто зробити театри…
 * у неї є "Одеський обласний академічний драматичний театр" замість посилання
 * на сайт театру робимо на внутрішню сторінку а там вже буде посилання на
 * театр».
 *
 * У цьому проханні вже є вся суть. Доти театр існував ЛИШЕ як зовнішнє
 * посилання посеред абзацу «про себе»: «У 2019 році пішла працювати в
 * [Одеський обласний академічний драматичний театр](https://academteatr.od.ua/)
 * актрисою». Таке посилання забирає читача з сайту й нічого не додає: з нього
 * не видно ні того, що в цьому театрі є ще хтось наш, ні того, що дев'ятеро
 * випускників розійшлися по одинадцяти театрах чотирьох міст і двох країн.
 * Тепер посилання веде на СВОЮ сторінку, а сайт театру стоїть уже на ній.
 *
 * ## ЧИМ ТЕАТР ВІДРІЗНЯЄТЬСЯ ВІД ЗАКЛАДУ ОСВІТИ
 *
 * У закладі (`data/institutions.ts`) ребро — це вступ: одна подія, один рік,
 * напрям і майстер курсу. Театр же не приймає раз і назавжди: у ньому
 * ПРАЦЮЮТЬ, і робота має початок, іноді кінець, і посаду. Катерина Кудлач
 * пробула в театрі імені Лесі Українки два роки (2019–2021), Марина Суханова
 * працює з 2019 і досі, Даніела Рибальченко була там на практиці, а Анфіса
 * Лазебна одночасно білетерка й учасниця вистав. Одним полем `year`, як у
 * закладі, цього не скажеш — тому `since`, `until` і `role`.
 *
 * ## Чому в записі є `mention`
 *
 * Первинне джерело тут — ПРОЗА самої людини в анкеті, і слова в ній свої:
 * «театр ляльок ім. Афанасьєва», «театр драми і комедії на лівому березі
 * Дніпра», «Театр Праска 52». Офіційні назви довші й інакші. Якби реєстр
 * тримав лише офіційну назву, зв'язок із анкетою існував би тільки в моїй
 * голові: анкету відредагували б, а сторінка театру далі впевнено показувала б
 * людину.
 *
 * Тому `mention` — це той самий фрагмент, яким людина назвала театр САМА, і
 * гейт вимагає, щоб він досі стояв у її анкеті. Це те саме правило, що вже
 * стереже заклади освіти, тільки там другим джерелом був документ школи, а тут
 * — власний текст випускника.
 */
export interface TheatreMember {
	/** `id` із реєстру випускників — стійкий ключ, а не адреса. */
	id: string;
	/** Рік, з якого людина в театрі. Немає — анкета його не називає. */
	since?: number;
	/** Рік, яким робота скінчилася. Немає — або триває, або невідомо. */
	until?: number;
	/** «актриса», «артист балету», «білетерка» — як сказано в анкеті. */
	role?: string;
	/**
	 * Фрагмент анкети, яким людина назвала цей театр сама.
	 *
	 * Стережеться гейтом: розбір — у докблоці вище. Немає поля — тоді гейт
	 * шукає в анкеті саму назву театру.
	 */
	mention?: string;
	/** Те, чого не скажеш попередніми полями: «студентські вистави», «практика». */
	note?: string;
}

/** Той, кого називає анкета, а реєстру випускників він невідомий. */
export interface UnlistedMember {
	name: string;
	since?: number;
	until?: number;
	role?: string;
	note?: string;
}

export interface Theatre {
	slug: string;
	/** Як театр називають: «Одеська опера», «Золоті Ворота». */
	name: string;
	nameEn?: string;
	/** Повна офіційна назва, якщо вона відома точно. Немає поля — не вигадуємо. */
	fullName?: string;
	/**
	 * Як театр називався ДОТИ.
	 *
	 * Не історична довідка, а робочий інструмент: у шкільних архівах той самий
	 * театр стоїть під давнішою назвою, і без цього поля наступний розбір завів
	 * би другий запис — рівно це й сталося 5 вересня з Одеським обласним, який
	 * у статті названий «російським драматичним». Автор підтвердив, що це один
	 * театр, перейменований.
	 *
	 * Пошук по сайту бере це поле в текст запису, тож театр знаходиться і за
	 * старою назвою.
	 */
	formerNames?: string[];
	city?: string;
	/**
	 * Країни кодами ISO 3166-1 alpha-2 — так само, як у фестивалів і закладів:
	 * назва країни залежить від мови сторінки, а код ні, і за тим самим кодом
	 * малює прапор `CountryFlag`.
	 */
	countries: string[];
	/**
	 * Сайт театру.
	 *
	 * Саме заради нього сторінка й існує в тому вигляді, у якому просив автор:
	 * посилання з анкети веде СЮДИ, а звідси — далі на театр. Одне зовнішнє
	 * посилання на сторінці замість десяти в чужих абзацах.
	 */
	website?: string;
	members: TheatreMember[];
	unlistedMembers?: UnlistedMember[];
	verificationStatus?: VerificationStatusProp;
}

/*
 * Приведення тут не потрібне: реєстр збігається з типом ТОЧНО, і це перевіряє
 * компілятор, а не довіра. `as` мовчки погодилося б і з файлом, у якому поля
 * роз'їхалися.
 */
export const THEATRES: readonly Theatre[] = theatresData satisfies readonly Theatre[];

const BY_SLUG = new Map(THEATRES.map((t) => [t.slug, t]));

/** Театр за адресою, або `undefined` — сторінка тоді віддає 404. */
export function getTheatreBySlug(slug: string): Theatre | undefined {
	return BY_SLUG.get(slug);
}

/**
 * Адреса сторінки театру.
 *
 * Типізована як `Pathname` із тієї ж причини, що шлях вистави, майстра й
 * закладу: за цим типом `svelte/no-navigation-without-resolve` визнає адресу
 * перевіреною, і описка ловиться компіляцією, а не читачем.
 */
export function theatrePath(slug: string): Pathname {
	return `/projects/galaxy-graduates/theatres/${slug}` as Pathname;
}

/** Скільком людям цей театр відомий — разом із тими, кого реєстр не знає. */
export function theatreSize(theatre: Theatre): number {
	return theatre.members.length + (theatre.unlistedMembers?.length ?? 0);
}

/**
 * Театри, у яких працює ця людина, — зворотний зріз реєстру.
 *
 * Повертає пару «театр + що саме про цю роботу відомо», бо роки й посада живуть
 * на ребрі, а не в театрі.
 */
export function theatresOfGraduate(
	graduateId: string
): { theatre: Theatre; member: TheatreMember }[] {
	const out: { theatre: Theatre; member: TheatreMember }[] = [];
	for (const theatre of THEATRES) {
		const member = theatre.members.find((m) => m.id === graduateId);
		if (member) out.push({ theatre, member });
	}
	return out;
}

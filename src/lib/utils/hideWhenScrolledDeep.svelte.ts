/**
 * «Читач опустився глибоко» — одна величина, придатна для плашки, що висить над
 * змістом.
 *
 * ## Навіщо окремо від компонента
 *
 * Першим власником був `MasterGraduateFlow`: потік учнів висить
 * `position: fixed` праворуч на всю висоту, і доки читач угорі сторінки — це
 * доречно, бо потік і є те, чим сторінка майстра починається. Але щойно він
 * гортає до груп, фестивалів і репертуару, той самий стовпець перекриває праву
 * частину рядків: обличчя лягають на позначки груп і номери курсів.
 *
 * Разом із цією логікою компонент переростав стелю `structure.test.ts`. І справа
 * не лише в рядках: «де саме читач» — це не про траєкторії зірок, а про
 * сторінку.
 *
 * ## Чому за ГЛИБИНОЮ, а не за напрямком
 *
 * Спершу тут був напрямок: поїхав униз — сховати, вгору — показати. Виглядало
 * розумно й поводилося зле. Напрямок нічого не знає про те, ДЕ читач: рух на
 * вісім пікселів угорі сторінки ховав потік, який нікому не заважав, а такий
 * самий рух угору біля підвалу повертав стовпець просто на текст. Плашка
 * смикалася від кожного дотику до тачпада, і передбачити її стан було годі.
 *
 * Глибина відповідає на те саме питання прямо: потік заважає тоді, коли під ним
 * пішов інший зміст, а це властивість ПОЗИЦІЇ, не руху. Тому й порогу дрижання
 * більше немає — його заводили проти інерційного скролу, який міняв напрямок
 * кілька разів за секунду. Позиція так не стрибає.
 *
 * ## Звідки 532
 *
 * Погоджене значення: приблизно на цій глибині картка майстра йде з екрана і
 * починаються розділи, чиї рядки стовпець перекривав би.
 */
/** Глибина, глибше за яку плашку прибирають. */
export const HIDE_DEPTH = 532;

/**
 * Саме РІШЕННЯ — чиста функція, без рун і без `window`.
 *
 * Виділена, щоб її перевіряв звичайний тест: браузерна панель у цьому оточенні
 * прокрутку не диспетчить, тож поведінку «зникає глибше, повертається вище» в
 * ній не заміряти. Реактивна обгортка нижче лишається тонкою настільки, що
 * ламатися в ній нічому.
 *
 * СУВОРА нерівність: «опустився БІЛЬШЕ ніж на 532» означає, що рівно на 532
 * плашка ще видима.
 */
export function hiddenAtDepth(y: number, depth: number): boolean {
	return y > depth;
}

export interface HideWhenScrolledDeep {
	/** `true` — читач глибоко, і плашку варто прибрати. */
	readonly hidden: boolean;
}

export function hideWhenScrolledDeep(depth = HIDE_DEPTH): HideWhenScrolledDeep {
	let hidden = $state(false);

	/*
	 * Слухач у `$effect`, а не в тілі функції: на сервері ефекти не виконуються,
	 * тож ні `window`, ні пререндер це не зачіпає. Прибирання слухача — у
	 * поверненій функції, тобто час життя дорівнює часу життя компонента.
	 *
	 * Перше значення читається одразу, а не з першої події: інакше плашка
	 * висіла б на місці, доки читач не торкнеться колеса — а він міг зайти за
	 * посиланням із якорем і опинитися глибоко з самого початку.
	 */
	$effect(() => {
		const onScroll = () => {
			hidden = hiddenAtDepth(window.scrollY, depth);
		};
		onScroll();
		window.addEventListener('scroll', onScroll, { passive: true });
		return () => window.removeEventListener('scroll', onScroll);
	});

	return {
		get hidden() {
			return hidden;
		}
	};
}

import { describe, expect, it } from 'vitest';
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { пропустити } from './installImageReveal';

/**
 * Контракт винятків плавної появи.
 *
 * Сам механізм перевіряти тут нема чим: у jsdom немає ні мережі, ні кадрів
 * рендеру, тож `load` не настає, а перехід не зрушує — перевірка «зображення
 * показалося» була б перевіркою заглушки. Замір робився в браузері й записаний
 * у шапці модуля.
 *
 * А от ВИНЯТКИ зламати мовчки легко, і саме вони тут. Виняток лишився ОДИН —
 * `[data-reveal="own"]`, зображення з власною появою (зірки галактики: своя
 * черга, точка-плейсхолдер, збільшення). Перелік таких файлів БУВ БИ ризиком,
 * тому нижче стоїть храповик: атрибут дозволений лише у названих файлах, і
 * мовчки «відписатися» від появи не вийде.
 *
 * ## Чому головний знімок більше не виняток
 *
 * `[fetchpriority]` виключався першою редакцією — і саме на ньому дефект і
 * побачили: герой головної (baseline JPEG 848 КБ, 4068×3070) малювався згори
 * вниз, тобто смужка фото вгорі й суцільний блок під нею. Перевірка нижче
 * тримає це рішення явно, щоб «оптимізацію LCP» не повернули назад, не
 * прочитавши, чим вона колись обійшлася.
 *
 * Зворотний експеримент (`PIT-REVERSE-EXPERIMENT`): `data-reveal="own"`
 * дописано в `ContentCard.svelte` — храповик назвав файл. У `пропустити`
 * повернено перевірку `fetchpriority` — упала перевірка про головний знімок.
 */

const МОДУЛЬ = 'src/lib/utils/installImageReveal.ts';

/** Файли, яким дозволено володіти появою самотужки. Перелік лише скорочується. */
const ВЛАСНА_ПОЯВА = ['src/lib/components/GraduateStar.svelte'];

const шлях = (p: string) => p.split('\\').join('/');
function обійти(dir: string, out: string[] = []): string[] {
	for (const entry of readdirSync(dir)) {
		const p = join(dir, entry);
		if (statSync(p).isDirectory()) обійти(p, out);
		else out.push(шлях(p));
	}
	return out;
}

const зображення = (attrs: Record<string, string>) => {
	const img = document.createElement('img');
	for (const [k, v] of Object.entries(attrs)) img.setAttribute(k, v);
	return img;
};

describe('предикат винятків', () => {
	it('звичайне зображення механізм бере', () => {
		expect(пропустити(зображення({ src: '/photo/x.jpg' }))).toBe(false);
	});

	it('головний знімок сторінки — БЕРЕ, і це навмисно', () => {
		// Виняток для `[fetchpriority]` існував і був скасований: герой головної
		// малювався згори вниз, бо це baseline JPEG на 848 КБ. Часткове
		// малювання — це зламаний вигляд сторінки, і жоден виграш LCP його не
		// виправдовує. Правильна ціна повертається зменшенням самого файлу.
		expect(пропустити(зображення({ src: '/photo/x.jpg', fetchpriority: 'high' }))).toBe(false);
		expect(пропустити(зображення({ src: '/photo/x.jpg', fetchpriority: 'low' }))).toBe(false);
		expect(пропустити(зображення({ src: '/photo/x.jpg', loading: 'eager' }))).toBe(false);
	});

	it('зображення з власною появою — не бере', () => {
		expect(пропустити(зображення({ src: '/g/x.webp', 'data-reveal': 'own' }))).toBe(true);
		// Будь-яке інше значення нічого не виключає: опт-аут мусить бути явним.
		expect(пропустити(зображення({ src: '/g/x.webp', 'data-reveal': 'later' }))).toBe(false);
	});

	it('уже взяте зображення не береться вдруге', () => {
		// Спостерігач бачить той самий елемент стільки разів, скільки його
		// переставляли в дереві. Без позначки друга спроба ховала б уже показане.
		expect(пропустити(зображення({ src: '/photo/x.jpg', 'data-revealed': '' }))).toBe(true);
	});
});

describe('храповик власної появи', () => {
	const компоненти = обійти('src').filter((f) => f.endsWith('.svelte'));

	it('перевірка жива: компоненти знайдено, модуль на місці', () => {
		expect(компоненти.length, 'обхід src/ не знайшов компонентів').toBeGreaterThan(50);
		expect(readFileSync(МОДУЛЬ, 'utf8')).toContain('data-reveal');
	});

	it('`data-reveal="own"` стоїть лише у дозволених файлах', () => {
		const самозванці = компоненти
			.filter((f) => !ВЛАСНА_ПОЯВА.includes(f))
			.filter((f) => /data-reveal=["']own["']/.test(readFileSync(f, 'utf8')));
		expect(
			самозванці,
			'ці компоненти відписалися від плавної появи, не маючи власної — ' +
				'або зробити свою, або прибрати атрибут: ' + самозванці.join(', ')
		).toEqual([]);
	});

	it('перелік дозволених не містить зайвого', () => {
		// Той самий храповик, що в стелях розміру: файл, який більше не володіє
		// появою, з переліку йде тим самим комітом, інакше дозвіл переживе причину.
		const без = ВЛАСНА_ПОЯВА.filter(
			(f) => !/data-reveal=["']own["']/.test(readFileSync(f, 'utf8'))
		);
		expect(
			без,
			'ці файли більше не мають `data-reveal="own"` — прибрати їх із переліку: ' + без.join(', ')
		).toEqual([]);
	});
});

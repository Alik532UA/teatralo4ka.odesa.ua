/**
 * Розкладка на рядки, у якій НАСТУПНИЙ рядок не коротший за попередній.
 *
 * ## Навіщо, якщо є `flex-wrap`
 *
 * Природний перенос набиває перший рядок до відмови, а в останній кидає
 * залишок: три плашки, з яких у рядок влазить дві, дають 2+1 — і одинока
 * плашка під повним рядком читається як «щось не вмістилося». Автор попросив
 * протилежне (2026-09-03): «якщо 3 групи, то 1 в першому рядку а дві в другому,
 * якщо 4 групи то 2 і 2, якщо 5 груп то 2 і 3 — у другому рядку не повинно бути
 * менше позицій, ніж у першому».
 *
 * Це та сама думка, що в `themeColumns` для кнопок тем: одинока позиція в
 * останньому рядку виглядає як помилка верстки, а не як частина групи.
 *
 * ## Правило
 *
 * Кількість рядків беремо мінімальну, за якої все вміщається:
 * `ceil(n / perRow)`. Далі ділимо порівну, а залишок віддаємо ПОСЛІДНІМ
 * рядкам — тому кожен наступний рядок або такий самий, або на одну позицію
 * довший. Ніколи не коротший.
 *
 * Приклади при `perRow = 2`: 3 → [1, 2]; 4 → [2, 2]; 5 → [2, 3]
 * (два рядки по 2 не вмістять п'ять, тож рядків три: [1, 2, 2]).
 *
 * Чиста функція без DOM: правило перевіряється тестом, а не оком на сторінці.
 */
export function balancedRows<T>(items: readonly T[], perRow: number): T[][] {
	const total = items.length;
	if (total === 0) return [];
	// Менше за одну позицію в рядку не буває: інакше рядків стало б безліч.
	const capacity = Math.max(1, Math.floor(perRow));
	if (total <= capacity) return [[...items]];

	const rows = Math.ceil(total / capacity);
	const base = Math.floor(total / rows);
	/* Скільком рядкам дістанеться на одну позицію більше — і це саме ОСТАННІ. */
	const extra = total % rows;

	const out: T[][] = [];
	let at = 0;
	for (let i = 0; i < rows; i++) {
		const size = base + (rows - i <= extra ? 1 : 0);
		out.push(items.slice(at, at + size));
		at += size;
	}
	return out;
}

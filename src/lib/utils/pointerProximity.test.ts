import { describe, expect, it } from 'vitest';
import { distanceToBox, isNearBox } from './pointerProximity';

/**
 * Відстань до прямокутника й зона наближення.
 *
 * ## Що саме стережеться
 *
 * 1. Відстань до ПРЯМОКУТНИКА, а не до центра. Рядок кнопок галактики широкий:
 *    від лівого його краю до центра — половина рядка, і за відстанню до центра
 *    курсор просто над кнопкою вважався б далеким.
 * 2. Усередині — нуль. Інакше кнопка під курсором не отримала б найяскравішого
 *    рівня.
 * 3. Межа СУВОРА: рівно на відстані зони — ще далеко.
 * 4. По діагоналі рахується гіпотенуза, а не сума катетів: інакше зона мала б
 *    форму ромба, і кут між «збоку» й «зверху» вмикався б помітно раніше.
 *
 * ## Зворотні експерименти (AI-AGENT-PITFALLS-v8 § 1.1)
 *
 * 1. Замінити `Math.hypot(dx, dy)` на `dx + dy` — падає перевірка діагоналі.
 * 2. Прибрати `0` із `Math.max(...)` — від'ємні відступи для точки всередині
 *    дадуть ненульову відстань, падає «усередині нуль».
 * 3. Замінити `<` на `<=` — падає «рівно на межі ще далеко».
 *
 * Усі три прогнані.
 */
const БОКС = { left: 100, top: 100, right: 300, bottom: 140 };

describe('distanceToBox', () => {
	it('усередині — нуль', () => {
		expect(distanceToBox({ x: 200, y: 120 }, БОКС)).toBe(0);
		expect(distanceToBox({ x: 100, y: 100 }, БОКС), 'кут теж усередині').toBe(0);
	});

	it('збоку — рівно відступ по одній осі', () => {
		expect(distanceToBox({ x: 60, y: 120 }, БОКС)).toBe(40);
		expect(distanceToBox({ x: 340, y: 120 }, БОКС)).toBe(40);
		expect(distanceToBox({ x: 200, y: 70 }, БОКС)).toBe(30);
		expect(distanceToBox({ x: 200, y: 190 }, БОКС)).toBe(50);
	});

	it('по діагоналі — ГІПОТЕНУЗА, а не сума катетів', () => {
		/* 30 ліворуч і 40 вище кута: 3-4-5, тобто 50, а не 70. */
		expect(distanceToBox({ x: 70, y: 60 }, БОКС)).toBe(50);
	});

	it('до ПРЯМОКУТНИКА, а не до центра', () => {
		/*
		 * Точка просто над лівим краєм. До центра (200, 120) було б понад сто
		 * пікселів, до прямокутника — двадцять.
		 */
		expect(distanceToBox({ x: 100, y: 80 }, БОКС)).toBe(20);
	});
});

describe('isNearBox', () => {
	it('ближче за зону — близько', () => {
		expect(isNearBox({ x: 60, y: 120 }, БОКС, 120)).toBe(true);
	});

	it('рівно на межі — ще ДАЛЕКО', () => {
		expect(isNearBox({ x: 100 - 120, y: 120 }, БОКС, 120)).toBe(false);
	});

	it('далі за зону — далеко', () => {
		expect(isNearBox({ x: 0, y: 0 }, БОКС, 120)).toBe(false);
	});
});

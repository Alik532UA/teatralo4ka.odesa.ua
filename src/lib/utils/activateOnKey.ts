/**
 * Enter і Space активують елемент, який лише ВИГЛЯДАЄ кнопкою.
 *
 * ACCESSIBILITY-v8 § 2 (WCAG 2.1.1, рівень A): `role="button"` разом із
 * `tabindex="0"` — це обіцянка. Елемент потрапляє у Tab-порядок, читалка
 * називає його кнопкою, і користувач тисне Enter. Якщо на ньому лише
 * `onclick`, не відбувається нічого — і це найтихіший вид недоступності:
 * фокус видно, дія не працює, жодної помилки ніде.
 *
 * ## Чому окремий модуль, а не інлайн у розмітці
 *
 * Місць два (плитки галереї на головній і на `/about`), і обидва мають
 * поводитися однаково. Інлайн-варіант із канону — це три умови в атрибуті,
 * скопійовані двічі; розійтися вони можуть у будь-якій із трьох. Заодно
 * `preventDefault` стає перевіреним один раз, а не двічі на віру.
 *
 * ## Чому не `<button>`
 *
 * Нативна кнопка була б канонічно правильнішою (ACCESSIBILITY-v8 § 2:
 * `div role="button"` — виняток для drag handle й подібних). Тут вона тягне
 * скидання власного вигляду кнопки (`appearance`, тло, рамка, шрифт) у двох
 * різних розкладках bento-сітки, тобто візуальну зміну там, де потрібна лише
 * клавіатурна. Заміна на `<button>` лишається окремою задачею; вона записана
 * в PROJECT-CONTEXT.md, щоб не виглядала зробленою.
 *
 * ## Space обов'язково з preventDefault
 *
 * Інакше браузер виконає СВОЮ дію для пробілу — прокрутку сторінки на екран
 * уперед — і зробить це РАЗОМ з активацією. Виглядає як «клік працює, але
 * сторінку кидає».
 */
export function activateOnKey(activate: () => void): (event: KeyboardEvent) => void {
	return (event: KeyboardEvent) => {
		// Лише ці дві клавіші: ARIA-контракт кнопки не обіцяє нічого іншого,
		// а перехоплювати решту означало б ламати навігацію по сторінці.
		if (event.key !== 'Enter' && event.key !== ' ') return;
		event.preventDefault();
		activate();
	};
}

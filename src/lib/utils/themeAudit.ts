import { AA_NORMAL, contrast, luminance, parseColor, type Rgb } from './contrast';

/**
 * Дві задачі лабораторії кольорів, які є ЧИСТОЮ АРИФМЕТИКОЮ, а не станом.
 *
 * Обидві народилися з одного питання дизайнера: «а що з цим не так і як
 * полагодити». Панель доти вміла лише сказати «не проходить» — і замовкала на
 * найцікавішому місці.
 *
 * Живуть окремим модулем, бо не залежать ні від документа, ні від сховища, ні
 * від рун: на вхід кольори, на вихід числа. Через це їх видно юніт-тестам, а
 * не лише оку в браузері.
 */

/** Наскільки темніша або світліша версія кольору проходить поріг. */
export interface ShadeFix {
	/** Готовий `#rrggbb`, який уже проходить. */
	value: string;
	/** Куди рухали: темніше чи світліше. */
	direction: 'darker' | 'lighter';
	/** Який контраст вийшов. */
	ratio: number;
}

const у16 = (n: number) => Math.round(n).toString(16).padStart(2, '0');
const вРядок = ([r, g, b]: Rgb) => `#${у16(r)}${у16(g)}${у16(b)}`;

/**
 * Змішує колір із чорним або білим на задану частку.
 *
 * Саме змішування, а не зсув яскравості в HSL: змішування зберігає ВІДТІНОК —
 * синій лишається синім, — тоді як робота з насиченістю на краях діапазону
 * зводить колір до сірого. Дизайнер просив «трохи темніше», а не «інший
 * колір».
 */
function змішати(колір: Rgb, до: 0 | 255, частка: number): Rgb {
	return колір.map((c) => c + (до - c) * частка) as Rgb;
}

/**
 * Найближчий відтінок переднього плану, який проходить поріг на цьому тлі.
 *
 * ## Чому рухається саме текст, а не тло
 *
 * Тло — це велика площина, яку дизайнер обирав першою і свідомо; текст на ній
 * підбирають. Зрушити тло означало б переробити вигляд сторінки заради однієї
 * пари, а зрушити текст — залишити задум і зробити його читабельним.
 *
 * ## Чому крок, а не формула
 *
 * Точну відповідь дала б інверсія формули WCAG, але вона неоднозначна: одному
 * контрасту відповідають два рішення (світліше й темніше), і яке з них ближче
 * до задуму — питання не арифметики. Тому перебираються обидва напрямки
 * дрібним кроком, і перемагає той, що дав відповідь раніше, тобто менше
 * змінив колір.
 *
 * `null` означає «немає» чесно: на середньо-сірому тлі поріг 4.5 не бере ані
 * чорний, ані білий, і вигадувати відповідь тут гірше за мовчання.
 */
export function suggestShade(fg: string, bg: string, threshold = AA_NORMAL): ShadeFix | null {
	const текст = parseColor(fg);
	const тло = parseColor(bg);
	if (!текст || !тло) return null;
	if (contrast(текст, тло) >= threshold) return null;

	/* Тло світле — текст треба темнішати, і навпаки. Починаємо з того боку, що
	   майже напевно спрацює, але перевіряємо обидва: на середніх тонах виграє
	   протилежний. */
	const тлоСвітле = luminance(тло) > 0.5;
	const напрямки: Array<{ до: 0 | 255; name: ShadeFix['direction'] }> = тлоСвітле
		? [
				{ до: 0, name: 'darker' },
				{ до: 255, name: 'lighter' }
			]
		: [
				{ до: 255, name: 'lighter' },
				{ до: 0, name: 'darker' }
			];

	for (const { до, name } of напрямки) {
		for (let частка = 0.04; частка <= 1.0001; частка += 0.04) {
			const кандидат = змішати(текст, до, частка);
			const r = contrast(кандидат, тло);
			if (r >= threshold) return { value: вРядок(кандидат), direction: name, ratio: r };
		}
	}
	return null;
}

/** Вердикт однієї пари в одній темі. */
export interface ThemePairVerdict {
	label: string;
	ratio: number | null;
	passes: boolean | null;
}

/** Що вийшло в темі: її назва й пари, які не пройшли. */
export interface ThemeVerdict {
	theme: string;
	failed: ThemePairVerdict[];
	/** Скільки пар узагалі порахувалося — щоб «нуль поганих» не плутати з «нічого не порахували». */
	measured: number;
}

/**
 * Чи проходять пари, якщо ці кольори покласти в КОЖНУ тему.
 *
 * ## Питання, на яке це відповідає
 *
 * Панель править одну тему, а гейт контрасту в CI міряє всі шість. Дизайнер
 * бачив зелене в панелі й червоне в CI — і причина щоразу та сама: він
 * переписав три токени з тринадцяти, а решта десять у сусідній темі інші.
 *
 * Тому тут для кожної теми береться ЇЇ власний набір, а зверху кладуться
 * правки дизайнера — рівно те, що станеться, якщо той самий блок вставити в
 * кожен файл теми.
 *
 * ## Чому функція нічого не читає з документа
 *
 * Читання теми — робота панелі: вона вміє тимчасово перемкнути `data-theme` і
 * зняти значення. Тут лишається арифметика над уже знятими числами, і саме
 * тому цю частину видно юніт-тестам.
 */
export function auditThemes(
	perTheme: Record<string, Record<string, string>>,
	overrides: Record<string, string>,
	pairs: readonly { fg: string; bg: string; label: string }[],
	threshold = AA_NORMAL
): ThemeVerdict[] {
	return Object.entries(perTheme).map(([theme, власні]) => {
		const зведене = { ...власні, ...overrides };
		let measured = 0;
		const failed: ThemePairVerdict[] = [];
		for (const пара of pairs) {
			const fg = parseColor(зведене[пара.fg] ?? '');
			const bg = parseColor(зведене[пара.bg] ?? '');
			if (!fg || !bg) continue;
			measured += 1;
			const ratio = contrast(fg, bg);
			if (ratio < threshold) failed.push({ label: пара.label, ratio, passes: false });
		}
		return { theme, failed, measured };
	});
}

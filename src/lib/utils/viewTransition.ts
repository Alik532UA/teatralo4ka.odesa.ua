import { onNavigate } from '$app/navigation';

/**
 * Плавні переходи між сторінками через View Transitions API.
 *
 * Доти перехід був різким: SvelteKit міняє вміст миттєво, тож стара сторінка
 * зникала в тому ж кадрі, у якому з'являлася нова. Браузер уміє зняти обидві й
 * перевести одну в іншу — треба лише сказати йому, коли саме міняється вміст.
 *
 * Сама анімація описана в `global.css` (`::view-transition-old/new`), бо це
 * псевдоелементи документа: до `<style>` компонента вони не належать, і
 * scoping Svelte до них не дотягується.
 *
 * ## Чому не CSS-правило `@view-transition { navigation: auto }`
 *
 * Воно вмикає переходи лише для НАВІГАЦІЇ БРАУЗЕРА (перехід між документами).
 * Тут же навігація клієнтська: документ той самий, змінюється лише вміст, і
 * браузер про цю зміну сам не дізнається. Тому потрібен саме `onNavigate`.
 */
export function installViewTransitions(): void {
	onNavigate((navigation) => {
		/*
		 * Підтримки немає — переходимо як раніше. Перевірка не косметична:
		 * `startViewTransition` немає в Firefox і в старих Safari, а виклик
		 * неіснуючого методу зупинив би НАВІГАЦІЮ, а не лише анімацію.
		 */
		if (!document.startViewTransition) return;

		/*
		 * Прохання про менший рух виконується тут, а не самою лише CSS: без
		 * цього браузер усе одно знімає й порівнює два кадри цілої сторінки на
		 * кожному переході — робота, яку ніхто не побачить.
		 */
		if (window.matchMedia('(prefers-reduced-motion: reduce)').matches) return;

		/*
		 * Перехід між тими самими сторінками (клік по вже відкритому пункті
		 * меню, зміна лише параметрів пошуку) анімувати нема чого: обидва
		 * знімки однакові, і вийшло б блимання без причини. `pushState` для
		 * картки випускника — саме такий випадок.
		 */
		if (navigation.from?.url.pathname === navigation.to?.url.pathname) return;

		/*
		 * ПЕРЕХІД СПОСТЕРІГАЄ ЗА НАВІГАЦІЄЮ, А НЕ ТРИМАЄ ЇЇ.
		 *
		 * Доти тут стояв взірець із документації SvelteKit: повернути обіцянку,
		 * яка резолвиться ВСЕРЕДИНІ зворотного виклику `startViewTransition`.
		 * Поки вона висить, SvelteKit не міняє сторінку — тобто перехід тримає
		 * навігацію. І якщо в цю мить прилітає «Назад», навігація губиться
		 * назовсім: адресу браузер уже змінив, а на екрані лишається ПОПЕРЕДНЯ
		 * сторінка. Не «повільно» — НАЗАВЖДИ.
		 *
		 * Це дефект сайту, а не прогону, і він дістається людині, а не лише
		 * тестові. Заміряно на зібраній статиці, телефон Pixel 7, БЕЗ жодного
		 * уповільнення: натиснути посилання й одразу «Назад» — 7 застрягань із
		 * 20. З паузою 250 мс перед «Назад» — 0 із 15, тобто вікно вразливості
		 * дорівнює тривалості самої анімації. З вимкненими переходами — 0 із 12.
		 *
		 * Пробували інакше, і числа названі, бо вони суперечать інтуїції:
		 *
		 *   рвати перший перехід (`skipTransition`) ..... 6 застрягань із 20
		 *   чекати, поки перший добіжить ................ 3 із 25
		 *   не анімувати «Назад» ........................ 6 із 20
		 *   ковтати відмову `navigation.complete` ....... 1 із 20
		 *
		 * Жодне не прибирало причину, бо причина одна: НАВІГАЦІЯ ЧЕКАЛА НА
		 * АНІМАЦІЮ. Тут вона більше не чекає — обіцянка не повертається зовсім.
		 * Знімок робиться, SvelteKit одразу міняє вміст, а зворотний виклик
		 * лише дочікується завершення навігації, щоб браузеру було що з чим
		 * порівняти. Втратити навігацію в цій схемі нема де.
		 *
		 * `catch` обов'язковий: коли навігацію витісняє наступна, `complete`
		 * відхиляється з «navigation aborted», і без нього це щоразу падало б у
		 * консоль людині, яка просто швидко натиснула «Назад».
		 */
		const перехід = document.startViewTransition(async () => {
			await navigation.complete.catch(() => {});
		});

		/*
		 * Наступний перехід згортає цей, і браузер відхиляє обидві обіцянки
		 * `AbortError: Transition was skipped`. Для сайту це не подія — людина
		 * просто натиснула швидше, ніж добігла анімація, — але без цих двох
		 * рядків воно летить їй у консоль справжньою помилкою сторінки.
		 */
		перехід.ready.catch(() => {});
		перехід.finished.catch(() => {});
	});
}

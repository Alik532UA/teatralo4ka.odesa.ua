import { describe, it, expect } from 'vitest';
import { fadeEdges } from './scrollFade';

/**
 * Тест на чисту частину згасання. Сам атачмент тут не монтується — з тієї ж
 * причини, що й у `focusTrap.test.ts`: середовища компонентних тестів у
 * проєкті ще немає. Перевіряється те, у чому справді буває помилка — котрий
 * край згасає на котрій позиції прокрутки.
 */
describe('fadeEdges', () => {
	it('нічого не згасає, коли вміст уміщається цілком', () => {
		expect(fadeEdges(0, 400, 400)).toBe('');
	});

	it('згори списку згасає лише нижній край', () => {
		expect(fadeEdges(0, 1200, 400)).toBe('bottom');
	});

	it('усередині списку згасають обидва краї', () => {
		expect(fadeEdges(300, 1200, 400)).toBe('top bottom');
	});

	it('унизу списку згасає лише верхній край', () => {
		expect(fadeEdges(800, 1200, 400)).toBe('top');
	});

	it('субпіксельний залишок прокрутки не вважається краєм', () => {
		expect(fadeEdges(0.4, 400.6, 400)).toBe('');
	});
});

/**
 * Медіа статті: один перелік для двох джерел.
 *
 * ## Що було до цього
 *
 * У новини з бази — ОДНА обкладинка й ОДНЕ відео (`ArticleTranslation.coverUrl`
 * і `videoUrl`), у новини з коду — перелік знімків плюс одне відео. Тобто «два
 * фото» з адмінки додати було нікуди, а «друге відео» — узагалі ніде. Автор
 * попросив рівно це: «можливість додавати багато фотографій та багато відео».
 *
 * Тому обидва джерела зводяться до одного переліку `ArticleMediaItem[]`, у
 * якому порядок задає автор, а вид кожного елемента названий явно. Старі поля
 * нікуди не поділися: `legacyMedia` перетворює їх у той самий перелік, тож
 * жодну наявну новину не треба переписувати.
 *
 * ## Чому чисті функції, а не методи компонента
 *
 * Тут живуть рішення, які видно лише в трьох станах одночасно: «одне фото й
 * одне відео», «багато медіа», «розкладка послідовністю». Кожне з них
 * ламається тихо — сторінка не падає, вона просто показує не те, — і саме тому
 * перевіряється тестом, а не оком у браузері.
 */

export type MediaKind = 'photo' | 'video';

/**
 * Пропорція плитки, яку вибирає автор новини.
 *
 * Автор попросив саме вибір, а не одне число: «в середині сторінки з'являється
 * можливість опціонально вибирати чи квадратне зображення, чи вертикальне, чи
 * горизонтальне». У переліку новин при цьому лишається вертикальна картка — там
 * пропорція належить сітці переліку, а не новині.
 */
export type MediaShape = 'square' | 'portrait' | 'landscape';

/**
 * Як показувати медіа.
 *
 * `column` — стовпець плиток збоку від тексту, решта широкою мозаїкою під ним.
 * `sequence` — «медіа не об'єднані під одним блоком, а йдуть один за одним»:
 * кожен елемент на всю ширину, у порядку, який задав автор.
 */
export type MediaLayout = 'column' | 'sequence';

export interface ArticleMediaItem {
	kind: MediaKind;
	/** Фото — шлях від кореня `static/` або зовнішня адреса; відео — посилання на запис. */
	url: string;
	/** Підпис і текст для читалки. */
	alt?: string;
	/** `object-position`, коли центр плитки ріже не те, що треба. */
	position?: string;
	/** Справжні розміри знімка — щоб під нього відвели місце до завантаження. */
	width?: number;
	height?: number;
}

export const MEDIA_SHAPES: readonly MediaShape[] = ['square', 'portrait', 'landscape'];
export const MEDIA_LAYOUTS: readonly MediaLayout[] = ['column', 'sequence'];

/**
 * Типова пропорція — ВЕРТИКАЛЬНА.
 *
 * Спершу тут стояв квадрат, і це була моя помилка: квадратними стали всі
 * наявні новини, зокрема ті, що прийшли з бази й пропорції не задавали. Автор
 * виправив одразу: «існуючі новини не треба було всі змінювати на квадрат; ті,
 * де параметр не виставлений явно, повинні бути вертикальні; я просив квадрат
 * лише для новини про вісімнадцять студентів».
 *
 * Тобто типове значення — це те, як сайт виглядав ДОТИ, а квадрат ставиться
 * там, де його попросили. Вибір при цьому лишається в кожної новини.
 */
export const DEFAULT_MEDIA_SHAPE: MediaShape = 'portrait';

/** Пропорція для CSS `aspect-ratio`. */
export function shapeRatio(shape: MediaShape = DEFAULT_MEDIA_SHAPE): string {
	if (shape === 'portrait') return '9 / 16';
	if (shape === 'landscape') return '16 / 9';
	return '1 / 1';
}

/**
 * Висота плитки, поділена на її ширину.
 *
 * Потрібне не для CSS, а для арифметики: скільком плиткам стати в стовпець,
 * рахується від їхньої висоти, а виміряти в компоненті можна лише ШИРИНУ
 * колонки — висоту задає пропорція.
 */
export function shapeFactor(shape: MediaShape = DEFAULT_MEDIA_SHAPE): number {
	if (shape === 'portrait') return 16 / 9;
	if (shape === 'landscape') return 9 / 16;
	return 1;
}

/**
 * Чи це та сама пара «одне фото + одне відео», яка живе в ОДНОМУ контейнері.
 *
 * Автор просив зберегти саме цю поведінку: «коли одна фотографія і одне відео,
 * то як зараз вони міняються в середині одного контейнера по запиту
 * користувача». Тобто це не спрощення заради лінощів, а названий випадок: два
 * елементи — і один із них запис.
 */
export function isSwapPair(media: readonly ArticleMediaItem[]): boolean {
	if (media.length !== 2) return false;
	const фото = media.filter((m) => m.kind === 'photo').length;
	const відео = media.filter((m) => m.kind === 'video').length;
	return фото === 1 && відео === 1;
}

/**
 * Медіа зі старих полів «одна обкладинка + одне відео».
 *
 * Порядок саме такий — спершу знімок: у картці переліку обкладинкою стає перше
 * фото, і в новин із бази це має лишитися тим самим знімком, що й доти.
 */
export function legacyMedia(
	coverUrl?: string | null,
	videoUrl?: string | null,
	alt?: string
): ArticleMediaItem[] {
	const out: ArticleMediaItem[] = [];
	const фото = (coverUrl ?? '').trim();
	const відео = (videoUrl ?? '').trim();
	if (фото) out.push({ kind: 'photo', url: фото, alt });
	if (відео) out.push({ kind: 'video', url: відео, alt });
	return out;
}

/** Перше фото переліку — обкладинка картки в переліку новин. */
export function coverOf(media: readonly ArticleMediaItem[]): ArticleMediaItem | undefined {
	return media.find((m) => m.kind === 'photo');
}

/**
 * Скільком плиткам стати в стовпець заввишки `textHeight`.
 *
 * Автор вибрав саме це правило: «скільки влізе по висоті тексту, решта —
 * широкою мозаїкою нижче». Тому число не константа, а обчислення — висота
 * тексту різна в українській та англійській, різна на телефоні й міняється,
 * щойно читач змінить масштаб.
 *
 * Щонайменше одна: інакше при короткому тексті (як у новині, де поки що один
 * рядок) стовпець був би порожній, а сторінка — без обкладинки взагалі.
 */
export function fitCount(textHeight: number, tileHeight: number, gap: number): number {
	if (!(tileHeight > 0)) return 1;
	const крок = tileHeight + gap;
	if (!(крок > 0)) return 1;
	return Math.max(1, Math.floor((textHeight + gap) / крок));
}

/**
 * «Схований, бо читач іде сторінкою вниз» — одна величина, придатна для класу.
 *
 * ## Навіщо окремо від компонента
 *
 * Першим власником був `MasterGraduateFlow`: потік учнів висить
 * `position: fixed` праворуч на всю висоту, і доки читач угорі сторінки — це
 * доречно, бо потік і є те, чим сторінка майстра починається. Але щойно він
 * гортає до груп, фестивалів і репертуару, той самий стовпець перекриває праву
 * частину рядків: обличчя лягають на позначки груп і номери курсів.
 *
 * Разом із цією логікою компонент переростав стелю `structure.test.ts` на 19
 * рядків. І справа не лише в рядках: «куди рухається читач» — це не про
 * траєкторії зірок, а про сторінку. Тому тут, і тому придатне будь-якій іншій
 * плашці, що висить над змістом.
 *
 * ## Чому за НАПРЯМКОМ, а не за позицією
 *
 * «Нижче за N пікселів» означало б, що на короткому екрані плашки не видно вже
 * вгорі, а внизу сторінки вона зникає назавжди. Напрямок відповідає на те, що
 * читач робить ЗАРАЗ: читає далі чи повертається до початку.
 *
 * ## Чому потрібен порог
 *
 * Без нього інерційний скрол на тачпаді перемикає напрямок кілька разів за
 * секунду, і плашка блимає. Вісім пікселів — приблизно один «щиглик» колеса,
 * тобто менше за будь-який намір.
 */
/** Що пам'ятає рішення між подіями прокрутки. */
export interface ScrollHideState {
	hidden: boolean;
	last: number;
}

/**
 * Саме РІШЕННЯ — чиста функція, без рун і без `window`.
 *
 * Виділена, щоб її можна було перевірити звичайним тестом: браузерна панель у
 * цьому оточенні прокрутку не диспетчить і має нульову ширину, тож поведінку
 * «зникає вниз, повертається вгору» в ній не заміряти. Реактивна обгортка нижче
 * лишається тонкою настільки, що ламатися в ній нічому.
 */
export function nextScrollHide(
	prev: ScrollHideState,
	y: number,
	showAbove: number,
	threshold: number
): ScrollHideState {
	const delta = y - prev.last;
	/* Дрижання тачпада: напрямок не змінився, пам'ять теж. */
	if (Math.abs(delta) < threshold) return prev;
	return { hidden: y > showAbove && delta > 0, last: y };
}

export interface HideOnScrollDown {
	/** `true` — читач іде вниз і плашку варто прибрати. */
	readonly hidden: boolean;
}

export function hideOnScrollDown(
	/** Доки не проїхали стільки — плашка показується завжди. */
	showAbove = 120,
	/** Менший зсув вважається дрижанням, а не рухом. */
	threshold = 8
): HideOnScrollDown {
	let hidden = $state(false);
	let memory: ScrollHideState = { hidden: false, last: 0 };

	/*
	 * Слухач у `$effect`, а не в тілі функції: на сервері ефекти не виконуються,
	 * тож ні `window`, ні пререндер це не зачіпає. Прибирання слухача — у
	 * поверненій функції, тобто час життя дорівнює часу життя компонента, який
	 * викликав.
	 */
	$effect(() => {
		const onScroll = () => {
			memory = nextScrollHide(memory, window.scrollY, showAbove, threshold);
			hidden = memory.hidden;
		};
		memory = { hidden: false, last: window.scrollY };
		window.addEventListener('scroll', onScroll, { passive: true });
		return () => window.removeEventListener('scroll', onScroll);
	});

	return {
		get hidden() {
			return hidden;
		}
	};
}

// @vitest-environment node
import { describe, expect, it } from 'vitest';
import { portraitBoxRatio } from './bannerRatio';
import { LOCAL_IMAGE_SIZES, type LocalImage } from '$lib/config/localImages';

/**
 * Одна вертикальна фотографія не має вирішувати за всю стопку.
 *
 * ## Що саме стережеться
 *
 * Дефект видно лише оком і лише на сторінці: коробка банера бере одну
 * пропорцію на всі знімки, і при змішаній стопці вибір «є хоч один портрет →
 * коробка вертикальна» різав горизонтальні навпіл. Заміряно 7 вересня 2026 на
 * `groups/tv-prodakshn`: додали три знімки, серед них один 960×1280, і афіша
 * 1280×850 втратила половину ширини разом із назвою.
 *
 * Компілятор такого не бачить: рядок `"960 / 1280"` валідний завжди.
 *
 * ## Зворотний експеримент (AI-AGENT-PITFALLS-v8 § 1.1)
 *
 * Проведено: умову більшості замінено назад на «є хоч один вертикальний» —
 * упала перевірка про меншість; умову звужено до строгої більшості — упала
 * перевірка про рівний поділ, тобто про сторінку `mrii-dim-2012`, якої ця
 * робота чіпати не мала.
 */

/** Справжні шляхи з мапи розмірів — вигадані `imageSize` не знає. */
const шляхи = Object.keys(LOCAL_IMAGE_SIZES) as LocalImage[];
const вертикальний = шляхи.find((p) => {
	const s = LOCAL_IMAGE_SIZES[p];
	return s.height > s.width;
})!;
const горизонтальний = шляхи.find((p) => {
	const s = LOCAL_IMAGE_SIZES[p];
	return s.width > s.height;
})!;

describe('пропорція коробки банера', () => {
	it('перевірка жива: у мапі є знімки обох орієнтацій', () => {
		expect(вертикальний, 'жодного вертикального знімка').toBeTruthy();
		expect(горизонтальний, 'жодного горизонтального знімка').toBeTruthy();
	});

	it('самі вертикальні — коробка бере пропорцію знімка', () => {
		const { width, height } = LOCAL_IMAGE_SIZES[вертикальний];
		expect(portraitBoxRatio([вертикальний])).toBe(`${width} / ${height}`);
	});

	it('самі горизонтальні — коробка лишається типовою', () => {
		expect(portraitBoxRatio([горизонтальний, горизонтальний])).toBeUndefined();
	});

	it('МЕНШІСТЬ вертикальних не перекроює стопку', () => {
		/*
		 * Той самий випадок, що зламався: п'ять знімків, вертикальний один.
		 * Доти коробка ставала вертикальною й різала решту чотири.
		 */
		const стопка = [горизонтальний, горизонтальний, вертикальний, горизонтальний, горизонтальний];
		expect(portraitBoxRatio(стопка)).toBeUndefined();
	});

	it('порівну — коробка вертикальна, і це не чіпає наявних сторінок', () => {
		// `festivals/mrii-dim-2012`: два знімки, один вертикальний.
		const { width, height } = LOCAL_IMAGE_SIZES[вертикальний];
		expect(portraitBoxRatio([горизонтальний, вертикальний])).toBe(`${width} / ${height}`);
	});

	it('більшість вертикальних — коробка вертикальна', () => {
		const { width, height } = LOCAL_IMAGE_SIZES[вертикальний];
		expect(portraitBoxRatio([вертикальний, вертикальний, горизонтальний])).toBe(
			`${width} / ${height}`
		);
	});

	it('порожня стопка — банера немає, пропорції теж', () => {
		expect(portraitBoxRatio([])).toBeUndefined();
	});
});

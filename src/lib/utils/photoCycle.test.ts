// @vitest-environment node
import { describe, expect, it } from 'vitest';
import { кадриШару, часткаПеретікання } from './photoCycle';

/**
 * Арифметика циклу мультифото.
 *
 * Доти вона жила всередині `$effect` у `GraduateStar.svelte` і не мала жодного
 * тесту — не «ще не написали», а «написати було нічим»: перевірити можна лише
 * те, що з файлу видно. Модуль виїхав туди, куди його попросив гейт розміру, і
 * заразом став перевірним.
 *
 * ## Що саме стережуть затискачі — і дві мої помилки дорогою
 *
 * У середньому шарі стоять `Math.min(поява + пів, зникнення - пів)` і
 * `Math.max(…)`. Перша редакція цієї шапки казала, що вони тримають `offset`
 * УПОРЯДКОВАНИМ, бо WAAPI на неупорядкованих `offset` кидає виняток. Обидва
 * зворотні експерименти це заперечили, і по-різному.
 *
 * Помилка перша: на діапазоні реєстру затискачі не роблять НІЧОГО. Вони діють
 * лише коли `частка > 1/n`, а частка має стелю 0.12 — тобто з дев'яти кадрів.
 * У реєстрі максимум три (11 анкет із кількома кадрами). Заміна `Math.min` на
 * голе `поява + пів` не впала жодною перевіркою, поки перелік кількостей
 * закінчувався п'ятіркою. Тому нижче він навмисно виходить за межі реєстру: 9
 * і 12 — це не вигадані дані, а та зона, де затискач узагалі щось означає.
 *
 * Помилка друга: навіть у тій зоні жоден із затискачів не рятує ПОРЯДОК.
 * Прибрано `Math.min` — падає «середній шар устигає побути видимим»; прибрано
 * `Math.max` — падає та сама перевірка. Порядок лишається цілим в обох
 * випадках, бо другий затискач добирає за перший. Тобто те, що затискачі
 * справді стережуть, — це ВІКНО ВИДИМОСТІ: без них кадр показується нульову
 * тривалість, і людина його просто не бачить.
 *
 * Перевірка на впорядкованість лишається, але чесно: сьогодні роботу робить не
 * вона. Вона стоїть на випадок, коли хтось змінить саме форму перетікання —
 * вимогу WAAPI це не скасовує.
 *
 * ## Чому немає тесту на `запуститиЦикл`
 *
 * `Element.animate` у jsdom не реалізований, тож перевірка була б перевіркою
 * заглушки. Усе, що можна зламати числами, лежить у двох чистих функціях вище.
 *
 * Зворотний експеримент (`PIT-REVERSE-EXPERIMENT`): проведено двічі, для
 * кожного затискача окремо, і результат обох записано вище — саме він
 * переписав цю шапку.
 */
describe('частка перетікання', () => {
	it('чотири секунди від тривалості, але не більше 12 %', () => {
		// Довгий проліт: чотири секунди — це менше за стелю, тож вони й діють.
		expect(часткаПеретікання(60)).toBeCloseTo(4 / 60, 6);
		expect(часткаПеретікання(40)).toBeCloseTo(0.1, 6);
		// Короткий: 4/26 — це вже 15 %, і стеля тримає 12.
		expect(часткаПеретікання(26)).toBeCloseTo(0.12, 6);
		expect(часткаПеретікання(18)).toBeCloseTo(0.12, 6);
	});

	it('стеля не дає перетіканню з’їсти весь цикл', () => {
		// Без стелі проліт на 10 секунд мав би 40 % циклу в перетіканні, тобто
		// жоден кадр не побув би видимим.
		expect(часткаПеретікання(10)).toBe(0.12);
	});
});

describe('кадри шару', () => {
	/**
	 * Кількості кадрів: реальні плюс дві понад реєстр.
	 *
	 * У реєстрі максимум три знімки, і на такому діапазоні затискачі порядку
	 * не діють зовсім (арифметику див. у шапці). 9 і 12 — саме та зона, де вони
	 * єдині тримають анімацію від невдалого запуску; без них перевірка нічого не
	 * доводить. Число 5 лишається як запас на найближче зростання реєстру.
	 */
	const КІЛЬКОСТІ = [2, 3, 4, 5, 9, 12];
	const ТРИВАЛОСТІ = [18, 26, 30, 34, 45, 60];

	it('перевірка жива: кадри повертаються для кожного шару', () => {
		for (const n of КІЛЬКОСТІ) {
			for (let i = 0; i < n; i++) {
				expect(кадриШару(i, n, 0.12).length, `n=${n}, шар ${i}`).toBeGreaterThan(3);
			}
		}
	});

	it('`offset` ніколи не спадає — інакше WAAPI кидає виняток', () => {
		const зламані: string[] = [];
		for (const тривалість of ТРИВАЛОСТІ) {
			const частка = часткаПеретікання(тривалість);
			for (const n of КІЛЬКОСТІ) {
				for (let i = 0; i < n; i++) {
					const кадри = кадриШару(i, n, частка);
					const зсуви = кадри.map((k) => k.offset as number);
					for (let j = 1; j < зсуви.length; j++) {
						if (зсуви[j] < зсуви[j - 1]) {
							зламані.push(
								`тривалість ${тривалість}s, n=${n}, шар ${i}: offset пішов назад ` +
									`(${зсуви[j - 1]} → ${зсуви[j]})`
							);
						}
					}
				}
			}
		}
		expect(зламані, зламані.join('\n')).toEqual([]);
	});

	it('`offset` лишається в межах 0..1', () => {
		const поза: string[] = [];
		for (const тривалість of ТРИВАЛОСТІ) {
			const частка = часткаПеретікання(тривалість);
			for (const n of КІЛЬКОСТІ) {
				for (let i = 0; i < n; i++) {
					for (const кадр of кадриШару(i, n, частка)) {
						const o = кадр.offset as number;
						if (o < 0 || o > 1) поза.push(`тривалість ${тривалість}s, n=${n}, шар ${i}: ${o}`);
					}
				}
			}
		}
		expect(поза, поза.join('\n')).toEqual([]);
	});

	it('на стику циклу зірка не блимає порожнім колом', () => {
		// Крайні шари особливі саме через це: перший мусить бути видимий на
		// самому початку циклу, останній — на самому кінці. Інакше між останнім
		// кадром і першим наступного циклу є мить, коли не видно нічого.
		for (const n of КІЛЬКОСТІ) {
			const перший = кадриШару(0, n, 0.12);
			const останній = кадриШару(n - 1, n, 0.12);
			expect(перший[0], `n=${n}: наймолодший кадр невидимий на початку`).toMatchObject({
				opacity: 1,
				offset: 0
			});
			expect(останній.at(-1), `n=${n}: поточний кадр невидимий у кінці`).toMatchObject({
				opacity: 1,
				offset: 1
			});
		}
	});

	it('кожен середній шар устигає побути видимим', () => {
		// Затискачі `min`/`max` тримають порядок, але не мусять зводити вікно
		// видимості в нуль: кадр, показаний на нульову тривалість, — це кадр,
		// якого людина не побачить.
		const невидимі: string[] = [];
		for (const тривалість of ТРИВАЛОСТІ) {
			const частка = часткаПеретікання(тривалість);
			for (const n of КІЛЬКОСТІ) {
				for (let i = 1; i < n - 1; i++) {
					const кадри = кадриШару(i, n, частка);
					const видимі = кадри.filter((k) => k.opacity === 1).map((k) => k.offset as number);
					const вікно = Math.max(...видимі) - Math.min(...видимі);
					if (вікно <= 0) {
						невидимі.push(`тривалість ${тривалість}s, n=${n}, шар ${i}: вікно видимості нульове`);
					}
				}
			}
		}
		expect(невидимі, невидимі.join('\n')).toEqual([]);
	});
});

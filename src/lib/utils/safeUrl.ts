/**
 * Дозволені схеми для адрес, які приходять із даних (SECURITY-v8 § 5.1).
 *
 * Svelte екранує ТЕКСТ, але не значення атрибута `href`. Тобто
 * `<a href={item.href}>` із `javascript:…` у даних — це працюючий XSS, і
 * жодна перевірка проєкту його не бачила: ані `svelte-check`, ані ESLint,
 * ані санітайзер (той чистить HTML статті, а не адресу з окремого поля).
 *
 * Куди такі адреси потрапляють у цьому проєкті:
 * - `externalUrl` перекладу статті — рендериться картками на ГОЛОВНІЙ,
 *   у списках новин і проєктів (`ContentCard`, `ArticlePreviewCard`);
 * - `href` пунктів меню, розділів меню й кнопки-CTA з налаштувань шапки —
 *   тобто на КОЖНІЙ сторінці сайту.
 *
 * Обидва джерела — Firestore, куди пише адміністратор через форму. Правила
 * Firestore перевіряють, ХТО пише, і не перевіряють ЩО.
 *
 * Перевіряти лише `javascript:` недостатньо — лишаються `data:`, `vbscript:`
 * і форми з пробілами, табуляціями чи переносами всередині схеми, які браузер
 * розбирає, а наївна перевірка ні. Тому тут ALLOWLIST, а не чорний список.
 */

/**
 * Схеми, які справді потрібні сайту. `tel:` і `mailto:` — контакти,
 * `/` і `#` — внутрішні адреси й якорі, `?` — рядок запиту без шляху.
 */
const SAFE_URL = /^(?:https?:|mailto:|tel:|[/?#])/i;

/** Усе до пробілу включно браузер із адреси викидає, тому й ми викидаємо. */
const LAST_CONTROL_CHAR = 0x20;
const DELETE_CHAR = 0x7f;

/**
 * Прибирає керівні й пробільні символи, які браузер ігнорує при розборі схеми.
 *
 * `java`+таб+`script:alert(1)` браузер виконує, а регулярка вище пропустила б,
 * бо рядок не починається з `javascript`. Перевіряти треба те, що ПОБАЧИТЬ
 * браузер, а не те, що записано.
 *
 * Цикл, а не регулярка з діапазоном керівних символів: такий діапазон вимагає
 * `eslint-disable no-control-regex` і, головне, легко псується при
 * редагуванні файлу інструментами — керівний символ у джерелі не видно.
 *
 * Результат вживається ЛИШЕ для перевірки; назовні йде початковий рядок —
 * інакше з адрес зникали б пробіли в параметрах запиту.
 */
function normalize(url: string): string {
	let out = '';
	for (const ch of url) {
		const code = ch.charCodeAt(0);
		if (code > LAST_CONTROL_CHAR && code !== DELETE_CHAR) out += ch;
	}
	return out.toLowerCase();
}

/** `true`, якщо адресу можна віддати в `href` без ризику виконати скрипт. */
export function isSafeUrl(url: unknown): url is string {
	if (typeof url !== 'string') return false;
	const trimmed = url.trim();
	// Порожній рядок не «небезпечний», але й адресою не є: у `href` він дає
	// перезавантаження поточної сторінки. Викликач підставляє своє типове.
	if (trimmed === '') return false;
	return SAFE_URL.test(normalize(trimmed));
}

/**
 * Повертає адресу або запасне значення, якщо вона непридатна.
 *
 * Типове запасне — `'#'`, а не порожній рядок: порожній `href` перезавантажує
 * сторінку, і дефект виглядав би як «кнопка нічого не робить, лише мигає».
 */
export function safeUrl(url: unknown, fallback = '#'): string {
	return isSafeUrl(url) ? url.trim() : fallback;
}

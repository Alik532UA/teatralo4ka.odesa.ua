import { codeNewsCards, codeNewsTime } from '$lib/config/codeNews';
import type { ContentCardItem } from '$lib/components/ContentCard.svelte';

/**
 * Перелік новин із ДВОХ джерел, зведений хронологією.
 *
 * ## Що було не так
 *
 * І головна, і сторінка новин робили просте склеювання: `[...новини з коду,
 * ...новини з бази]`. У докблоці це було записано як свідома тимчасовість —
 * «поки їх одна, порядок код-далі-база і є хронологією», — і зараз перелік
 * справді виглядає правильно. Але лише тому, що обидві новини з коду
 * найновіші.
 *
 * Автор так і сказав: «не розумію в чому проблема, бо на сайті я бачу у
 * правильній хронології». Проблема в тому, що правильність тут ВИПАДКОВА:
 * щойно в код переїде старіша новина — а саме це й задумано, — вона стрибне на
 * початок переліку поперед вересневих. Тобто дефект чекає на першу ж корисну
 * дію.
 *
 * ## Чому не сортували раніше
 *
 * Причина в докблоці була справжня: новини з коду вже в бандлі й малюються з
 * першого кадру, а база відповідає згодом, тож «сортувати нема з чим». Тут це
 * враховано: функція просто зводить те, що є ЗАРАЗ. Поки база не відповіла, у
 * переліку самі лише новини з коду — уже в правильному порядку між собою; коли
 * відповіла, порядок перебудовується один раз.
 *
 * ## Чому час окремим полем
 *
 * У картці дата вже РЯДОК («5 вер. 2026 р.») — за ним не сортують. Тому
 * викликач приносить час у мілісекундах поруч із карткою: для бази це
 * `getDisplayDate`, для коду — `codeNewsTime`, який для цього й написали (і
 * який доти не викликався ніде).
 */

/** Картка з бази разом із часом, за яким її ставити в перелік. */
export interface DatedCard {
	картка: ContentCardItem;
	/** Мілісекунди. `0` — дати немає (`dateMode: 'hidden'`), тож піде в кінець. */
	час: number;
}

export function newsFeed(lang: 'uk' | 'en', зБази: readonly DatedCard[]): ContentCardItem[] {
	const зКоду: DatedCard[] = codeNewsCards(lang).map((картка) => ({
		картка,
		час: codeNewsTime(lang, картка.id)
	}));

	/*
	 * Новіші перші, а за однакового часу вище лишається те, що стояло раніше в
	 * масиві, — тобто новина з КОДУ. Це не випадковість: `Array.prototype.sort`
	 * стабільний, а дата в коді записана днем без години, тож новина з бази того
	 * самого дня має рівно той самий час. Без цієї пари (порядок масиву +
	 * стабільність) картки того самого дня переставлялися б залежно від того, як
	 * швидко відповіла база.
	 */
	return [...зКоду, ...зБази]
		.sort((a, b) => b.час - a.час)
		.map((x) => x.картка);
}

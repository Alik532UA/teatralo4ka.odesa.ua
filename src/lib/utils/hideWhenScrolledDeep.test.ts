import { describe, expect, it } from 'vitest';
import { HIDE_DEPTH, hiddenAtDepth } from './hideWhenScrolledDeep.svelte';

/**
 * Рішення «плашку прибрати» — за ГЛИБИНОЮ, а не за напрямком руху.
 *
 * ## Чому це перевіряється тестом
 *
 * Браузерна панель у цьому оточенні прокрутку не диспетчить: після присвоєння
 * `scrollTop` подія `scroll` не приходить, а кадрів рендеру немає взагалі. Тобто
 * поведінку «зникає глибше, повертається вище» там не заміряти жодним способом.
 * Тому саме рішення винесене в чисту функцію, і перевіряється воно тут.
 *
 * ## Що саме стережеться
 *
 * 1. Межа СУВОРА: «опустився більше ніж на 532» означає, що рівно на 532 плашка
 *    ще видима. Помилка на одиницю тут не падає й не малює нічого дивного —
 *    просто плашка зникає на піксель раніше, ніж домовлялися.
 * 2. Напрямок більше НЕ впливає. Це головне, що змінилося: попередня версія
 *    ховала плашку від руху вниз на вісім пікселів угорі сторінки й повертала
 *    її рухом угору біля підвалу. Перевірка «те саме число дає ту саму
 *    відповідь» ловить будь-яку спробу знову внести в рішення пам'ять про
 *    попередній кадр.
 *
 * ## Зворотні експерименти (AI-AGENT-PITFALLS-v8 § 1.1)
 *
 * 1. Замінити `y > depth` на `y >= depth` — падає «рівно на межі ще видима».
 * 2. Замінити на `y < depth` — падають обидві перевірки глибини й називають
 *    очікуване та отримане.
 * 3. Повернути `HIDE_DEPTH` до 120 — падає «погоджена глибина 532».
 *
 * Усі три прогнані: кожна правка валить свою перевірку.
 */
describe('hiddenAtDepth', () => {
	it('глибше за межу — плашки немає', () => {
		expect(hiddenAtDepth(533, 532)).toBe(true);
		expect(hiddenAtDepth(3000, 532)).toBe(true);
	});

	it('рівно на межі плашка ще ВИДИМА', () => {
		/* «Більше ніж на 532» — саме більше, не «від». */
		expect(hiddenAtDepth(532, 532)).toBe(false);
	});

	it('вище за межу — плашка на місці', () => {
		expect(hiddenAtDepth(0, 532)).toBe(false);
		expect(hiddenAtDepth(531, 532)).toBe(false);
	});

	it('НАПРЯМОК не впливає: та сама глибина — та сама відповідь', () => {
		/*
		 * Найважливіша перевірка файлу. Попередня версія тримала пам'ять про
		 * попередній кадр, і відповідь залежала від того, звідки читач прийшов у
		 * цю точку. Тепер прихід «згори вниз» і «знизу вгору» в ту саму точку
		 * мусить давати те саме.
		 */
		const шлях = [0, 200, 400, 600, 800, 600, 400, 200, 0];
		const відповіді = шлях.map((y) => hiddenAtDepth(y, 532));
		expect(відповіді).toEqual([false, false, false, true, true, true, false, false, false]);

		for (const y of шлях) {
			expect(hiddenAtDepth(y, 532), `${y} дало різні відповіді`).toBe(y > 532);
		}
	});

	it('погоджена глибина — 532', () => {
		expect(HIDE_DEPTH).toBe(532);
	});
});

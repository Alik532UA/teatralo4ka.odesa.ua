/**
 * Цикл мультифото зірки: перетікання між кадрами, синхронізоване з прольотом.
 *
 * ## Чому Web Animations API, а не CSS keyframes
 *
 * Точки переходу для N кадрів — це `1/N`, `2/N`, …, тобто відсотки, яких у
 * момент написання стилів ще ніхто не знає: у різних людей від двох до чотирьох
 * знімків. CSS не вміє динамічних відсотків, і єдина альтернатива — по набору
 * `@keyframes` на кожне можливе N. WAAPI живе на тому самому шарі композитора,
 * що й CSS-анімації, тож ціна нульова.
 *
 * ## Чому це окремий модуль, а не `$effect` у компоненті
 *
 * Винесено, коли `GraduateStar.svelte` переріс стелю розміру: гейт запропонував
 * вибір «розділити або підняти стелю», і поділ тут природний — обчислення
 * кадрів не знає ні про кнопку, ні про ранги, ні про плейсхолдер. Заразом воно
 * стало перевірним: доти найскладніша арифметика компонента не мала жодного
 * тесту, бо жила всередині ефекту.
 */

/**
 * Скільки циклу займає одне перетікання.
 *
 * Чотири секунди — стільки, щоб зміна обличчя читалася як дорослішення, а не як
 * підміна. Але в короткого прольоту чотири секунди — це майже весь цикл, тож
 * зверху стоїть межа у 12 % тривалості: інакше кадри перетікали б безперервно й
 * жоден не встиг би побути видимим.
 */
export function часткаПеретікання(тривалістьСекунд: number): number {
	return Math.min(4 / тривалістьСекунд, 0.12);
}

/**
 * Кадри прозорості для шару `i` зі `n`.
 *
 * Порядок шарів — від наймолодшого знімка до поточного, тобто метафора
 * дорослішення за один проліт. Тому крайні шари особливі: перший видимий із
 * початку циклу, останній лишається видимим до кінця. Якби вони теж
 * з'являлися й зникали за загальним правилом, на стику циклу зірка блимала б
 * порожнім колом.
 */
export function кадриШару(i: number, n: number, часткаПереходу: number): Keyframe[] {
	const пів = часткаПереходу / 2;
	const поява = i / n;
	const зникнення = (i + 1) / n;

	if (i === 0) {
		// Наймолодший: видимий з початку, зникає на своєму `зникнення`.
		return [
			{ opacity: 1, offset: 0 },
			{ opacity: 1, offset: Math.max(0, зникнення - пів) },
			{ opacity: 0, offset: Math.min(1, зникнення + пів) },
			{ opacity: 0, offset: 1 }
		];
	}

	if (i === n - 1) {
		// Поточний: приховане, з'являється й лишається до кінця циклу.
		return [
			{ opacity: 0, offset: 0 },
			{ opacity: 0, offset: Math.max(0, поява - пів) },
			{ opacity: 1, offset: Math.min(1, поява + пів) },
			{ opacity: 1, offset: 1 }
		];
	}

	return [
		{ opacity: 0, offset: 0 },
		{ opacity: 0, offset: Math.max(0, поява - пів) },
		{ opacity: 1, offset: Math.min(поява + пів, зникнення - пів) },
		{ opacity: 1, offset: Math.max(поява + пів, зникнення - пів) },
		{ opacity: 0, offset: Math.min(1, зникнення + пів) },
		{ opacity: 0, offset: 1 }
	];
}

/**
 * Запускає цикл на шарах усередині `корінь` і повертає його зняття.
 *
 * `тривалість` і `затримка` приходять із `--duration` і `--delay` доріжки, тому
 * один цикл дорівнює одному прольоту: людина бачить повну послідівність
 * знімків саме за той час, поки зірка йде через екран.
 */
export function запуститиЦикл(
	корінь: HTMLElement,
	відбірШарів: string,
	тривалістьСекунд: number,
	затримкаСекунд: number
): () => void {
	const шари = корінь.querySelectorAll<HTMLElement>(відбірШарів);
	const частка = часткаПеретікання(тривалістьСекунд);
	const анімації: Animation[] = [];

	шари.forEach((шар, i) => {
		анімації.push(
			шар.animate(кадриШару(i, шари.length, частка), {
				duration: тривалістьСекунд * 1000,
				delay: затримкаСекунд * 1000,
				iterations: Infinity,
				easing: 'linear'
			})
		);
	});

	return () => анімації.forEach((a) => a.cancel());
}

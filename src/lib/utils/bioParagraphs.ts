/**
 * Біографія — рядок із бази, а на сторінці АБЗАЦИ.
 *
 * ## Навіщо окремим модулем
 *
 * Доти шаблон сторінки майстра виводив `bio` одним `<p>`. Це не було
 * недоглядом: усі 142 профілі майстрів мали порожній `bio`, тож перевірити було
 * нічому. Перші дві біографії — Володимира Туманова (сім абзаців) і Михайла
 * Дроботова — показали, чого бракує.
 *
 * Саме рішення «де кінчається абзац» винесене з шаблону, бо його треба
 * стерегти тестом: у розмітці правило перевіряється лише очима, а очима видно
 * тільки той текст, який зараз у базі. Заодно сторінка не переростає стелі
 * `structure.test.ts` — 403 рядки проти 400 стали причиною, чому цей файл
 * з'явився саме тепер.
 *
 * ## Чому саме ПОРОЖНІЙ рядок
 *
 * Усередині абзацу перенос буває просто переносом — так набирають довгі
 * перелічення вистав. Якби розділювачем був будь-який `\n`, текст розсипався б
 * на рядки. Порожній рядок — це те, як абзац відбивають руками в самому файлі
 * профілю, тобто правило вже діє, просто його ніхто не читав.
 *
 * ## Чому тут НЕ прибираються `\r`
 *
 * Профілі правляться руками, і редактор може лишити віндовські кінці рядків,
 * тож спершу тут стояло `.replace(/\r/g, '')`. Зворотний експеримент показав,
 * що воно не тримає нічого: у `\r\n\r\n` перший `\n` починає розділювач, `\s*`
 * поглинає `\r`, другий `\n` його закінчує, а `\r` на кінці абзацу з'їдає
 * `trim()`. Прибирання рядка не завалило жодної з п'яти перевірок — і рядка
 * більше немає. CRLF стереже сам тест, а не зайвий крок у ланцюжку.
 */
export function bioParagraphs(bio: string | null | undefined): string[] {
	return (bio ?? "")
		.split(/\n\s*\n/)
		.map((part) => part.trim())
		.filter(Boolean);
}

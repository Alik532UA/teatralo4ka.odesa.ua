import { describe, it, expect } from 'vitest';
import { fitsBeside } from './floatBottom';

/**
 * Тест на чисту частину — рішення «обтікати чи ставити смугою». Сам атачмент
 * не монтується з тієї ж причини, що й у `focusTrap.test.ts`: середовища
 * компонентних тестів у проєкті немає, а jsdom однаково не рахує розкладку.
 *
 * Числа взяті з живих замірів на 375px: блок пункту — 278px, стопка фото з
 * полем — 76, чипси груп — 189, ряд із чотирьох викладачів — 241.
 */
describe('fitsBeside', () => {
	it('вузька ілюстрація на телефоні лишає придатну колонку', () => {
		expect(fitsBeside(278, 76)).toBe(true);
	});

	it('чипси груп на телефоні колонки не лишають', () => {
		// 278 - 189 = 89 при потрібних 160 — у рядок стало б два слова
		expect(fitsBeside(278, 189)).toBe(false);
	});

	it('ряд із чотирьох викладачів на телефоні — тим паче', () => {
		expect(fitsBeside(278, 241)).toBe(false);
	});

	it('у широкому вікні обтікається все те саме', () => {
		expect(fitsBeside(960, 241)).toBe(true);
		expect(fitsBeside(960, 189)).toBe(true);
	});

	it('у широкому блоці порогом стає частка, а не 160px', () => {
		// 960 - 500 = 460 більше за 160, але менше за 55% від 960
		expect(fitsBeside(960, 500)).toBe(false);
	});

	it('нульова ілюстрація не заважає нікому', () => {
		expect(fitsBeside(278, 0)).toBe(true);
	});
});

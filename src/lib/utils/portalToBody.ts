import type { Attachment } from 'svelte/attachments';

/**
 * Переносить елемент у `document.body` — щоб `position: fixed` знову означав
 * «відносно вікна».
 *
 * ## Що саме поламалося
 *
 * Плеєр запису відкривався ВСЕРЕДИНІ картки випускника: вузька смужка ліворуч,
 * половину якої закривала сама картка. Заміряно на анкеті Аліка Запольнова при
 * вікні 1280×800: завіса плеєра вийшла 1229×752, тобто розміром КАРТКИ, а не
 * вікна.
 *
 * Причин дві, і обидві не в плеєрі:
 *
 * 1. `.profile__card` зсувається `transform: translateY()` зі змінної
 *    `--shift-y`: прокрутка веде саму картку, бо сцена з зорями мусить
 *    стояти. Будь-який `transform`, `filter`, `backdrop-filter`,
 *    `perspective`, `contain` чи `will-change` робить елемент КОНТЕЙНЕРОМ для
 *    `position: fixed` усередині — і `inset: 0` після цього означає «на всю
 *    картку».
 * 2. Колонка `galaxy-profile-column-panel-*` має `overflow: auto` і стоїть між
 *    плеєром та цим контейнером — тож вона плеєр ще й обрізає.
 *
 * Та сама пастка вже ловила підказку в рядку облич: там її обійшли
 * `containingBlockOffset` у `dropdownPlace`. Для підказки це годиться — вона
 * маленька і не мусить закривати екран. Для модального вікна ні: воно має бути
 * поверх УСЬОГО, і єдиний надійний спосіб — вийти з-під винних предків, а не
 * перераховувати координати.
 *
 * ## Чому не `<dialog showModal()>`
 *
 * Він теж вирішив би це — і навіть краще, бо потрапляє у верхній шар браузера.
 * Але це переписування всіх наших модалок разом із фокусом, закриттям і
 * анімаціями. Перенос у `body` дає той самий результат для `position: fixed`
 * трьома рядками.
 *
 * ## Чому прибирати вручну
 *
 * Svelte, знищуючи блок, шукає вузол там, де його створив. Ми його звідти
 * забрали, тож приберемо самі — інакше плеєр лишався б у `body` після
 * закриття.
 */
export function portalToBody(): Attachment {
	return (node: Element) => {
		document.body.appendChild(node);
		return () => node.remove();
	};
}

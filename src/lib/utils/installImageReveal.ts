import { browser } from '$app/environment';

/**
 * Плавна поява КОЖНОГО зображення сайту, крім головного знімка сторінки.
 *
 * ## Чому одним механізмом на документ, а не атрибутом на кожному тезі
 *
 * Тегів `<img>` у проєкті 65 у 35 файлах. Патерн сусіднього проєкту
 * (`adoptananimal`, `AnimalCard.svelte`) навісити на кожен було першим планом і
 * поганим: 62 однакові правки — це 62 нагоди проминути одну, і жодного способу
 * довести, що не проминув. Гірше: половина цих зображень приходить із
 * Firestore уже в браузері — картки новин, вміст статей, вкладки адмінки, — і
 * тег, дописаний туди наступного місяця, атрибута не мав би ніколи.
 *
 * Тому спостерігач: він накриває і те, що є, і те, що з'явиться. Ціна —
 * `MutationObserver` на документ; вигода — покриття, яке не залежить від того,
 * чи згадав автор про атрибут.
 *
 * ## Головне рішення: механізм НІЧОГО НЕ ВСТАНОВЛЮЄ, лише знімає
 *
 * Прозорістю на самому `<img>` у цьому проєкті вже володіють інші: стопка
 * знімків в анкеті випускника (`.photo--stacked`), лайтбокс, карусель, шари
 * зірки в галактиці. Механізм, який дописував би `opacity: 1`, побився б із
 * ними — і не падінням, а мовчки, як уже було між WAAPI і CSS у
 * `GraduateStar`.
 *
 * Тут цього не станеться за побудовою. Послідовність рівно така:
 *
 *   1. ставимо інлайновий `opacity: 0` (жодного кінцевого значення);
 *   2. на `load` оголошуємо перехід і ЗНІМАЄМО свій `opacity` —
 *      зображення перетікає з нуля до того значення, яке дав ЙОГО власник,
 *      хай би яке воно було;
 *   3. після переходу знімаємо й свій `transition`.
 *
 * Тобто наприкінці від механізму не лишається жодного оголошення. Шар, який
 * компонент навмисно тримає прихованим, так і лишиться прихованим; шар, який
 * має бути видимим, стане видимим. Механізм не має власної думки про кінцевий
 * вигляд.
 *
 * ## Чому не `opacity: 0` у стилях
 *
 * Так зроблено в сусідньому проєкті — і там це прикрито атрибутом `data-js`,
 * який ставить скрипт першого кадру. Тут такого атрибута немає, а більшість
 * цих зображень, на відміну від зірок галактики, стоять у ПРЕРЕНДЕРЕНОМУ
 * HTML: правило в CSS зробило б їх невидимими назавжди для краулера й для
 * відвідувача без скриптів. Прозорість, яку ставить сам скрипт, цієї проблеми
 * не має — без JS її ніхто не поставить, і знімок просто видимий. Заразом не
 * доводиться чіпати `app.html`, чий інлайновий скрипт стоїть під хешем CSP.
 *
 * ## Кого механізм не торкається
 *
 * `[fetchpriority]` — головний знімок сторінки. Перелік не вписаний рукою, а
 * виведений із коду: атрибут стоїть рівно там, де автор ПІДНІМАВ пріоритет
 * завантаження, тобто в героя головної, банері групи й головному фото статті.
 * Затримувати їх суперечило б самому наміру, а в героя прозорість ще й зайнята
 * слайдшоу (`class:active`) — другий власник там мовчки не подіяв би.
 *
 * `[data-reveal="own"]` — зображення з власною появою. Сьогодні це зірки
 * галактики: у них своя черга завантаження, точка-плейсхолдер і збільшення
 * (`GraduateStar.svelte`), і другий механізм там лише дублював би роботу.
 *
 * ## Чого механізм НЕ робить
 *
 * Не переграє появу, коли в наявного тега міняється `src` — карусель і
 * лайтбокс міняють знімок у тому самому елементі, і перетікання на кожному
 * перегортанні читалося б як гальмування, а не як плавність.
 */

/** Скільки триває поява. */
const ТРИВАЛІСТЬ_МС = 500;

/**
 * Півсекунди, а не секунда, як у галактиці.
 *
 * У галактиці секунда обґрунтована рухом: зірка летить, і за цей час вона
 * проходить близько півтора відсотка ширини екрана — коротший перехід там
 * губиться. Тут вміст стоїть на місці, тобто рухового бюджету немає зовсім, і
 * єдине питання — коли перехід починає читатися як затримка. Півсекунди
 * лишаються переходом; секунда на дрібному значку в підвалі вже виглядає, ніби
 * сторінка гальмує.
 */

/** Запобіжник: `transitionend` не настане, якщо кінцева прозорість — нуль. */
const ЗАПАС_МС = ТРИВАЛІСТЬ_МС + 200;

const ОПРАЦЬОВАНО = 'data-revealed';

function готове(img: HTMLImageElement): boolean {
	return img.complete && img.naturalWidth > 0;
}

/**
 * Кого механізм не бере. Експортується заради перевірок: контракт винятків —
 * єдине, що тут можна зламати мовчки, і він мусить бути перевірним окремо від
 * DOM.
 */
export function пропустити(img: HTMLImageElement): boolean {
	return (
		img.hasAttribute(ОПРАЦЬОВАНО) ||
		img.hasAttribute('fetchpriority') ||
		img.dataset.reveal === 'own'
	);
}

function взяти(img: HTMLImageElement): void {
	if (пропустити(img)) return;
	// Позначка стоїть одразу й назавжди: спостерігач бачить той самий елемент
	// стільки разів, скільки його переставляли в дереві, і без неї друга спроба
	// ховала б уже показане зображення.
	img.setAttribute(ОПРАЦЬОВАНО, '');

	// Уже намальоване — з кеша або просто швидше за гідрацію. Ставити нуль тут
	// означало б блимнути назад, тобто зробити гірше, ніж було.
	if (готове(img)) return;

	/*
	 * Прозорість І перехід ставляться ОДРАЗУ, ще до завантаження, — і це не
	 * дрібниця порядку.
	 *
	 * Перша редакція оголошувала перехід аж на `load`, а прозорість знімала в
	 * `requestAnimationFrame`: браузер мусив побачити нуль як початкове значення
	 * окремим кадром. Замір це відкинув. На головній сторінці 150 зображень;
	 * ті, що у в'юпорті, показалися правильно, а нижче згину 135 із 141 уже
	 * ЗАВАНТАЖИЛИСЯ й лишилися з інлайновим `opacity: 0` — тобто невидимими.
	 * Причина: `requestAnimationFrame` не викликається там, де немає кадрів
	 * рендеру. У панелі браузера це артефакт заміру, але в проді те саме
	 * означає неактивну вкладку — сторінка, відкрита у фоні, лишалася б без
	 * жодного зображення, доки на неї не перейдуть.
	 *
	 * Коли перехід оголошено від початку, нуль стає початковим значенням
	 * природним шляхом — кадром раніше, ніж прийдуть байти, — і зняття
	 * прозорості перетікає без жодного кадру-синхронізатора. Заразом зникає
	 * альтернатива, яку я розглядав: примусовий reflow (`void img.offsetWidth`)
	 * на кожному `load` дав би 141 синхронний перерахунок розкладки на цій
	 * сторінці.
	 *
	 * Ціна нульова: доки зображення не прийшло, малювати нічого, тож
	 * піваекундне «згасання» з одиниці до нуля нічого не показує. Уже
	 * намальовані зображення сюди не доходять зовсім — їх відсіює `готове()`
	 * вище, і саме тому згасання назад не буває видимим ніколи.
	 */
	img.style.opacity = '0';
	img.style.transition = `opacity ${ТРИВАЛІСТЬ_МС}ms ease-out`;

	let прибрано = false;
	const прибрати = () => {
		if (прибрано) return;
		прибрано = true;
		img.style.removeProperty('transition');
		img.removeEventListener('transitionend', наКінці);
	};
	const наКінці = (e: TransitionEvent) => {
		if (e.propertyName === 'opacity') прибрати();
	};

	const показати = () => {
		img.removeEventListener('load', показати);
		img.removeEventListener('error', показати);

		img.addEventListener('transitionend', наКінці);
		img.style.removeProperty('opacity');
		// `transitionend` не настане, коли власник тримає нуль (прихований шар
		// стопки) або коли зображення вже поза деревом. Без цього запасу
		// інлайновий `transition` лишився б назавжди й перебивав би чужий.
		setTimeout(прибрати, ЗАПАС_МС);
	};

	// `error` показує так само: розбите зображення мусить віддати місце своєму
	// `alt`, а не лишитися прозорим прямокутником.
	img.addEventListener('load', показати);
	img.addEventListener('error', показати);
}

/**
 * Вішає появу на всі наявні зображення й на всі майбутні.
 *
 * Кличеться з `+layout.svelte` — тим самим порядком, що `installTrail` і
 * `installViewTransitions`.
 */
export function installImageReveal(): void {
	if (!browser) return;

	for (const img of document.images) взяти(img);

	const спостерігач = new MutationObserver((записи) => {
		for (const запис of записи) {
			for (const вузол of запис.addedNodes) {
				if (вузол instanceof HTMLImageElement) {
					взяти(вузол);
					continue;
				}
				// Піддерево: картку новини вставляють цілим блоком, і сам `<img>`
				// у `addedNodes` не з'являється.
				if (вузол instanceof Element) {
					for (const img of вузол.querySelectorAll('img')) взяти(img);
				}
			}
		}
	});
	спостерігач.observe(document.documentElement, { childList: true, subtree: true });
}

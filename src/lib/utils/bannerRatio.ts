import { imageSize, type LocalImage } from '$lib/config/localImages';

/**
 * Пропорція коробки банера, коли в стопці є ВЕРТИКАЛЬНІ знімки.
 *
 * ## Що це вирішує
 *
 * Банер показує стопку знімків в одній коробці й кадрує їх `object-fit: cover`.
 * Коробка одна, знімки різні — тож будь-яка пропорція комусь щось відріже, і
 * питання лише в тому, кому саме.
 *
 * Типова коробка 16:10. Вертикальний знімок у ній втрачає ≈60 % висоти —
 * обличчя зрізаються, — тому для нього коробка бере пропорцію самого знімка.
 *
 * ## Чому БІЛЬШІСТЬ, а не «хоч один»
 *
 * Перша редакція правила брала перший-ліпший вертикальний знімок: є такий —
 * коробка стає вертикальною. На стопці з самих портретів це правильно, а на
 * ЗМІШАНІЙ — навпаки.
 *
 * Заміряно 7 вересня 2026 на `groups/tv-prodakshn`: до знімків групи додали три
 * нові, серед них один вертикальний (960×1280). Коробка через нього стала
 * 960/1280, і афіша 1280×850 втратила половину ширини — на сторінці лишилася
 * смуга з обрізаною назвою «TV-продакшн». Автор побачив це одразу: «фотографії
 * стали обрізаними».
 *
 * Тобто один вертикальний знімок із п'яти вирішував за чотирьох.
 *
 * ## Порівну — коробка лишається ВЕРТИКАЛЬНОЮ
 *
 * Не тому, що так краще в теорії, а тому, що при рівному числі кращої відповіді
 * немає: хтось однаково втратить половину. Зате межа «більшість або порівну»
 * не чіпає жодної наявної сторінки, крім тієї, що зламалася: перевірено по всіх
 * трьох реєстрах — груп, вистав і фестивалів, — і змінюється рівно
 * `tv-prodakshn`. Правило, яке мовчки перекроює чужі сторінки заради однієї,
 * коштувало б дорожче за саму помилку.
 */
export function portraitBoxRatio(photos: readonly string[]): string | undefined {
	const вертикальні = photos.filter((p) => {
		const s = imageSize(p as LocalImage);
		return s.height > s.width;
	});
	if (вертикальні.length === 0 || вертикальні.length * 2 < photos.length) return undefined;

	const { width, height } = imageSize(вертикальні[0] as LocalImage);
	return `${width} / ${height}`;
}

/**
 * Чи курсор БІЛЯ прямокутника — і на якій відстані.
 *
 * ## Навіщо окремо від компонента
 *
 * Рішення «близько чи ні» вирішує, як виглядають кнопки галактики: 50% удалині,
 * 75% поблизу, 100% під курсором. Перевірити його в браузері цього оточення
 * не можна — прихована панель не дає кадрів рендеру, тож `requestAnimationFrame`,
 * яким рух курсора притишується до кадру, не викликається взагалі. Тобто
 * поведінку там не заміряти жодним способом, а очима вона перевіряється лише
 * «наче працює».
 *
 * Тому сама математика тут, під звичайним тестом, а в компоненті лишається
 * слухач і клас.
 */

/** Точка курсора у координатах вікна. */
export interface Point {
	x: number;
	y: number;
}

/** Те, що дає `getBoundingClientRect()` — беремо лише потрібні чотири числа. */
export interface Box {
	left: number;
	top: number;
	right: number;
	bottom: number;
}

/**
 * Відстань від точки до ПРЯМОКУТНИКА, а не до його центра.
 *
 * Різниця істотна: рядок кнопок широкий, і до його центра з лівого краю
 * далеко, хоч курсор стоїть просто над кнопкою. Для точки всередині відстань
 * нульова.
 */
export function distanceToBox(point: Point, box: Box): number {
	const dx = Math.max(box.left - point.x, 0, point.x - box.right);
	const dy = Math.max(box.top - point.y, 0, point.y - box.bottom);
	return Math.hypot(dx, dy);
}

/**
 * Чи точка в межах зони наближення.
 *
 * СУВОРА нерівність: «ближче за зону», тобто рівно на межі — ще далеко. Межа
 * мусить бути визначена однозначно, інакше на самій відстані `zone` відповідь
 * залежала б від округлення координат курсора.
 */
export function isNearBox(point: Point, box: Box, zone: number): boolean {
	return distanceToBox(point, box) < zone;
}

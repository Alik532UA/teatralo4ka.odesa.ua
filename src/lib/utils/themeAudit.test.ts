// @vitest-environment node
import { describe, expect, it } from 'vitest';
import { auditThemes, suggestShade } from './themeAudit';
import { contrast, parseColor } from './contrast';

/**
 * Арифметика лабораторії кольорів: підказка відтінку й перевірка чужих тем.
 *
 * ## Навіщо тест, коли є око в браузері
 *
 * Обидві відповіді — числа, і помилка в них ТИХА. Підказка, що повертає колір
 * із контрастом 4.3 замість 4.5, виглядає в панелі точно так само, як
 * правильна: дизайнер натискає «полагодити», бачить новий колір і йде далі —
 * а гейт контрасту в CI червоніє через тиждень і вже на іншій парі.
 *
 * Саме тому ці дві функції й живуть окремо від компонента: вони нічого не
 * читають із документа, тож їх видно тестам без браузера.
 *
 * ## Зворотний експеримент (AI-AGENT-PITFALLS-v9 § 1.1)
 *
 * У `auditThemes` порядок злиття перевернуто на `{ ...overrides, ...власні }`
 * — тобто правки дизайнера перестають перемагати над власними значеннями
 * теми. Перевірка «правка однієї теми міряється в кожній» падає. Зроблено,
 * падає з очікуваним текстом.
 */

const АА = 4.5;
const пара = (fg: string, bg: string) => contrast(parseColor(fg)!, parseColor(bg)!);

describe('підказка відтінку', () => {
	it('на світлому тлі темнішає — і результат справді проходить', () => {
		const порада = suggestShade('#9ad1ff', '#ffffff');
		expect(порада).not.toBeNull();
		expect(порада!.direction).toBe('darker');
		expect(пара(порада!.value, '#ffffff')).toBeGreaterThanOrEqual(АА);
	});

	it('на темному тлі світлішає', () => {
		const порада = suggestShade('#1f3d5c', '#101010');
		expect(порада).not.toBeNull();
		expect(порада!.direction).toBe('lighter');
		expect(пара(порада!.value, '#101010')).toBeGreaterThanOrEqual(АА);
	});

	it('зберігає відтінок, а не зводить колір до сірого', () => {
		// Обіцянка з докблоку `змішати`: синій лишається синім. Без неї підказка
		// «лагодила» б контраст, підмінюючи задум дизайнера.
		const порада = suggestShade('#9ad1ff', '#ffffff');
		const [r, g, b] = parseColor(порада!.value)!;
		expect(b).toBeGreaterThan(r);
		expect(b).toBeGreaterThan(g);
	});

	it('мовчить, коли пара й так проходить', () => {
		expect(suggestShade('#000000', '#ffffff')).toBeNull();
	});

	it('мовчить чесно, коли відповіді немає', () => {
		// Середньо-сірий на порозі AAA не бере ані чорний, ані білий: 5.32 і 3.95.
		// Вигадана відповідь тут гірша за мовчання.
		expect(suggestShade('#808080', '#808080', 7)).toBeNull();
	});

	it('мовчить на нерозібраному кольорі, а не падає', () => {
		expect(suggestShade('var(--щось)', '#ffffff')).toBeNull();
	});
});

const ТЕМИ = {
	light: { '--text-main': '#111111', '--bg-page': '#ffffff' },
	dark: { '--text-main': '#eeeeee', '--bg-page': '#101010' }
};
const ПАРИ = [{ fg: '--text-main', bg: '--bg-page', label: 'текст на сторінці' }];

describe('перевірка інших тем', () => {
	it('правка однієї теми міряється в КОЖНІЙ', () => {
		// Рівно той випадок, заради якого написано: дизайнер підібрав темний
		// текст у світлій темі й не побачив, що в темній він ліг на темне тло.
		const [світла, темна] = auditThemes(ТЕМИ, { '--text-main': '#111111' }, ПАРИ);
		expect(світла.failed).toEqual([]);
		expect(темна.failed).toHaveLength(1);
		expect(темна.failed[0].label).toBe('текст на сторінці');
		expect(темна.failed[0].ratio!).toBeLessThan(АА);
	});

	it('без правок теми лишаються собою', () => {
		for (const вердикт of auditThemes(ТЕМИ, {}, ПАРИ)) {
			expect(вердикт.failed, вердикт.theme).toEqual([]);
			expect(вердикт.measured, вердикт.theme).toBe(1);
		}
	});

	it('невідомий токен не рахується за пройдену пару', () => {
		// Межа, без якої «жодної поганої пари» означало б «нічого не порахували»:
		// найтихіший спосіб показати зелене там, де перевірки не було.
		const [вердикт] = auditThemes({ light: {} }, {}, ПАРИ);
		expect(вердикт.measured).toBe(0);
		expect(вердикт.failed).toEqual([]);
	});
});

import { describe, expect, it } from "vitest";
import { bioParagraphs } from "./bioParagraphs";

/**
 * Поділ біографії на абзаци.
 *
 * ## Що саме стережеться
 *
 * 1. Розділювач — ПОРОЖНІЙ рядок, а не будь-який перенос. Це головне: у
 *    біографії Туманова абзац із переліченням вистав довгий, і якби рвали на
 *    кожному `\n`, сторінка показала б не сім абзаців, а рядкове кришиво.
 * 2. Порожній `bio` дає порожній масив, а не масив із порожнім рядком —
 *    інакше сторінка малювала б контейнер «Про викладача» з пустим `<p>`
 *    усередині для всіх 140 профілів, де біографії ще немає.
 * 3. Віндовські кінці рядків не ламають поділ: профілі правляться руками, і
 *    редактор може лишити CRLF. Ця перевірка тримає поведінку, яку доти
 *    забезпечував окремий `.replace(/\r/g, '')` — його прибрано, бо зворотний
 *    експеримент показав, що він не тримав нічого (див. докблок модуля).
 *
 * ## Зворотні експерименти (AI-AGENT-PITFALLS-v8 § 1.1)
 *
 * 1. Замінити `/\n\s*\n/` на `/\n/` — падає «перенос усередині абзацу не рве»,
 *    рівно одна перевірка з п'яти.
 * 2. Прибрати `.filter(Boolean)` — падає «порожня біографія — порожній
 *    перелік», теж рівно одна.
 * 3. Прибрати `\s*` із розділювача, тобто `/\n\n/` — CRLF перестає
 *    розділятися, падає перевірка віндовських кінців.
 *
 * Усі три прогнані: кожна правка валить свою перевірку й не валить файл
 * цілком — саме це відрізняє живий тест від зламаного імпорту.
 */
describe("bioParagraphs", () => {
  it("рве на порожньому рядку", () => {
    expect(bioParagraphs("Перший.\n\nДругий.\n\nТретій.")).toEqual([
      "Перший.",
      "Другий.",
      "Третій.",
    ]);
  });

  it("перенос УСЕРЕДИНІ абзацу не рве", () => {
    /*
     * Так набирають довгі перелічення вистав: рядки для читабельності у
     * файлі, але абзац один.
     */
    expect(
      bioParagraphs("Поставив вистави:\n«Черевички»,\n«Витівки Скапена»."),
    ).toEqual(["Поставив вистави:\n«Черевички»,\n«Витівки Скапена»."]);
  });

  it("порожня біографія — порожній перелік", () => {
    expect(bioParagraphs("")).toEqual([]);
    expect(bioParagraphs(null)).toEqual([]);
    expect(bioParagraphs(undefined)).toEqual([]);
    expect(bioParagraphs("   \n\n  \n ")).toEqual([]);
  });

  it("віндовські кінці рядків не ламають поділ", () => {
    expect(bioParagraphs("Перший.\r\n\r\nДругий.")).toEqual([
      "Перший.",
      "Другий.",
    ]);
  });

  it("зайві порожні рядки й пробіли по краях прибираються", () => {
    expect(bioParagraphs("  Перший.  \n\n\n\n   Другий.\n")).toEqual([
      "Перший.",
      "Другий.",
    ]);
  });
});

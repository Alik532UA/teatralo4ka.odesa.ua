// @vitest-environment node
import { describe, expect, it } from 'vitest';
import { faceFloor, fitFaceFraction, planetCapacity, planetSpots } from './planetLayout';

/**
 * Обличчя на планеті НЕ перекриваються — і це рахується, а не оглядається.
 *
 * ## Звідки перевірка
 *
 * Доти розкладка була спіраллю за золотим кутом, і 2026-09-08 автор надіслав
 * знімок: з одинадцяти імен читалися п'ять, решта лежали одне на одному. Спіраль
 * рівномірно заповнює диск НАСІНИНАМИ — однаковими кружечками без підписів; наші
 * кружечки мають підпис завширшки як три обличчя, і саме він усе й ламав.
 *
 * Головне тут не «стало гарніше», а те, що дефект був НЕВИДИМИЙ для машини:
 * сторінка рендерилася, гейти зеленіли, і лише око бачило кашу. Тому перевірка
 * міряє САМУ ГЕОМЕТРІЮ — відстань між центрами проти діаметра обличчя.
 *
 * ## Зворотний експеримент (AI-AGENT-PITFALLS-v9 § 1.1)
 *
 * Проведено: крок між центрами зменшено з 1.25 діаметра до 0.6 — перевірка
 * «жодна пара не ближча за діаметр» почервоніла й назвала пару індексів і
 * відстань. Повернуто — знову зелена.
 */

/** Діаметр обличчя як частка діаметра планети — те саме число, що в компоненті. */
const ОБЛИЧЧЯ = 0.16;

/** Відстань між центрами у частках ДІАМЕТРА планети (координати — відсотки сторони). */
function відстань(a: { x: number; y: number }, b: { x: number; y: number }): number {
	return Math.hypot(a.x - b.x, a.y - b.y) / 100;
}

describe('розкладка облич на планеті', () => {
	it('перевірка жива: місця повертаються й лежать усередині кола', () => {
		const місця = planetSpots(12, ОБЛИЧЧЯ);
		expect(місця.length, 'жодного місця — міряти нема чого').toBe(12);
		for (const м of місця) {
			const від_центру = Math.hypot(м.x - 50, м.y - 50) / 50;
			expect(від_центру, `місце ${м.index} вилетіло за коло`).toBeLessThanOrEqual(0.79);
		}
	});

	it('жодна пара не ближча за діаметр обличчя — за будь-якої кількості', () => {
		for (const скільки of [1, 2, 5, 11, 12, 20, 37, 60, 120]) {
			// Обличчя меншає разом із кількістю — саме так розкладка й масштабується.
			const ОБЛИЧЧЯ = fitFaceFraction(скільки);
			const місця = planetSpots(скільки, ОБЛИЧЧЯ);
			const близькі: string[] = [];
			for (let i = 0; i < місця.length; i += 1) {
				for (let j = i + 1; j < місця.length; j += 1) {
					const d = відстань(місця[i], місця[j]);
					if (d < ОБЛИЧЧЯ) близькі.push(`${i}↔${j} = ${d.toFixed(3)} при ${ОБЛИЧЧЯ}`);
				}
			}
			expect(близькі, `при ${скільки} учнях обличчя накладаються:\n  ${близькі.join('\n  ')}`).toEqual(
				[]
			);
		}
	});

	it('кількість росте кільцями, а не ущільненням', () => {
		expect(planetSpots(5, ОБЛИЧЧЯ).every((м) => м.ring === 0), 'п’ятеро мали стати одним кільцем').toBe(
			true
		);
		const двадцять = planetSpots(20, ОБЛИЧЧЯ);
		expect(Math.max(...двадцять.map((м) => м.ring)), 'двадцятеро в одне кільце не влазять').toBeGreaterThan(
			0
		);
	});

	it('планета скінченна, і про це чесно кажуть числом', () => {
		const ємність = planetCapacity(ОБЛИЧЧЯ);
		expect(ємність, 'ємність нульова — розкладка нічого не кладе').toBeGreaterThan(10);
		// Понад ємність місць більше не з'являється: решту сторінка показує списком.
		expect(planetSpots(ємність + 40, ОБЛИЧЧЯ).length).toBe(ємність);
	});

	it('менше обличчя — більше вміщається', () => {
		expect(planetCapacity(0.08)).toBeGreaterThan(planetCapacity(0.16));
	});

	/**
	 * ЦЕ Й Є ВІДПОВІДЬ НА «А ЯК ПРИ РОСТІ КІЛЬКОСТІ».
	 *
	 * Кілець скінченно, тож саме обличчя мусить меншати. Перевірка вимагає двох
	 * речей одразу: більшій групі — менше обличчя, і при цьому всі вміщаються,
	 * поки не впремося в ціль дотику.
	 */
	it('обличчя меншає з ростом групи, і всі вміщаються до самої межі', () => {
		expect(fitFaceFraction(50)).toBeLessThan(fitFaceFraction(10));
		for (const скільки of [10, 25, 50, 65]) {
			const f = fitFaceFraction(скільки);
			expect(planetCapacity(f), `${скільки} учнів не вмістилися`).toBeGreaterThanOrEqual(скільки);
		}
		/*
		 * ДНО Й ЙОГО ЦІНА. Менше за 0.071 діаметра обличчя перестає бути ціллю
		 * дотику 44 px, тож меншати йому нікуди — і планета вміщає 67. Це не
		 * «досить на всі часи», а чесна межа: учнів зараз дванадцятеро, а коли їх
		 * стане більше за 67, зайві підуть у перелік замість того, щоб мовчки
		 * лягти одне на одного.
		 */
		expect(fitFaceFraction(100000)).toBe(0.071);
		expect(planetCapacity(0.071), 'межа планети при цілі дотику 44 px').toBe(67);
	});

	/**
	 * ДНО МІРЯЄТЬСЯ В ПІКСЕЛЯХ ЦІЄЇ КУЛІ, а не в частках гіпотетичної.
	 *
	 * Частка 0.071 — це 44 px рівно на кулі 620 px. На телефоні куля 292 px, і
	 * та сама частка дала б 21 px: ціль, у яку не влучити пальцем. Тому дно
	 * приходить із заміру, і на вузькому екрані здається ЄМНІСТЬ, а не розмір.
	 */
	it('на вузькій кулі обличчя лишається пальцевим, а вміщається менше', () => {
		expect(faceFloor(620)).toBeCloseTo(0.071, 3);

		const телефон = faceFloor(292);
		expect(292 * телефон, 'дно на телефоні — ті самі 44 px').toBeCloseTo(44, 6);

		/* Сорок людей на телефон не влазять — і розкладка це КАЖЕ, а не приховує. */
		const f = fitFaceFraction(40, 0.16, телефон);
		expect(292 * f, 'обличчя менше за палець').toBeGreaterThanOrEqual(44);
		expect(planetSpots(40, f).length, 'зайвих мовчки поклали на кулю').toBeLessThan(40);

		/* На широкій кулі ті самі сорок вміщаються всі. */
		const широка = fitFaceFraction(40, 0.16, faceFloor(620));
		expect(planetSpots(40, широка).length).toBe(40);
	});

	/**
	 * КУЛЯ ЗАСЕЛЕНА РІВНО, а не «ядро й приблуди на обідку».
	 *
	 * Доти кільця наливалися по черзі до країв, і на знімку з сорока п'ятьма
	 * учнями останньому кільцю діставалося 5 місць із 26: щільна серцевина й
	 * порожній обідок. Перекриття не було — а виглядало недоробленим.
	 *
	 * Рівність тут — не однакові числа: зовнішнє кільце довше, і людей на ньому
	 * має бути більше. Однаковою мусить бути ЩІЛЬНІСТЬ, тобто кількість на
	 * одиницю довжини кола, а вона пропорційна радіусу. Радіуси беруться з самих
	 * місць, а не з припущення про розкладку.
	 */
	it('усі задіяні кільця заселені однаково щільно', () => {
		const місця = planetSpots(45, fitFaceFraction(45));
		expect(місця).toHaveLength(45);

		const кільця = new Map<number, { скільки: number; радіус: number }>();
		for (const м of місця) {
			const радіус = Math.hypot(м.x - 50, м.y - 50);
			const було = кільця.get(м.ring);
			кільця.set(м.ring, { скільки: (було?.скільки ?? 0) + 1, радіус });
		}

		/* Задіяні кільця йдуть підряд від центру — дірок між ними немає. */
		const номери = [...кільця.keys()].sort((a, b) => a - b);
		expect(номери).toEqual(номери.map((_, i) => i));
		expect(номери.length, 'сорок п’ятеро вмістилися в одне кільце?').toBeGreaterThan(2);

		const щільність = номери.map((n) => {
			const к = кільця.get(n)!;
			return к.скільки / к.радіус;
		});
		const мін = Math.min(...щільність);
		const макс = Math.max(...щільність);
		expect(
			мін / макс,
			`щільність по кільцях: ${щільність.map((щ) => щ.toFixed(2)).join(', ')}`
		).toBeGreaterThan(0.6);
	});

	it('порожній і від’ємний перелік не падають', () => {
		expect(planetSpots(0, ОБЛИЧЧЯ)).toEqual([]);
		expect(planetSpots(-3, ОБЛИЧЧЯ)).toEqual([]);
	});
});

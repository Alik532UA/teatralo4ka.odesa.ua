/**
 * Розкладка облич на планеті — кільцями, які НЕ перекриваються за побудовою.
 *
 * ## Що було до цього і чому воно ламалося
 *
 * Обличчя стояли спіраллю за золотим кутом (137,5°) — так ростуть насінини
 * соняшника. Для НАСІНИН це ідеально: вони однакового розміру й без підписів.
 * Наші «насінини» мають підпис завширшки як три обличчя, і саме він робив
 * малюнок нечитним: 2026-09-08 автор надіслав знімок, де з одинадцяти імен
 * читалися п'ять, а решта лежали одне на одному. З ростом числа учнів ставало б
 * тільки гірше — спіраль ущільнюється, а підпис не меншає.
 *
 * ## Чому кільця
 *
 * У кільця є те, чого немає у спіралі: ВІДОМА ЄМНІСТЬ. Довжина кола — 2πr, і
 * скільки на ньому поміститься кружечків із заданим проміжком, рахується
 * наперед. Тому розкладка тут не «розкидати й сподіватися», а «покласти рівно
 * стільки, скільки влазить, решту — на наступне кільце».
 *
 * ## Як воно масштабується
 *
 * Кілець на планеті скінченна кількість, тож самими кільцями зростання не
 * вирішити: при незмінному обличчі планета переповнюється десь на двадцятьох.
 * Тому розмір обличчя — НЕ стала, а результат: `fitFaceFraction` знаходить
 * найбільше обличчя, за якого всі ще вміщаються. Дванадцятеро стоять великими,
 * шістдесят — дрібними, і жодне не лізе на сусіда.
 *
 * Дно є й у цього: обличчя не меншає за ціль дотику (44 px). Коли й воно не
 * рятує, розкладка чесно вертає менше місць, ніж просили, — а сторінка показує
 * «ще N» і веде в перелік. Мовчки накладати обличчя одне на одне не можна: саме
 * з цього все й почалося.
 *
 * ## Одиниці
 *
 * Радіуси кілець — у частках РАДІУСА планети; розмір обличчя задається часткою
 * ДІАМЕТРА (так його зручно рахувати: 96 px на кулі 620 px ≈ 0.155). Переведення
 * стоїть в одному місці — `step` нижче, і воно вже коштувало одного червоного
 * прогону. Координати вертаються у відсотках сторони квадрата — саме те, що
 * чекають `left`/`top`.
 */

export interface PlanetSpot {
	/** Номер елемента у вхідному переліку. */
	index: number;
	/** Відсоток сторони квадрата: `left`. */
	x: number;
	/** Відсоток сторони квадрата: `top`. */
	y: number;
	/** Номер кільця, 0 — найближче до центру. Потрібен для затримки появи. */
	ring: number;
	/** Кут на колі в градусах — щоб підпис знав, у який бік відсуватися. */
	angle: number;
}

/** Найдальша частка радіуса, де ще ставимо обличчя: далі край кулі загинається. */
const КРАЙ = 0.78;

/** Крок між центрами: діаметр обличчя плюс чверть на повітря, у частках радіуса. */
const крок = (faceFraction: number) => faceFraction * 2 * 1.25;

/** Радіуси всіх кілець, які вміщаються між центром і краєм. */
function кільця(faceFraction: number, edge: number): number[] {
	const s = крок(faceFraction);
	/* Перше кільце — не в центрі: там обличчя лізло б на «полюс» кулі. */
	const перше = Math.max(s * 0.9, 0.22);
	const вих: number[] = [];
	for (let r = перше; r <= edge + 1e-9; r += s) вих.push(r);
	return вих;
}

/**
 * Розкласти `count` облич кільцями. Вертає стільки місць, скільки ВЛІЗЛО.
 *
 * @param faceFraction Діаметр обличчя як частка ДІАМЕТРА планети.
 * @param edge Найдальша частка радіуса, до якої ставимо обличчя.
 */
export function planetSpots(count: number, faceFraction = 0.16, edge = КРАЙ): PlanetSpot[] {
	if (count <= 0 || faceFraction <= 0) return [];

	const s = крок(faceFraction);
	const радіуси = кільця(faceFraction, edge);
	const ємності = радіуси.map((r) => Math.max(1, Math.floor((2 * Math.PI * r) / s)));
	const spots: PlanetSpot[] = [];
	let placed = 0;

	розподіл(count, ємності).forEach((беремо, ring) => {
		if (беремо === 0) return;
		const radius = радіуси[ring];

		/*
		 * Сусідні кільця повернуті одне відносно одного на пів кроку: інакше
		 * обличчя стоять радіальними «спицями», і підписи вишиковуються
		 * стовпчиком — тобто знову одне під одним.
		 */
		const зсув = (ring % 2 === 0 ? 0 : Math.PI / беремо) - Math.PI / 2;

		for (let i = 0; i < беремо; i += 1) {
			const кут = зсув + (2 * Math.PI * i) / беремо;
			spots.push({
				/* Люди йдуть підряд: перші — на внутрішнє кільце, і так назовні. */
				index: placed + i,
				// Множник 50, а не 100: радіус — частка РАДІУСА, а відсотки
				// відлічуються від сторони квадрата, тобто від двох радіусів.
				x: 50 + radius * 50 * Math.cos(кут),
				y: 50 + radius * 50 * Math.sin(кут),
				ring,
				angle: (кут * 180) / Math.PI
			});
		}
		placed += беремо;
	});

	return spots;
}

/**
 * Скільки людей поставити на кожне кільце.
 *
 * ## Чому не «наливати від центру»
 *
 * Спершу кільця заповнювалися по черзі до країв: перше вщент, потім друге, і
 * так поки люди не скінчаться. На знімку з сорока п'ятьма учнями це виглядало
 * як щільне ядро й п'ятеро приблуд на порожньому обідку — останньому кільцю
 * діставалося 5 місць із 26. Планета читалася недоробленою, хоч жодного
 * перекриття й не було.
 *
 * Тому спершу вибирається, СКІЛЬКИ кілець задіяти (найменше, куди все влазить),
 * а тоді люди діляться між ними ПРОПОРЦІЙНО ємності: всі задіяні кільця стають
 * однаково повними, і куля виглядає рівно заселеною.
 *
 * ## Чому це не ламає обіцянку про перекриття
 *
 * Проміжок усередині кільця — `2πr / беремо`, і він тільки РОСТЕ, коли беремо
 * менше за ємність. Відстань між кільцями лишається кроком. Тобто розподіл
 * може зробити просторіше, ніж треба, але тісніше — ніколи.
 *
 * Остача роздається за найбільшим дробовим залишком: інакше округлення то
 * недорахує кілька людей, то перевищить ємність кільця.
 */
function розподіл(count: number, ємності: number[]): number[] {
	const беремо = ємності.map(() => 0);
	if (ємності.length === 0) return беремо;

	/* Найменше кілець, куди все влазить; більше за наявні не буває. */
	let k = 0;
	let вміщає = 0;
	while (k < ємності.length && вміщає < count) {
		вміщає += ємності[k];
		k += 1;
	}

	const задіяні = ємності.slice(0, k);
	const всього = задіяні.reduce((с, e) => с + e, 0);
	const скільки = Math.min(count, всього);

	const точні = задіяні.map((e) => (e * скільки) / всього);
	точні.forEach((т, i) => (беремо[i] = Math.floor(т)));

	let лишок = скільки - беремо.reduce((с, b) => с + b, 0);
	const черга = точні
		.map((т, i) => ({ i, дріб: т - Math.floor(т) }))
		.sort((a, b) => b.дріб - a.дріб);
	for (const { i } of черга) {
		if (лишок <= 0) break;
		if (беремо[i] >= задіяні[i]) continue;
		беремо[i] += 1;
		лишок -= 1;
	}

	return беремо;
}

/** Скільки облич заданого розміру вміщається на планеті. */
export function planetCapacity(faceFraction = 0.16, edge = КРАЙ): number {
	const s = крок(faceFraction);
	return кільця(faceFraction, edge).reduce(
		(сума, radius) => сума + Math.max(1, Math.floor((2 * Math.PI * radius) / s)),
		0
	);
}

/** Найменше обличчя, яке ще можна впевнено торкнутися (WCAG 2.2 SC 2.5.8). */
export const МІНІМАЛЬНЕ_ОБЛИЧЧЯ_PX = 44;

/**
 * Дно розміру обличчя — у частках діаметра ЦІЄЇ кулі.
 *
 * Частка сама по собі нічого не каже про палець: 0.071 на кулі 620 px — це 44
 * px, а на телефоні, де куля 292 px, ті самі 0.071 дають 21 px, тобто ціль,
 * у яку не влучити. Тому дно рахується від ЗАМІРЯНОЇ ширини кулі, і на вузькому
 * екрані першою здається не величина обличчя, а ЄМНІСТЬ: на кулю стає менше
 * людей, решта йде в «ще N» і в перелік. Це чесний обмін — на телефоні
 * сорок 21-піксельних кружечків не показ, а каша.
 */
export function faceFloor(planetWidthPx: number): number {
	if (!(planetWidthPx > 0)) return 0.071;
	return МІНІМАЛЬНЕ_ОБЛИЧЧЯ_PX / planetWidthPx;
}

/**
 * Найбільше обличчя, за якого вміщаються ВСІ `count`.
 *
 * Перебором зверху вниз із дрібним кроком, а не формулою: ємність — сума
 * цілих частин по кільцях, вона стрибає, і зворотної формули в неї немає.
 * Кроків тут максимум півтори сотні, і рахується це раз на зміну кількості.
 *
 * @param min Дно: частка діаметра, менше за яку обличчя перестає бути ціллю
 *   дотику; беруть його з `faceFloor` за заміряною шириною кулі. Дно ВИЩЕ за
 *   `max` — не помилка, а вузький екран: тоді обличчя лишається завбільшки з
 *   палець, а на кулю просто стає менше людей.
 */
export function fitFaceFraction(count: number, max = 0.16, min = 0.071, edge = КРАЙ): number {
	if (count <= 0) return Math.max(max, min);
	for (let f = max; f > min; f -= 0.002) {
		if (planetCapacity(f, edge) >= count) return f;
	}
	return min;
}

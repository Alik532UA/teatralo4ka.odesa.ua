/**
 * Яка з двох кнопок «усі» існує у віджеті вмісту — і чому вони НЕ можуть
 * існувати разом.
 *
 * ## Що було зламано
 *
 * `ContentWidget` мав дві незалежні умови в розмітці:
 *
 *   - кнопка `cw-show-all-btn` — рендерилася, коли список усічений (`hasMore`);
 *   - посилання `cw-all-link` — рендерилося, коли викликач дав адресу «усіх».
 *
 * Обидві умови правдиві одночасно на кожній головній сторінці, де список
 * усічений межею вигляду. Гірше: обробник кнопки, побачивши адресу, робив рівно
 * те саме, що посилання — зберігав вигляд у сховище й `goto(allLinkHref)`.
 * І підпис кнопка брала той самий: `allLinkLabel || $t('common.showAll')`.
 *
 * Тобто одна дія, дві кнопки, однаковий підпис. На мобільному вони стояли
 * впритул одна під одною (заміряно: `top` 2664 і 2733), і виглядало це просто
 * як дубль. Клік по кожній вів на `/projects/` — перевірено в браузері.
 *
 * ## Чому це не полагодили CSS-ом
 *
 * Спокуса схована `display: none` велика й неправильна: у DOM лишилися б два
 * контроли з однаковим ім'ям, тобто той самий дефект, лише невидимий оком і так
 * само присутній для читалки. Дубль тут не візуальний — він логічний.
 *
 * ## Чому окремим модулем, а не двома виправленими умовами в шаблоні
 *
 * Дві умови в розмітці — це два місця, які МОЖНА розсинхронізувати наступною
 * правкою, і рівно так дефект і з'явився. Правило «або перейти, або дописати
 * решту тут, ніколи обидва» тут одне значення, яке обчислюється один раз і має
 * власний інваріант на всі шістнадцять комбінацій входу.
 *
 * ## Чому саме взаємне виключення, а не «показати обидві з різними підписами»
 *
 * Продуктово це теж можливо: «показати ще три тут» плюс «усі на окремій
 * сторінці». Але тоді це дві РІЗНІ дії з різними підписами, і вирішувати таке
 * має автор, а не залишок логіки. Доти правило просте: є куда піти — іди;
 * немає — дописуй решту на місці.
 */

export interface AllControlsInput {
	/** Викликач попросив показати посилання на сторінку «усіх». */
	showAllLink: boolean;
	/** Адреса тієї сторінки. Порожня означає «сторінки немає». */
	allLinkHref: string;
	/** Список усічений межею вигляду — тобто показано не все. */
	hasMore: boolean;
	/** Людина вже дописала решту на місці. */
	showingAll: boolean;
}

export interface AllControls {
	/** Посилання на сторінку «усіх»: у панелі на десктопі, під списком на мобільному. */
	link: boolean;
	/** Кнопка, що дописує решту списку ТУТ. Лише коли йти нікуди. */
	expander: boolean;
}

/**
 * @returns які контроли «усі» має рендерити віджет. `link` і `expander` ніколи
 * не бувають `true` одночасно — це перевіряється інваріантом у
 * `contentWidgetControls.test.ts` на всіх комбінаціях входу.
 */
export function allControls({
	showAllLink,
	allLinkHref,
	hasMore,
	showingAll
}: AllControlsInput): AllControls {
	// Порожня адреса — це «сторінки немає», навіть якщо прапорець стоїть.
	// Перевірка саме на довжину, а не на правдивість: типове значення пропа —
	// порожній рядок, і без цього віджет показував би посилання в нікуди.
	const link = showAllLink && allLinkHref.length > 0;

	return {
		link,
		// `!link` — і є те взаємне виключення. Воно тут, а не в розмітці, саме
		// тому, що в розмітці його вже один раз забули.
		expander: hasMore && !showingAll && !link
	};
}

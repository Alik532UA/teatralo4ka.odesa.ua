/**
 * Зведення рядків до вигляду, у якому порівняння не залежить від дрібниць.
 *
 * ## Чому окремий модуль
 *
 * Це правило жило приватною функцією в `masters.ts` і працювало лише для
 * пошуку по людях. Щойно пошук з'явився на другій сторінці — переліку груп, —
 * вибір став між копією й спільним модулем. Копія тут особливо погана: правило
 * про апострофи виведене з РЕАЛЬНИХ даних, і друга копія без нього мовчки
 * ховала б записи, які в реєстрі є, а помітити це можна лише набравши точну
 * назву з «неправильним» апострофом.
 *
 * Даних модуль не тягне — це чисті перетворення рядків, тобто саме те, що
 * перевіряється тестом, а не оком на сторінці.
 */

/**
 * Зводить рядок до вигляду, у якому порівняння не залежить від дрібниць.
 *
 * Апострофи зводяться до одного: у даних трапляються всі три варіанти
 * (`'`, `’`, `ʼ`), і без цього «Бур'ян» не знаходився б за «Бурʼян» — тобто
 * пошук мовчки не показував би людину, яка в списку є.
 */
export function normalizeQuery(value: string): string {
	return value
		.toLowerCase()
		.replace(/['’`ʼ]/gu, "'")
		.replace(/\s+/gu, ' ')
		.trim();
}

/**
 * Літери, які в НАШИХ даних означають одне й те саме.
 *
 * Таблиця виведена з реальних розходжень, а не з фонетики: и/і/ы/й/ї — це те
 * саме прізвище, записане різними руками («Тункевич» і «Тункевіч», «Марина» і
 * «Маріна»), а «є/э/ё» так само розходяться в іменах, перенесених із давніх
 * списків.
 *
 * Плата за це — трохи менша точність: «били» і «білі» стають одним словом. Для
 * пошуку по іменах це правильний бік вибору: не знайти людину, яка в реєстрі є,
 * гірше, ніж побачити один зайвий рядок у переліку.
 */
const FOLD: Record<string, string> = {
	и: 'і',
	ы: 'і',
	й: 'і',
	ї: 'і',
	є: 'е',
	э: 'е',
	ё: 'е',
	ґ: 'г',
	/*
	 * Апострофи тут ТЕЖ, хоч їх зводить і `normalizeQuery`.
	 *
	 * Це не випадкове дублювання: `siteSearch` має власне зведення до
	 * порівнюваного вигляду (`normalize`) і `normalizeQuery` не кличе. Якби
	 * апострофи жили лише там, «Дар'я» з прямим апострофом знову не знаходила
	 * б «Дар’я» — саме той дефект, з якого почалася ця робота.
	 */
	'’': "'",
	'ʼ': "'",
	'`': "'",
	'´': "'"
};

/**
 * Згортання схожих літер — символ у символ.
 *
 * ДОВЖИНА ЗБЕРІГАЄТЬСЯ, і це не дрібниця: `siteSearch` шукає позицію збігу у
 * згорнутому тексті, а ріже фрагмент із тексту для показу. Згортання, яке
 * викидає символи (класичний «кістяк» слова), зсунуло б фрагмент — і виглядало
 * б це як обрізане посеред слова, тобто як помилка, якої не видно в коді.
 *
 * Апострофи зводяться тут само́ю таблицею — чому, сказано в ній.
 */
export function foldLetters(value: string): string {
	let out = '';
	for (const ch of value) {
		const low = ch.toLowerCase();
		// Регістр буває довшим за оригінал (турецьке «İ») — тоді лишаємо як є.
		const one = low.length === ch.length ? low : ch;
		out += FOLD[one] ?? one;
	}
	return out;
}

/**
 * Чи підходить набір полів запису під запит.
 *
 * Порожній запит підходить усім — інакше поле пошуку в стані спокою ховало б
 * увесь список.
 *
 * Різні написання тієї самої літери зводяться разом (`foldLetters`): «Тункевіч»
 * знаходить «Тункевич», «Маріна» — «Марину». Це той самий клас дефекту, що й
 * апострофи, і ламається він так само тихо.
 *
 * Кожне слово запиту звіряється ОКРЕМО: так «риськіна майстерність» знаходить
 * людину за іменем І предметом, а «чайники 2016» — групу за назвою і роком, не
 * вимагаючи, щоб слова стояли поруч одним рядком. Порядок слів при цьому не
 * має значення, і це навмисно: людина не пам'ятає, у якому полі що лежить.
 */
export function matchesQuery(fields: readonly (string | number | undefined | null)[], query: string): boolean {
	const q = foldLetters(normalizeQuery(query));
	if (!q) return true;
	const haystack = foldLetters(
		normalizeQuery(fields.filter((f) => f !== undefined && f !== null && f !== '').join(' '))
	);
	return q.split(' ').every((word) => haystack.includes(word));
}

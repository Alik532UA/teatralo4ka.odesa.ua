/**
 * Зведення рядків до вигляду, у якому порівняння не залежить від дрібниць.
 *
 * ## Чому окремий модуль
 *
 * Це правило жило приватною функцією в `masters.ts` і працювало лише для
 * пошуку по людях. Щойно пошук з'явився на другій сторінці — переліку груп, —
 * вибір став між копією й спільним модулем. Копія тут особливо погана: правило
 * про апострофи виведене з РЕАЛЬНИХ даних, і друга копія без нього мовчки
 * ховала б записи, які в реєстрі є, а помітити це можна лише набравши точну
 * назву з «неправильним» апострофом.
 *
 * Даних модуль не тягне — це чисті перетворення рядків, тобто саме те, що
 * перевіряється тестом, а не оком на сторінці.
 */

/**
 * Зводить рядок до вигляду, у якому порівняння не залежить від дрібниць.
 *
 * Апострофи зводяться до одного: у даних трапляються всі три варіанти
 * (`'`, `’`, `ʼ`), і без цього «Бур'ян» не знаходився б за «Бурʼян» — тобто
 * пошук мовчки не показував би людину, яка в списку є.
 */
export function normalizeQuery(value: string): string {
	return value
		.toLowerCase()
		.replace(/['’`ʼ]/gu, "'")
		.replace(/\s+/gu, ' ')
		.trim();
}

/**
 * Чи підходить набір полів запису під запит.
 *
 * Порожній запит підходить усім — інакше поле пошуку в стані спокою ховало б
 * увесь список.
 *
 * Кожне слово запиту звіряється ОКРЕМО: так «риськіна майстерність» знаходить
 * людину за іменем І предметом, а «чайники 2016» — групу за назвою і роком, не
 * вимагаючи, щоб слова стояли поруч одним рядком. Порядок слів при цьому не
 * має значення, і це навмисно: людина не пам'ятає, у якому полі що лежить.
 */
export function matchesQuery(fields: readonly (string | number | undefined | null)[], query: string): boolean {
	const q = normalizeQuery(query);
	if (!q) return true;
	const haystack = normalizeQuery(fields.filter((f) => f !== undefined && f !== null && f !== '').join(' '));
	return q.split(' ').every((word) => haystack.includes(word));
}

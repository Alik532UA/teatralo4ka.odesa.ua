/**
 * Висота елемента, яка справді оновлюється.
 *
 * ## Чому не `bind:clientHeight`
 *
 * Спершу тут стояла саме прив'язка Svelte — рядок замість файлу. Заміряно
 * 2026-09-05 на сторінці новини: компонент бачив 1347 px при справжніх 1579, і
 * далі значення не змінювалося ВЗАГАЛІ — ні коли текст виріс від довантаженого
 * шрифту, ні коли в `.article-main` уставили блок на 600 px, ні коли вікно
 * звузили з 1200 до 700 (тоді ж застигла й ширина: 280 замість 240).
 *
 * Наслідок був не «трохи не те число», а неправильна розкладка: стовпець
 * показував чотири плитки там, де влізало п'ять, і при кожній зміні розміру
 * лишався з тим самим числом.
 *
 * Тому замір свій: `ResizeObserver` плюс `document.fonts.ready`. Шрифт — окремий
 * випадок, і саме він дав ті 232 px різниці: спостерігач бачить зміну РОЗМІРУ, а
 * заголовок у три рядки замість двох з'являється тоді, коли шрифт приїхав.
 *
 * ## Чому не в компоненті
 *
 * Бо це не про статтю. Правило «скільком плиткам стати збоку» рахується з
 * висоти тексту, і будь-яке інше місце, де знадобиться жива висота, мусить
 * брати той самий замір, а не третю копію спостерігача.
 */

/**
 * Прикріплення, яке повідомляє висоту елемента й далі стежить за нею.
 *
 * ВАЖЛИВО: результат треба зберегти в змінну ОДИН раз, а не викликати просто в
 * розмітці. Кожен виклик дає нове прикріплення, і Svelte перечіпляв би його на
 * кожен рендер — а оскільки замір змінює стан, це була б нескінченна петля.
 *
 *     const мірка = measureHeight((h) => (висота = h));
 *     <div {@attach мірка}>…</div>
 */
export function measureHeight(set: (value: number) => void) {
	return (node: HTMLElement) => {
		const оновити = () => set(node.getBoundingClientRect().height);
		оновити();

		const спостерігач = new ResizeObserver(оновити);
		спостерігач.observe(node);

		/* Шрифти доїжджають після першого кадру, і саме тоді висота тексту
		   стрибає найпомітніше. `?.` — бо `document.fonts` є не всюди, а падати
		   через замір розкладки не варто. */
		document.fonts?.ready?.then(оновити).catch(() => {});

		return () => спостерігач.disconnect();
	};
}

/** Те саме для ширини — нею задається розмір плитки в стовпці. */
export function measureWidth(set: (value: number) => void) {
	return (node: HTMLElement) => {
		const оновити = () => set(node.getBoundingClientRect().width);
		оновити();

		const спостерігач = new ResizeObserver(оновити);
		спостерігач.observe(node);

		return () => спостерігач.disconnect();
	};
}

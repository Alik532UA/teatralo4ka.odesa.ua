		 * Ще один замір, коли ШРИФТИ готові.
		 *
		 * Перший замір трапляється на гідратації, а тоді назва поруч намальована
		 * запасним шрифтом і вужча. Заміряно на «Слов'янському вінку»: назва 187,
		 * список 919, звідси 28 облич. Далі приїжджає вебшрифт, назва стає 221,
		 * список звужується до 885 — і плашку «+3» обрізало на 5 пікселів.
		 *
		 * Одного `ResizeObserver` на це не досить: сповіщення про власне звуження
		 * до нас не дійшло (браузер глушить каскад, у якому обробник змінює
		 * розміри). Тож не покладаємося на нього одного.
		 */
		void document.fonts?.ready.then(порахувати);

		return () => ro.disconnect();
	});

	const скількиПоказати = $derived(showAll ? ordered.length : (fits ?? max));
	const people = $derived(ordered.slice(0, скількиПоказати));
	const hidden = $derived(ordered.slice(скількиПоказати));
</script>


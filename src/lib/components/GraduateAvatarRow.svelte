	/**
	 * Рядок мініатюр випускників — по СПИСКУ ключів, а не по одній сутності.
	 *
	 * ## Чому окремо від `GroupMatesRow`
	 *
	 * Спершу такий рядок умів лише одне: узяти склад НАВЧАЛЬНОЇ ГРУПИ за її
	 * адресою. Але той самий рядок потрібен ще в трьох місцях, і в жодному з них
	 * групи немає: склад вистави приходить зі зрізу анкет, учасники фестивалю —
	 * з реєстру фестивалів, а на сторінці викладача поряд стоять і групи, і
	 * вистави. Копіювати розмітку й стилі вчетверте означало б, що мініатюри
	 * почнуть розходитися розміром і поведінкою в сусідніх блоках однієї
	 * сторінки.
	 *
	 * Тому тут — сам рядок, який знає лише «ось ключі людей», а
	 * `GroupMatesRow` лишився тонкою обгорткою, що дістає склад групи.
	 *
	 * ## Хто показується
	 *
	 * Не лише ті, у кого є портрет: заміряно на складі груп — фото є у 62 із 91
	 * членства, тож фільтр за наявністю знімка сховав би майже третину людей.
	 * Замість портрета — перша літера імені; тьмяність кружечка означає рівно те
	 * саме, що й у списку учасників вистави: сторінки в цієї людини ще немає.
	 *
	 * Але порядок обличчями ВПЕРЕД (див. `max`), бо рядок обмежений: інакше під
	 * обмеження раз за разом потрапляли б самі літери.
	 */
	interface Props {
		/** СТІЙКІ ключі випускників (`id`), а не адреси: адресу законно виправляють. */
		ids: readonly string[];
		/** Чия це картка: сама людина серед інших не показується. */
		excludeId?: string;
		/**
		 * Чи робити кожну мініатюру посиланням.
		 *
		 * `false` потрібне там, де рядок лежить УСЕРЕДИНІ посилання — у картці
		 * переліку груп, у картці вистави. `<a>` всередині `<a>` — невалідна
		 * розмітка, і Svelte у dev валить на ній сторінку цілком
		 * (`node_invalid_placement_ssr`); гейт `e2e/nested-interactive.spec.ts`
		 * тримає нульову терпимість саме до цього випадку.
		 */
		linked?: boolean;
		/**
		 * Початок `data-testid`. Свій ОБОВ'ЯЗКОВИЙ на кожному місці показу:
		 * `e2e/testid.spec.ts` вимагає унікальності в межах сторінки, а таких
		 * рядків на сторінці стільки ж, скільки груп, вистав або фестивалів.
		 */
		testIdPrefix: string;
		/**
		 * Скільки мініатюр показати, ПОКИ ширина невідома. Решта згортається в «+N».
		 *
		 * Обмеження потрібне тому, що рядок НЕ ПЕРЕНОСИТЬСЯ: 31 учасник фестивалю
		 * в повну ширину давав два рядки облич, і блок переставав читатися як один
		 * підпис до однієї поїздки.
		 *
		 * Але саме ЧИСЛО тут — лише запасне. Доти воно було головним, і кожне
		 * місце показу вгадувало свою ширину: 6, 8, 10, 12, 16, 20. Вгадування
		 * помилялося в обидва боки, і найгірше — у бік «+15» там, де заміряно 366
		 * вільних пікселів, тобто місце ще на одинадцять облич. Тепер число
		 * рахується з РЕАЛЬНОЇ ширини (див. `fits` нижче), а цей проп працює:
		 *
		 * - на сервері й до першого заміру — бо ширини там немає;
		 * - як стеля там, де контейнер сам стискається під вміст: у сітці рядка
		 *   колонка складу оголошена `auto`, тож її ширина ДОРІВНЮЄ вмісту, і
		 *   замір лише підтверджує наявне число (нерухома точка), а не збільшує
		 *   його. Саме тому в рядках переліків цей проп і далі керує.
		 */
		max?: number;
		/**
		 * Натискання відкриває картку НА ЦІЙ сторінці (типово), а не веде на іншу.
		 *
		 * `false` потрібне там, де картка САМА і є сторінкою — на власній сторінці
		 * випускника. Там стану нікому малювати: приймача немає, і перехоплене
		 * натискання лишало адресу зміненою, а на екрані того самого господаря
		 * сторінки. Заміряно: адреса ставала
		 * `/projects/galaxy-graduates/oleksandr-chehlatonev`, а заголовок і далі
		 * «Алік Запольнов».
		 */
		openInPlace?: boolean;
		/**
		 * Показати ВСІХ, скільком би це не коштувало рядків.
		 *
		 * Знімає й `max`, і замір, і плашку «+N»: у деяких місцях половина складу
		 * гірша за високий блок. Наприклад у картці випускника, де однокурсники
		 * стоять під назвою групи: там їх щонайбільше одинадцять, і «двоє та +3»
		 * не відповідає на питання «з кем я вчився».
		 *
		 * Разом із цим рядок ЗРОСТАЄ під свій вміст (`width: max-content`) і лише
		 * потім переноситься. Без цього він лишався б блоковим — тобто брав ширину
		 * батька й не давав чипу розширитися: заміряно 105 пікселів під назву
		 * «ЗТК» при потрібних 165.
		 *
		 * Для великих наборів не годиться: 31 учасник фестивалю дав би шість
		 * поверхів облич, і блок перестав би читатися як один підпис.
		 */
		showAll?: boolean;
		/**
		 * Рахувати число облич із ЖИВОЇ ширини, а не брати з `max`.
		 *
		 * Вимикається типово, і це не обережність заради обережності. Замір має
		 * сенс лише там, де контейнер має ВЛАСНУ ширину — картка, рядок, що
		 * розтягується. Там, де контейнер стискається під вміст (колонка `auto` у
		 * сітці рядка), він виявився руйнівним: замір відлічує місце під «+N» від
		 * уже стиснутої колонки, колонка стискається ще, і так по колу. Заміряно
		 * на переліку вистав: 199 рядків із 255 осіли до ОДНОГО обличчя, і
		 * «Голоси» показували одне обличчя та «+3» у колонці 58 пікселів.
		 *
		 * Тому увімкнення — це заява того, хто кличе: «тут є свій простір».
		 * Помилитися в безпечний бік легко (діє `max`), у руйнівний — ні.
		 */
		fitToWidth?: boolean;
		/**
		 * Рядок стоїть УСЕРЕДИНІ іншого рядка, а не під ним.
		 *
		 * Знімає власні відступи: типово вони тримають мініатюри під карткою, а
		 * посередині лінії той самий нижній відступ збиває обличчя щодо назви й
		 * прапорів на кілька пікселів.
		 */
		inline?: boolean;
	}

	let {
		ids,
		excludeId = '',
		linked = true,
		testIdPrefix,
		max = 12,
		openInPlace = true,
		showAll = false,
		fitToWidth = false,
		inline = false
	}: Props = $props();

	const lang = $derived<'uk' | 'en'>($locale === 'en' ? 'en' : 'uk');

	/* Пошук за `id` по повному реєстру: він і так приходить на клієнт цілком, а
	 * невідомий ключ мовчки минається — інакше одна описка в даних валила б
	 * увесь рядок. */
	const found = $derived(
		ids
			.filter((id) => id !== excludeId)
			.map((id) => GRADUATES.find((g) => g.id === id))
			.filter((g) => g !== undefined)
	);

	/**
	 * Порядок ДОВІЛЬНИЙ, але з обличчями попереду.
	 *
	 * Дві вимоги разом: показуємо не всіх, і в першу чергу тих, у кого є
	 * портрет — інакше під обмеження раз за разом потрапляли б самі літери, і
	 * рядок виглядав би так, ніби фото немає ні в кого. Тому перемішуються ДВІ
	 * частини окремо, а вже потім склеюються: спершу з фото, далі решта.
	 *
	 * Перемішування живе в `$effect`, а НЕ в тілі компонента, і це не стиль:
	 * сторінки пререндеряться, тож на сервері порядок мусить лишитися тим
	 * самим, що й у готовому HTML. Перемішай його там — і гідратація побачить
	 * іншу розмітку, ніж прийшла з мережі. Той самий порядок міркувань, що в
	 * переліку груп (`galaxy-graduates/groups/+page.svelte`).
	 *
	 * Фішер—Йейтс, а не `sort(() => Math.random() - 0.5)`: другий дає нерівний
	 * розподіл (порівняння не транзитивне) і в частині рушіїв майже не рухає
	 * початок списку — тобто «випадковість», якої насправді немає.
	 */
	function shuffle<T>(list: T[]): T[] {
		const out = [...list];
		for (let i = out.length - 1; i > 0; i--) {
			const j = Math.floor(Math.random() * (i + 1));
			[out[i], out[j]] = [out[j], out[i]];
		}
		return out;
	}

	/* До гідратації — стабільний порядок: спершу з портретами, у межах кожної
	 * частини як у даних. Пререндерена розмітка мусить мати ЯКИЙСЬ порядок, і
	 * осмислений кращий за довільний, якщо скрипт не дійде. */
	const byPhoto = $derived([
		...found.filter((g) => g.hasPhoto),
		...found.filter((g) => !g.hasPhoto)
	]);

	/*
	 * `svelte/prefer-writable-derived` тут пропонує рівно те, чого робити НЕ
	 * можна: `$derived` обчислюється і на сервері, тобто перемішає порядок у
	 * пререндереному HTML, а клієнт під час гідратації перемішає інакше — і
	 * розмітка розійдеться з тією, що приїхала з мережі. Правило цього не
	 * бачить, бо не знає, що вираз недетермінований.
	 *
	 * У переліку груп той самий патерн проходить лінт без виключення лише через
	 * дрібницю: там ефект читає модульну константу `GROUPS`, а не реактивне
	 * значення, тож правило не розпізнає в ньому похідну.
	 */
	// eslint-disable-next-line svelte/prefer-writable-derived
	let mixed = $state<typeof byPhoto | null>(null);

	$effect(() => {
		mixed = [...shuffle(found.filter((g) => g.hasPhoto)), ...shuffle(found.filter((g) => !g.hasPhoto))];
	});

	const ordered = $derived(mixed ?? byPhoto);

	/**
	 * Натискання відкриває картку НА ЦІЙ сторінці, а не веде на іншу.
	 *
	 * Доти обличчя були звичайними посиланнями, і читач, який натиснув склад
	 * вистави на сторінці викладача, опинявся в галактиці — а закривши картку,
	 * мусив шукати викладача заново. Потік учнів на тій самій сторінці давно
	 * поводився правильно, і різниці між ним і рештою облич ніщо не виправдовувало.
	 *
	 * `<a href>` при цьому ЛИШАЄТЬСЯ, і це головне в цьому обробнику. Адреса
	 * потрібна пошуковикам, вона показується в статусному рядку, і саме вона
	 * відкривається середньою кнопкою чи з Ctrl — тобто «відкрити в новій вкладці»
	 * працює й далі. Перехоплюється РІВНО просте натискання лівою.
	 *
	 * Сторінка мусить малювати `GraduateCardOnPage` — інакше стан покладеться, а
	 * показувати картку буде нікому.
	 */
	/**
	 * Підказка — ОДНА на рядок і у фіксованому шарі.
	 *
	 * Спершу вона була абсолютною всередині клітинки, і це не працює: рядок
	 * обрізає вміст, і обрізає не сам по собі. Заміряно ланцюжок — обрізали три
	 * рівні: сам кружечок (він робить із квадрата коло), рядок і колонка складу в
	 * сітці. Знявши обрізання в двох зовнішніх, я отримав інше: у 36 рядках із 36
	 * обличчя полізли на плашки праворуч, бо сітка стискає колонку (88 пікселів
	 * під 129 вмісту).
	 *
	 * `position: fixed` виносить підказку з усіх цих коробок разом. Координати
	 * рахуються на вході курсора — від прямокутника самого кружечка.
	 *
	 * Одна на рядок, а не по одній у клітинці: показується однаково завжди рівно
	 * одна, а 27 порожніх вузлів на рядок при 733 рядках переліку вистав — це
	 * двадцять тисяч вузлів ні за що.
	 */
	let tip = $state<{ text: string; x: number; y: number } | null>(null);

	/*
	 * Координати — віконні, але з поправкою на КОНТЕЙНЕР.
	 *
	 * Підказка стоїть `position: fixed`, і доти цього вважалося досить: беремо
	 * прямокутник кружечка з `getBoundingClientRect` — і по місцях. Заміряно
	 * 2026-09-01, що виходило насправді: на сторінці випускника підказка
	 * малювалася на 208 пікселів праворуч і на 122 вниз від своєї аватарки.
	 *
	 * `position: fixed` рахується від вікна лише доки жоден предок не створив
	 * свого контейнера, а тут його створює сама картка — `.profile__card` з
	 * `transform`, якою вона виїжджає на місце. Її кут (208, 122) підказка й
	 * вважала початком вікна.
	 *
	 * Тому від віконних координат віднімається кут контейнера. Там, де
	 * контейнера немає (рядок у звичайному потоці), зсув нульовий і нічого не
	 * змінюється.
	 */
	function showTip(event: Event, text: string) {
		const el = event.currentTarget;
		if (!(el instanceof HTMLElement)) return;
		const r = el.getBoundingClientRect();
		const зсув = containingBlockOffset(el);
		tip = {
			text,
			x: Math.round(r.left + r.width / 2 - зсув.x),
			y: Math.round(r.top - зсув.y)
		};
	}

	function hideTip() {
		tip = null;
	}

	function openHere(event: MouseEvent, mate: GraduateIndexEntry) {
		if (!openInPlace) return;
		/* Модифікатори й не-ліва кнопка — не наша справа: це навмисне «відкрити
		   інакше», і забирати його в читача ми не маємо права. */
		if (event.button !== 0 || event.metaKey || event.ctrlKey || event.shiftKey || event.altKey)
			return;
		event.preventDefault();
		openGraduateModal(mate);
	}

	/**
	 * Скільки мініатюр ВМІЩУЄТЬСЯ — із заміру, а не з припущення.
	 *
	 * `null` — ще не міряли: на сервері й до першого кадру діє запасне `max`.
	 *
	 * Крок беремо з живих вузлів, а не з констант: діаметр і відступ оголошені
	 * нижче в CSS, і зашиті поруч числа розійшлися б із ними на першій правці.
	 * Константи лишаються лише як запас на випадок, коли міряти ще нічого.
	 *
	 * Місце під «+N» відлічується ОКРЕМО: без цього плашка або не влазила й
	 * обрізалася, або витісняла обличчя вже після того, як його намалювали.
	 *
	 * І відлічується КОНСТАНТОЮ, а не заміром самої плашки. Замір тут циклічний:
	 * ширина плашки залежить від того, скільки цифр у числі, а число — від того,
	 * скільки облич ми щойно вирішили показати. Перша версія міряла її живцем і
	 * ганялася за власним хвостом: рахувала по «+15» (33 px), показувала 28
	 * облич, після чого плашка ставала «+3» — і замір, зроблений по старій
	 * ширині, лишався хибним на 5–10 px, тобто плашку обрізало. Константа взята
	 * з запасом на три цифри.
	 *
	 * Зациклення немає, і це не збіг: там, де контейнер має власну ширину
	 * (рядок фестивалю, картка), число облич на неї не впливає. Там, де
	 * контейнер стискається під вміст, `n` облич дають ширину рівно
	 * `n * (діаметр + відступ) - відступ`, з якої формула повертає те саме `n` —
	 * нерухома точка, тож другий замір нічого не міняє.
	 */
	const ЗАПАСНИЙ_ДІАМЕТР = 26;
	const ЗАПАСНИЙ_ВІДСТУП = 4.8;
	/** Ширина «+N» із запасом на три цифри. Чому не заміром — вище. */
	const ПЛАШКА = 44;

	let holder = $state<HTMLUListElement | null>(null);
	let fits = $state<number | null>(null);

	$effect(() => {
		const ul = holder;
		/* `showAll` міряти нічого: він показує всіх незалежно від ширини. */
		if (!ul || !fitToWidth || showAll) return;
		/* Читаємо довжину тут, щоб замір повторився, коли склад змінився. */
		const скільки = found.length;

		const порахувати = () => {
			const style = getComputedStyle(ul);
			const відступ = parseFloat(style.columnGap) || ЗАПАСНИЙ_ВІДСТУП;
			const діаметр =
				ul.querySelector('li')?.getBoundingClientRect().width || ЗАПАСНИЙ_ДІАМЕТР;
			const крок = діаметр + відступ;
			/* `clientWidth` містить власні відступи списку — у картці вони є. */

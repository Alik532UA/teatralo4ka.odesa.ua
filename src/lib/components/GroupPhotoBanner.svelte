	.banner:focus-visible .banner__img {
		box-shadow: 0 20px 50px rgba(0, 0, 0, 0.55);
	}

	.banner:focus-visible {
		outline: 2px solid var(--accent-primary);
		outline-offset: 4px;
	}

	/* Внутрішня рамка — той самий прийом, що в героя на головній: вона лежить
	   ПОВЕРХ знімка й не займає місця, тож не змінює його пропорцій. */


	/* Стопка: усі знімки один на одному, видно лише активний. */
	/*
	 * Знімок займає РІВНО свій прямокутник, а не всю коробку.
	 *
	 * `height: 100%` + `width: auto` дає точний кадр, бо коробка має пропорцію
	 * НАЙШИРШОГО знімка стопки: будь-який інший вужчий, отже за висотою він
	 * вписується завжди, а ширину бере свою. `margin: auto` між нульовими
	 * `inset` центрує його в коробці.
	 *
	 * Через це рамка й тінь тепер обводять сам кадр. `outline` замість `border`
	 * навмисно: рамка не змінює розміру елемента, тобто не з'їдає ані пікселя

import { Trophy } from 'lucide-svelte';
import type { ResolvedPathname } from '$app/types';

/**
 * Один рядок сторінки-переліку — спільна форма для вистав, груп і фестивалів.
 *
 * ## Навіщо спільна форма
 *
 * Трьом сторінкам потрібні режими «хронологія» і «список», і в усіх трьох рядок
 * складається з того самого: рік, назва, підпис під нею, обличчя учасників,
 * плашки праворуч. Шість окремих рендерерів (по два на сторінку) означали б, що
 * рядок вистави й рядок групи почнуть розходитися висотою, відступами й
 * поведінкою на вузькому екрані — а стоять вони в сусідніх розділах однієї
 * галактики, і читач переходить між ними за два натискання.
 *
 * Тому сторінки не малюють рядки, а ПЕРЕКЛАДАЮТЬ свої дані в цю форму. Плитка
 * при цьому лишилася в кожної своя: там картка справді різна — у вистави автор і
 * нагороди, у групи майстри курсу, у фестивалю місто й прапори країн.
 *
 * ## Чого тут навмисно немає
 *
 * Ані «типу сутності», ані прапорців «це фестиваль». Щойно рендерер починає
 * питати, що йому дали, спільність зникає — лишається три гілки в одному файлі
 * замість трьох файлів. Усе особливе приходить готовим: підписом, плашкою або
 * списком ключів.
 */
/**
 * Тип значка плашки.
 *
 * Через `typeof` конкретної іконки, бо всі іконки lucide однакові за формою, а
 * власного типу для них пакет не віддає. Той самий прийом уже стоїть у
 * `MasterViewToggle` — заводити тут інший означало б два способи назвати те саме.
 */
export type MarkIcon = typeof Trophy;

/** Плашка праворуч у рядку: назва курсу, число складу, нагорода, запис. */
export interface GalaxyMark {
	/** `null` — плашка лише з текстом: так підписані назви курсів і груп. */
	icon: MarkIcon | null;
	text?: string;
	/** Підказка на наведення: повний перелік того, що згорнуто в число. */
	title?: string;
	/**
	 * Забарвлення. `group` — тихий підпис курсу, `award` і `video` — акценти.
	 * Типове (без значення) — звичайна плашка.
	 */
	tone?: 'group' | 'award' | 'video';
	/**
	 * ЗОВНІШНЯ адреса, якщо плашка сама є посиланням (запис вистави на YouTube).
	 * Внутрішні адреси тут не бувають: усередину веде назва рядка.
	 */
	href?: string;
}

export interface GalaxyRow {
	/** Ключ `{#each}` і хвіст `data-testid`. Стійкий: `id` або слаг, не індекс. */
	key: string;
	/** Куди веде назва — уже локалізована адреса. */
	href: ResolvedPathname;
	/**
	 * Рік, за яким рядок стає під заголовок у хронології.
	 *
	 * Один, хоч у групи їх буває два, а у фестивалю чотири: під заголовком рядок
	 * стоїть РАЗ, інакше та сама група показувалася б двічі й лічильник року
	 * брехав би. Беруть найновіший — те саме правило, за яким ці сторінки досі
	 * сортувалися.
	 */
	year: number;
	/**
	 * Усі роки підписом — «2012, 2013».
	 *
	 * Показується лише коли НЕ дорівнює `year`: інакше в списку поруч стояли б
	 * «2013» і «2013», а в хронології рік дублював би заголовок.
	 */
	yearLabel?: string;
	title: string;
	/** Другим рядком під назвою: автор вистави, майстри курсу, місто фестивалю. */
	subtitle?: string;
	/** Стійкі ключі випускників для мініатюр. Порожній список — рядка облич не буде. */
	memberIds?: readonly string[];
	marks?: readonly GalaxyMark[];
	/**
	 * Прапори країн — правим краєм рядка.
	 *
	 * Пара «код + підпис», а не самий код: підпис іде в `title` і в
	 * `aria-label`, а перекладати країну мусить той, хто кличе, — рядок нічого
	 * не знає про словники й не має їх знати.
	 *
	 * Спершу країни стояли в рядку самим лише текстом (у `subtitle`), і причина
	 * була така: три прапорці поспіль читаються як смужка кольорів. Але в плитці
	 * вони стоять разом із назвами й читаються, і тримати два різні показники
	 * того самого на одній сторінці — гірше за будь-яку з двох вад. Тому тут
	 * тепер і прапор, і назва.
	 */
	flags?: readonly { code: string; label: string }[];
}

/**
 * Рядки за роками, від новіших до давніших.
 *
 * Узагальнена НЕ заради краси: та сама петля вже стояла окремо в переліку вистав
 * і в хронології репертуару майстра, і третій примірник означав би, що правка
 * порядку доходить не всюди. Рік дістає викликач — у рядка він свій, у знайденої
 * вистави лежить глибше.
 *
 * Без `Map`: `svelte/prefer-svelte-reactivity` забороняє змінюваний `Map` у
 * рунному коді, а `SvelteMap` тут зайвий — величина проміжна й назовні не
 * виходить. Пошук роком по вже зібраних групах коштує O(років) на рядок, а років
 * тридцять із чимось.
 *
 * Порядок УСЕРЕДИНІ року зберігається той, що прийшов: його вже визначили пошук
 * і сортування сторінки, і перевпорядковувати тут означало б мовчки з ними
 * сперечатися.
 *
 * Функція окремо від компонента, щоб її перевіряв звичайний тест: порядок років
 * і стабільність усередині року — саме те, що ламається тихо.
 */
export function groupByYear<T>(
	items: readonly T[],
	yearOf: (item: T) => number
): Array<[number, T[]]> {
	const groups: Array<[number, T[]]> = [];
	for (const item of items) {
		const year = yearOf(item);
		const found = groups.find(([y]) => y === year);
		if (found) found[1].push(item);
		else groups.push([year, [item]]);
	}
	return groups.sort((a, b) => b[0] - a[0]);
}

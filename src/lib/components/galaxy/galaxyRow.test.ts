import { describe, expect, it } from 'vitest';
import { groupByYear } from './galaxyRow';
import { GALAXY_VIEWS, isGalaxyView } from '$lib/services/galaxyViewMode.svelte';

/**
 * Групування за роками — те, на чому стоїть режим «хронологія» на трьох
 * сторінках-переліках галактики.
 *
 * ## Чому це перевіряється тестом, а не оком
 *
 * Помилка тут не падає й не малює нічого дивного: сторінка показує всі рядки, і
 * лише при уважному читанні видно, що 2014-й трапляється двічі, або що всередині
 * року порядок не той, який задали пошук і сортування. Тобто рівно той клас
 * поломок, який на екрані не видно, а в даних живе роками.
 *
 * ## Зворотні експерименти (AI-AGENT-PITFALLS-v8 § 1.1)
 *
 * 1. Замінити `b[0] - a[0]` на `a[0] - b[0]` — падає «від новіших до давніших»
 *    і називає обидва порядки (заразом валить ще дві перевірки: порядок років
 *    видно з кількох боків).
 * 2. Замість `groups.find` дивитися лише в останню групу — падає «той самий рік
 *    одним заголовком»: роки, розділені іншим роком, дають два заголовки 2014.
 * 3. Додавати рядок через `unshift` замість `push` — падає «порядок усередині
 *    року зберігається» (і, за компанію, склад групи в перевірці 2).
 *
 * Усі три прогнані: кожна правка валить свою перевірку й лишає решту зеленими.
 */
interface Проба {
	name: string;
	рік: number;
}

const рядки = (...пари: Array<[string, number]>): Проба[] =>
	пари.map(([name, рік]) => ({ name, рік }));

const рік = (item: Проба) => item.рік;

describe('groupByYear', () => {
	it('віддає роки від новіших до давніших', () => {
		const згруповано = groupByYear(рядки(['а', 2011], ['б', 2020], ['в', 2015]), рік);

		expect(
			згруповано.map(([р]) => р),
			'роки не за спаданням — хронологія почалася б із найдавнішого'
		).toEqual([2020, 2015, 2011]);
	});

	it('той самий рік — одним заголовком, навіть коли рядки не поруч', () => {
		const згруповано = groupByYear(рядки(['а', 2014], ['б', 2018], ['в', 2014]), рік);

		expect(
			згруповано.map(([р]) => р),
			'рік трапився двічі — читач бачить два заголовки 2014 і не розуміє, який із них його'
		).toEqual([2018, 2014]);
		expect(згруповано.find(([р]) => р === 2014)?.[1].map((i) => i.name)).toEqual(['а', 'в']);
	});

	it('порядок УСЕРЕДИНІ року зберігається той, що прийшов', () => {
		/* Його вже визначили пошук і сортування сторінки; перевпорядкувати тут
		   означало б мовчки з ними сперечатися. */
		const згруповано = groupByYear(рядки(['перший', 2019], ['другий', 2019], ['третій', 2019]), рік);

		expect(згруповано).toHaveLength(1);
		expect(згруповано[0][1].map((i) => i.name)).toEqual(['перший', 'другий', 'третій']);
	});

	it('рік дістає ВИКЛИКАЧ, а не поле з назвою year', () => {
		/* Саме заради цього функція узагальнена: у рядка рік свій, а у знайденої
		   вистави лежить у `item.play.year`. */
		const вистави = [{ play: { year: 2007 } }, { play: { year: 2021 } }];
		expect(groupByYear(вистави, (i) => i.play.year).map(([р]) => р)).toEqual([2021, 2007]);
	});

	it('на порожньому списку не вигадує років', () => {
		expect(groupByYear([], рік)).toEqual([]);
	});

	it('усі рядки лишаються на місці — жоден не зникає й не дублюється', () => {
		const вхід = рядки(['а', 2001], ['б', 2003], ['в', 2001], ['г', 2003], ['д', 2010]);
		const назви = groupByYear(вхід, рік)
			.flatMap(([, items]) => items)
			.map((i) => i.name)
			.sort();

		expect(назви, 'групування втратило або продублювало рядок').toEqual(['а', 'б', 'в', 'г', 'д']);
	});
});

describe('режим показу', () => {
	it('приймає рівно три відомі режими', () => {
		expect(GALAXY_VIEWS).toEqual(['timeline', 'list', 'tiles']);
		for (const режим of GALAXY_VIEWS) expect(isGalaxyView(режим)).toBe(true);
	});

	it('відкидає сміття зі сховища, а не показує порожню сторінку', () => {
		/* У сховище пише не лише ця версія коду: «cards» лишилося від сусідніх
		   переліків, і без охоронця сторінка не показала б ЖОДНОГО режиму. */
		for (const чуже of ['cards', 'gallery', 'compact', '', 'TIMELINE', null]) {
			expect(isGalaxyView(чуже), `«${чуже}» пройшло як режим показу`).toBe(false);
		}
	});
});

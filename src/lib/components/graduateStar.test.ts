// @vitest-environment node
import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';

/**
 * Геометрія рангів зірки лежить у ТРЬОХ місцях — і мусить бути однакова.
 *
 * ## Звідки взявся цей інваріант
 *
 * Історія розходження в цьому файлі вже записана в його ж коментарях: діаметр
 * обличчя стояв двічі, ранги переозначували лише одне з місць, і в колеги з
 * кількома знімками коло ставало овалом 44×52. Тоді це полагодили змінною
 * `--photo-size`, тобто прибрали ДРУГЕ місце.
 *
 * Тепер число потрібне й скриптові — щоб `sizes` описував справжній розмір
 * зірки, а не запас на наведення, — і місць знову стало три:
 *
 *   1. `РАНГИ` у `<script>`: розмір і множник наближення;
 *   2. `--photo-size` у стилях кожного ранга;
 *   3. `transform: scale()` наведення й дільник `scale: calc(1 / N)` підпису.
 *
 * Змінною їх не звести: CSS не бачить значень зі скрипта без інлайнового
 * стилю на кожній зірці, а це 124 вузли з власним `style` замість одного
 * класу. Тож замість зведення — гейт.
 *
 * ## Чому дільник підпису тут найважливіший
 *
 * Підпис не масштабується разом із зіркою навмисно: інакше текст стає
 * розмитим. Робиться це `scale: calc(1 / N)`, де `N` мусить дорівнювати
 * множнику наведення ТОГО САМОГО ранга. Розходження не ламає нічого видимого —
 * підпис просто стає трохи більшим або меншим і трохи мутним. Тобто рівно той
 * дефект, який не помічають роками.
 *
 * ## Зворотний експеримент (`PIT-REVERSE-EXPERIMENT`)
 *
 * `--photo-size: 52px` у ранга `colleague` замінено на 48px — перевірка
 * назвала ранг і обидва числа. Дільник підпису студента змінено з 1.8 на 1.9 —
 * упала друга перевірка. Після відкоту обидві зелені.
 */

const ФАЙЛ = 'src/lib/components/GraduateStar.svelte';
const джерело = readFileSync(ФАЙЛ, 'utf8');

/** Перелік зі `<script>`: `colleague: { розмір: 52, наближення: 1.6 }`. */
function рангиЗіСкрипта(): Record<string, { розмір: number; наближення: number }> {
	const out: Record<string, { розмір: number; наближення: number }> = {};
	const блок = /const РАНГИ = \{([\s\S]*?)\} as const;/.exec(джерело)?.[1] ?? '';
	for (const m of блок.matchAll(
		/(\w+):\s*\{\s*розмір:\s*(\d+),\s*наближення:\s*([\d.]+)\s*\}/g
	)) {
		out[m[1]] = { розмір: Number(m[2]), наближення: Number(m[3]) };
	}
	return out;
}

/**
 * Стилі компонента без коментарів.
 *
 * Коментарі знімаються ДО розбору блоків, і це не косметика: у цьому файлі
 * докблоки цитують ті самі числа («44×52», «66 / 56 / 50 px»), і розбір, що
 * читає їх як код, порівнював би пояснення саме з собою. Той самий клас, який у
 * цьому репозиторії вже коштував відкоту в іншому гейті.
 *
 * Береться саме `<style>`: у `<script>` теж є фігурні дужки, і без відсікання
 * розбір блоків витягав би з нього об'єкти.
 */
const стилі = (/<style>([\s\S]*)<\/style>/.exec(джерело)?.[1] ?? '').replace(
	/\/\*[\s\S]*?\*\//g,
	' '
);

/**
 * Значення властивості в блоці, чий перелік селекторів містить `селектор`
 * ДОСЛІВНО.
 *
 * Дослівно, а не підрядком: `.star--tier-colleague` містить `.star`, тож пошук
 * підрядком віддав би розмір колеги на запит про типовий ранг — і перевірка
 * стала б зеленою саме в тому випадку, який має ловити.
 */
function зБлоку(селектор: string, властивість: RegExp): string | undefined {
	for (const m of стилі.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
		const перелік = m[1].split(',').map((s) => s.trim().replace(/\s+/g, ' '));
		if (!перелік.includes(селектор)) continue;
		const знайдено = властивість.exec(m[2]);
		if (знайдено) return знайдено[1];
	}
	return undefined;
}

describe(`геометрія рангів у ${ФАЙЛ}`, () => {
	const ранги = рангиЗіСкрипта();

	it('перевірка жива: перелік рангів прочитано зі скрипта', () => {
		expect(Object.keys(ранги).sort(), 'розбір переліку РАНГИ зламався').toEqual([
			'colleague',
			'graduate',
			'student'
		]);
	});

	it('`--photo-size` кожного ранга збігається зі скриптом', () => {
		const розходження: string[] = [];

		// `graduate` — типовий ранг, його розмір стоїть на самому `.star`.
		const типовий = зБлоку('.star', /--photo-size:\s*(\d+)px/);
		if (Number(типовий) !== ранги.graduate.розмір) {
			розходження.push(`graduate: у скрипті ${ранги.graduate.розмір}, у .star ${типовий}`);
		}

		for (const ранг of ['colleague', 'student'] as const) {
			const уCSS = зБлоку(`.star--tier-${ранг}`, /--photo-size:\s*(\d+)px/);
			if (Number(уCSS) !== ранги[ранг].розмір) {
				розходження.push(`${ранг}: у скрипті ${ранги[ранг].розмір}, у стилях ${уCSS}`);
			}
		}

		expect(
			розходження,
			'розмір обличчя розійшовся між скриптом і стилями — `sizes` почне ' +
				`обіцяти не той розмір, який зірка займає:\n${розходження.join('\n')}`
		).toEqual([]);
	});

	it('множник наведення й дільник підпису збігаються зі скриптом', () => {
		const розходження: string[] = [];

		const наведення = {
			graduate: зБлоку('.star:hover', /transform:\s*scale\(([\d.]+)\)/),
			colleague: зБлоку('.star--tier-colleague:hover', /transform:\s*scale\(([\d.]+)\)/),
			student: зБлоку('.star--tier-student:hover', /transform:\s*scale\(([\d.]+)\)/)
		};
		const підпис = {
			graduate: зБлоку('.star__label', /scale:\s*calc\(1 \/ ([\d.]+)\)/),
			colleague: зБлоку('.star--tier-colleague .star__label', /scale:\s*calc\(1 \/ ([\d.]+)\)/),
			student: зБлоку('.star--tier-student .star__label', /scale:\s*calc\(1 \/ ([\d.]+)\)/)
		};

		for (const ранг of ['graduate', 'colleague', 'student'] as const) {
			const очікуване = ранги[ранг].наближення;
			if (Number(наведення[ранг]) !== очікуване) {
				розходження.push(`${ранг}: наведення у скрипті ${очікуване}, у стилях ${наведення[ранг]}`);
			}
			if (Number(підпис[ранг]) !== очікуване) {
				розходження.push(
					`${ранг}: дільник підпису ${підпис[ранг]} проти множника наведення ${очікуване} — ` +
						'підпис буде не того розміру й розмитий'
				);
			}
		}

		expect(розходження, розходження.join('\n')).toEqual([]);
	});

	it('`sizes` не обіцяє більше, ніж зірка займає', () => {
		// Саме те, що коштувало 2,7 МБ: `sizes` описував запас на наведення, а
		// платила за нього кожна зірка й завжди. Тепер обидва значення
		// обчислюються з переліку рангів, і в розмітці не лишилося літералів.
		expect(
			/sizes="\(hover: hover\)/.test(джерело),
			'у розмітку повернувся літеральний `sizes` із запасом на наведення'
		).toBe(false);
		expect(
			/const sizes = \$derived\.by/.test(джерело),
			'`sizes` більше не обчислюється з переліку рангів'
		).toBe(true);
	});
});

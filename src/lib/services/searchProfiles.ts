import { asset } from '$app/paths';

/**
 * Текст анкет для пошуку — один файл, і тягнеться він раз за сеанс.
 *
 * ## Чому окремий файл, а не бандл
 *
 * Анкети живуть по одній на людину (`static/graduates/profiles/*.json`,
 * `static/masters/profiles/*.json`) — 361 файл, які сторінка тягне поштучно,
 * коли відкривають картку. Пошуку потрібен увесь текст одразу, а покласти його в
 * бандл означало б додати 45 КБ анкет випускників і 76 КБ анкет майстрів до
 * ваги, яку платить КОЖНА сторінка сайту, — заради накладки, яку більшість
 * відвідувачів не відкриє.
 *
 * Тому текст збирається на збірці (`scripts/build-search-index.ts`) в один
 * файл, і браузер тягне його тоді ж, коли й реєстри галактики: у мить, коли
 * пошук відкрили. 23 КБ у brotli — приблизно як одне середнє фото.
 *
 * ## Чому це «додатковий текст», а не власні записи
 *
 * У файлі лежить `{ "person:<slug>": "…", "master:<slug>": "…" }` — ключі ті
 * самі, що будує `searchGalaxy`. Тобто анкета не додає НОВОГО рядка в
 * результати, а дописує текст до наявного запису людини. Інакше на запит
 * «Тункевич» вона з'являлася б двічі: як людина і як «текст про людину».
 *
 * ## Що з помилкою мережі
 *
 * Нічого не кидаємо далі: пошук по іменах, сторінках і новинах мусить працювати
 * й тоді, коли файл не приїхав. Порожня мапа означає «шукаємо по шапках, як
 * раніше», а не «пошук зламався» — те саме рішення, що для новин у
 * `searchIndex`.
 */

/** Прочитане раз за сеанс: ключ запису → текст його анкети. */
let кеш: ReadonlyMap<string, string> | null = null;

export async function profileText(): Promise<ReadonlyMap<string, string>> {
	if (кеш) return кеш;

	try {
		const відповідь = await fetch(asset('/search/profiles.json'));
		if (!відповідь.ok) throw new Error(`HTTP ${відповідь.status}`);
		const дані = (await відповідь.json()) as Record<string, string>;
		кеш = new Map(Object.entries(дані));
	} catch (error) {
		console.warn('Пошук: текст анкет недоступний, шукаємо по іменах і назвах', error);
		кеш = new Map();
	}

	return кеш;
}

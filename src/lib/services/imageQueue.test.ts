// @vitest-environment node
import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';
import { зайнятиСлот, станЧерги } from './imageQueue';

/**
 * Черга слотів завантаження.
 *
 * Перевіряється саме розподіл слотів, а не робота з `<img>`: подія `load` у
 * jsdom не настає ніколи, бо мережі там немає, тож перевірка «портрет
 * показався» була б перевіркою заглушки. Розподіл слотів — це чиста
 * арифметика, і саме в ній живе єдиний спосіб зламати все назавжди:
 * ЗАГУБЛЕНИЙ СЛОТ. Слот, який не віддали, не повертається ніколи; шість таких,
 * і галактика лишається крапками до перезавантаження сторінки.
 *
 * Тому нижче найважливіші три випадки — подвійна віддача, віддача з черги
 * очікування та передача слота напряму наступному.
 *
 * Зворотний експеримент (`PIT-REVERSE-EXPERIMENT`): у `зайнятиСлот` прибрано
 * охорону `if (віддано) return` — упала перевірка про подвійну віддачу й
 * назвала число зайнятих. Повернено `зайнято--` замість передачі наступному —
 * упала перевірка про межу.
 */
describe('черга слотів завантаження', () => {
	it('перевірка жива: черга починає з нуля', () => {
		expect(станЧерги()).toEqual({ зайнято: 0, очікує: 0 });
	});

	it('перші шість стартують одразу, сьомий чекає', () => {
		const порядок: number[] = [];
		const віддати = Array.from({ length: 7 }, (_, i) =>
			зайнятиСлот(() => порядок.push(i))
		);

		expect(порядок, 'стартувати мусили рівно шість').toEqual([0, 1, 2, 3, 4, 5]);
		expect(станЧерги()).toEqual({ зайнято: 6, очікує: 1 });

		// Віддача слота пускає того, хто чекав, — і не збільшує кількості зайнятих.
		віддати[0]();
		expect(порядок).toEqual([0, 1, 2, 3, 4, 5, 6]);
		expect(станЧерги()).toEqual({ зайнято: 6, очікує: 0 });

		віддати.forEach((f) => f());
		expect(станЧерги(), 'після віддачі всіх слотів черга мусить спорожніти').toEqual({
			зайнято: 0,
			очікує: 0
		});
	});

	it('подвійна віддача не додає слотів понад межу', () => {
		// Без охорони від повторної віддачі лічильник пішов би в мінус, і межа
		// перестала б діяти взагалі: далі стартувало б усе підряд.
		const віддати = зайнятиСлот(() => undefined);
		віддати();
		віддати();
		віддати();
		expect(станЧерги()).toEqual({ зайнято: 0, очікує: 0 });

		const порядок: number[] = [];
		const усі = Array.from({ length: 8 }, (_, i) => зайнятиСлот(() => порядок.push(i)));
		expect(порядок.length, 'межа мусить лишитися шість').toBe(6);
		усі.forEach((f) => f());
	});

	it('віддача того, хто ще чекав, нікого не пускає', () => {
		// Зірка, яка зникла з екрана до своєї черги: слота вона не мала, тож і
		// передавати нема чого — але й лишатися в черзі не повинна.
		const порядок: number[] = [];
		const шість = Array.from({ length: 6 }, () => зайнятиСлот(() => undefined));
		const сьомий = зайнятиСлот(() => порядок.push(7));
		const восьмий = зайнятиСлот(() => порядок.push(8));

		expect(станЧерги()).toEqual({ зайнято: 6, очікує: 2 });
		сьомий();
		expect(порядок, 'сьомий сам вийшов із черги — стартувати не мусив ніхто').toEqual([]);
		expect(станЧерги()).toEqual({ зайнято: 6, очікує: 1 });

		шість[0]();
		expect(порядок, 'слот мусив дістатися восьмому').toEqual([8]);

		восьмий();
		шість.slice(1).forEach((f) => f());
		expect(станЧерги()).toEqual({ зайнято: 0, очікує: 0 });
	});
});

/**
 * Межа завантажень — число обґрунтоване, а не заміряне, і саме тому воно мусить
 * лишатися з поясненням.
 *
 * Копіювати сюда з сусіднього проєкту трійку було б помилкою: там знімки
 * 1280 px, тут портрети 96×96 по 2,9 КБ, і межа впирається не в ширину каналу,
 * а в затримку. Ця перевірка не судить саме число — вона стежить, щоб його не
 * змінили молча: разом із межею мусить рухатися й розділ шапки, що її пояснює.
 */
describe('межа завантажень пояснена', () => {
	const джерело = readFileSync('src/lib/services/imageQueue.ts', 'utf8');

	it('межа задана одним числом, а не розсипана по коду', () => {
		expect(/const МЕЖА = (\d+);/.exec(джерело)?.[1], 'константу МЕЖА не знайдено').toBeDefined();
		const вжитки = джерело.match(/МЕЖА/g) ?? [];
		expect(вжитки.length, 'МЕЖА мусить згадуватися рівно двічі: оголошення й порівняння').toBe(2);
	});

	it('шапка називає те саме число, що й код', () => {
		const число = /const МЕЖА = (\d+);/.exec(джерело)?.[1];
		expect(число).toBeDefined();
		// Число в прозі або генерується, або стоїть під гейтом
		// (AI-AGENT-PITFALLS-v9, `PIT-NUMBER-UNDER-GATE`). Тут — під гейтом.
		expect(
			new RegExp(`Чому ${число}, а не`).test(джерело),
			`шапка не пояснює межу ${число}: заголовок «Чому ${число}, а не …» відстав від коду`
		).toBe(true);
	});
});

/**
 * Чи показувати «Ранні покази» в переліку вистав майстра.
 *
 * Це роботи до заснування ДТШ (`isDtsh === false`) — у Федора Ткача їх вісім із
 * вісімдесяти. Вони не помилкові й не зайві, тому їх ХОВАЮТЬ, а не видаляють:
 * дані лишаються в профілі, а серія `J` повертає їх на екран, коли треба
 * звірити хронологію.
 *
 * Стан у пам'яті, а не в сховищі — на відміну від `adultsVisibility`. Там
 * запис потрібен, бо з телефона людина йде з розділу й повертається без
 * параметра; тут нікуди йти не треба, весь блок на одній сторінці, і
 * перезавантаження свідомо повертає типовий вигляд.
 *
 * Модуль, а не локальний `$state` у компоненті: жест живе в `ServiceLayer`
 * разом з усіма іншими — там єдиний слухач клавіатури й спільні захисти, — а
 * читає прапорець `MasterProductions`.
 */
/**
 * Другий вхід — параметр адреси, поруч із серією `J`.
 *
 * Службовий жест не буває ЄДИНИМ входом (DEBUGGING-v8 § 3.1,
 * `DBG-KEY-SEQUENCE`): на дотику клавіатури немає, тож із телефона покази були
 * б недосяжні зовсім. Розбирає значення `visibilityFromUrl` — та сама пара
 * `1`/`0`, що й у розділу викладачів, щоб для одного й того самого стану не
 * з'явилося двох мов.
 */
export const EARLY_URL_PARAM = 'early';

class EarlyShowsState {
	/** Типово сховані. */
	visible = $state(false);

	/** Задати явним значенням — для входу за адресою: він каже, ЧОГО просять. */
	setVisible(value: boolean): void {
		this.visible = value;
	}

	/** Гортання доречне: жест один на обидві дії — і показати, і сховати. */
	toggle(): boolean {
		this.visible = !this.visible;
		return this.visible;
	}
}

export const earlyShows = new EarlyShowsState();

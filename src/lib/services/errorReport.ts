import { errorLogger, redact } from './errorLogger';

/**
 * Текстовий звіт про роботу — той, що копіює службове табло (DEBUGGING-v8 § 2.3).
 *
 * **Окремий файл, а не метод логера, і причина не в розмірі.** Логер відповідає за
 * ЗБІР подій: рівні, маскування, обрізаний буфер, консоль. Складання тексту для
 * людини — інша відповідальність, з іншими причинами змінюватися: формат шапки
 * залежить від того, що питають у скаргах, а не від того, як пишуться події.
 * Розмір лише зробив це видимим — файл переріс стелю § 7 рівно на цю функцію.
 *
 * **Шапка тут, а не в кнопці.** Копіювати звіт може не одне місце, і друга шапка
 * розійшлася б із першою — у сусідньому проєкті так і сталося: один із двох
 * варіантів не мав ні адреси, ні пристрою, ні стану мережі, і збігалися вони лише
 * в номері версії.
 */
export function buildLogReport(): string {
	const inBrowser = typeof window !== 'undefined';
	const all = errorLogger.getCache();

	const header = [
		'--- LOG REPORT ---',
		// ISO, а не toLocaleString(): звіт читає той, хто розбирає збій, а не
		// відвідувач, який його скопіював. Голий toLocaleString() форматує в локалі
		// СИСТЕМИ відвідувача — 03.08 чи 08.03 залежно від того, де він живе, і
		// зрозуміти, що з них день, за самим рядком не можна.
		`DATE: ${new Date().toISOString()}`,
		`VERSION: ${errorLogger.appVersion}`,
		// Адреса маскується: рядок запиту з токеном приходить саме нею. Записи в
		// буфері вже замасковані при записі, а `location` читається живим.
		`URL: ${inBrowser ? redact(window.location.href) : 'SSR'}`,
		`DEVICE: ${inBrowser ? navigator.userAgent : 'SSR'}`,
		// Половина скарг «нічого не працює» пояснюється саме цим рядком, і дізнатися
		// це заднім числом уже неможливо.
		`ONLINE: ${inBrowser ? navigator.onLine : 'n/a'}`,
		`ERRORS: ${errorLogger.errorCount} / ${all.length}`,
		'---'
	].join('\n');

	/*
	 * У тіло йдуть ВСІ записи, не лише помилки.
	 *
	 * `logWarning` і `logInfo` — це те, що сталося ДО поломки: офлайн, скасований
	 * запит, вхід в акаунт. Саме вони й пояснюють помилку, яка стоїть останньою.
	 * `errorLogger.getErrors()` лишається для місць, яким потрібні саме поломки.
	 */
	const body = all
		.map(
			(e) =>
				`[${e.context.timestamp}] [${e.level.toUpperCase()}] ` +
				`[${e.context.component ?? 'app'}] ${e.message}` +
				(e.stack ? `\n${e.stack}` : '')
		)
		.join('\n');

	return `${header}\n${body}`;
}

import { beforeEach, describe, expect, it } from 'vitest';
import { session } from './storage';
import { samePage, shortenTitle, TRAIL_KEY, trail } from './trail.svelte';

/**
 * СЛІД «звідки прийшов».
 *
 * ## Що саме стережеться
 *
 * Не те, що крихта малюється, — це видно оком, — а три правила, кожне з яких
 * при поломці дає не порожнечу, а НЕПРАВДУ на екрані. Мовчазна неправда в
 * навігації гірша за її відсутність: людина йде за нею й опиняється не там.
 *
 * 1. ЗАПИС ПРИВ'ЯЗАНИЙ ДО ЦІЛІ. Без цього після «Назад» браузера сторінка
 *    показувала б слід на СЕБЕ САМУ.
 * 2. ПЕРЕМИКАННЯ МОВИ — НЕ ПЕРЕХІД. Інакше крихта пропонує повернутися на
 *    сторінку з тією самою назвою.
 * 3. ПІДПИС БЕРЕТЬСЯ ЗА ПРАВИЛОМ, а не «як вийде»: заголовки сайту мають сталу
 *    форму, і саме з неї береться коротке ім'я. Довжину тут не ріже НІЩО —
 *    перша версія різала на 28 знаках і зіпсувала «Осадча (Бур'ян) Євгенія
 *    Олександрівна» на широкому екрані, де місця вистачало з запасом.
 *
 * Самої підписки на `beforeNavigate` тут немає навмисно — вона в
 * `utils/installTrail` і не вирішує нічого, крім «звідки взяти три значення».
 * У середовищі юніт-тестів `$app/navigation` не резолвиться взагалі, тож
 * тримати правила поруч із ним означало б лишити їх без перевірки.
 */

const УК = 'https://teatralo4ka.odesa.ua';
const url = (шлях: string) => new URL(шлях, УК);

describe('shortenTitle — коротка назва із заголовка сторінки', () => {
	/*
	 * Заміряно на зібраній статиці 2026-09-08: у кожному HTML рівно один
	 * `<title>`, і форма скрізь та сама. Рядки нижче — не вигадані приклади, а
	 * дослівні заголовки п'яти різних типів сторінок.
	 */
	it.each([
		['Групи випускників | Одеська театральна школа', 'Групи випускників'],
		['«Акварель» — Групи випускників | Одеська театральна школа', '«Акварель»'],
		['Алік Запольнов — Галактика випускників', 'Алік Запольнов'],
		['Планета творчості | Одеська театральна школа', 'Планета творчості'],
		['Одеська театральна школа', 'Одеська театральна школа']
	])('%s → %s', (заголовок, очікуване) => {
		expect(shortenTitle(заголовок)).toBe(очікуване);
	});

	it("довге ім'я лишається цілим — обрізає ширина, а не лічильник знаків", () => {
		expect(shortenTitle('Ніколаєва Анастасія Олексіївна — Резиденти — Одеська театральна школа')).toBe(
			'Ніколаєва Анастасія Олексіївна'
		);
		expect(shortenTitle("Осадча (Бур'ян) Євгенія Олександрівна — Галактика випускників")).toBe(
			"Осадча (Бур'ян) Євгенія Олександрівна"
		);
	});

	it('порожній заголовок не дає підпису', () => {
		expect(shortenTitle('   |   ')).toBe('');
	});
});

describe('samePage', () => {
	it('хвостова риска не робить сторінку іншою', () => {
		expect(samePage('/projects/galaxy-graduates/plays', '/projects/galaxy-graduates/plays/')).toBe(
			true
		);
	});

	it('відсутня адреса ніколи не збігається — інакше «немає» читалося б як «те саме»', () => {
		expect(samePage(undefined, '/plays/')).toBe(false);
		expect(samePage('/plays/', undefined)).toBe(false);
	});
});

describe('trail — крок віддається лише тій сторінці, на яку він вів', () => {
	beforeEach(() => {
		/* Слід — стан модуля, спільний для всіх перевірок файлу: чистимо обидві копії. */
		trail.record(url('/x/'), url('/y/'), 'скидання');
		session.remove(TRAIL_KEY);
	});

	it('зберігає адресу з параметрами, а звіряється без них', () => {
		trail.record(url('/residents/adults/?adults=1'), url('/projects/galaxy-graduates/groups/7t-19/'), 'Ніколаєва Анастасія Олексіївна — Резиденти');

		const крок = trail.forPath('/projects/galaxy-graduates/groups/7t-19/');
		expect(крок?.href).toBe('/residents/adults/?adults=1');
		expect(крок?.path).toBe('/residents/adults/');
		expect(крок?.label).toBe('Ніколаєва Анастасія Олексіївна');
	});

	it('ЧУЖІЙ сторінці крок не віддається — це і є захист від «Назад»', () => {
		trail.record(url('/a/'), url('/b/'), 'Сторінка А');
		trail.record(url('/b/'), url('/c/'), 'Сторінка Б');

		/* Людина натиснула «Назад» і знову на /b/: слід веде на /c/, тож тут нічого. */
		expect(trail.forPath('/b/')).toBeNull();
		expect(trail.forPath('/c/')?.label).toBe('Сторінка Б');
	});

	it('перемикання мови слідом не є', () => {
		trail.record(url('/a/'), url('/b/'), 'Сторінка А');
		trail.record(url('/projects/galaxy-graduates/'), url('/en/projects/galaxy-graduates/'), 'Галактика випускників');

		expect(trail.forPath('/en/projects/galaxy-graduates/')).toBeNull();
	});

	it('сторінка без заголовка сліду не лишає', () => {
		trail.record(url('/a/'), url('/b/'), '   ');
		expect(trail.forPath('/b/')).toBeNull();
	});

	it('слід переживає перезавантаження — інакше він блимав би без причини', () => {
		trail.record(url('/a/'), url('/b/'), 'Сторінка А');
		expect(session.get(TRAIL_KEY)).toContain('"to":"/b/"');

		/* Зіпсований запис читається як порожній, а не валить сторінку. */
		session.set(TRAIL_KEY, '{не json');
		expect(() => trail.restore()).not.toThrow();
	});
});

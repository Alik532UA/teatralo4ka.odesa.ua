import { stripLocale } from '$lib/i18n/routing';
import { session } from './storage';

/**
 * СЛІД — сторінка, з якої людина сюди прийшла.
 *
 * ## Навіщо
 *
 * Вистава належить одночасно групі, фестивалю, випускникові, театру й закладу
 * освіти. Ієрархія тут ГРАФ, а не дерево, тому статична крихта «всі вистави»
 * завжди називає не того батька: людина прийшла з профілю Аліка, а їй кажуть,
 * що вона в розділі вистав. Слід відповідає на це чесно — і додається ПЕРЕД
 * статичною крихтою, не заміняючи її.
 *
 * ## Чому лише переходи всередині сайту
 *
 * Сайт весь prerender: один HTML на всіх відвідувачів. Сервера, який міг би
 * підставити «звідки прийшов», немає в принципі, тож слід існує тільки в
 * браузері й тільки після гідрації. `document.referrer` не взято навмисно:
 * адресу він дає, а НАЗВУ сторінки — ні, і довелося б заводити карту
 * «адреса → назва» на весь сайт, яка застаріває мовчки.
 *
 * ## Чому запис прив'язаний до ЦІЛІ, а не просто «останній перехід»
 *
 * Без цього ламався звичайний «Назад» браузера. Б → В записує «звідки: Б»;
 * далі В → Г записує «звідки: В»; людина тисне «Назад» і опиняється на В — а в
 * пам'яті лишилося «звідки: В», тобто крихта показувала б сторінці ЇЇ САМУ.
 * Тому зберігається пара «звідки → куди», і крихта малюється лише там, куди
 * цей перехід справді вів.
 *
 * `popstate` не записується окремо: «Назад» уже є в браузера, і другий «назад»
 * на екрані, який веде в інше місце, — це не допомога, а пастка.
 */

/**
 * Ключ у сховищі вкладки: слід переживає перезавантаження сторінки.
 *
 * Без префікса — його ставить сам фасад `session` (STORAGE-NAMESPACE-v9), і
 * писати повз фасад заборонено правилом лінтера: у приватному вікні доступ до
 * сховища кидає ще до будь-якого try/catch у місці виклику.
 */
export const TRAIL_KEY = 'trail';

/**
 * Стеля довжини підпису.
 *
 * Заміряно на найдовшому реальному випадку — «Ніколаєва Анастасія Олексіївна»
 * (30 знаків): на екрані 360 px три крихти в один рядок не влазять, а перенос
 * на третій рядок зсуває заголовок сторінки. 28 знаків лишають перенос
 * щонайбільше на другий рядок.
 */
export const TRAIL_LABEL_MAX = 28;

/** Найкоротше слово, після якого обрізання рветься по пробілу, а не по літері. */
const WORD_FLOOR = 18;

export interface TrailStep {
	/** Куди вести — з параметрами, щоб повернути людину туди, де вона була. */
	href: string;
	/** Той самий крок без параметрів: за ним звіряються збіги. */
	path: string;
	/** Що написати на крихті. */
	label: string;
}

interface TrailRecord {
	from: TrailStep;
	/** Адреса, НА ЯКУ вів цей перехід. Крихта малюється лише там. */
	to: string;
}

/** Хвостова риска є скрізь (`trailingSlash: 'always'`), але не в усіх джерелах. */
function withSlash(pathname: string): string {
	return pathname.endsWith('/') ? pathname : `${pathname}/`;
}

export function samePage(a: string | undefined, b: string | undefined): boolean {
	if (!a || !b) return false;
	return withSlash(a) === withSlash(b);
}

/**
 * Підпис крихти із заголовка сторінки.
 *
 * Заголовки сайту мають одну форму: `НАЗВА — РОЗДІЛ | БРЕНД`. Заміряно на
 * зібраній статиці — окремого `<title>` у layout немає, шаблон сторінки його
 * перебиває, тож у HTML рівно один заголовок:
 *
 *   «Групи випускників | Одеська театральна школа»          → «Групи випускників»
 *   ««Акварель» — Групи випускників | Одеська...»            → ««Акварель»»
 *   «Алік Запольнов — Галактика випускників»                 → «Алік Запольнов»
 *   «Ніколаєва Анастасія Олексіївна — Резиденти — ...»       → «Ніколаєва Анастасія…»
 *
 * Тире беруться обидва (— і –): у даних трапляються обидва знаки, і різниця
 * між ними на око невидима, тобто помилку в даних ніхто не помітив би.
 */
export function shortenTitle(raw: string): string {
	const untilBrand = raw.split('|')[0] ?? '';
	const untilSection = untilBrand.split(/\s[—–]\s/)[0] ?? '';
	const clean = untilSection.replace(/\s+/g, ' ').trim();
	if (clean.length <= TRAIL_LABEL_MAX) return clean;

	const cut = clean.slice(0, TRAIL_LABEL_MAX);
	const space = cut.lastIndexOf(' ');
	return `${(space >= WORD_FLOOR ? cut.slice(0, space) : cut).trimEnd()}…`;
}

class Trail {
	#record = $state<TrailRecord | null>(null);

	/** Крок, який справді вів на цю сторінку, — або нічого. */
	forPath(pathname: string): TrailStep | null {
		const record = this.#record;
		return record && samePage(record.to, pathname) ? record.from : null;
	}

	/**
	 * Записати перехід `from → to`, якщо він узагалі є слідом.
	 *
	 * Правила відсіву тут, а не в перехіднику: саме вони й ламалися, тож саме
	 * вони мусять бути під юніт-перевіркою. `beforeNavigate` лишається тонким
	 * шаром, який не вирішує нічого.
	 */
	record(from: URL, to: URL, title: string): void {
		/*
		 * Та сама сторінка іншою мовою (і будь-яка зміна лише параметрів) слідом
		 * не є: інакше після перемикання мови крихта пропонувала б повернутися на
		 * сторінку з тією самою назвою.
		 */
		if (stripLocale(from.pathname) === stripLocale(to.pathname)) return;

		const label = shortenTitle(title);
		if (!label) return;

		this.#remember({
			from: { href: `${from.pathname}${from.search}`, path: from.pathname, label },
			to: to.pathname
		});
	}

	#remember(record: TrailRecord): void {
		this.#record = record;
		/* Відмову сховища ковтає фасад: без сліду сторінка робоча, з винятком — ні. */
		session.setJSON(TRAIL_KEY, record);
	}

	/** Прочитати слід, записаний перед перезавантаженням цієї ж сторінки. */
	restore(): void {
		const parsed = session.getJSON<TrailRecord>(TRAIL_KEY);
		/* Зіпсований чи чужий запис — рівно те саме, що й порожній. */
		if (parsed?.from?.href && parsed?.from?.label && parsed?.to) this.#record = parsed;
	}
}

export const trail = new Trail();

import { STORAGE_PREFIX } from '$lib/config/storage';
import { session, storage } from './storage';

/**
 * Аварійне скидання: стерти локальні налаштування сайту й перезавантажитися.
 *
 * **Навіщо воно.** Тема, режим смуги прокрутки, кешовані налаштування шапки й
 * позначки бета-тесту живуть у сховищі. Коли вони суперечать новій збірці,
 * сторінка відкривається зламаною — а лікується це відкриттям DevTools, чого
 * відвідувач не зробить. Жест на клавіатурі дає той самий результат без
 * інструментів розробника.
 *
 * **Чому все одно через префіксований фасад, хоч origin тут ексклюзивний.** Сайт
 * на власному домені (`base: ''`, PROJECT-CONTEXT § базові параметри), тобто
 * сусідів по сховищу немає. Префікс лишається з тієї самої причини, з якої він
 * лишається в самому фасаді: він коштує нічого і страхує від переїзду на спільний
 * хостинг. `localStorage.clear()` тут не зламав би нічого сьогодні — і зламав би
 * усе першого дня після такого переїзду.
 *
 * **Чого скидання НЕ торкається — і це рішення.** Firebase Auth тримає сеанс не в
 * `localStorage`, а в IndexedDB, і його база лишається. Тобто після скидання
 * людина лишається залогіненою. Так і має бути: жест лікує МІСЦЕВИЙ стан
 * інтерфейсу, а не особу — вибити адміністратора з сеансу через зламану тему було
 * б лікуванням дорожчим за хворобу. Виходу з акаунта є власна кнопка.
 *
 * **Кукі теж не чистяться, і теж навмисно.** Сайт їх не ставить: жодного
 * `document.cookie =` у коді немає, а кукі Firebase і reCAPTCHA належать домену
 * Google, тобто з цієї сторінки їх не видно й не видалити.
 *
 * **Ніколи не кидає.** Це аварійний шлях: його кличуть тоді, коли вже щось не
 * працює. Виняток усередині означав би «навіть скидання зламане».
 */

/** Скільком натисканням запускати жест. Різні числа — різна ціна помилки. */
export const RESET_PRESSES_DEV = 5;
/**
 * 55 у проді — те саме число, що в сусідніх проєктах.
 *
 * Число велике не для складності, а тому що ціна випадкового спрацювання — усі
 * місцеві налаштування. Плюс підтвердження: разом це два незалежні барʼєри, і
 * жоден не покладається на уважність.
 */
export const RESET_PRESSES_PROD = 55;

/**
 * Текст підтвердження свідомо НЕ через i18n.
 *
 * `confirm()` — блокуючий діалог браузера, і він може знадобитися саме тоді, коли
 * зламалося завантаження словників: тоді `$t()` віддав би ключ замість тексту,
 * тобто людина побачила б «reset.confirm» перед знищенням своїх даних. Тому обидві
 * мови сайту стоять тут поруч жорстким рядком.
 */
const CONFIRM_TEXT =
	'Це видалить локальні налаштування цього сайту: тему, вигляд, позначки. Вхід в акаунт залишиться. Продовжити? / This clears local settings for this site. You stay signed in. Continue?';

/**
 * @param askConfirmation питати підтвердження. У проді — обовʼязково: без нього
 * жест стирає налаштування без жодного запитання.
 */
export async function hardReset(askConfirmation = true): Promise<void> {
	if (typeof window === 'undefined') return;

	if (askConfirmation && !window.confirm(CONFIRM_TEXT)) return;

	/*
	 * Під власним `try`, а не разом із рештою: збій сховища не має скасовувати
	 * чищення кешів. Скидання кличуть, коли вже зламано, тож воно мусить зробити
	 * стільку, скільки зможе. Порожній `catch` тут не недогляд: повідомляти нема
	 * кому й нема куди — сторінка зараз зникне.
	 */
	try {
		storage.clear();
		session.clear();
	} catch {
		/* сховище недоступне — решта скидання все одно потрібна */
	}

	await clearOwnCaches();
	await unregisterControllingWorkers();

	window.location.reload();
}

/**
 * Кеші — за префіксом проєкту.
 *
 * `caches.keys()` віддає імена кешів усього origin. Тут він ексклюзивний, тож
 * фільтр сьогодні нічого не відсіює — але саме він робить різницю між «скинути
 * свій сайт» і «скинути все, що є на домені» в той день, коли на домені зʼявиться
 * щось друге. Умова названа префіксом, а не переліком імен: перелік розійшовся б
 * із тим, що справді створює service worker.
 */
async function clearOwnCaches(): Promise<void> {
	if (!('caches' in window)) return;
	try {
		const names = await caches.keys();
		await Promise.all(
			names.filter((name) => name.startsWith(STORAGE_PREFIX)).map((name) => caches.delete(name))
		);
	} catch {
		/* Cache API недоступний або заблокований */
	}
}

/**
 * Реєстрації service worker — лише ті, що керують ЦІЄЮ сторінкою.
 *
 * Умова не залежить від `base` (він тут порожній, тобто нічого не відрізняв би):
 * scope service worker завжди є префіксом адрес, якими він керує, отже «керує цією
 * сторінкою» = адреса сторінки починається зі scope.
 *
 * Service worker у проєкті ще немає (ні `vite-plugin-pwa`, ні свого файла), тож
 * сьогодні ця половина не робить нічого. Написати її ПІСЛЯ появи PWA означало б
 * написати її в поспіху — а саме тут поспіх коштує чужих даних.
 */
async function unregisterControllingWorkers(): Promise<void> {
	if (!('serviceWorker' in navigator)) return;
	try {
		const registrations = await navigator.serviceWorker.getRegistrations();
		const here = window.location.href;
		await Promise.all(
			registrations
				.filter((registration) => here.startsWith(registration.scope))
				.map((registration) => registration.unregister())
		);
	} catch {
		/* реєстрації недоступні — решта скидання вже виконана */
	}
}

import type { Attachment } from 'svelte/attachments';

/**
 * Черга завантаження портретів: скільки їх качається одночасно і коли кожен
 * показувати.
 *
 * ## Що саме тут лагодиться
 *
 * У галактиці 124 зірки з обличчями, і всі доріжки лежать за розкладкою на
 * `left: 0` — рух дає лише `translate` в анімації. Тобто з погляду браузера всі
 * 124 зображення стоять у в'юпорті одночасно, `loading="lazy"` не відкладає
 * нічого, і 124 запити стартують однією миттю.
 *
 * Далі найважливіше, і воно не про мережу. Файли після виправлення `sizes`
 * важать близько 2,9 КБ, тож на нормальній лінії вони приходять майже разом —
 * і 124 переходи «точка → обличчя» стартують в одну мить. Саме це на екрані
 * читається як «різка поява всього одразу», проти якої ця черга й стоїть.
 * Показ по кілька за раз перетворює появу з блимання на заповнення.
 *
 * ## Чому 6, а не 3, як у сусідньому проєкті
 *
 * `adoptananimal` тримає 3, і там це правильно: картки несуть знімки по
 * 1280 px у контейнері 300 px, тобто десятки кілобайтів кожен, і межа
 * впирається в ширину каналу. Тут файл — 2,9 КБ, і межа впирається не в канал,
 * а в затримку: GitHub Pages віддає все одним з'єднанням HTTP/2, де 124 дрібні
 * запити коштують майже нічого, а межа 3 перетворила б їх на ~41 послідовний
 * оберт. При 50 мс RTT це дві секунди чистого чекання, доданих на рівному місці.
 *
 * Шість — середина, яку видно з обох боків: на повільній лінії черга ще
 * стримує натовп, на швидкій не додає стіни затримок. Заміряти це в панелі
 * браузера не вийшло: у прихованій панелі ширина 0, зображення не входять у
 * в'юпорт і не вантажаться зовсім, тобто замір показав би нуль запитів
 * незалежно від межі. Тому число обґрунтоване, а не заміряне, і це сказано
 * прямо.
 *
 * ## Чого тут НЕМА і чому
 *
 * `IntersectionObserver`, який у сусідньому проєкті тримає завантаження до
 * підходу картки, тут не потрібен: усі зірки вже у в'юпорті за розкладкою (див.
 * вище), тож спостерігач спрацював би одразу для всіх і додав би лише код.
 *
 * Немає й забирання `src` з розмітки. У тому проєкті `src` стоїть у
 * прередереному HTML, щоб краулер і відвідувач без скриптів бачили знімок, і
 * забирати його доводиться вже в браузері. Тут зірок у прередереному HTML немає
 * ЗОВСІМ — і галактика, і потік майстра малюють їх лише після `onMount`
 * (перевірено: `star--photo` у `build/projects/galaxy-graduates/index.html`
 * зустрічається 0 разів). Тобто відбирати нічого: `src` просто не з'являється,
 * доки черга не дасть слот.
 */

/** Скільки портретів качається одночасно. Обґрунтування — у шапці файлу. */
const МЕЖА = 6;

let зайнято = 0;
const черга: Array<() => void> = [];

/**
 * Виконує `почати`, щойно звільниться слот, і повертає функцію, яка слот
 * віддає.
 *
 * Віддати треба РІВНО ОДИН раз — і на успіху, і на помилці, і на зірці, яка
 * зникла з екрана до своєї черги. Загублений слот не повертається ніколи:
 * шість таких, і більше не завантажиться нічого.
 */
export function зайнятиСлот(почати: () => void): () => void {
	let віддано = false;
	const запуск = () => почати();

	if (зайнято < МЕЖА) {
		зайнято++;
		запуск();
	} else {
		черга.push(запуск);
	}

	return () => {
		if (віддано) return;
		віддано = true;

		const уЧерзі = черга.indexOf(запуск);
		if (уЧерзі !== -1) {
			// Слота він так і не отримав — передавати нема чого.
			черга.splice(уЧерзі, 1);
			return;
		}

		// Слот іде НАСТУПНОМУ напряму, а не через зменшення лічильника: інакше
		// між віддачею й новим захопленням пачка охочих проскочила б межу.
		const наступний = черга.shift();
		if (наступний) наступний();
		else зайнято--;
	};
}

/** Лише для перевірок: скільком слотам зараз дано хід і скільки чекає. */
export function станЧерги(): { зайнято: number; очікує: number } {
	return { зайнято, очікує: черга.length };
}

/**
 * Вантажить портрет, коли звільниться слот, і показує його ПІСЛЯ `load`.
 *
 * ## Чому саме `load`, а не `decode()`
 *
 * Обличчя, обрізане горизонтально посередині, бралося не з декодування, а з
 * того, що елемент був видимий, поки байти ще їхали: браузер малює прогресивно
 * те, що вже прийшло. Прозорість нуль до `load` знімає цю причину цілком —
 * видимим портрет стає, коли ресурс уже повний, тож намалювати половину нічого
 * не може за визначенням.
 *
 * `decode()` тут стояв першою редакцією, за прикладом сусіднього проєкту, і
 * замір показав, чому його краще не мати. У контексті, який не малює кадрів
 * (прихована панель, згорнута вкладка), проміс `decode()` не завершується
 * ЖОДНИМ боком — ні успіхом, ні відмовою. Заміряно на dev-сервері: 137 із 137
 * зображень завантажені, `star--ready` — нуль зірок зі 124. Тобто галактика
 * лишалася б крапками, доки вкладку не відкриють.
 *
 * Втрата від відмови нульова: там знімки 1280 px у картці 300 px, і чекання
 * декодування справді береже кадр, а тут портрет 96×96 — його декодування
 * коштує мікросекунди, і `decoding="async"` віддає перший кадр переходу з
 * прозорістю близько нуля, де його однаково не видно.
 *
 * ## Помилка
 *
 * Власної гілки не має навмисно: зірка, чий портрет не приїхав, лишається
 * точкою — тим самим плейсхолдером, що стояв до того. Це і є потрібна
 * поведінка, і вона нічого не коштує. Розбіжність «`hasPhoto` є, а файлу
 * немає» — не справа цього модуля, її ловить інваріант реєстру випускників.
 */
export function портретУЧерзі(
	src: string,
	srcset: string | undefined,
	показати: () => void
): Attachment<HTMLImageElement> {
	return (img) => {
		// Уже на місці — з кеша, або браузер устиг раніше, ніж Svelte приєднав
		// що-небудь. Події `load` вже не буде, і без цієї гілки зірка лишилася б
		// точкою назавжди.
		if (img.complete && img.naturalWidth > 0) {
			показати();
			return;
		}

		let віддати: (() => void) | undefined;
		const віддатиСлот = () => {
			віддати?.();
			віддати = undefined;
		};

		const наЗавантаженні = () => {
			// Слот — це частка мережі, тож він повертається щойно байти в руках.
			віддатиСлот();
			показати();
		};

		const наПомилці = () => віддатиСлот();

		img.addEventListener('load', наЗавантаженні);
		img.addEventListener('error', наПомилці);

		віддати = зайнятиСлот(() => {
			// `eager` обов'язковий: звідси й далі саме цей код вирішує, коли
			// вантажити. При `lazy` браузер міг би відкласти запит — і затримати
			// разом із ним слот, тобто всю чергу.
			img.loading = 'eager';
			if (srcset) img.srcset = srcset;
			img.src = src;
		});

		return () => {
			img.removeEventListener('load', наЗавантаженні);
			img.removeEventListener('error', наПомилці);
			віддатиСлот();
		};
	};
}

/**
 * Скільки накладок наразі забрали клавіатуру собі.
 *
 * **Лічильник, а не `boolean`.** Дві накладки можуть існувати одночасно (модалка
 * поверх модалки), і тоді закриття верхньої з `boolean` віддало б клавіатуру
 * сайту, поки нижня ще відкрита.
 *
 * **Чому не через `event.stopPropagation`.** Обробники висять на `window`, а
 * порядок між слухачами одного вузла — це порядок реєстрації, тобто порядок
 * монтування компонентів; він змінюється від того, з якої сторінки прийшли.
 */
let captureCount = 0;

/**
 * Забрати клавіатуру собі. Повертає функцію, яка її віддає.
 *
 * Повертає саме функцію, а не має пари `release()`: тоді її можна віддати прямо в
 * cleanup `$effect`, і забути про звільнення важче.
 */
export function captureKeyboard(): () => void {
	captureCount += 1;
	let released = false;
	return () => {
		// Захист від подвійного виклику: cleanup у Svelte може прийти двічі під час
		// HMR, і лічильник пішов би в мінус — тобто клавіатура лишилася б «зайнятою»
		// назавжди.
		if (released) return;
		released = true;
		captureCount = Math.max(0, captureCount - 1);
	};
}

/** Чи зайнята клавіатура накладкою. Читають обробник сайту й тести. */
export function isKeyboardCaptured(): boolean {
	return captureCount > 0;
}

/**
 * Чи друкує людина зараз у полі.
 *
 * `closest`, а не порівняння `tagName`: у `contenteditable` фокус стоїть на
 * вкладеному вузлі, і його `tagName` — це `SPAN`, тож перевірка за тегом такий
 * випадок пропускає. Тут це не теорія: редактор статей в адмінці — саме
 * `contenteditable`.
 */
export function isTypingTarget(target: EventTarget | null | undefined): boolean {
	const element = target as HTMLElement | null | undefined;
	if (!element || typeof element.closest !== 'function') return false;
	return (
		element.closest('input, textarea, select, [contenteditable]:not([contenteditable="false"])') !==
		null
	);
}

/**
 * Чи це одиночна клавіша без модифікаторів.
 *
 * `Ctrl+T` відкриває вкладку, `Ctrl+R` перезавантажує, `Ctrl+V` вставляє — і всі
 * три дають той самий `event.code`, що й одиночна клавіша. `Shift` навмисно не
 * перевіряється: він не змінює `code`, а комбінації з ним браузер зазвичай не
 * займає.
 */
export function isPlainKey(event: {
	ctrlKey?: boolean;
	metaKey?: boolean;
	altKey?: boolean;
}): boolean {
	return !event.ctrlKey && !event.metaKey && !event.altKey;
}

/**
 * Усі три захисти разом — те, що потрібно обробникові сайту.
 *
 * `Escape` тут НЕ виняток: поки клавіатуру зайнято, він належить тій накладці, що
 * її зайняла, — і кожна закриває себе сама. Пропустити його сюди означало б
 * закрити заодно й меню шапки під модалкою.
 */
export function acceptsShortcut(event: KeyboardEvent): boolean {
	if (isKeyboardCaptured()) return false;
	if (!isPlainKey(event)) return false;
	if (event.code === 'Escape') return true;
	return !isTypingTarget(event.target);
}

import { describe, expect, it } from 'vitest';
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';

/**
 * Середовище прогону обирається ФАЙЛОМ, а типового браузера немає
 * (CODE-QUALITY-v9 § 4.1, `CQ-COMPONENT-ENV`: «типового немає — є правило
 * вибору за ознакою»).
 *
 * ## Що тут сталося і чому це не косметика
 *
 * До 10.09.2026 у `vitest.config.ts` типовим середовищем стояв jsdom, і його
 * платили ВСІ 135 файлів перевірок. DOM при цьому потрібен восьми: пастка
 * фокуса, перенесення вузла в тіло сторінки, розбір кліку по поштовому
 * посиланню, поява зображень, дросель перевірки версії, оверлей смуги
 * прокрутки, контролер інтерфейсу й повноекранний режим. Решта — гейти, що
 * читають вихідні тексти й реєстри з диска.
 *
 * Заміряно на незміненому коді того ж дня:
 *
 * | | типовий jsdom | типовий node |
 * | --- | --- | --- |
 * | `environment` | 205 с | 19 мс |
 * | увесь прогін | 125 с | 49 с |
 * | випадкових падінь | 2 | 0 |
 *
 * Останній стовпчик і є причиною. Два файли (`faculty-relations` і
 * `config/localImages`) впали в таймаут 5 000 мс, хоча поодинці проходять за
 * 70 і 118 мс і читають лише диск: воркери голодували на піднятті зайвих
 * середовищ. Гейт, що червоніє від навантаження, вчить не вірити червоному
 * взагалі — це рівно AI-AGENT-PITFALLS-v9 § 1.2, і коштує воно дорожче за
 * будь-які секунди.
 *
 * ## Що стереже ця перевірка
 *
 * Дві речі, і обидві — про мовчазний відкат:
 *
 * 1. Типове середовище лишається `node`. Один рядок у конфізі повертає всі
 *    135 файлів у jsdom, і жоден тест від цього не почервоніє — прогін просто
 *    знову стане повільним і плавучим.
 * 2. Перелік файлів, які беруть jsdom, збігається з дійсністю В ОБИДВА БОКИ.
 *    Новий файл із DOM, доданий без запису сюди, впаде на власних тестах — а
 *    от файл, який DOM переріс, лишався б у переліку пам'ятником, і перелік
 *    поступово перестав би щось означати.
 *
 * ## Чому перевірка не бачить сама себе
 *
 * Нижче в коді написано те саме слово, яке шукає сканер, — інакше шукати було
 * б нічим. Тому власний файл із обходу вилучений: без цього перевірка
 * порахувала б себе споживачем jsdom і зажадала запису в переліку. Це та сама
 * пастка, що в `orphan-modules` і `static-orphans`: гейт по джерелах читає
 * файл ТЕКСТОМ і не відрізняє згадки від використання.
 *
 * Зворотний експеримент (AI-AGENT-PITFALLS-v9 § 1.1): прибрати рядок вибору
 * середовища з `utils/focusTrap.test.ts` — перевірка мусить назвати саме цей
 * файл як «бере jsdom, але його немає в переліку»... точніше навпаки: файл
 * лишається в переліку, а середовища не оголошує. Зроблено, падає обома
 * боками.
 */

/** Місця, які збирає `include` у `vitest.config.ts`. */
const МІСЦЯ = ['src', 'vitest/support'];

/**
 * Файли, яким справді потрібен DOM, і чим саме.
 *
 * Перелік не «дозволений максимум», а знімок дійсності: кожен рядок мусить
 * знайтися на диску з оголошеним середовищем, і кожне оголошення на диску
 * мусить знайтися тут.
 */
const З_JSDOM: Record<string, string> = {
	'src/lib/controllers/ui.svelte.test.ts': 'підписка на matchMedia і запис у documentElement',
	'src/lib/services/fullscreen.svelte.test.ts': 'повноекранний режим — API самого документа',
	'src/lib/services/version.test.ts': 'дросель читає navigator.onLine і адресу вкладки',
	'src/lib/utils/customScroll.test.ts': 'створює елементи оверлею і знімає з них слухачів',
	'src/lib/utils/focusTrap.test.ts': 'фокусовані елементи в справжньому дереві',
	'src/lib/utils/installImageReveal.test.ts': 'предикат дивиться на живий img і його предків',
	'src/lib/utils/mailtoLink.test.ts': 'справжня подія кліку та її ланцюжок предків',
	'src/lib/utils/portalToBody.test.ts': 'переносить вузол у body і прибирає за собою'
};

/** Власний файл: див. «Чому перевірка не бачить сама себе» вище. */
const ВЛАСНИЙ = 'src/test-environment.test.ts';

/**
 * Слово, за яким Vitest обирає середовище. Складається з частин навмисно: у
 * цілому вигляді воно в цьому файлі не пишеться, інакше сам Vitest прочитав би
 * його з докблока вище й підняв би тут браузерне вікно.
 */
const ДИРЕКТИВА = ['@vitest', 'environment'].join('-');

function усіФайлиПеревірок(): string[] {
	const out: string[] = [];
	const walk = (dir: string) => {
		for (const entry of readdirSync(dir)) {
			const full = join(dir, entry).replace(/\\/g, '/');
			if (statSync(full).isDirectory()) walk(full);
			else if (/\.(test|spec)\.ts$/.test(entry)) out.push(full);
		}
	};
	for (const місце of МІСЦЯ) walk(місце);
	return out.filter((f) => f !== ВЛАСНИЙ).sort();
}

/** Оголошене середовище файлу або `null`, коли він бере типове. */
function середовище(file: string): string | null {
	const перший = readFileSync(file, 'utf8').slice(0, 2000);
	const m = new RegExp(`${ДИРЕКТИВА}\\s+([\\w-]+)`).exec(перший);
	return m ? m[1] : null;
}

describe('вибір середовища прогону', () => {
	const файли = усіФайлиПеревірок();

	it('перевірка жива: файли перевірок знайдено', () => {
		expect(файли.length, 'жодного файлу перевірок — сканер зламався').toBeGreaterThan(100);
	});

	it('типове середовище в конфізі — node, а не браузерне вікно', () => {
		const конфіг = readFileSync('vitest.config.ts', 'utf8');
		expect(
			/environment:\s*'node'/.test(конфіг),
			'у vitest.config.ts типовим середовищем стоїть не node — усі файли перевірок ' +
				'знову платять за браузерне вікно, і прогін стає повільним та плавучим'
		).toBe(true);
	});

	it('кожен файл із переліку справді оголошує jsdom', () => {
		const відстали: string[] = [];
		for (const [file, why] of Object.entries(З_JSDOM)) {
			if (середовище(file) !== 'jsdom') відстали.push(`${file} (${why})`);
		}
		expect(
			відстали,
			'у переліку є, а на диску середовища не оголошує — або файл перейменували, ' +
				'або DOM йому більше не потрібен; тоді рядок звідси прибрати'
		).toEqual([]);
	});

	it('жоден файл не бере jsdom потай від переліку', () => {
		const зайві = файли.filter((f) => середовище(f) === 'jsdom' && !(f in З_JSDOM));
		expect(
			зайві,
			'файл оголосив браузерне вікно, але в переліку його немає — впишіть рядком ' +
				'із причиною, чому DOM тут справді потрібен'
		).toEqual([]);
	});

	it('оголошене середовище буває лише node або jsdom', () => {
		const чужі = файли
			.map((f) => [f, середовище(f)] as const)
			.filter(([, env]) => env !== null && env !== 'node' && env !== 'jsdom');
		expect(чужі, 'невідоме середовище — у проєкті є лише node і jsdom').toEqual([]);
	});
});

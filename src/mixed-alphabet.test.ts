// @vitest-environment node
import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';

/**
 * Одне слово — один алфавіт.
 *
 * ## Що це за дефект
 *
 * У назві «Рудa п'єса» остання літера слова «Руда» була ЛАТИНСЬКА `a`. Оком
 * різниці немає жодної, а наслідки цілком реальні: пошук за «Руда» не знаходить
 * нічого, сортування ставить назву не туди, а зіставлення з анкетою — де
 * написано кирилицею — розходиться без видимої причини.
 *
 * Знайдено 2026-09-05 при звірці анкет із реєстром вистав, і в тому ж прогоні
 * знайшлися ще два: «Solo musicа» з кириличною `а` в кінці латинського слова і
 * «Смiх і сльози» з латинською `i`. Тобто це не одиничний друк, а клас — він
 * з'являється, коли назву копіюють із листа, документа чи месенджера.
 *
 * ## Чому перевіряються саме реєстри
 *
 * Назва з реєстру — те, за чим річ шукають і з чим звіряють анкети. Текст
 * анкети чи новини такої суворості не потребує: він читається, а не
 * зіставляється.
 *
 * ## Зворотний експеримент (AI-AGENT-PITFALLS-v8 § 1.1)
 *
 * Замінити будь-яку кириличну `а` в назві вистави на латинську — перевірка
 * падає й називає і запис, і саме слово.
 */

/** Слово, у якому є літери з ОБОХ алфавітів. */
const ЗМІШАНЕ = (слово: string) => /[\p{Script=Cyrillic}]/u.test(слово) && /[a-zA-Z]/.test(слово);

/**
 * Навмисна стилізація, а не описка.
 *
 * Курс «ПаХLава» так і зветься — латинська `L` усередині кириличного слова це
 * його ім'я, а не збій копіювання. Виняток названий тут, щоб наступний, хто
 * побачить це слово, не «виправив» його мовчки.
 */
const НАВМИСНО = new Set(['ПаХLава']);

const читати = (шлях: string): unknown => JSON.parse(readFileSync(шлях, 'utf8'));
const масив = <T>(дані: unknown, ключ: string): T[] =>
	(Array.isArray(дані) ? дані : ((дані as Record<string, T[]>)[ключ] ?? [])) as T[];

function слова(текст: string): string[] {
	return текст.split(/[\s«»"'’,.:;()/—–\-!?]+/u).filter(Boolean);
}

/** Усі назви реєстрів разом із тим, звідки вони. */
function назви(): { де: string; текст: string }[] {
	const out: { де: string; текст: string }[] = [];
	const додати = (де: string, текст?: string | null) => {
		if (typeof текст === 'string' && текст.trim()) out.push({ де, текст });
	};

	for (const p of масив<{ id: string; title: string; programme?: { id: string; title: string }[] }>(
		читати('src/lib/data/plays.data.json'),
		'plays'
	)) {
		додати(`вистава ${p.id}`, p.title);
		for (const ф of p.programme ?? []) додати(`номер ${p.id}#${ф.id}`, ф.title);
	}

	for (const g of масив<{ slug: string; name: string }>(
		читати('src/lib/data/graduates.index.json'),
		'graduates'
	)) {
		додати(`випускник ${g.slug}`, g.name);
	}

	for (const m of масив<{ slug: string; displayName?: string; fullName?: string }>(
		читати('src/lib/data/masters.index.json'),
		'masters'
	)) {
		додати(`майстер ${m.slug}`, m.displayName ?? m.fullName);
	}

	for (const [файл, ключ, підпис] of [
		['groups.data.json', 'groups', 'курс'],
		['festivals.data.json', 'festivals', 'фестиваль'],
		['institutions.data.json', 'institutions', 'заклад'],
		['theatres.data.json', 'theatres', 'театр']
	] as const) {
		for (const x of масив<{ slug: string; name: string }>(
			читати(`src/lib/data/${файл}`),
			ключ
		)) {
			додати(`${підпис} ${x.slug}`, x.name);
		}
	}

	return out;
}

const усі = назви();

describe('одне слово — один алфавіт', () => {
	it('перевірка жива: назви реєстрів прочитані', () => {
		expect(усі.length, 'жодної назви — перевірка міряє порожнечу').toBeGreaterThan(500);
	});

	it('перевірка жива: розбір бачить змішане слово', () => {
		// `Рудa` з латинською `a` — саме той випадок, з якого перевірка й почалася.
		expect(ЗМІШАНЕ('Рудa')).toBe(true);
		expect(ЗМІШАНЕ('Руда')).toBe(false);
		expect(ЗМІШАНЕ('Solo')).toBe(false);
	});

	it('у назвах реєстрів немає слів із двох алфавітів (CRITICAL)', () => {
		const bad: string[] = [];
		for (const { де, текст } of усі) {
			for (const слово of слова(текст)) {
				if (ЗМІШАНЕ(слово) && !НАВМИСНО.has(слово)) bad.push(`${де}: «${слово}» у «${текст}»`);
			}
		}
		expect(
			bad,
			'літера з іншого алфавіту всередині слова. Оком її не видно, а пошук за таким ' +
				'словом не знаходить нічого, і зіставлення з анкетою розходиться без причини. ' +
				`Якщо це навмисна стилізація — назвати слово в НАВМИСНО:\n  ${bad.join('\n  ')}`
		).toEqual([]);
	});
});

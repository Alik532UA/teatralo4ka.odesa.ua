/**
 * Плашка «дані зібрав AI» — гейт проти ТИХОЇ втрати попередження.
 *
 * ## Звідки взялася перевірка
 *
 * `/projects/galaxy-graduates/groups/hruffish` плашки не показував, і збоку це
 * читалося як «сторінку забули підключити». Сторінка ціла: вона малює
 * `VerificationNoticeBanner`, а той з'являється лише на `possible_errors` /
 * `definite_errors`. У групи стояло `verified` — тобто «людина це перевірила».
 *
 * Ніхто не перевіряв. Коміт `3c06f9f` («додати категорії "Поточні групи" та
 * "Потребує уточнення"») — про КАТЕГОРІЇ в переліку груп — дорогою створив
 * дев'ятнадцять нових груп і кожній проставив `verified`, та ще й перевів шість
 * наявних із `possible_errors` у `verified`. Двадцять п'ять сторінок втратили
 * попередження всередині коміту, який про попередження не згадує жодним словом.
 * Півгодиною раніше коміт `e846b69`, що плашку й приніс, лишив `verified` рівно
 * в ОДНІЄЇ групи — ЗТК.
 *
 * Це не одиничний випадок, а форма дефекту: `verified` дешевий (одне слово в
 * JSON), його наслідок невидимий (плашка просто не з'являється), і жоден
 * компілятор про нього не скаже — поле необов'язкове й типізоване як рядок.
 *
 * ## Чому саме три перевірки
 *
 * Сторінка мовчить трьома різними способами, і кожен ловиться окремо:
 *
 *   1. сторінка сутності взагалі не малює плашку;
 *   2. у записі реєстру поля немає — плашки не буде, і це не видно ніде;
 *   3. у записі стоїть `verified`, якого людина не ставила — випадок hruffish.
 *
 * Третя перевірка — ХРАПОВИК, а не заборона. `verified` дозволений, але
 * поіменно й з причиною, як стелі розмірів у `structure.test.ts`. Перелік може
 * лише скорочуватися: запис, що перестав бути `verified`, мусить піти звідси,
 * інакше список стає пам'ятником. Саме ця перевірка почервоніла б на `3c06f9f`.
 *
 * ## Зворотний експеримент (AI-AGENT-PITFALLS-v8 § 1.1)
 *
 * Проведено на трьох дефектах, по одному на перевірку: прибраний рядок
 * `<VerificationNoticeBanner …>` зі сторінки вистави; знятий
 * `verificationStatus` у групи `fresh`; повернутий `verified` для `hruffish`.
 * Кожна перевірка впала й назвала саме той запис або файл.
 */

/** Значення поля. Джерело — `VerificationStatus` у `lib/data/groups.ts`. */
const СТАТУСИ = new Set(['verified', 'possible_errors', 'definite_errors']);

interface Запис {
	[поле: string]: unknown;
}

interface Сутність {
	/** Як назветься запис у повідомленні про помилку. */
	назва: string;
	реєстр: string;
	/** Поле-ідентифікатор запису в цьому реєстрі. */
	ключ: string;
	сторінка: string;
	/**
	 * Виняток — сторінка плашки НЕ показує, і це рішення, а не недоробка.
	 * Рядок пояснює, чому. Немає поля — сторінка мусить плашку малювати.
	 */
	виняток?: string;
}

/**
 * Реєстр сутностей і сторінок, що їх показують.
 *
 * Перелік РУКАМИ, а не обходом маршрутів, і причина та сама, що в
 * `gates.mjs`: вивести «яка сторінка показує який реєстр» з тексту
 * завантажувача можна лише вгадуванням, а вгадування тут коштувало б дорого —
 * помилка розпізнавання читалася б як «плашка на місці».
 *
 * Ціна відома: нову сутність треба вписати сюди. Проти забутого запису стоїть
 * перевірка «перелік накриває всі реєстри» нижче.
 */
const СУТНОСТІ: Сутність[] = [
	{
		назва: 'група',
		реєстр: 'src/lib/data/groups.data.json',
		ключ: 'slug',
		сторінка: 'src/routes/projects/galaxy-graduates/groups/[slug]/+page.svelte'
	},
	{
		назва: 'вистава',
		реєстр: 'src/lib/data/plays.data.json',
		ключ: 'id',
		сторінка: 'src/routes/projects/galaxy-graduates/plays/[id]/+page.svelte'
	},
	{
		назва: 'фестиваль',
		реєстр: 'src/lib/data/festivals.data.json',
		ключ: 'slug',
		сторінка: 'src/routes/projects/galaxy-graduates/festivals/[slug]/+page.svelte'
	},
	{
		назва: 'працівник',
		реєстр: 'src/lib/data/masters.index.json',
		ключ: 'id',
		сторінка: 'src/routes/residents/adults/[slug]/+page.svelte'
	},
	{
		назва: 'випускник',
		реєстр: 'src/lib/data/graduates.index.json',
		ключ: 'id',
		сторінка: 'src/routes/projects/galaxy-graduates/[address]/+page.svelte',
		/*
		 * 2026-09-03, рішення замовника. Анкету випускника надсилає САМА ЛЮДИНА —
		 * сайт для того й кличе «Заповнити анкету». Тобто джерело тут не AI, і
		 * попередження «інформацію зібрав AI, тут можуть бути помилки» на такій
		 * сторінці було б просто неправдою про автора тексту.
		 *
		 * Тому 529 сторінок випускників — не борг, який колись закриють, а
		 * ВИНЯТОК: єдиний клас сторінок, де плашки не має бути ніколи. Поля
		 * `verificationStatus` у `graduates.index.json` немає й не потрібно.
		 *
		 * Виняток теж під храповиком: перевірка нижче впаде, якщо плашку на цю
		 * сторінку колись додадуть, — тобто рішення не можна скасувати мовчки.
		 */
		виняток: 'анкету надсилає сама людина, а не AI — плашка брехала б про автора'
	}
];

/**
 * Записи, яким `verified` поставила ЛЮДИНА. Ключ — «сутність/ідентифікатор».
 *
 * Значення — не опис запису, а ДОКАЗ: коміт, у якому статус проставлено, і чому
 * цей коміт про перевірку, а не про щось інше.
 */
const ПЕРЕВІРЕНІ_ЛЮДИНОЮ: Record<string, string> = {
	'група/zakhysnyky-teatralnykh-kulis':
		'e846b69 — коміт, що приніс саму плашку; єдина група, якій статус ' +
		'проставлено разом із механізмом',
	'фестиваль/slovianskyi-vinok': '61e0706 — окремий коміт «встановити статус verified»',
	'фестиваль/kvitucha-chekhiia': '61e0706 — той самий коміт',
	'фестиваль/mrii-dim-2012': '61e0706 — той самий коміт',
	'фестиваль/mrii-dim-2013': '61e0706 — той самий коміт',
	'вистава/uryvky-z-klasyky-2015':
		'6bf7396 — коміт правив саме цей запис (відео до «Уривків з класики» 2015)',
	'вистава/uryvky-z-klasyky-2015-3': '6bf7396 — той самий коміт, другий показ того ж вечора',
	'вистава/durochka-2010': 'a4e0494 — коміт названий «Дурочка … Русалонька»: записи перебрані руками',
	'вистава/sestra-moia-rusalochka-2012': 'a4e0494 — той самий коміт',
	'вистава/moia-voobrazylyia-2012': 'a4e0494 — той самий коміт'
};

function читати(файл: string): string {
	return readFileSync(файл, 'utf8');
}

function записи(сутність: Сутність): Запис[] {
	return JSON.parse(читати(сутність.реєстр)) as Запис[];
}

function ідентифікатор(сутність: Сутність, запис: Запис): string {
	return String(запис[сутність.ключ] ?? '(без ідентифікатора)');
}

describe('плашка «дані зібрав AI»', () => {
	it('перевірка жива — реєстри читаються й не порожні', () => {
		for (const сутність of СУТНОСТІ) {
			expect(записи(сутність).length, `порожній реєстр ${сутність.реєстр}`).toBeGreaterThan(3);
		}
	});

	it('сторінка сутності малює плашку з її ж статусом', () => {
		const bad: string[] = [];

		for (const сутність of СУТНОСТІ) {
			const текст = читати(сутність.сторінка);
			const тег = текст.match(/<VerificationNoticeBanner[^>]*status=\{([^}]*)\}/);

			if (сутність.виняток) {
				/*
				 * Виняток звіряється на РІВНІСТЬ, а не «просто пропускається»:
				 * плашка, що з'явилася на сторінці-винятку, — це скасоване рішення,
				 * і воно мусить бути помічене так само, як зникла плашка деінде.
				 */
				if (тег)
					bad.push(
						`${сутність.сторінка}: сутність «${сутність.назва}» позначена винятком ` +
							`(${сутність.виняток}), але плашку на сторінці додано`
					);
				continue;
			}

			if (!тег) {
				bad.push(`${сутність.сторінка}: немає <VerificationNoticeBanner status={…}>`);
				continue;
			}
			if (!тег[1].includes('verificationStatus'))
				bad.push(
					`${сутність.сторінка}: плашці передано «${тег[1].trim()}» — ` +
						`це не статус запису, тож плашка не залежить від даних`
				);
		}

		expect(
			bad,
			'сторінка сутності мовчить про те, що дані зібрав AI:\n  ' + bad.join('\n  ')
		).toEqual([]);
	});

	it('кожен запис реєстру має явний статус із трьох дозволених', () => {
		const bad: string[] = [];

		for (const сутність of СУТНОСТІ) {
			if (сутність.виняток) continue;
			for (const запис of записи(сутність)) {
				const статус = запис.verificationStatus;
				const хто = `${сутність.назва} ${ідентифікатор(сутність, запис)}`;
				if (статус === undefined) bad.push(`${хто} → поля немає, плашки не буде`);
				else if (typeof статус !== 'string' || !СТАТУСИ.has(статус))
					bad.push(`${хто} → «${String(статус)}»`);
			}
		}

		expect(bad, 'запис без статусу або з невідомим статусом:\n  ' + bad.join('\n  ')).toEqual([]);
	});

	it('«verified» стоїть лише там, де його поставила людина', () => {
		const знайдено = new Set<string>();
		const зайві: string[] = [];

		for (const сутність of СУТНОСТІ) {
			if (сутність.виняток) continue;
			for (const запис of записи(сутність)) {
				if (запис.verificationStatus !== 'verified') continue;
				const ключ = `${сутність.назва}/${ідентифікатор(сутність, запис)}`;
				знайдено.add(ключ);
				if (!(ключ in ПЕРЕВІРЕНІ_ЛЮДИНОЮ)) зайві.push(ключ);
			}
		}

		expect(
			зайві,
			'статус «verified» без запису в переліку — плашка зникла, і ніхто цього не\n' +
				'вирішував. Якщо запис справді перевірено людиною, впиши його в\n' +
				'ПЕРЕВІРЕНІ_ЛЮДИНОЮ разом із доказом:\n  ' + зайві.join('\n  ')
		).toEqual([]);

		const пам_ятники = Object.keys(ПЕРЕВІРЕНІ_ЛЮДИНОЮ).filter((к) => !знайдено.has(к));
		expect(
			пам_ятники,
			'запис у переліку більше не «verified» — прибери рядок, щоб перелік лишався\n' +
				'переліком, а не пам\'ятником:\n  ' + пам_ятники.join('\n  ')
		).toEqual([]);

		const без_доказу = Object.entries(ПЕРЕВІРЕНІ_ЛЮДИНОЮ)
			.filter(([, чому]) => чому.trim().length < 20)
			.map(([к]) => к);
		expect(без_доказу, 'дозвіл без доказу:\n  ' + без_доказу.join('\n  ')).toEqual([]);
	});
});

// @vitest-environment node
import { describe, expect, it } from 'vitest';
import { readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

/**
 * `.prose` — СПІЛЬНИЙ словник, і власник у нього один: `global.css`.
 *
 * ## Що зламалося, і чому цього не бачив жоден гейт
 *
 * 2026-09-04 у новині про вісімнадцять студентів пункти після дев'ятого
 * нумерувалися «0, 1, 2…»: у двоцифрового номера зникала ПЕРША цифра. Причина
 * записана в `global.css` біля `.prose ol` — маркер `outside` малюється в
 * паддингу списку, і в 1.5rem при шрифті 1.15rem «10.» не влазить, а `.prose`
 * має `overflow-x: hidden`, тобто те, що вилізло, не видно взагалі. Тоді ж це
 * виправили: `padding-left: 2.5rem`.
 *
 * За добу дефект повернувся. Не тому, що правку скасували — вона на місці, — а
 * тому, що `DetailPage` роками тримав ВЛАСНУ копію `.prose :global(ol)` з тим
 * самим 1.5rem, і копія специфічніша за глобальне правило. Копію ніхто не
 * шукав: сторінка новини малювалася `StaticPage`, у якого її не було. А коли
 * розкладку статті винесли в `ArticleView`, копія переїхала разом із нею — і
 * лягла рівно на ту сторінку, де дефект уже одного разу лікували.
 *
 * Автор сказав про це прямо: «я вже просив перевірити проєкт, щоб виправити цю
 * помилку скрізь; не латай ями на дорогах». Тому лікується не число, а спосіб:
 * копій більше немає, і поява нової — червоний гейт.
 *
 * ## Що саме заборонено
 *
 * Правило, яке цілиться в НАЩАДКА `.prose`: `.prose h2`, `.prose :global(img)`,
 * `:global(.prose td)`. Такі правила перекривають спільну типографію тихо —
 * специфічність компонентного селектора вища, і різницю видно лише оком і лише
 * на тій сторінці, де компонент трапився.
 *
 * ## Що НЕ заборонено
 *
 * Свій клас-модифікатор: `.statute-prose h2`, `.prose--zoomable img`. Різниця
 * не формальна — модифікатор ДОДАЄ правило для названого випадку, і його видно
 * в розмітці тієї сторінки, яка його просить, а не перекриває спільне мовчки.
 *
 * ## Зворотний експеримент (AI-AGENT-PITFALLS-v8 § 1.1)
 *
 * Повернути в `ArticleView.svelte` блок `.prose :global(ul), .prose :global(ol)
 * { padding-left: 1.5rem }` — перевірка падає й називає файл із селектором.
 * Друга половина цієї пари — `e2e/news-code.spec.ts`: вона міряє готову
 * сторінку й ловить те саме з боку браузера, звідки б перекриття не прийшло.
 */

const SRC = 'src';
const ВЛАСНИК = join('src', 'lib', 'styles', 'global.css');

function walk(dir: string, out: string[] = []): string[] {
	for (const entry of readdirSync(dir, { withFileTypes: true })) {
		const full = join(dir, entry.name);
		if (entry.isDirectory()) walk(full, out);
		else if (/\.(svelte|css)$/.test(entry.name)) out.push(full);
	}
	return out;
}

/** Тіла всіх `<style>` у компоненті; для `.css` — файл цілком. */
function стилі(file: string): string {
	const текст = readFileSync(file, 'utf8');
	if (file.endsWith('.css')) return текст;
	return [...текст.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/g)].map((m) => m[1]).join('\n');
}

/**
 * Селектори з тіла стилів.
 *
 * Розбір навмисно грубий — розділити по `{` і `}` і взяти те, що перед дужкою.
 * Повного парсера CSS тут не треба: питання одне — чи згадується `.prose` у
 * селекторі, — і воно не залежить від вкладеності `@media`.
 */
function селектори(css: string): string[] {
	const без = css.replace(/\/\*[\s\S]*?\*\//g, '');
	const out: string[] = [];
	for (const шматок of без.split('}')) {
		const дужка = шматок.indexOf('{');
		if (дужка < 0) continue;
		for (const s of шматок.slice(0, дужка).split(',')) {
			const селектор = s.trim();
			if (селектор && !селектор.startsWith('@')) out.push(селектор);
		}
	}
	return out;
}

/**
 * Чи цілиться селектор у нащадка `.prose`.
 *
 * `:global(...)` знімається перед перевіркою: для питання «чи це правило про
 * вміст `.prose`» обгортка не має значення, а Svelte без неї взагалі не
 * дозволяє цілитися у вставлений HTML — тобто саме в цій формі копії й жили.
 */
function цілитьсяВНащадка(селектор: string): boolean {
	const голий = селектор.replace(/:global\(/g, ' ').replace(/\)/g, ' ');
	return /(^|[\s>+~])\.prose(?![\w-])[\s>+~]+\S/.test(` ${голий} `);
}

const файли = walk(SRC).filter((f) => f !== ВЛАСНИК);

describe('`.prose` належить global.css', () => {
	it('перевірка жива: власник справді описує `.prose`', () => {
		// Без цього перевірка нижче була б зеленою й тоді, коли спільних правил
		// немає взагалі — тобто коли перекривати вже нема чого.
		const правил = селектори(readFileSync(ВЛАСНИК, 'utf8')).filter((s) =>
			цілитьсяВНащадка(s)
		);
		expect(
			правил.length,
			'у global.css немає правил для вмісту `.prose` — гейт міряє порожнечу'
		).toBeGreaterThan(8);
	});

	it('перевірка жива: розбір знаходить саме ту форму, якою жили копії', () => {
		expect(цілитьсяВНащадка('.prose :global(ol)')).toBe(true);
		expect(цілитьсяВНащадка(':global(.prose img)')).toBe(true);
		expect(цілитьсяВНащадка('.prose')).toBe(false);
		expect(цілитьсяВНащадка('.prose--zoomable img')).toBe(false);
		expect(цілитьсяВНащадка('.statute-prose h2')).toBe(false);
	});

	it('жоден компонент не перекриває спільну типографію (CRITICAL)', () => {
		const bad: string[] = [];
		for (const file of файли) {
			for (const селектор of селектори(стилі(file))) {
				if (цілитьсяВНащадка(селектор)) bad.push(`${file} — ${селектор}`);
			}
		}
		expect(
			bad,
			'правило цілиться у вміст `.prose` повз його власника. Специфічність ' +
				'компонентного селектора вища за глобальний, тож таке правило тихо ' +
				'скасовує спільне — саме так повернулася обрізана нумерація списків. ' +
				'Або перенести правило в src/lib/styles/global.css, або зробити свій ' +
				'клас-модифікатор (як .statute-prose, .prose--zoomable):\n  ' +
				bad.join('\n  ')
		).toEqual([]);
	});

	it('місця під двоцифровий номер вистачає', () => {
		/*
		 * Число, а не просто наявність правила: саме воно й було дефектом.
		 * 2.5rem при шрифті 1.15rem — це 40 px проти ≈18 px «10.», тобто із
		 * запасом на три цифри.
		 */
		const css = readFileSync(ВЛАСНИК, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');

		/*
		 * Береться ОСТАННЄ правило, а не перше, і це не дрібниця розбору.
		 *
		 * `.prose ol` описаний двічі: спершу разом із `ul` (спільний відступ
		 * 1.5rem), потім окремо — саме там і стоїть 2.5rem. Специфічність у них
		 * однакова, тож виграє те, що нижче. Перша редакція цієї перевірки брала
		 * перше збігання й падала на правильному коді, показуючи 1.5.
		 */
		const падінги = [...css.matchAll(/([^{}]+)\{([^{}]*)\}/g)]
			.filter((m) => m[1].split(',').some((s) => s.trim() === '.prose ol'))
			.map((m) => /padding-left:\s*([\d.]+)rem/.exec(m[2])?.[1])
			.filter((v): v is string => Boolean(v));

		expect(падінги.length, 'у `.prose ol` немає padding-left у rem').toBeGreaterThan(0);
		expect(Number(падінги.at(-1)), 'у паддинг не влізе двоцифровий номер').toBeGreaterThanOrEqual(
			2.2
		);
	});
});

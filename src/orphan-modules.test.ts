import { describe, it, expect } from 'vitest';
import { readdirSync, readFileSync, statSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';

/**
 * Інваріант: кожен модуль у `src/lib` ДОСЯЖНИЙ графом імпортів від точок входу.
 *
 * PROJECT-STRUCTURE-v9 називає непідключений модуль порушенням рівня HIGH, і
 * причина не в охайності. Осиротілий файл читається як робоча частина проєкту:
 * його правлять, на нього посилаються в обговореннях, його бачить агент і бере
 * за приклад — а він не виконується ніколи. Рівно так у цьому проєкті прожив
 * `errorLogger`: написаний, покритий дев'ятьма тестами й не імпортований
 * нізвідки (AI-AGENT-PITFALLS-v9 § 3, «існування ≠ досяжність»).
 *
 * ## ЧОМУ ГРАФ, А НЕ «ХТОСЬ ЗГАДАВ ІМ'Я ФАЙЛУ» (`PS-REACHABILITY`)
 *
 * Перша версія цієї перевірки збирала всі специфікатори імпорту з репозиторію
 * в одну множину імен і питала кожен файл: «твоє ім'я там є?». Це дешево і
 * ловить поодиноку сироту — але має сліпу зону рівно того розміру, заради якої
 * правило й переписали у v9: **ланцюжок сиріт виглядає використаним**.
 *
 * Хай `a.ts` імпортує `b.ts`, `b.ts` імпортує `a.ts`, і більше їх не кличе
 * ніхто. За іменами обидва «використані» — кожен згаданий у другому. Графом
 * від точок входу обидва недосяжні, бо в них не веде жоден шлях. Той самий
 * ефект дає будь-який довший ланцюжок: видаляєш голову — хвіст стає видимим
 * лише НАСТУПНОГО прогону, і так по одному файлу за коміт.
 *
 * Тому тут обхід: множина досяжного будується від коренів і росте лише
 * імпортами. Ціна — треба вміти РОЗВ'ЯЗУВАТИ специфікатор у шлях; що саме
 * довелося врахувати, нижче.
 *
 * ## Точки входу — три набори, і всі три обов'язкові
 *
 * 1. **SvelteKit**: файли `+page`, `+layout`, `+error` на будь-якій глибині
 *    `src/routes`, плюс `src/hooks.ts` і `src/hooks.client.ts`. Це те, що
 *    справді виконується у браузері відвідувача.
 * 2. **Інструменти проєкту**: `scripts/`, `e2e/`, `vitest/` і конфіги в корені.
 *    Модуль, потрібний лише збірці чи тестам, не осиротілий — `config/redirects.ts`
 *    читають `scripts/generate-sitemap.ts` і `e2e/pages.ts`, а
 *    `config/previewHops.ts` — тільки `e2e/pages.ts`. Реєстр, спільний для
 *    збірки й тестів, — саме та річ, яку варто мати, і перевірка карала б за неї.
 * 3. Більше нічого. Зокрема, **файли перевірок коренями НЕ є** — і це головне
 *    рішення тут. Саме такий випадок інваріант і має ловити: `errorLogger` був
 *    покритий дев'ятьма тестами й не імпортований нізвідки, тобто логування
 *    помилок виглядало працюючим і не існувало. Якби власний тест зараховувався
 *    за досяжність, перевірка пропустила б рівно ту помилку, заради якої стоїть.
 *
 * ## Чотири пастки розв'язувача — усі спрацювали тут
 *
 * 1. **Barrel-імпорт.** `schemas/index.ts` беруть як `from '../schemas'` — імені
 *    файлу в специфікаторі немає взагалі. Тому серед розширень пробується
 *    `/index.ts`.
 * 2. **Побічний імпорт без `from`.** `import '$lib/i18n';` у `+layout.ts` не має
 *    слова `from`, і регулярка, написана лише під `from '…'`, оголосила б
 *    осиротілими `i18n/index.ts` і слідом усі чотири контролери.
 * 3. **`.svelte.ts` імпортують БЕЗ `.ts`** (`from './toast.svelte'`), тож серед
 *    розширень мусить бути і `.svelte.ts`, і `.svelte` — у такому порядку не
 *    можна, бо `toast.svelte` файлом не є; порядок у `РОЗШИРЕННЯ` це враховує.
 * 4. **`import.meta.glob`.** Шаблон розкривається в регулярний вираз і зараховує
 *    все, що йому підходить. Сьогодні обидва наявні шаблони вказують на `.md`,
 *    тобто на код не впливають зовсім — але прибрати їх означало б поставити
 *    міну під перший же глоб по `.ts`.
 *
 * ## Чому текст читається БЕЗ коментарів
 *
 * `from './foo'` у докблоці — не імпорт, а цитата. Гейт, що читає коментарі як
 * код, оголошує досяжним модуль, який лише ЗГАДАЛИ, і саме так осиротілий файл
 * доживає до наступного переїзду: хтось описав його в шапці сусіда. Тому блокові
 * коментарі, HTML-коментарі й рядкові `//` знімаються перед розбором. Рядкові —
 * обережно: `https://` не коментар, і без винятку на двокрапку перевірка
 * з'їдала б половину адрес у розмітці.
 *
 * ## Зворотний експеримент (`PIT-REVERSE-EXPERIMENT`)
 *
 * Дві тимчасові пари файлів у `src/lib/`: одинока сирота і взаємна пара
 * `a ↔ b`. Стара перевірка бачила лише першу, ця називає всі три. Прогнано,
 * падає; після видалення файлів — зелено.
 */

const КОРІНЬ_БІБЛІОТЕКИ = 'src/lib';

/**
 * Дозволені винятки. Список має лишатися коротким: щойно в ньому з'явиться
 * десяток записів, він перестане читатися й перевірка перетвориться на
 * декорацію. Двадцять модулів, з яких вона починалася, тому не внесені сюди,
 * а видалені.
 */
const ДОЗВОЛЕНІ_СИРОТИ = new Set([
	// Заглушка зі скаффолда SvelteKit: сам файл — це коментар «кладіть сюди те,
	// що імпортуєте через $lib». Видалення нічого не дає, бо `svelte-kit sync`
	// створює його знову.
	'src/lib/index.ts'
]);

/** Теки з кодом, який виконують інструменти проєкту, а не браузер відвідувача. */
const ІНСТРУМЕНТИ = ['scripts', 'e2e', 'vitest'];

/** Конфіги в корені: їхні імпорти теж тримають модулі живими. */
const КОНФІГИ = [
	'svelte.config.js',
	'vite.config.ts',
	'vitest.config.ts',
	'playwright.config.ts',
	'eslint.config.js'
];

const КОД = /\.(svelte|ts|js|mjs)$/;
const ПЕРЕВІРКА = /\.(test|spec)\.ts$/;
const ОГОЛОШЕННЯ_ТИПІВ = /\.d\.ts$/;

/**
 * Порядок значущий: `''` першим, щоб точний шлях вигравав у здогадок, а
 * `.svelte.ts` — раніше за `/index.*`, бо каталогу з такою назвою не буває.
 */
const РОЗШИРЕННЯ = [
	'',
	'.ts',
	'.js',
	'.svelte',
	'.svelte.ts',
	'/index.ts',
	'/index.js',
	'/index.svelte',
	'.json'
];

const шлях = (p: string) => p.split('\\').join('/');

function обійти(dir: string, out: string[] = []): string[] {
	if (!existsSync(dir)) return out;
	for (const entry of readdirSync(dir)) {
		const p = join(dir, entry);
		if (statSync(p).isDirectory()) обійти(p, out);
		else out.push(шлях(p));
	}
	return out;
}

/** Знімає коментарі, лишаючи довжину рядків неважливою: розбір потім по тексту. */
function безКоментарів(текст: string): string {
	return текст
		.replace(/\/\*[\s\S]*?\*\//g, ' ')
		.replace(/<!--[\s\S]*?-->/g, ' ')
		.replace(/(^|[^:/'"`])\/\/[^\n]*/g, '$1');
}

function специфікатори(текст: string): string[] {
	const out: string[] = [];
	for (const m of текст.matchAll(/from\s+['"]([^'"]+)['"]/g)) out.push(m[1]);
	for (const m of текст.matchAll(/import\s*\(\s*['"]([^'"]+)['"]\s*\)/g)) out.push(m[1]);
	for (const m of текст.matchAll(/^\s*import\s+['"]([^'"]+)['"]/gm)) out.push(m[1]);
	return out;
}

function шаблониGlob(текст: string): string[] {
	const out: string[] = [];
	for (const m of текст.matchAll(/import\.meta\.glob\w*\(\s*(\[[^\]]*\]|['"][^'"]+['"])/g)) {
		for (const g of m[1].matchAll(/['"]([^'"]+)['"]/g)) out.push(g[1]);
	}
	return out;
}

function абсолютний(специфікатор: string, звідки: string): string | null {
	if (специфікатор.startsWith('$lib')) return шлях(join('src/lib', специфікатор.slice(4)));
	if (специфікатор.startsWith('.')) return шлях(join(dirname(звідки), специфікатор));
	// `$app/*`, `$env/*`, пакети — поза репозиторієм, графа не продовжують.
	return null;
}

function розвʼязати(специфікатор: string, звідки: string): string | null {
	const база = абсолютний(специфікатор, звідки);
	if (!база) return null;
	for (const ext of РОЗШИРЕННЯ) {
		const кандидат = база + ext;
		if (existsSync(кандидат) && statSync(кандидат).isFile()) return шлях(кандидат);
	}
	return null;
}

function globУРегулярку(шаблон: string, звідки: string): RegExp {
	const база = шаблон.startsWith('/')
		? шаблон.replace(/^\//, '')
		: (абсолютний(шаблон, звідки) ?? шаблон);
	const тіло = база
		.replace(/[.+^${}()|[\]\\]/g, '\\$&')
		.split('**/')
		.join('(?:.*/)?')
		.split('**')
		.join('.*')
		.split('*')
		.join('[^/]*');
	return new RegExp(`^${тіло}$`);
}

type Граф = { точкиВходу: string[]; досяжні: Set<string>; модуліБібліотеки: string[] };

function побудуватиГраф(): Граф {
	const уSrc = обійти('src').filter((f) => КОД.test(f) && !ОГОЛОШЕННЯ_ТИПІВ.test(f));
	const уІнструментах = ІНСТРУМЕНТИ.flatMap((d) => обійти(d)).filter(
		(f) => КОД.test(f) && !ОГОЛОШЕННЯ_ТИПІВ.test(f)
	);
	const конфіги = КОНФІГИ.filter((f) => existsSync(f));
	const відомі = new Set([...уSrc, ...уІнструментах, ...конфіги]);

	const точкиВходу = [
		...уSrc.filter(
			(f) =>
				/^src\/routes\/(.*\/)?\+[a-z]+(\.[a-z]+)?\.(svelte|ts|js)$/.test(f) ||
				/^src\/hooks(\.[a-z]+)?\.ts$/.test(f) ||
				/^src\/service-worker\.(ts|js)$/.test(f)
		),
		...уІнструментах.filter((f) => !ПЕРЕВІРКА.test(f)),
		...конфіги
	];

	const досяжні = new Set(точкиВходу);
	const стос = [...точкиВходу];
	while (стос.length) {
		const файл = стос.pop() as string;
		const текст = безКоментарів(readFileSync(файл, 'utf8'));
		for (const s of специфікатори(текст)) {
			const ціль = розвʼязати(s, файл);
			if (ціль && відомі.has(ціль) && !досяжні.has(ціль)) {
				досяжні.add(ціль);
				стос.push(ціль);
			}
		}
		for (const g of шаблониGlob(текст)) {
			const re = globУРегулярку(g, файл);
			for (const ціль of відомі) {
				if (re.test(ціль) && !досяжні.has(ціль)) {
					досяжні.add(ціль);
					стос.push(ціль);
				}
			}
		}
	}

	const модуліБібліотеки = уSrc.filter(
		(f) => f.startsWith(`${КОРІНЬ_БІБЛІОТЕКИ}/`) && !ПЕРЕВІРКА.test(f)
	);
	return { точкиВходу, досяжні, модуліБібліотеки };
}

describe('осиротілі модулі (PROJECT-STRUCTURE-v9, PS-REACHABILITY)', () => {
	const граф = побудуватиГраф();

	it('кожен модуль у src/lib досяжний від точки входу', () => {
		const сироти = граф.модуліБібліотеки
			.filter((f) => !граф.досяжні.has(f) && !ДОЗВОЛЕНІ_СИРОТИ.has(f))
			.sort();
		expect(
			сироти,
			'модулі, у які не веде жоден шлях від точок входу — підключити або ' +
				`видалити (PROJECT-STRUCTURE-v9, PS-REACHABILITY):\n${сироти.join('\n')}`
		).toEqual([]);
	});

	it('перевірка жива: точки входу й модулі знайдено', () => {
		expect(граф.точкиВходу.length, 'жодної точки входу — граф почався б із порожнечі').toBeGreaterThan(
			50
		);
		expect(граф.модуліБібліотеки.length, 'у src/lib не знайдено модулів').toBeGreaterThan(50);
	});

	it('обхід іде вглиб, а не лише по прямих імпортах точок входу', () => {
		// Якби `стос` не розкручувався, досяжними лишилися б самі корені та їхні
		// сусіди першого рівня — і перевірка вище стала б декорацією.
		const прямі = new Set(граф.точкиВходу);
		for (const файл of граф.точкиВходу) {
			for (const s of специфікатори(безКоментарів(readFileSync(файл, 'utf8')))) {
				const ціль = розвʼязати(s, файл);
				if (ціль) прямі.add(ціль);
			}
		}
		const глибші = [...граф.досяжні].filter((f) => !прямі.has(f));
		expect(глибші.length, 'жодного модуля глибше першого рівня — обхід не розкрутився').toBeGreaterThan(
			20
		);
	});

	it('множина досяжного — не «усе підряд»', () => {
		// Друга половина живості: занадто щедрий розв'язувач (наприклад, глоб, що
		// збігається з усім) зробив би перевірку зеленою назавжди. Файли перевірок
		// коренями не є й нікого не імпортують — жоден із них досяжним бути не може.
		const зайві = [...граф.досяжні].filter((f) => ПЕРЕВІРКА.test(f));
		expect(зайві, `файли перевірок опинилися в множині досяжного:\n${зайві.join('\n')}`).toEqual(
			[]
		);
	});
});

/** Розмір реєстру в brotli — тим самим рівнем 11, що й `sizeKb` нижче. */
function registryKb(file: string): number {
	return (
		zlib.brotliCompressSync(fs.readFileSync(file), {
			params: { [zlib.constants.BROTLI_PARAM_QUALITY]: 11 }
		}).length / 1024
	);
}


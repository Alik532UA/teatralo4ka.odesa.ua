import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';

/**
 * Відпечаток САМИХ ЗАЛЕЖНОСТЕЙ — ключ кешу для CI.
 *
 * ## Що зламано без цього
 *
 * `actions/setup-node` з `cache: "npm"` і `actions/cache` з
 * `hashFiles('package-lock.json')` беруть ключ від УСЬОГО lock-файлу. А в цьому
 * проєкті `.husky/pre-commit` викликає `npm run bump-version`, який на кожен
 * коміт піднімає `version` у `package.json` і в `package-lock.json` (двічі:
 * зверху й у `packages[""]`). Тобто ключ кешу змінюється на КОЖНОМУ коміті,
 * навіть коли жодна залежність не рушила.
 *
 * Наслідок заміряний, а не припущений. У журналі кожного job стоїть `npm cache
 * is not found`, а `gh cache list` показує три різні ключі
 * `node-cache-Linux-x64-npm-*` на `refs/heads/main` за одні півтори години.
 * Тобто кеш npm не влучав НІКОЛИ — ані разу за весь час його існування.
 *
 * Доки реєстр npm швидкий, це не видно: `npm ci` качає 647 пакетів за 14 с
 * (замір, прогін 33772902182). 2026-09-04 реєстр деградував — і той самий крок
 * дав 5 хв 02 с у деплої, 7 хв 03 с у глибоких перевірках і 4 хв 09 с у гейтах.
 * Три різні job, кожен платить окремо, і все це — у часі до публікації сайту.
 *
 * ## Чому не `restore-keys` замість цього
 *
 * `restore-keys` теж лікує влучання, і він тут стоїть — але як запасний шлях.
 * Самого його мало: первинний ключ і далі був би новим на кожен коміт, а
 * `actions/cache` зберігає кеш тоді, коли первинний ключ НЕ влучив. Тобто після
 * кожного коміту в сховище їхало б 176 МБ (`npm`) і 268 МБ (браузери) — при
 * межі 10 ГБ на репозиторій це витісняє чужі кеші, зокрема свій же попередній.
 *
 * Стабільний ключ дає і влучання, і тишу в сховищі.
 *
 * ## Чому скрипт, а не рядок у workflow
 *
 * Той самий відпечаток потрібен трьом воркфлоу й двом кешам у кожному. Три копії
 * тонкого однорядковика з `jq` розійшлися б — а розходження ключів кешу
 * непомітне: воно виглядає як «щось у CI знову довго».
 */

/** Поля, які піднімає `bump-version` і які до складу залежностей не належать. */
function безВерсії(lock) {
	const копія = structuredClone(lock);
	delete копія.version;
	if (копія.packages?.['']) delete копія.packages[''].version;
	return копія;
}

/**
 * `JSON.stringify` після `JSON.parse` дає стабільний рядок: порядок ключів у
 * lock-файлі задає npm і зберігає при перезаписі, тож сортувати не потрібно —
 * а якби й змінився, змінився б лише сам ключ, і кеш просто перезбереглося б.
 */
export function depsHash(lockText) {
	const відпечаток = JSON.stringify(безВерсії(JSON.parse(lockText)));
	return createHash('sha256').update(відпечаток).digest('hex');
}

// Виконання напряму — тільки хеш у stdout, без жодного оздоблення: рядок іде
// в `$GITHUB_OUTPUT` як є.
if (import.meta.url === `file://${process.argv[1]}` || process.argv[1]?.endsWith('deps-hash.mjs')) {
	process.stdout.write(depsHash(readFileSync('package-lock.json', 'utf8')));
}

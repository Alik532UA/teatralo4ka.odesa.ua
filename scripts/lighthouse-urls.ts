import { existsSync, readFileSync, readdirSync, writeFileSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { REDIRECT_PAGES } from '../src/lib/config/redirects';
import { isHiddenRoute } from '../src/lib/config/hiddenRoutes';
import { isPreviewHop } from '../src/lib/config/previewHops';

/**
 * Перелік адрес для Lighthouse — з МАРШРУТІВ, а не з того, що інструмент
 * знайшов сам (OBSERVABILITY-v9 § 2.2.1, `OBS-LHCI-REAL-PAGES`, MEDIUM).
 *
 * ## Що було не так
 *
 * `lighthouserc.cjs` мав `staticDistDir` і жодного `url`, тобто працювало
 * автовиявлення. Прочитано у джерелі `@lhci/cli@0.15.1`
 * (`src/collect/fallback-server.js`): воно бере HTML-файли на глибині **до
 * двох** каталогів від кореня збірки. Заміряно на цій збірці: 62 адреси.
 *
 * Що з цього виходило:
 *
 * - **найважчі сторінки сайту не мірялися жодного разу** — галактика
 *   випускників, анкети людей, сторінки вистав, груп, фестивалів і закладів
 *   лежать глибше за два каталоги;
 * - `404.html` мірялася як звичайна сторінка;
 * - нова верхньорівнева сторінка потрапляла в аудит мовчки, зникла — так само
 *   мовчки, і скорочення покриття ніхто не бачив;
 * - у конфізі стояв ключ `maxAutodiscoverIsolate`, якого в LHCI НЕМАЄ (є
 *   `maxAutodiscoverUrls`). Він не робив нічого, але читався як обмеження —
 *   тобто конфіг описував налаштування, якого не існує.
 *
 * ## Один представник на маршрут, а не всі сторінки
 *
 * Канон каже «перелік адрес генерується з переліку МАРШРУТІВ». Це не те саме,
 * що «всі сторінки»: сторінок 3025, і аудит кожної — це години. Маршрут же
 * визначає ВИГЛЯД сторінки: анкети всіх випускників зроблені тим самим
 * `+page.svelte`, і виміряти варто одну.
 *
 * Тому для кожного `+page.svelte` береться одна адреса: сам шлях, коли в
 * ньому немає параметрів, або перша реальна сторінка цього маршруту у
 * `build/` (див. `розкрити` нижче — там пояснено, чому саме збірка, а не
 * `prerender.entries`). Нова сторінка з'являється в аудиті сама; зниклий
 * маршрут забирає з переліку рівно свій рядок.
 *
 * ## Що виключено і чому
 *
 * Заглушки перенаправлення (`REDIRECT_PAGES`) і сторінки-пересадки
 * (`isPreviewHop`) — браузер іде далі, і виміряна була б чужа сторінка.
 * Приховані маршрути (`isHiddenRoute`) — службові, і в них навмисно немає
 * canonical. Сторінки адмінки лишаються: це живий інтерфейс, і
 * `lighthouserc.cjs` тримає для них власні пороги.
 *
 * ## Канарка
 *
 * Канон вимагає доводити, що сторінка вимірюється ЗАВАНТАЖЕНОЮ: «продуктивність
 * 100» без CSS і JS означає, що не завантажилося нічого. Тому перед записом
 * переліку перевіряється перша адреса: у її HTML є таблиця стилів і модуль
 * JavaScript, і обидва файли справді лежать у збірці й не порожні. Форма цих
 * двох посилань у SvelteKit не така, як у прикладі канону, — розбір у `канарка`.
 */

const BUILD = 'build';
const ВИХІД = '.lighthouse-urls.json';
const МАРШРУТИ = 'src/routes';

/** Шляхи всіх сторінок проєкту у вигляді маршрутів SvelteKit. */
function усіМаршрути(dir: string, prefix = ''): string[] {
	const out: string[] = [];
	for (const entry of readdirSync(dir)) {
		const full = join(dir, entry);
		if (statSync(full).isDirectory()) {
			// Групи маршрутів `(name)` в адресу не входять.
			const сегмент = /^\(.*\)$/.test(entry) ? '' : `/${entry}`;
			out.push(...усіМаршрути(full, prefix + сегмент));
		} else if (entry === '+page.svelte') {
			out.push(prefix || '/');
		}
	}
	return out;
}

const виключено = (p: string) => p in REDIRECT_PAGES || isHiddenRoute(p) || isPreviewHop(p);

/** Чи існує сторінка у збірці. */
const уЗбірці = (p: string) => existsSync(join(BUILD, p.replace(/^\//, ''), 'index.html'));

/**
 * Представник маршруту з параметрами шукається у ЗБІРЦІ, а не в
 * `prerender.entries`.
 *
 * Це не дрібниця реалізації, і перша редакція на ній спіткнулася. У
 * `prerender.entries` лежить лише те, до чого не дійде обхідник посилань, —
 * тобто переважно ЗАГЛУШКИ ПЕРЕНАПРАВЛЕННЯ зі старих адрес. Заміряно: усі 46
 * записів під `/projects/galaxy-graduates/plays/[id]` — заглушки, а справжні
 * сторінки вистав народжуються обходом і в переліку не згадані жодного разу.
 * Тобто маршрут, який видно кожному відвідувачеві, лишався б без представника.
 *
 * У `build/` натомість лежить те, що справді поїде на хостинг. Параметр
 * розкривається каталогами: беремо перший за абеткою, який не є заглушкою й має
 * власний `index.html`.
 */
function розкрити(сегменти: string[], шлях = ''): string | null {
	if (сегменти.length === 0) {
		const адреса = шлях || '/';
		return !виключено(адреса) && уЗбірці(адреса) ? адреса : null;
	}
	const [перший, ...решта] = сегменти;
	if (!/^\[.*\]$/.test(перший)) return розкрити(решта, `${шлях}/${перший}`);

	const каталог = join(BUILD, шлях.replace(/^\//, ''));
	if (!existsSync(каталог)) return null;
	for (const вкладений of readdirSync(каталог).sort()) {
		if (!statSync(join(каталог, вкладений)).isDirectory()) continue;
		const знайдене = розкрити(решта, `${шлях}/${вкладений}`);
		if (знайдене) return знайдене;
	}
	return null;
}

function представники(): string[] {
	const out: string[] = [];
	for (const маршрут of усіМаршрути(МАРШРУТИ).sort()) {
		const адреса = розкрити(маршрут.split('/').filter(Boolean));
		if (адреса) out.push(адреса);
	}
	return [...new Set(out)];
}

/**
 * Канарка: сторінка справді приїжджає зі своїми стилями й скриптом.
 *
 * ## Чому не «є тег `<link rel=stylesheet>` і `<script type=module src=…>`»
 *
 * Саме так канон і формулює, і саме на цьому перша редакція впала на власній
 * головній. У цьому проєкті вигляд розмітки інший, і обидві відмінності —
 * властивості SvelteKit, а не дефекти:
 *
 * - у `<link>` спершу стоїть `href`, і регулярка «rel одразу після тега» його
 *   не бачить;
 * - модуля з `src` немає взагалі: точку входу піднімає ІНЛАЙНОВИЙ
 *   `import("./_app/immutable/entry/start.…js")`, а решта чанків оголошена
 *   через `rel="modulepreload"`.
 *
 * Тому шукається суть, а не форма: таблиця стилів і модуль JavaScript, у
 * будь-якому написанні. Обидва посилання перевіряються НА ДИСКУ — саме так
 * виглядав би файл, якого сервер не віддасть.
 */
function канарка(адреса: string): string[] {
	const файл = join(BUILD, адреса.replace(/^\//, ''), 'index.html');
	const html = readFileSync(файл, 'utf8');
	const біди: string[] = [];

	const стиль = /<link[^>]*rel=["']stylesheet["'][^>]*>/i.exec(html)?.[0];
	const стильHref = стиль ? /href=["']([^"']+)["']/i.exec(стиль)?.[1] : undefined;
	const модуль = /import\(["']([^"']*_app\/immutable\/[^"']+\.js)["']\)/.exec(html)?.[1];

	if (!стильHref) біди.push(`${адреса}: у HTML немає таблиці стилів`);
	if (!модуль) біди.push(`${адреса}: у HTML немає імпорту точки входу JavaScript`);

	for (const посилання of [стильHref, модуль]) {
		if (!посилання) continue;
		const шлях = посилання.replace(/^\.?\//, '').replace(/^(\.\.\/)+/, '');
		const наДиску = join(BUILD, шлях);
		if (!existsSync(наДиску)) біди.push(`${адреса}: ${посилання} немає у збірці`);
		else if (statSync(наДиску).size === 0) біди.push(`${адреса}: ${посилання} порожній`);
	}
	return біди;
}

function main() {
	if (!existsSync(BUILD)) {
		console.error(`❌ ${BUILD}/ не існує — перелік адрес складається після збірки`);
		process.exit(1);
	}

	const адреси = представники();
	if (адреси.length < 10) {
		console.error(
			`❌ маршрутів знайдено лише ${адреси.length} — обхід ${МАРШРУТИ} зламався, ` +
				'а не сайт зменшився'
		);
		process.exit(1);
	}

	const біди = канарка(адреси[0]);
	if (біди.length > 0) {
		console.error('❌ канарка Lighthouse: сторінка виміряється без стилів або скрипта');
		for (const b of біди) console.error(`   ${b}`);
		console.error('   «продуктивність 100» у такому стані означає «нічого не завантажилося»');
		process.exit(1);
	}

	writeFileSync(ВИХІД, JSON.stringify(адреси, null, '\t') + '\n', 'utf8');
	console.log(
		`💡 Lighthouse: ${адреси.length} адрес із маршрутів (${ВИХІД}), ` +
			`канарка на ${адреси[0]} пройшла`
	);
}

main();

export { представники, канарка, усіМаршрути };

import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';

/**
 * Як виставу звуть В АНКЕТІ і як — у реєстрі.
 *
 * ## Звідки взялося
 *
 * Автор побачив те саме на двох сторінках по-різному: в анкеті —
 * «Уривки з класики: Той, що отримує ляпаса», у реєстрі вистав —
 * «Л. Андреєв „Той, хто отримує ляпаси“». І попросив не лише виправити, а
 * зібрати список подібних місць.
 *
 * Це той клас розходження, якого не бачить ЖОДЕН гейт: `playId` в анкеті
 * правильний, посилання веде куди слід, сторінка не падає. Розходиться тільки
 * ТЕКСТ, який читає людина, — і побачити його можна, лише поклавши дві сторінки
 * поруч.
 *
 * ## Що саме звіряється
 *
 * Рядок анкети виглядає як «‹назва вистави›: ‹уривок›», ‹роль›. Звідси:
 *
 *   1. назва вистави — проти `title` запису реєстру;
 *   2. уривок — проти назви номера в `programme` (зв'язок явний, коли в рядку є
 *      `items`; інакше береться найближчий за написанням).
 *
 * ## Три класи, а не один список
 *
 * - **інші слова** — «Чиполліно» проти «Цибуліно», «Чучело» проти «Бойкот».
 *   Тут треба рішення людини: котра назва правильна.
 * - **інше написання** — різниця в літері, апострофі чи великій літері. Коли
 *   кілька анкет пишуть однаково, а реєстр інакше, помилка радше в реєстрі.
 * - **формат** — анкета дописує автора («Антігона; Софокл»), реєстр тримає його
 *   окремо. Виправляти нема чого, і автор сказав це прямо.
 *
 * ## Чому скрипт, а не гейт
 *
 * Гейт мусив би бути зеленим, а зараз розходжень сотня. Зробити його червоним
 * назавжди — те саме, що вимкнути. Скрипт же можна ганяти після кожної правки й
 * дивитися, як число спадає; гейт має сенс тоді, коли воно дійде до нуля.
 */

const АНКЕТИ = 'static/graduates/profiles';
const ЗВІТ = '.private/plays-naming-audit.md';

interface Уривок {
	id: string;
	title: string;
}

interface Вистава {
	id: string;
	title: string;
	programme?: Уривок[];
}

interface РядокАнкети {
	year?: number;
	text?: string;
	playId?: string;
	items?: string[];
}

export interface Розбіжність {
	вид: 'назва вистави' | 'уривок';
	хто: string;
	рік?: number;
	вАнкеті: string;
	уРеєстрі: string;
	вистава: string;
	подібність: number;
}

const читати = <T>(шлях: string): T => JSON.parse(readFileSync(шлях, 'utf8')) as T;

/** Порівнюваний вигляд: регістр, лапки, апострофи, крайні розділові. */
function строго(s: string): string {
	return (s ?? '')
		.toLowerCase()
		.replace(/[«»"“”„]/gu, '')
		.replace(/['’ʼ`]/gu, "'")
		.replace(/\s+/gu, ' ')
		.trim()
		.replace(/^[.,;\s]+|[.,;\s]+$/gu, '');
}

/** Те саме, але без різниці и/і та розділових — для оцінки СХОЖОСТІ. */
function кістяк(s: string): string {
	let out = строго(s);
	for (const [a, b] of [
		['и', 'і'],
		['ы', 'і'],
		['й', 'і'],
		['ї', 'і'],
		['є', 'е'],
		['э', 'е'],
		['ё', 'е'],
		['ґ', 'г']
	]) {
		out = out.split(a).join(b);
	}
	return out.replace(/[^\p{L}\p{N} ]/gu, '');
}

function відстань(a: string, b: string): number {
	if (a === b) return 0;
	let prev = Array.from({ length: b.length + 1 }, (_, i) => i);
	for (let i = 1; i <= a.length; i++) {
		const row = [i];
		for (let j = 1; j <= b.length; j++) {
			row.push(Math.min(prev[j] + 1, row[j - 1] + 1, prev[j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1)));
		}
		prev = row;
	}
	return prev[b.length];
}

/** 1 — те саме, 0 і менше — зовсім різне. */
function подібність(a: string, b: string): number {
	const ка = кістяк(a);
	const кб = кістяк(b);
	return 1 - відстань(ка, кб) / Math.max(1, кб.length);
}

/** Назва в лапках: у реєстрі номер зветься «Софокл „Антігона“». */
function всерединіЛапок(s: string): string {
	const m = /«([^»]+)»/u.exec(s ?? '');
	return m ? m[1] : (s ?? '');
}

export function зібрати(): { розбіжності: Розбіжність[]; перевірено: number } {
	const дані = читати<Вистава[] | { plays: Вистава[] }>('src/lib/data/plays.data.json');
	const вистави = Array.isArray(дані) ? дані : дані.plays;
	const заId = new Map(вистави.map((p) => [p.id, p]));

	const розбіжності: Розбіжність[] = [];
	let перевірено = 0;

	for (const файл of readdirSync(АНКЕТИ).filter((f) => f.endsWith('.json')).sort()) {
		const анкета = читати<{ name?: string; slug?: string; plays?: РядокАнкети[] }>(
			join(АНКЕТИ, файл)
		);
		const хто = анкета.name ?? анкета.slug ?? файл.replace(/\.json$/, '');

		for (const рядок of анкета.plays ?? []) {
			const вистава = рядок.playId ? заId.get(рядок.playId) : undefined;
			if (!вистава) continue;
			перевірено += 1;

			const m = /^«(.+?)»(.*)$/u.exec((рядок.text ?? '').trim());
			if (!m) continue;

			const [назва, уривок] = m[1].split(': ');

			if (строго(назва) !== строго(вистава.title)) {
				розбіжності.push({
					вид: 'назва вистави',
					хто,
					рік: рядок.year,
					вАнкеті: назва,
					уРеєстрі: всерединіЛапок(вистава.title),
					вистава: вистава.id,
					подібність: подібність(назва, вистава.title)
				});
			}

			const програма = вистава.programme ?? [];
			const названі = (рядок.items ?? []).length
				? програма.filter((f) => рядок.items!.includes(f.id))
				: [];
			const варіанти = названі.length ? названі : програма;
			if (!уривок || варіанти.length === 0) continue;

			let найкращий = варіанти[0];
			let бал = -Infinity;
			for (const ф of варіанти) {
				const б = подібність(уривок, всерединіЛапок(ф.title));
				if (б > бал) {
					бал = б;
					найкращий = ф;
				}
			}
			const назваУривка = всерединіЛапок(найкращий.title);
			if (строго(уривок) !== строго(назваУривка)) {
				розбіжності.push({
					вид: 'уривок',
					хто,
					рік: рядок.year,
					вАнкеті: уривок,
					уРеєстрі: назваУривка,
					вистава: `${вистава.id}#${найкращий.id}`,
					подібність: бал
				});
			}
		}
	}

	return { розбіжності, перевірено };
}

/**
 * Чи вся різниця в тому, що анкета ДОПИСУЄ автора («Антігона; Софокл»).
 *
 * Це різні способи запису, а не розходження назв: реєстр тримає автора окремим
 * полем. Автор сказав про це прямо, тож ані звіт, ані гейт цього не рахують.
 */
export function лишеАвтор(р: Розбіжність): boolean {
	return р.вид === 'уривок' && строго(р.вАнкеті.replace(/;.*$/u, '')) === строго(р.уРеєстрі);
}

function звіт(): void {
	const { розбіжності, перевірено } = зібрати();

	/* Однакові випадки зводяться в один рядок: «Чиполліно» проти «Цибуліно» в
	   трьох анкетах — це одне рішення, а не три. */
	const групи = new Map<string, Розбіжність[]>();
	for (const р of розбіжності) {
		const ключ = `${р.вид}|${строго(р.вАнкеті)}|${строго(р.уРеєстрі)}`;
		групи.set(ключ, [...(групи.get(ключ) ?? []), р]);
	}

	const формат: Розбіжність[][] = [];
	const написання: Розбіжність[][] = [];
	const слова: Розбіжність[][] = [];

	for (const випадки of групи.values()) {
		const [перший] = випадки;
		// «Антігона; Софокл» проти «Антігона» — анкета ДОДАЄ автора.
		if (лишеАвтор(перший)) формат.push(випадки);
		else if (перший.подібність >= 0.85) написання.push(випадки);
		else слова.push(випадки);
	}

	const блок = (назва: string, перелік: Розбіжність[][], пояснення: string): string[] => {
		const out = [`\n## ${назва}\n`, `${пояснення}\n`];
		for (const випадки of перелік.sort((a, b) => b[0].подібність - a[0].подібність)) {
			const [перший] = випадки;
			const хто = [...new Set(випадки.map((c) => c.хто))].sort().join(', ');
			out.push(`- анкета «${перший.вАнкеті}» → реєстр «${перший.уРеєстрі}»  `);
			out.push(
				`  ${перший.вид}, подібність ${перший.подібність.toFixed(2)}, анкет: ${випадки.length} — ${хто}  `
			);
			out.push(`  вистава: \`${перший.вистава}\``);
		}
		return out;
	};

	const рядки = [
		'# Написання вистав: анкети проти реєстру\n',
		`Звірено ${перевірено} рядків анкет, які посилаються на конкретну виставу реєстру.\n`,
		`Знайдено ${розбіжності.length} розбіжностей, зведених у ${групи.size} випадків: ` +
			`${написання.length} — те саме слово іншим написанням, ${слова.length} — інші слова, ` +
			`${формат.length} — різниця формату (анкета дописує автора).\n`,
		...блок(
			`Інші слова — ${слова.length} випадків`,
			слова,
			'Анкета й реєстр звуть виставу РІЗНИМИ словами. Кожен рядок потребує рішення: ' +
				'котра назва правильна.'
		),
		...блок(
			`Те саме слово, інше написання — ${написання.length} випадків`,
			написання,
			'Різниця в літері, апострофі чи великій літері. Здебільшого описка в анкеті, але ' +
				'коли кілька анкет пишуть однаково, а реєстр інакше — помилка радше в реєстрі.'
		),
		...блок(
			`Формат, а не помилка — ${формат.length} випадків`,
			формат,
			'Анкета дописує автора через крапку з комою, реєстр тримає його окремим полем.'
		)
	];

	if (!existsSync('.private')) mkdirSync('.private', { recursive: true });
	writeFileSync(ЗВІТ, `${рядки.join('\n')}\n`, 'utf8');

	console.log(
		`📚 написання вистав: ${розбіжності.length} розбіжностей у ${перевірено} рядках — ` +
			`${слова.length} інші слова, ${написання.length} інше написання, ${формат.length} формат`
	);
	console.log(`   звіт: ${ЗВІТ}`);
}

/*
 * Звіт пишеться лише при ПРЯМОМУ запуску: гейт `src/play-naming.test.ts`
 * імпортує звідси `зібрати`, і побічний запис файлу під час прогону перевірок
 * був би несподіванкою.
 */
if (process.argv[1]?.includes('audit-play-naming')) звіт();

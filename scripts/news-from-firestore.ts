/**
 * Новини з бази → новини в КОДІ. Один файл на вході, шість файлів на виході.
 *
 * ## Навіщо
 *
 * Робочий хід автора: «коли мені треба терміново опублікувати новину, то я це
 * роблю через адмінку, бо це моментально. а потім коли у мене накопилися
 * новини, то я виділяю новини які є в firebase і зберігаю на комп'ютер, і
 * віддаю AI агенту щоб він зробив ці новини в коді». Мета — швидкість сайту:
 * «більшість новин в коді, щоб швидше вантажився сайт і менше запитів до
 * firebase».
 *
 * Перенести новину руками — це шість узгоджених правок у шести файлах, жодна з
 * яких не перевіряється компілятором. Саме на них і йде цей скрипт.
 *
 * ## Що робиться
 *
 * 1. Знімки ЗАВАНТАЖУЮТЬСЯ в `static/news/<дата>/` і міряються за заголовком.
 *    Автор обрав саме це: «Скачувати у static/news/<дата>/ і прописувати
 *    розміри». Причина проста — сторонній хостинг зображень нам не належить, і
 *    новина в коді не має від нього залежати.
 * 2. Пишеться markdown двома мовами (`src/lib/i18n/pages/{uk,en}/news-<id>.md`).
 * 3. Дописуються `LOCAL_IMAGE_SIZES`, `SEARCHABLE_PAGES`, `PUBLIC_ENTRIES` у
 *    `svelte.config.js` і сам запис у `CODE_NEWS`.
 *
 * ## Чого скрипт НЕ робить
 *
 * Не чіпає базу — ані в dev, ані на prod. Автор сказав це прямо: «в dev версії
 * ми не робимо автоматичний переїзд, бо мені тут треба тестувати з різних
 * джерел», а стару статтю «я видаляю чи приховую» сам. Зв'язок між копіями
 * лишається один: `replacesArticleId` у записі коду, через який перелік не
 * показує статтю з бази двічі.
 *
 * Не вигадує пояснень. У `CODE_NEWS` кожен наявний запис має коментар про те,
 * ЧОМУ саме така пропорція й таке кадрування; машині сказати тут нічого, тож
 * вона лишає позначку про своє походження, а решту допише той, хто дивився на
 * знімки.
 *
 * ## Ключ адреси
 *
 * Типово — транслітерація назви з роком (`potriinyi-triumf-uchniv-2026`). Це
 * робоча, але не найкраща адреса: наявні новини мають придумані англійські
 * ключі («30th-season-opened-2026»). Тому в пункті файла можна дописати
 * `"codeId": "…"` — і скрипт візьме його. Саме так і задумано: адресу вибирає
 * той, хто розуміє новину, а решту роботи робить скрипт.
 *
 * ## Запуск
 *
 *   npm run news:from-firestore -- .temp/news-batch-2026-09-06-3.json
 *   npm run news:from-firestore -- <файл> --dry   (нічого не писати, лише звіт)
 */


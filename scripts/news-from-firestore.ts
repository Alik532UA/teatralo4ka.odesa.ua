/**
 * Українська → латиниця за нормою КМУ № 55 (та сама, що в закордонному паспорті).
 *
 * Вибрано її, а не «як зручніше», з однієї причини: адреса новини живе вічно, і
 * правило, за яким її склали, має бути назване. Свій варіант через півроку ніхто
 * не відтворить — а цей відтворює будь-хто.
 */
const ЛАТИНИЦЯ: Record<string, string> = {
	а: 'a', б: 'b', в: 'v', г: 'h', ґ: 'g', д: 'd', е: 'e', є: 'ie', ж: 'zh', з: 'z',
	и: 'y', і: 'i', ї: 'i', й: 'i', к: 'k', л: 'l', м: 'm', н: 'n', о: 'o', п: 'p',
	р: 'r', с: 's', т: 't', у: 'u', ф: 'f', х: 'kh', ц: 'ts', ч: 'ch', ш: 'sh',
	щ: 'shch', ю: 'iu', я: 'ia', ь: '', "'": '', '’': '', ʼ: ''
};

export function транслітерувати(текст: string): string {
	return [...текст.toLowerCase()]
		.map((літера) => ЛАТИНИЦЯ[літера] ?? літера)
		.join('')
		.replace(/[^a-z0-9]+/g, '-')
		.replace(/^-+|-+$/g, '');
}

/** Скільки слів брати в адресу: довша за це вона стає нечитаною. */
const СЛІВ_В_АДРЕСІ = 4;

export function ключНовини(пункт: ПунктФайла): string {
	if (пункт.codeId?.trim()) return пункт.codeId.trim();
	const рік = (пункт.dateISO ?? new Date().toISOString()).slice(0, 4);
	const слова = транслітерувати(пункт.translations.uk.title).split('-').filter(Boolean);
	return [...слова.slice(0, СЛІВ_В_АДРЕСІ), рік].join('-');
}

/** Тека знімків — це ДАТА новини, як у наявних новин коду. */
export function текаЗнімків(пункт: ПунктФайла): string {
	return (пункт.dateISO ?? new Date().toISOString()).slice(0, 10);
}

/**
 * Значення у frontmatter — у подвійних лапках, а внутрішні перетворюються на «».
 *
 * Розбирач frontmatter (`i18n/loader.ts`) навмисно простий і екранування не
 * знає: він знімає крайні лапки регуляркою. Внутрішня подвійна лапка обрізала б
 * рядок мовчки. Українські «ялинки» тут не косметика — це єдиний спосіб не
 * зламати розбір, і в тексті вони й так доречні.
 */
export function значення(текст: string): string {
	let відкрито = false;
	const чисте = текст.replace(/"/g, () => {
		відкрито = !відкрито;
		return відкрито ? '«' : '»';
	});
	return `"${чисте.replace(/\r?\n/g, ' ').trim()}"`;
}

/** Голий текст із markdown або HTML — для опису, коли свого немає. */
export function голийТекст(текст: string): string {
	return текст
		.replace(/<[^>]+>/g, ' ')
		.replace(/!\[[^\]]*\]\([^)]*\)/g, ' ')
		.replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
		.replace(/[#*`_>|-]/g, ' ')
		.replace(/\s+/g, ' ')
		.trim();
}

const ШКОЛА = 'Одеська театральна школа «Театрало4ка»';
const МІН_ОПИС = 50;
const МАКС_ОПИС = 300;

/**
 * Опис для пошуковика й прев'ю: не коротший за 50 символів і не довший за 300.
 *
 * Межі не наші — це `pageMetadataSchema`, і порушення валить збірку на розборі
 * frontmatter. Коротка новина («опис пустий, пізніше буде») трапляється часто,
 * тому короткий опис ДОПОВНЮЄТЬСЯ назвою школи, а не відкидається: порожнє
 * прев'ю в месенджері гірше за загальну фразу.
 */
export function опис(пункт: ПунктФайла, мова: 'uk' | 'en'): string {
	const переклад = пункт.translations[мова];
	const своє = (переклад.excerpt || голийТекст(переклад.content)).trim();
	const повне = своє.length >= МІН_ОПИС ? своє : `${переклад.title}. ${своє} ${ШКОЛА}`.trim();
	return повне.slice(0, МАКС_ОПИС).trim();
}

/** Назва вкладки: не коротша за 10 і не довша за 100 — знову ж таки, схема. */
export function назваДляПошуковика(заголовок: string): string {
	const повна = `${заголовок} — ${ШКОЛА}`;
	return повна.length <= 100 ? повна : повна.slice(0, 99).trim();
}

/**
 * Підпис під новиною — ІМ'Я, а не логін.
 *
 * У базі поле `author` заповнює адмінка, і туди лягає адреса пошти того, хто
 * натиснув «зберегти»: «alikzapolnov@gmail.com». У markdown це поле публічне —
 * файл лежить у відкритому репозиторії, — тож перенос як є опублікував би
 * особисту адресу в 28 файлах. Заміряно на першій же партії з чотирнадцяти
 * новин.
 *
 * Пошта відкидається, а не переписується здогадом: підпис за наявними новинами
 * в коді — «Alik», і саме він і є типовим.
 */
const ПІДПИС_ТИПОВИЙ = 'Alik';

export function підпис(автор?: string): string {
	const своє = (автор ?? '').trim();
	return !своє || своє.includes('@') ? ПІДПИС_ТИПОВИЙ : своє;
}

export function сторінка(пункт: ПунктФайла, мова: 'uk' | 'en', дата: string): string {
	const переклад = пункт.translations[мова];
	const анотація = (переклад.excerpt || '').trim();
	const рядки = [
		'---',
		`title: ${значення(переклад.title)}`,
		`date: "${дата}"`,
		`author: ${значення(підпис(пункт.author))}`,
		/*
		 * `category` — РІД сторінки, і для новини він завжди `news`: цього вимагає
		 * гейт `config/codeNews.test.ts`, і саме так новина не стає в один ряд із
		 * розділами сайту. Плашка показу їде окремим полем — інакше стаття, яку
		 * автор позначив «Благодійність», ставала б у коді звичайною новиною.
		 */
		'category: "news"',
		...(пункт.category && пункт.category !== 'news'
			? [`newsCategory: "${пункт.category}"`]
			: []),
		`lang: "${мова}"`,
		'seo:',
		`  title: ${значення(назваДляПошуковика(переклад.title))}`,
		`  description: ${значення(опис(пункт, мова))}`,
		`status: "${переклад.isPublished ? 'published' : 'draft'}"`,
		'version: "1.0.0"'
	];
	if (анотація) рядки.push(`excerpt: ${значення(анотація.slice(0, МАКС_ОПИС))}`);
	рядки.push('---', '', переклад.content.trim(), '');
	return рядки.join('\n');
}

/**
 * Ім'я знімка в теці: `01.jpg`, `02.png` — номер за порядком, розширення за
 * СПРАВЖНІМ форматом файлу.
 *
 * Не за адресою: у знімка зі стороннього хостингу її часто немає взагалі
 * (`.../image?token=…`), а буває й неправдива. Розширення тут — це те, що
 * прочитано з підпису завантажених байтів.
 */
export function назваЗнімка(номер: number, розширення: string): string {
	return `${String(номер).padStart(2, '0')}.${розширення}`;
}

/** Медіа новини: новий перелік або старі `coverUrl`/`videoUrl` — те саме правило, що в `utils/articleMedia`. */
export function медіаПункту(пункт: ПунктФайла): Медіа[] {
	const свій = пункт.translations.uk.media;
	if (свій && свій.length > 0) return свій;
	const старе: Медіа[] = [];
	const обкладинка = пункт.translations.uk.coverUrl?.trim();
	const запис = пункт.translations.uk.videoUrl?.trim();
	if (обкладинка) старе.push({ kind: 'photo', url: обкладинка });
	if (запис) старе.push({ kind: 'video', url: запис });
	return старе;
}

export interface ЗнімокНаДиску {
	файл: string;
	width: number;
	height: number;
	alt: string;
	position?: string;
}

/** Ім'я змінної з текою знімків: ключ адреси з дефісами, заміненими підкресленням. */
export function змінноюДляТеки(ключ: string): string {
	return `медіа_${ключ.replace(/-/g, '_')}`;
}

export function записРеєстру(
	пункт: ПунктФайла,
	ключ: string,
	знімки: ЗнімокНаДиску[],
	записи: Медіа[]
): string {
	const змінна = змінноюДляТеки(ключ);
	const пропорція = пункт.mediaShape ? `\n		mediaShape: '${пункт.mediaShape}',` : '';
	const розкладка = пункт.mediaLayout ? `\n		mediaLayout: '${пункт.mediaLayout}',` : '';
	const медіа = [
		...знімки.map(
			(з) =>
				`			${змінна}('${з.файл}', ${з.width}, ${з.height}, ${JSON.stringify(з.alt)}` +
				`${з.position ? `, '${з.position}'` : ''})`
		),
		...записи.map((в) => `			відео(${JSON.stringify(в.url)}, ${JSON.stringify(в.alt ?? '')})`)
	].join(',\n');

	return [
		'	{',
		'		/*',
		'		 * Перенесено з бази конвертером новин.',
		'		 *',
		'		 * Пропорція, кадрування й підписи знімків тут ТИПОВІ — машина на знімки',
		'		 * не дивилася. Якщо плитка ріже не те, місце для причини — саме тут.',
		'		 */',
		`		id: '${ключ}',`,
		`		slug: 'news-${ключ}',`,
		`		replacesArticleId: '${пункт.id}',${пропорція}${розкладка}`,
		'		media: [',
		медіа,
		'		]',
		'	},'
	].join('\n');
}

// ── дії з диском ─────────────────────────────────────────────────────────────

async function завантажитиЗнімок(адреса: string): Promise<Buffer> {
	const відповідь = await fetch(адреса);
	if (!відповідь.ok) {
		throw new Error(`${відповідь.status} ${відповідь.statusText} — ${коротко(адреса)}`);
	}
	return Buffer.from(await відповідь.arrayBuffer());
}

/** Адреса знімка буває на кілька екранів (`data:`) — у помилку йде початок. */
function коротко(адреса: string): string {
	return адреса.length > 90 ? `${адреса.slice(0, 90)}…` : адреса;
}

/**
 * Вставка перед МІТКОЮ — рядком-коментарем, який стоїть у кожному з чотирьох
 * реєстрів.
 *
 * Мітка, а не здогад про останній рядок: `'
];'` трапляється в тому ж файлі
 * не раз, а «перед закриттям масиву» перестане працювати від першої ж правки
 * руками. Мітка натомість видима, гріпається однією фразою й сама пояснює, чому
 * там стоїть.
 *
 * Відсутність мітки — помилка, а не привід дописати в кінець: краще стати, ніж
 * мовчки покласти запис не туди.
 */
const МІТКА = 'дописує `npm run news:from-firestore`';

function вставити(файл: string, текст: string): void {
	const було = readFileSync(файл, 'utf8');
	const рядки = було.split('\n');
	const де = рядки.findIndex((р) => р.includes(МІТКА));
	if (де === -1) throw new Error(`у ${файл} немає мітки конвертера («${МІТКА}»)`);
	рядки.splice(де, 0, текст);
	writeFileSync(файл, рядки.join('\n'), 'utf8');
}

/** Друга мітка того самого файла — теки знімків стоять ПЕРЕД самим реєстром. */
function вставитиВДругуМітку(файл: string, текст: string): void {
	const було = readFileSync(файл, 'utf8');
	const рядки = було.split('\n');
	const перша = рядки.findIndex((р) => р.includes(МІТКА));
	const друга = рядки.findIndex((р, i) => i > перша && р.includes(МІТКА));
	if (друга === -1) throw new Error(`у ${файл} немає другої мітки конвертера`);
	рядки.splice(друга, 0, текст);
	writeFileSync(файл, рядки.join('\n'), 'utf8');
}

interface Готове {
	ключ: string;
	тека: string;
	знімки: ЗнімокНаДиску[];
	записи: Медіа[];
	пункт: ПунктФайла;
}

async function підготувати(пункт: ПунктФайла, сухий: boolean): Promise<Готове> {
	const ключ = ключНовини(пункт);
	const тека = текаЗнімків(пункт);
	const тека_на_диску = join(СТАТИКА, 'news', тека);
	if (!сухий && !existsSync(тека_на_диску)) mkdirSync(тека_на_диску, { recursive: true });

	const медіа = медіаПункту(пункт);
	const знімки: ЗнімокНаДиску[] = [];
	let номер = 0;

	for (const елемент of медіа.filter((м) => м.kind === 'photo')) {
		номер += 1;
		if (сухий) {
			знімки.push({ файл: `${String(номер).padStart(2, '0')}.?`, width: 0, height: 0, alt: '' });
			continue;
		}

		const байти = await завантажитиЗнімок(елемент.url);
		const вид = формат(байти);
		const розмір = розмірБайтів(байти);
		if (!вид || !розмір) {
			throw new Error(`не зображення або невідомий формат: ${коротко(елемент.url)}`);
		}

		const назва = назваЗнімка(номер, вид);
		writeFileSync(join(тека_на_диску, назва), байти);
		знімки.push({
			файл: назва,
			width: розмір[0],
			height: розмір[1],
			alt: елемент.alt?.trim() || пункт.translations.uk.title,
			position: елемент.position
		});
	}

	return { ключ, тека, знімки, записи: медіа.filter((м) => м.kind === 'video'), пункт };
}

function записати(г: Готове): void {
	const дата = текаЗнімків(г.пункт);

	for (const мова of ['uk', 'en'] as const) {
		writeFileSync(join(СТОРІНКИ, мова, `news-${г.ключ}.md`), сторінка(г.пункт, мова, дата), 'utf8');
	}

	if (г.знімки.length > 0) {
		вставити(
			РОЗМІРИ,
			г.знімки
				.map((з) => `	'/news/${г.тека}/${з.файл}': { width: ${з.width}, height: ${з.height} },`)
				.join('\n')
		);
	}

	вставити(
		ПОШУК,
		`	{ slug: 'news-${г.ключ}', href: () => resolve('/news/[id]', { id: '${г.ключ}' }) },`
	);

	вставити(КОНФІГ, `	'/news/${г.ключ}',`);

	вставити(
		РЕЄСТР,
		`/** Знімки новини «${г.пункт.translations.uk.title}» — тека дорівнює її даті. */\n` +
			`const ${змінноюДляТеки(г.ключ)} = зТеки('${г.тека}');\n`
	);
	вставитиВДругуМітку(РЕЄСТР, записРеєстру(г.пункт, г.ключ, г.знімки, г.записи));
}

export async function конвертувати(шляхДоФайла: string, сухий: boolean): Promise<void> {
	const файл = JSON.parse(readFileSync(шляхДоФайла, 'utf8'));
	if (файл.kind !== ОЧІКУВАНИЙ_ФОРМАТ) {
		throw new Error(
			`не той файл: kind="${файл.kind}". Потрібен експорт із /admin/content ` +
				`(кнопка «Зберегти вибрані одним файлом»), а не чернетка редактора.`
		);
	}
	const пункти: ПунктФайла[] = файл.items ?? [];
	if (пункти.length === 0) throw new Error('у файлі немає жодної новини');

	console.log(`📥 новин у файлі: ${пункти.length}${сухий ? ' (сухий прогін)' : ''}`);

	for (const пункт of пункти) {
		const готове = await підготувати(пункт, сухий);
		if (!сухий) записати(готове);
		console.log(
			`  ${сухий ? '·' : '✅'} ${готове.ключ} — ${готове.знімки.length} знімків, ` +
				`${готове.записи.length} відео, тека /news/${готове.тека}/`
		);
	}

	console.log(
		сухий
			? '\nНічого не записано. Приберіть --dry, коли ключі адрес влаштовують.'
			: [
					'',
					'Далі — руками, бо машині тут сказати нічого:',
					'  1. `npm run test:gates` і `npm run build` — шість файлів мусять зійтися.',
					'  2. У `CODE_NEWS` дописати причину пропорції й кадрування, якщо плитка ріже не те.',
					'  3. В адмінці приховати або видалити перенесені статті з бази.',
					'     (перелік і без цього не покаже їх двічі — `replacesArticleId` уже стоїть)'
				].join('\n')
	);
}

if (process.argv[1]?.includes('news-from-firestore')) {
	const аргументи = process.argv.slice(2);
	const шлях = аргументи.find((а) => !а.startsWith('--'));
	if (!шлях) {
		console.error('Вкажіть файл: npm run news:from-firestore -- <файл.json> [--dry]');
		process.exit(1);
	}
	конвертувати(шлях, аргументи.includes('--dry')).catch((помилка) => {
		console.error(`❌ ${(помилка as Error).message}`);
		process.exit(1);
	});
}

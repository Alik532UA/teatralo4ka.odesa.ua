import { existsSync, readdirSync } from 'node:fs';
import { spawnSync } from 'node:child_process';

/**
 * Швидкі гейти — ті, що ганяються ПЕРЕД кожним комітом.
 *
 * ## Навіщо окремий запуск, а не `npm test`
 *
 * Повний прогін триває близько ста секунд, і половину цього часу з'їдає
 * `eslint-baseline`, який піднімає ESLint на весь репозиторій. Стільки на кожен
 * коміт — це гачок, який вимкнуть на третій день. Решта гейтів разом
 * укладається в шість із половиною секунд на 306 перевірок (заміряно
 * 2026-09-02): вони не запускають ані браузера, ані лінтера, а читають вихідні
 * тексти й порівнюють із правилами.
 *
 * ## Чому за МІСЦЕМ, а не за переліком
 *
 * Перелік файлів руками застаріває мовчки: хтось додає гейт, забуває вписати
 * його сюди, і той не ганяється роками. Тому правило географічне — усе, що
 * лежить у корені `src/`, і є загальнорепозиторними гейтами: там `structure`,
 * `testid-conventions`, `contrast`, `css-variables` і ще три десятки таких
 * самих. Тести, що перевіряють конкретний модуль, лежать поруч із ним, глибше,
 * і сюди не потрапляють — вони й не про угоди.
 *
 * Новий гейт у корені підхоплюється сам. Це головне, заради чого тут скрипт, а
 * не рядок у `package.json`: розкриття `src/*.test.ts` оболонкою працює в Git
 * Bash і не працює в PowerShell, а `readdirSync` однаковий скрізь.
 *
 * ## Друге місце: `src/lib/data/`
 *
 * Реєстри даних (`*.data.json`, `*.index.json`) — єдина частина репозиторію,
 * яку правлять РУКАМИ щодня: додають виставу, переносять людину, виправляють
 * рік. Їхні інваріанти (`SKD-REGISTRY`, `GATE-DATA-REGISTRY` у пакеті) ловлять
 * саме те, що ламається від такої правки: посилання на неіснуючий запис,
 * розбіжність двобічного зв'язку, індекс, що відстав від анкети.
 *
 * Заміряно 2026-09-02: разом із кореневими це +64 перевірки і **+0,5 секунди**
 * (5,5 → 6,0 с). Дешево саме тому, що воркери на цей момент уже прогріті —
 * поодинці ці ж шість файлів коштують 24 с холодного старту, і саме це число
 * колись і виглядало як причина їх сюди не брати.
 *
 * Межа лишається географічною: не «перелік потрібних файлів», а два МІСЦЯ.
 * Новий реєстр зі своїм інваріантом підхоплюється так само сам.
 *
 * ## Що це НЕ ловить
 *
 * Ані типів (`npm run check`, 11 секунд), ані ESLint, ані Playwright. Гачок —
 * це сито з великими вічками проти конкретного класу помилок: угоди про назви,
 * стелі розміру, змінні CSS, контраст. Саме на них я спіткнувся двічі за одну
 * сесію, і обидва рази вже ПІСЛЯ коміту.
 */
const ПОВІЛЬНІ = new Set([
	// Піднімає ESLint на весь репозиторій: 46 секунд самотужки.
	'eslint-baseline.test.ts'
]);

/** Місця, а не перелік файлів. Порядок значення не має. */
const МІСЦЯ = ['src', 'src/lib/data'];

/**
 * Порожнє місце валить прогін, а не мовчить.
 *
 * Каталог перейменували чи перенесли — і скрипт, який просто пропустив би його,
 * лишився б зеленим, ганяючи менше, ніж обіцяє рядок нижче. Це рівно той клас,
 * від якого тут узагалі є перевірка (AI-AGENT-PITFALLS-v8 § 1.2).
 */
const гейти = МІСЦЯ.flatMap((місце) => {
	const файли = existsSync(місце)
		? readdirSync(місце)
				.filter((f) => f.endsWith('.test.ts') && !ПОВІЛЬНІ.has(f))
				.map((f) => `${місце}/${f}`)
		: [];

	if (файли.length === 0) {
		console.error(`❌ у ${місце}/ не знайдено жодного гейта — перевірка сама зламалася`);
		process.exit(1);
	}
	return файли;
});

console.log(`🚦 швидкі гейти: ${гейти.length} файлів із ${МІСЦЯ.join(', ')}`);

const { status } = spawnSync('npx', ['vitest', 'run', ...гейти], {
	stdio: 'inherit',
	shell: process.platform === 'win32'
});

process.exit(status ?? 1);

import { readdirSync } from 'node:fs';
import { spawnSync } from 'node:child_process';

/**
 * Швидкі гейти — ті, що ганяються ПЕРЕД кожним комітом.
 *
 * ## Навіщо окремий запуск, а не `npm test`
 *
 * Повний прогін триває близько сорока секунд, і майже весь цей час з'їдає
 * `eslint-baseline`, який піднімає ESLint на весь репозиторій. Сорок секунд на
 * кожен коміт — це гачок, який вимкнуть на третій день. Решта гейтів разом
 * укладається в чотири секунди на 239 перевірок: вони не запускають ані
 * браузера, ані лінтера, а читають вихідні тексти й порівнюють із правилами.
 *
 * ## Чому за МІСЦЕМ, а не за переліком
 *
 * Перелік файлів руками застаріває мовчки: хтось додає гейт, забуває вписати
 * його сюди, і той не ганяється роками. Тому правило географічне — усе, що
 * лежить у корені `src/`, і є загальнорепозиторними гейтами: там `structure`,
 * `testid-conventions`, `contrast`, `css-variables` і ще три десятки таких
 * самих. Тести, що перевіряють конкретний модуль, лежать поруч із ним, глибше,
 * і сюди не потрапляють — вони й не про угоди.
 *
 * Новий гейт у корені підхоплюється сам. Це головне, заради чого тут скрипт, а
 * не рядок у `package.json`: розкриття `src/*.test.ts` оболонкою працює в Git
 * Bash і не працює в PowerShell, а `readdirSync` однаковий скрізь.
 *
 * ## Що це НЕ ловить
 *
 * Ані типів (`npm run check`, 11 секунд), ані ESLint, ані Playwright. Гачок —
 * це сито з великими вічками проти конкретного класу помилок: угоди про назви,
 * стелі розміру, змінні CSS, контраст. Саме на них я спіткнувся двічі за одну
 * сесію, і обидва рази вже ПІСЛЯ коміту.
 */
const ПОВІЛЬНІ = new Set([
	// Піднімає ESLint на весь репозиторій: 46 секунд самотужки.
	'eslint-baseline.test.ts'
]);

const гейти = readdirSync('src')
	.filter((f) => f.endsWith('.test.ts') && !ПОВІЛЬНІ.has(f))
	.map((f) => `src/${f}`);

if (гейти.length === 0) {
	console.error('❌ у корені src/ не знайдено жодного гейта — перевірка сама зламалася');
	process.exit(1);
}

console.log(`🚦 швидкі гейти: ${гейти.length} файлів`);

const { status } = spawnSync('npx', ['vitest', 'run', ...гейти], {
	stdio: 'inherit',
	shell: process.platform === 'win32'
});

process.exit(status ?? 1);

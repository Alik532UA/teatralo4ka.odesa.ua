import { readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

/**
 * ЗВІТ: кого з наших людей новини називають, але не пов'язують посиланням.
 *
 * ## Навіщо звіт, а не гейт
 *
 * Збіг за іменем — здогад, а не факт. «Олена Ткач» у тексті майже напевно наша
 * директорка, а «Анастасія Цвєтус» — учасниця фестивалю, якої в нас немає
 * зовсім; ще буває тезка. Червоний гейт на здогаді змушував би або вимикати
 * його, або вписувати виняток на кожну чужу людину з таким самим прізвищем —
 * і те, і те гірше за відсутній (`CODE-QUALITY-v9` § 6.4.1).
 *
 * Тому скрипт нічого не змінює й нічим не валить збірку: він дає перелік, який
 * читає людина. Заміряно 16 вересня 2026 на першому прогоні: 19 знахідок у
 * восьми файлах, і всі 19 виявилися правильними — зокрема Дмитро Богомазов,
 * якого новина називала в орудному відмінку.
 *
 * ## Як шукає
 *
 * Відмінки. «Дмитром Богомазовим» — це «Дмитро Богомазов» із хвостами, тож
 * порівнюються КОРЕНІ: слово мінус два останні знаки (мінус один у коротких),
 * плюс до чотирьох будь-яких літер після. Чотири, а не три, саме через орудний
 * («Богомаз» + «овим»). Порядок слів вільний: «Ткач Олена» знайдеться так само.
 *
 * Пропускається те, що вже в посиланні, і те, що стоїть у frontmatter: в
 * `seo.description` посилання зіпсувало б опис для прев'ю.
 */

const КОРІНЬ = join('src', 'lib', 'i18n', 'pages');
const ПОСИЛАННЯ = /\[[^\]]*\]\([^)]*\)/g;

interface Людина {
	вид: string;
	адреса: string;
	імена: (string | undefined)[];
}

const дані = <T>(файл: string): T =>
	JSON.parse(readFileSync(join('src', 'lib', 'data', файл), 'utf8')) as T;

const люди: Людина[] = [
	...дані<{ id: string; slug: string; code?: string; name: string; nameEn?: string }[]>(
		'graduates.index.json'
	).map((g) => ({
		вид: 'випускник',
		адреса: `/projects/galaxy-graduates/${g.code ?? g.slug}`,
		імена: [g.name, g.nameEn]
	})),
	...дані<{ slug: string; displayName: string; displayNameEn?: string }[]>(
		'masters.index.json'
	).map((m) => ({
		вид: 'викладач',
		адреса: `/residents/adults/${m.slug}`,
		імена: [m.displayName, m.displayNameEn]
	})),
	...дані<{ slug: string; name: string; nameEn?: string }[]>('experts.data.json').map((e) => ({
		вид: 'фахівець',
		адреса: `/projects/galaxy-graduates/masters/${e.slug}`,
		імена: [e.name, e.nameEn]
	}))
];

/** Корінь слова без відмінкового хвоста. Короткі не ріжемо — забагато збігів. */
const корінь = (слово: string) => {
	const с = слово.replace(/^[«"'(]+|[»"'.,)]+$/g, '');
	return с.length >= 7 ? с.slice(0, -2) : с.length >= 5 ? с.slice(0, -1) : с;
};

function шаблон(повне: string | undefined): RegExp | null {
	const частини = (повне ?? '').split(/\s+/).filter((ч) => ч.length > 2);
	if (частини.length < 2) return null;
	const [о1, о2] = [корінь(частини[0]), корінь(частини[частини.length - 1])];
	if (о1.length < 3 || о2.length < 4) return null;
	/*
	 * `\p{L}`, а НЕ `\w`, і це не педантизм: у JavaScript `\w` — це
	 * `[A-Za-z0-9_]`, тобто кирилиці в ньому немає ЗОВСІМ. Перша редакція
	 * цього скрипта була дослівним переписом із Python, де `\w` розуміє
	 * Unicode, — і мовчки не знаходила жодного українського імені. Показав це
	 * зворотний експеримент: прибрав посилання на Богомазова, а звіт сказав
	 * «незвʼязаних згадок немає».
	 *
	 * `String.raw` — щоб зворотні скісні дійшли до RegExp, а не з'їлися рядком.
	 */
	const хвіст = String.raw`\p{L}{0,4}`;
	const пробіл = String.raw`\s+`;
	const пара = (a: string, b: string) => `${a}${хвіст}${пробіл}${b}${хвіст}`;
	return new RegExp(`(?:${пара(о1, о2)}|${пара(о2, о1)})`, 'iu');
}

const шаблони = люди.flatMap((л) =>
	л.імена.map((ім) => ({ л, ш: шаблон(ім) })).filter((x) => x.ш !== null)
);

let знайдено = 0;
for (const мова of readdirSync(КОРІНЬ)) {
	const тека = join(КОРІНЬ, мова);
	for (const файл of readdirSync(тека).sort()) {
		if (!файл.startsWith('news-') || !файл.endsWith('.md')) continue;
		const текст = readFileSync(join(тека, файл), 'utf8');
		const тіло = текст.replace(/^---\n[\s\S]*?\n---\n/, '');
		const зайняте = [...тіло.matchAll(ПОСИЛАННЯ)].map((m) => [m.index, m.index + m[0].length]);
		for (const { л, ш } of шаблони) {
			if (тіло.includes(л.адреса)) continue;
			const m = ш!.exec(тіло);
			if (!m || зайняте.some(([a, b]) => a <= m.index && m.index < b)) continue;
			знайдено++;
			console.log(`${мова}/${файл}\n   ${л.вид} «${m[0]}» → ${л.адреса}`);
		}
	}
}
console.log(знайдено === 0 ? '✅ незвʼязаних згадок немає' : `\n🔎 знахідок: ${знайдено}`);

import fs from 'fs';
import path from 'path';

/**
 * Один власник на кожен мета-тег у зібраному `<head>` (SEO-v9, `SEO-HEAD-SINGLE-OWNER`).
 *
 * ## Чому це ловиться лише над `build/`
 *
 * `<svelte:head>` ДОПИСУЄ до `<head>`, а не заміщує в ньому. Тобто макет і
 * сторінка можуть спокійно оголосити свій `canonical` кожен — у джерелах це
 * два різні файли, у кожному з них по одному тегу, і жоден лінтер не бачить
 * нічого дивного. Дубль виникає лише в зібраному HTML, і саме там його треба
 * шукати.
 *
 * Ціна дубля не в охайності. Два `canonical` — це вказівка краулеру, яку він
 * розв'язує на власний розсуд: Google при конфлікті ігнорує ОБИДВА й обирає
 * адресу сам. Два `description` — той самий випадок, тільки тихіший: сторінка
 * лишається в індексі, а в сніпеті стоїть не той текст. Два `og:image` дають
 * різну картинку в різних месенджерах.
 *
 * ## Чому перелік саме такий
 *
 * Тут лише теги, у яких ДРУГЕ значення заперечує перше. `hreflang` навмисно
 * не в переліку: їх стільки, скільки мов, і це нормально. `og:image` у
 * специфікації OpenGraph теж може повторюватися (галерея), але в цьому
 * проєкті картинка одна на сторінку, і другий тег означав би саме конфлікт
 * власників, а не галерею.
 *
 * ## Чому рахується всередині `<head>`, а не по всьому файлу
 *
 * `<title>` буває не лише в шапці: це ще й підпис усередині `<svg>`, яким
 * озвучують значок. Сьогодні таких у проєкті немає, і рахунок по всьому файлу
 * дав би те саме число — але перша ж іконка з підписом зробила б перевірку
 * червоною на порожньому місці, а гейт, який червоніє від правильного коду,
 * вимикають.
 *
 * ## Зворотний експеримент (`PIT-REVERSE-EXPERIMENT`)
 *
 * У `build/index.html` дописано другий `<link rel="canonical">` — перевірка
 * назвала файл, тег і кількість. Після відкоту — зелено. Другий бік:
 * зіпсовано регулярку `canonical` — упала перевірка живості, а не мовчазний
 * нуль знахідок.
 */

const BUILD_DIR = 'build';

/** Тег → як він виглядає в шапці. Другий такий самий тег — конфлікт власників. */
const ВЛАСНИКИ: { назва: string; шаблон: RegExp }[] = [
	{ назва: '<link rel="canonical">', шаблон: /<link[^>]+rel=["']canonical["']/gi },
	{ назва: '<meta name="description">', шаблон: /<meta[^>]+name=["']description["']/gi },
	{ назва: '<meta name="robots">', шаблон: /<meta[^>]+name=["']robots["']/gi },
	{ назва: '<meta property="og:image">', шаблон: /<meta[^>]+property=["']og:image["']/gi },
	{ назва: '<meta property="og:title">', шаблон: /<meta[^>]+property=["']og:title["']/gi },
	{
		назва: '<meta property="og:description">',
		шаблон: /<meta[^>]+property=["']og:description["']/gi
	},
	{ назва: '<meta property="og:url">', шаблон: /<meta[^>]+property=["']og:url["']/gi },
	{ назва: '<title>', шаблон: /<title[\s>]/gi }
];

function htmlFiles(dir: string, out: string[] = []): string[] {
	for (const entry of fs.readdirSync(dir)) {
		const full = path.join(dir, entry);
		if (fs.statSync(full).isDirectory()) htmlFiles(full, out);
		else if (entry.endsWith('.html')) out.push(full);
	}
	return out;
}

/** Шапка сторінки. Без неї рахувати не можна: `<title>` буває і всередині `<svg>`. */
function head(html: string): string | null {
	const m = /<head[^>]*>([\s\S]*?)<\/head>/i.exec(html);
	return m ? m[1] : null;
}

/**
 * Заглушка перенаправлення, а не сторінка.
 *
 * `check-links` і `redirects.spec.ts` знають ці файли як окремий вид: два рядки
 * без `<head>` узагалі — `location.href` і `<meta http-equiv="refresh">`. Мета-тегів
 * там немає й бути не мусить, тож у рахунок власників вони не входять. Але й
 * тихо пропускати «файл без шапки» не можна: саме так виглядав би зламаний
 * розбір. Тому ознака вимагається явна.
 */
const заглушкаПеренаправлення = (html: string) =>
	/http-equiv=["']refresh["']/i.test(html) && html.length < 1024;

function main() {
	if (!fs.existsSync(BUILD_DIR)) {
		console.error(`❌ немає каталогу ${BUILD_DIR}/ — спершу npm run build`);
		process.exit(1);
	}

	const файли = htmlFiles(BUILD_DIR);
	const проблеми: string[] = [];
	/** Скільки сторінок несуть кожен тег хоча б раз — для перевірки живості. */
	const знайдено = new Map(ВЛАСНИКИ.map((в) => [в.назва, 0]));
	let безШапки = 0;
	let заглушок = 0;
	let сторінок = 0;

	for (const файл of файли) {
		const html = fs.readFileSync(файл, 'utf8');
		const шапка = head(html);
		if (шапка === null) {
			if (заглушкаПеренаправлення(html)) заглушок++;
			else безШапки++;
			continue;
		}
		сторінок++;
		for (const { назва, шаблон } of ВЛАСНИКИ) {
			const скільки = (шапка.match(шаблон) ?? []).length;
			if (скільки > 0) знайдено.set(назва, (знайдено.get(назва) ?? 0) + 1);
			if (скільки > 1) {
				проблеми.push(
					`${файл.split(path.sep).join('/')}: ${назва} — ${скільки} разів, очікується 1`
				);
			}
		}
	}

	// --- живість, три боки ---
	//
	// Без цього блоку зіпсована регулярка або зміна розмітки шапки давали б
	// НУЛЬ знахідок, тобто зелений колір, який нічого не означає.
	if (сторінок < 100) {
		проблеми.push(`знайдено лише ${сторінок} сторінок із шапкою — обхід build/ зламався`);
	}
	if (безШапки > 0) {
		проблеми.push(
			`${безШапки} файлів без <head> і без ознаки перенаправлення — розбір шапки зламався`
		);
	}
	for (const [назва, скільки] of знайдено) {
		if (скільки === 0) {
			проблеми.push(`${назва} не знайдено в жодній шапці — шаблон застарів`);
		}
	}

	if (проблеми.length) {
		console.error(`❌ два власники в одного мета-тега (${проблеми.length}):`);
		for (const p of проблеми) console.error(`   ${p}`);
		process.exit(1);
	}

	console.log(
		`🏷️  шапка: ${ВЛАСНИКИ.length} тегів, по одному власнику на ${сторінок} сторінках ` +
			`(+${заглушок} заглушок перенаправлення)`
	);
}

main();

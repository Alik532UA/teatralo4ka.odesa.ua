import { spawnSync } from 'node:child_process';

/**
 * `npm audit`, який падає від ЗНАХІДОК, а не від недоступного реєстру.
 *
 * ## Що зламало деплой
 *
 * 2026-09-04: крок `npm audit --audit-level=high` завершився кодом 1 із
 * повідомленням `503 Service Unavailable - POST
 * https://registry.npmjs.org/-/npm/v1/security/audits/quick`. Тобто реєстр npm
 * лежав, і розгортання не сталося — при тому, що в самому проєкті не змінилося
 * НІЧОГО. Заміряно локально того ж дня: 15 знахідок, усі low/moderate, порогу
 * `high` жодна не досягає, тож перевірка мусила бути зеленою.
 *
 * Це не гіпотетична крихкість, а вже здійснене падіння: мережевий збій третьої
 * сторони блокував публікацію сайту.
 *
 * ## Чому не `|| true`
 *
 * Бо тоді перевірка перестає бути перевіркою: справжня знахідка рівня `high`
 * теж стала б зеленою, і про це ніхто не дізнався б. Тут розрізняються ДВІ різні
 * події, які `npm audit` подає одним кодом виходу:
 *
 *   знайдено high/critical .... падіння, як і було
 *   реєстр не відповів ........ гучне попередження й код 0
 *
 * Різниця видна лише в `--json`, і саме тому код виходу тут не читається
 * взагалі: `npm audit --json` виходить ненульовим і тоді, коли просто знайшов
 * уразливості.
 *
 * Ознака успіху — наявність `metadata.vulnerabilities`, а НЕ відсутність поля
 * `error`. Перша редакція перевіряла друге й падала на кожному прогоні:
 * заміряно, що npm кладе в успішний звіт `error: { summary: '', detail: '' }` —
 * порожній, але присутній.
 *
 * ## Чому три спроби
 *
 * Збій був 503, тобто тимчасовий. Три спроби з паузою 5 с покривають коротку
 * недоступність і коштують у зеленому випадку нуль — перша ж відповідь виходить
 * із циклу.
 *
 * ## Чому в кожної спроби є таймаут
 *
 * Перша редакція його не мала, і того ж дня це заміряно: `npm audit` не відповів
 * 503, а ЗАВИС. У прогоні 33862103312 крок `Audit dependencies` тривав понад
 * 15 хвилин, а в журналі за цей час — рівно два рядки «спроба 1 з 3 не вдалася»
 * і «спроба 2 з 3». Тобто механізм, доданий проти чужої недоступності, сам став
 * її підсилювачем: три нескінченні спроби замість одного швидкого «не вдалося».
 *
 * Мертвий реєстр мусить коштувати секунди. `--fetch-timeout` тут не годиться:
 * він стосується однієї HTTP-спроби, а не всієї команди, і власні ретраї npm
 * усередині нікуди не діваються — межу треба ставити самому процесу.
 */

/** Той самий поріг, що стояв у обох воркфлоу. Причина відхилення — у `deploy.yml`. */
const ПОРІГ = ['high', 'critical'];
const СПРОБ = 3;
const ПАУЗА_МС = 5000;
/**
 * 60 с на спробу. Замір зеленого випадку — 1 с (прогін 33772902182) і 1 хв 27 с
 * на деградованому реєстрі, який усе-таки відповів (прогін 33860191302). Межа
 * взята з запасом до першого, але свідомо НИЖЧЕ другого: звіт, який їде хвилину
 * й довше, у неблокуючому прогоні не вартий того, щоб три спроби склалися в
 * п'ять хвилин. Гірший випадок тепер — 3 хв замість необмеженого.
 */
const ТАЙМАУТ_МС = 60_000;

function спробувати() {
	/*
	 * Команда ОДНИМ рядком, а не ім'я плюс масив аргументів.
	 *
	 * З масивом і `shell: true` Node попереджає, що аргументи не екрануються
	 * (DEP0190). А без шелла на Windows `npm` узагалі не запускається: там це
	 * `npm.cmd`, і заміряно, що `spawnSync` тоді віддає порожній stdout — тобто
	 * перевірка звітувала б «реєстр не відповів» на цілком робочому реєстрі.
	 * Рядок без підстановок обидві пастки й обходить.
	 */
	const out = spawnSync('npm audit --json', {
		shell: true,
		encoding: 'utf8',
		timeout: ТАЙМАУТ_МС,
		// Без цього `timeout` на Windows убиває лише сам шелл, а `npm` лишається
		// жити далі — і в CI це виглядало б як завершений крок із процесом, що
		// й далі тримає мережу.
		killSignal: 'SIGKILL'
	});
	if (out.signal) {
		return { збій: `не відповів за ${ТАЙМАУТ_МС / 1000} с — процес припинено (${out.signal})` };
	}
	const текст = (out.stdout ?? '').trim();
	if (!текст) {
		// `out.error` тут важливіший за stderr: він означає, що процес не
		// запустився взагалі, і плутати це з недоступним реєстром не можна.
		const причина = out.error?.message ?? out.stderr?.trim();
		return { збій: причина || `npm audit не віддав нічого (код ${out.status})` };
	}
	try {
		return { звіт: JSON.parse(текст) };
	} catch {
		return { збій: `розбір JSON не вдався: ${текст.slice(0, 200)}` };
	}
}

let звіт = null;
let останнійЗбій = '';

for (let спроба = 1; спроба <= СПРОБ; спроба += 1) {
	const результат = спробувати();
	if (результат.звіт && !результат.звіт.error) {
		звіт = результат.звіт;
		break;
	}
	/*
	 * `error.summary` у npm буває ПОРОЖНІЙ навіть коли саме він і є причиною —
	 * заміряно: `{"summary":"","detail":""}`. Тому в повідомлення йде ще й те,
	 * що звіт узагалі приїхав без `metadata`: інакше в журналі лишається
	 * загадкове «не вдалося» без жодної підказки.
	 */
	останнійЗбій =
		результат.збій ??
		результат.звіт?.error?.summary ??
		'реєстр віддав звіт без metadata.vulnerabilities';
	console.warn(`⚠️  npm audit: спроба ${спроба} з ${СПРОБ} не вдалася — ${останнійЗбій}`);
	// `await` у модулі, а не цикл на `Date.now()`: той крутив би процесор п'ять
	// секунд, і в CI це видно як зайняте ядро.
	if (спроба < СПРОБ) await new Promise((r) => setTimeout(r, ПАУЗА_МС));
}

if (!звіт) {
	console.warn(
		'⚠️  Реєстр npm не відповів за три спроби — перевірку ПРОПУЩЕНО.\n' +
			'   Це не «уразливостей немає»: це «дізнатися не вдалося».\n' +
			`   Остання відповідь: ${останнійЗбій}`
	);
	process.exit(0);
}

const рівні = звіт.metadata?.vulnerabilities ?? {};
const порогові = ПОРІГ.reduce((сума, рівень) => сума + (рівні[рівень] ?? 0), 0);
/*
 * `total` серед рівнів — окремий ключ npm, а не рівень. Перша редакція
 * підсумовувала всі значення й казала «30 знахідок (4 low, 11 moderate, 15
 * total)»: тобто подвоювала число й називала `total` рівнем.
 */
const усього = рівні.total ?? 0;

const розклад = Object.entries(рівні)
	.filter(([рівень, n]) => рівень !== 'total' && n > 0)
	.map(([рівень, n]) => `${n} ${рівень}`)
	.join(', ');

console.log(`🔒 npm audit: ${усього} знахідок${розклад ? ` (${розклад})` : ''}, поріг ${ПОРІГ[0]}`);

if (порогові > 0) {
	console.error(`❌ уразливостей рівня ${ПОРІГ.join('/')}: ${порогові}`);
	console.error('   Подробиці: npm audit --audit-level=high');
	process.exit(1);
}

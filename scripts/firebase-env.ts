/**
 * Секрети Firebase, без яких зібраний сайт мертвий для відвідувача.
 *
 * ## Навіщо окремий модуль, а не рядок у `vite.config.ts`
 *
 * Щоб охорону можна було перевірити, не збираючи проєкт. Логіка тут чиста:
 * «дай набір змінних — скажу, чого бракує». Плагін у конфізі Vite лише
 * підставляє в неї справжнє оточення й кидає помилку. Без цього поділу
 * перевірити можна було б тільки один шлях — той, де все на місці, — а
 * цікавий якраз другий.
 *
 * Перелік мусить збігатися з тим, що читає `src/lib/firebase/config.ts`;
 * розходження в обидва боки ловить `src/firebase-env.test.ts`.
 */

/** Поля `firebaseConfig`. App Check сюди не входить: без нього сайт працює. */
export const ОБОВʼЯЗКОВІ_СЕКРЕТИ = [
	'VITE_FIREBASE_API_KEY',
	'VITE_FIREBASE_AUTH_DOMAIN',
	'VITE_FIREBASE_PROJECT_ID',
	'VITE_FIREBASE_STORAGE_BUCKET',
	'VITE_FIREBASE_MESSAGING_SENDER_ID',
	'VITE_FIREBASE_APP_ID'
] as const;

/**
 * Яких секретів бракує в наданому оточенні.
 *
 * Порожній рядок і рядок із самих пробілів рахуються відсутністю: саме такою
 * буває змінна, оголошена в CI без значення, і саме вона найнебезпечніша —
 * `undefined` видно, а порожній рядок мовчки їде в бандл.
 */
export function відсутніСекрети(env: Record<string, string | undefined>): string[] {
	return ОБОВʼЯЗКОВІ_СЕКРЕТИ.filter((k) => !(env[k] ?? '').trim());
}

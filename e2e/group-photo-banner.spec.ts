import { expect, test } from '@playwright/test';
import { gotoReady } from './ready';

/**
 * Банер знімків групи не гасне при переході між групами.
 *
 * ## Що саме тут стережеться
 *
 * Кроки, якими це знайдено: `/groups/tu-154/` (два знімки) → дочекатися, поки
 * автоперегортання перемкне на другий → перейти по зв'язку родоводу на
 * `/groups/freestyle/` (один знімок). Банер був ПОРОЖНІЙ.
 *
 * Причина не в даних і не в CSS. Маршрут той самий — `groups/[slug]`, — тож
 * `GroupPhotoBanner` не перемонтовується, а його `index` лишається станом
 * попередньої групи, тобто одиницею. Активний знімок обирався через
 * `index === i`, а `i` тепер буває лише нулем: жоден не збігався, стопка малювала
 * нічого, і навіть крапок для порятунку не було — їхній рядок з'являється лише
 * при двох і більше знімках.
 *
 * ## Чому саме e2e, а не юніт
 *
 * Дефект живе РІВНО в переході між двома сторінками одного маршруту: у будь-якому
 * окремому рендері компонент правильний. Юніт-тест, який змонтував би банер із
 * одним знімком, був би зелений і до виправлення.
 *
 * ## Чому клік по крапці, а не очікування
 *
 * Автоперегортання має період 5 секунд, і перший знімок обирається ВИПАДКОВО.
 * Тест, що чекає перемикання, коштував би секунд і лишався б хитким. Клік по
 * другій крапці ставить той самий стан (`index = 1`) детерміновано — а дефект
 * саме в стані, а не в тому, як він туди потрапив.
 *
 * ## Зворотний експеримент (AI-AGENT-PITFALLS-v8 § 1.1)
 *
 * Запобіжників у компоненті два — обмеження індексу межами переліку й скидання
 * в ефекті, — і кожен САМЕ СОБОЮ цей шлях лагодить. Тому експеримент проведено
 * двома проходами, а не одним:
 *
 *   обидва знято ..... знімок FreeStyle без `is-active`, банер порожній —
 *                      дефект відтворено дослівно;
 *   лише скидання .... знімок активний, тобто перевірка ЗЕЛЕНА.
 *
 * Отже ця перевірка стереже сам симптом, а не котрийсь із двох запобіжників;
 * друге пояснення — у докблоці `GroupPhotoBanner`.
 *
 * Проходи виконано на dev-сервері: у прихованій панелі браузера `opacity` не
 * рухається (переходи не отримують кадрів рендеру), тож там суддею був КЛАС.
 * У Playwright кадри є, тому нижче перевіряється й `opacity`.
 */
const ТУ154 = '/projects/galaxy-graduates/groups/tu-154';

test.describe('банер знімків групи', () => {
	test('перехід на групу з меншою кількістю знімків не гасить банер', async ({ page }) => {
		await gotoReady(page, ТУ154);

		/* Другий знімок — клацанням, а не очікуванням: див. докблок. */
		await page.getByTestId('group-photo-item-1').click();
		await expect(page.getByTestId('group-photo-img-1')).toHaveClass(/is-active/);

		await page.getByTestId('group-lineage-before-link-freestyle').click();
		await expect(page).toHaveURL(/groups\/freestyle/);

		/*
		 * Перевіряється `opacity`, а не сам клас: клас — це механізм, а порожній
		 * банер — те, що бачить читач. Стопка малює всі знімки одночасно й гасить
		 * неактивні прозорістю, тож `toBeVisible()` тут сказав би «видно» й про
		 * повністю прозорий знімок.
		 */
		const знімок = page.getByTestId('group-photo-img-0');
		await expect(знімок).toHaveClass(/is-active/);
		await expect(знімок).toHaveCSS('opacity', '1');
	});
});

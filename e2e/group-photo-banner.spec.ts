import { expect, test } from '@playwright/test';
import { gotoReady } from './ready';

/**
 * Банер знімків групи не гасне при переході між групами.
 *
 * ## Що саме тут стережеться
 *
 * Кроки, якими це знайдено: `/groups/tu-154/` (два знімки) → дочекатися, поки
 * автоперегортання перемкне на другий → перейти по зв'язку родоводу на
 * `/groups/freestyle/` (один знімок). Банер був ПОРОЖНІЙ.
 *
 * Причина не в даних і не в CSS. Маршрут той самий — `groups/[slug]`, — тож
 * `GroupPhotoBanner` не перемонтовується, а його `index` лишається станом
 * попередньої групи, тобто одиницею. Активний знімок обирався через
 * `index === i`, а `i` тепер буває лише нулем: жоден не збігався, стопка малювала
 * нічого, і навіть крапок для порятунку не було — їхній рядок з'являється лише
 * при двох і більше знімках.
 *
 * ## Чому саме e2e, а не юніт
 *
 * Дефект живе РІВНО в переході між двома сторінками одного маршруту: у будь-якому
 * окремому рендері компонент правильний. Юніт-тест, який змонтував би банер із
 * одним знімком, був би зелений і до виправлення.
 *
 * ## Чому клік по крапці, а не очікування
 *
 * Автоперегортання має період 5 секунд, і перший знімок обирається ВИПАДКОВО.
 * Тест, що чекає перемикання, коштував би секунд і лишався б хитким. Клік по
 * другій крапці ставить той самий стан (`index = 1`) детерміновано — а дефект
 * саме в стані, а не в тому, як він туди потрапив.
 *
 * ## Зворотний експеримент (AI-AGENT-PITFALLS-v8 § 1.1)
 *
 * Запобіжників у компоненті два — обмеження індексу межами переліку й скидання
 * в ефекті, — і кожен САМЕ СОБОЮ цей шлях лагодить. Тому експеримент проведено
 * двома проходами, а не одним:
 *
 *   обидва знято ..... знімок FreeStyle без `is-active`, банер порожній —
 *                      дефект відтворено дослівно;
 *   лише скидання .... знімок активний, тобто перевірка ЗЕЛЕНА.
 *
 * Отже ця перевірка стереже сам симптом, а не котрийсь із двох запобіжників;
 * друге пояснення — у докблоці `GroupPhotoBanner`.
 *
 * Проходи виконано на dev-сервері: у прихованій панелі браузера `opacity` не
 * рухається (переходи не отримують кадрів рендеру), тож там суддею був КЛАС.
 * У Playwright кадри є, тому нижче перевіряється й `opacity`.
 */
const ТУ154 = '/projects/galaxy-graduates/groups/tu-154';

/**
 * Пропорції знімків «ТВ Продакшн»: чотири горизонтальні й один вертикальний.
 *
 * Саме на цій змішаній стопці двічі ламався банер, тож числа тут — із реєстру
 * розмірів, а не з голови.
 */
const ТВ_ПРОДАКШН = '/projects/galaxy-graduates/groups/tv-prodakshn';
const ПРОПОРЦІЇ: Record<string, number> = {
	'tv-prodakshn.webp': 1079 / 720,
	'tv-prodakshn-2.webp': 1280 / 850,
	'tv-prodakshn-3.webp': 960 / 1280,
	'tv-prodakshn-4.webp': 1280 / 960,
	'tv-prodakshn-5.webp': 1280 / 960
};
/** Стеля висоти коробки — та сама, що в компоненті. */
const МАКС_ВИСОТА = 600;

test.describe('банер знімків групи', () => {
	test('перехід на групу з меншою кількістю знімків не гасить банер', async ({ page }) => {
		await gotoReady(page, ТУ154);

		/* Другий знімок — клацанням, а не очікуванням: див. докблок. */
		await page.getByTestId('group-photo-item-1').click();
		await expect(page.getByTestId('group-photo-img-1')).toHaveClass(/is-active/);

		await page.getByTestId('group-lineage-before-link-freestyle').click();
		await expect(page).toHaveURL(/groups\/freestyle/);

		/*
		 * Перевіряється `opacity`, а не сам клас: клас — це механізм, а порожній
		 * банер — те, що бачить читач. Стопка малює всі знімки одночасно й гасить
		 * неактивні прозорістю, тож `toBeVisible()` тут сказав би «видно» й про
		 * повністю прозорий знімок.
		 */
		const знімок = page.getByTestId('group-photo-img-0');
		await expect(знімок).toHaveClass(/is-active/);
		await expect(знімок).toHaveCSS('opacity', '1');
	});

	/**
	 * КОЖЕН знімок показується у власній пропорції, і жоден не кадрується.
	 *
	 * ## Чому це e2e, а не юніт
	 *
	 * Стверджується тут не значення функції, а РОЗМІР коробки на екрані: саме
	 * він двічі виявився неправильним, і обидва рази — не через дані. Юніт бачив
	 * би лише рядок `aspect-ratio`; він був «валідний» в обох зламаних
	 * редакціях.
	 *
	 * ## Що саме ламалося
	 *
	 * Перша редакція: «є хоч один вертикальний знімок → коробка вертикальна».
	 * На стопці з п'яти знімків один вертикальний зробив коробку вертикальною, і
	 * афішу 1280×850 зрізало навпіл.
	 *
	 * Друга: «більшість або порівну». Дзеркально — коробка лишилася
	 * горизонтальною, і зрізало вже вертикальний знімок. Автор побачив обидва
	 * рази.
	 *
	 * Спільна помилка — одна пропорція на різні знімки. Тепер її задає той
	 * знімок, який показується зараз.
	 *
	 * ## Чому миша відводиться
	 *
	 * `.banner:hover` масштабує коробку на 1.01, а після кліку по стрілці
	 * вказівник лишається над банером. Перший прогін через це намиряв 828×553
	 * замість 820×547 — тобто перевірка падала на округленні, а не на дефекті.
	 */
	test('коробка одна на стопку, знімки цілі, і стрілки гортають', async ({ page }) => {
		/** Найширший знімок «ТВ Продакшн» — його пропорцію бере коробка. */
		const НАЙШИРША = Math.max(...Object.values(ПРОПОРЦІЇ));
		await gotoReady(page, ТВ_ПРОДАКШН);
		const банер = page.locator('[data-testid="group-photo-banner"]');
		await expect(банер).toBeVisible();

		/*
		 * Знімок і коробку заміряємо ОДНИМ заходом у сторінку, а не двома.
		 *
		 * Банер сам перегортається кожні п'ять секунд. Перша редакція читала
		 * `src`, потім чекала 350 мс і міряла коробку — і в паралельному прогоні
		 * між цими двома діями встигав спрацювати таймер: перевірка звіряла
		 * пропорцію одного знімка з коробкою вже іншого. Падало не завжди, тобто
		 * найгіршим способом. Тепер обидва числа беруться з одного кадру.
		 */
		/*
		 * Кроків БІЛЬШЕ, ніж знімків, і зупиняємося на повному колі.
		 *
		 * Той самий таймер перегортає банер сам, тож рівно N натискань іноді
		 * дають N−1 різних знімків: клік і тік таймера збігаються, і один кадр
		 * пролітає. Заміряно в паралельному прогоні: `бачені.size` 4 замість 5.
		 * Тому перевіряється те, що справді твердиться, — що стрілка обходить усю
		 * стопку, а не що вона робить це рівно за N кроків.
		 */
		const бачені = new Set<string>();
		const МЕЖА = Object.keys(ПРОПОРЦІЇ).length * 3;
		for (let крок = 0; крок < МЕЖА && бачені.size < Object.keys(ПРОПОРЦІЇ).length; крок += 1) {
			await page.mouse.move(5, 5);
			await page.waitForTimeout(350);
			const замір = await банер.evaluate((el) => {
				const активний = el.querySelector('.banner__img.is-active') as HTMLImageElement | null;
				const рамка = el.getBoundingClientRect();
				return {
					файл: (активний?.getAttribute('src') ?? '').split('/').pop() ?? '',
					своя: активний ? активний.naturalWidth / активний.naturalHeight : 0,
					вписування: активний ? getComputedStyle(активний).objectFit : '',
					ширина: рамка.width,
					висота: рамка.height
				};
			});
			const очікувана = ПРОПОРЦІЇ[замір.файл];
			expect(очікувана, `невідомий знімок у банері: ${замір.файл}`).toBeDefined();

			/*
			 * Коробка ОДНА на всю стопку — пропорція найширшого знімка, — і саме
			 * тому вона не змінюється від кадру до кадру. Попередня редакція
			 * вимагала протилежного (коробка під кожен знімок), і автор побачив
			 * ціну: «не зафіксований по висоті і як наслідок при переключені
			 * фотографій стрибає інші елементи».
			 */
			expect(
				Math.abs(замір.ширина / замір.висота - НАЙШИРША),
				`${замір.файл}: коробка ${замір.ширина}×${замір.висота} змінилася — має бути ` +
					`однакова на всій стопці (${НАЙШИРША})`
			).toBeLessThan(0.02);

			// А не кадрується нічого через `contain`: він і є та обіцянка.
			expect(замір.вписування, `${замір.файл}: знімок кадрується`).toBe('contain');
			expect(замір.висота, `${замір.файл}: коробка вища за стелю`).toBeLessThanOrEqual(
				МАКС_ВИСОТА + 1
			);

			бачені.add(замір.файл);
			await page.getByTestId('group-photo-next-btn').click();
			await page.waitForTimeout(350);
		}

		// Стрілка обійшла всю стопку, а не топталася на місці.
		expect(бачені.size).toBe(Object.keys(ПРОПОРЦІЇ).length);

		// І не відкрила лайтбокс: коробка під стрілками робить саме це.
		await expect(page.locator('[data-testid="photo-lightbox-prev-btn"]')).toHaveCount(0);
	});

	/**
	 * Правило спільне для ВСІХ, хто малює банер, а не для однієї сторінки.
	 *
	 * Компонент малюють троє: сторінка групи, сторінка фестивалю і шапка
	 * вистави. Перевірка вище ходить по групі; ця бере виставу — саме там жив
	 * окремий режим `fit="whole"` («показати афішу цілком»), який зник, бо тепер
	 * так поводяться всі. Якщо колись повернуть кадрування «за замовчуванням»,
	 * упаде саме ця перевірка, а не сторінка в проді.
	 *
	 * Заміряно на решті видів під час цієї роботи: `groups/paradoks` і
	 * `groups/rost-ok` (лише вертикальний, 400×600), `festivals/mrii-dim-2012`
	 * (960×720 і 697×720 — кожен свій), `festivals/art-like-fest-2026`
	 * (338×601), `plays/uryvky-z-klasyky-2015` (804×600).
	 */
	test('те саме правило на сторінці вистави', async ({ page }) => {
		await gotoReady(page, '/projects/galaxy-graduates/plays/tryvozhni-liudy-2024');
		const банер = page.locator('[data-testid="group-photo-banner"]');
		await expect(банер).toBeVisible();

		await page.mouse.move(5, 5);
		await page.waitForTimeout(350);
		const рамка = (await банер.boundingBox())!;
		const афіша = 1280 / 859;

		expect(
			Math.abs(рамка.width / рамка.height - афіша),
			`афіша ${рамка.width}×${рамка.height} кадрується, а мусить бути цілою`
		).toBeLessThan(0.02);
	});

	/**
	 * Той самий банер у ПЛАШЦІ випускника.
	 *
	 * Сторінка випускника складається з плашок, які розкладає алгоритм за
	 * заміряними висотами, і банер тут живе всередині колонки завширшки близько
	 * 420 px — тобто вужчої за його власні 820. Перевірка стежить рівно за цим:
	 * знімок не вилазить за плашку й не кадрується, бо в колонці пропорція
	 * тримається так само, як на всю ширину сторінки.
	 */
	test('банер у плашці випускника вміщається в колонку', async ({ page }) => {
		await gotoReady(page, '/projects/galaxy-graduates/margotcine');
		const плашка = page.getByTestId('galaxy-card-gallery-card');
		await expect(плашка).toBeVisible();

		const банер = плашка.locator('[data-testid="group-photo-banner"]');
		await expect(банер).toBeVisible();

		await page.mouse.move(5, 5);
		await page.waitForTimeout(350);
		const рамкаПлашки = (await плашка.boundingBox())!;
		const рамка = (await банер.boundingBox())!;
		expect(
			рамка.width,
			`банер ${рамка.width} ширший за плашку ${рамкаПлашки.width}`
		).toBeLessThanOrEqual(рамкаПлашки.width + 1);

		/*
		 * Коробка не змінюється при перегортанні — саме через це плашки поруч
		 * і стрибали, поки пропорція бралася з поточного знімка.
		 */
		const НАЙШИРША = 1280 / 904;
		expect(
			Math.abs(рамка.width / рамка.height - НАЙШИРША),
			`коробка ${рамка.width}×${рамка.height} не збігається з найширшим знімком`
		).toBeLessThan(0.02);

		await page.getByTestId('group-photo-next-btn').click();
		// Курсор геть від банера: під наведенням він `scale(1.01)`, і замір
		// показував би 2.5 px різниці там, де коробка насправді нерухома.
		await page.mouse.move(5, 5);
		await page.waitForTimeout(500);
		const післяКлацання = (await банер.boundingBox())!;
		expect(
			Math.abs(післяКлацання.height - рамка.height),
			`після перегортання коробка стала ${післяКлацання.width}×${післяКлацання.height}`
		).toBeLessThan(1);
	});
});

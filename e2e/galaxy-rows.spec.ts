import { expect, test } from '@playwright/test';
import { gotoReady } from './ready';

/**
 * Правий край рядка галактики однаковий у ВСІХ рядках переліку.
 *
 * ## Чому це знадобилося
 *
 * Рядок — сітка з чотирьох колонок: рік, назва, обличчя, плашки. Комірка з
 * обличчями малюється лише там, де в записі є люди, тож у рядку без них плашки
 * автоматично лягали в ТРЕТЮ колонку замість четвертої — і зупинялися на 12 px
 * лівіше за решту. Рівно на ширину проміжку між колонками: сама колонка без
 * вмісту стискається в нуль, а проміжок нікуди не дівається.
 *
 * Заміряно 2026-09-11: на переліку фестивалів це зачіпало три рядки з двадцяти,
 * на переліку вистав — кожен рядок без складу з трьохсот сімнадцяти. Побачив це
 * автор, а не перевірка: «іноді прапори не вирівняні по лівому краю».
 *
 * ## Чому саме E2E, а не інваріант по джерелах
 *
 * Дефект не в розмітці й не в даних — обидва правильні. Він у тому, ЯК браузер
 * розклав правильну розмітку, і побачити його можна лише виміряними
 * прямокутниками. Це третя поломка розкладки поспіль на тих самих сторінках
 * (перед нею — зниклий банер дипломів і різна висота кадру й каруселі), і всі
 * три були невидимі для `svelte-check`, юніт-гейтів і axe.
 *
 * ## Чому міряється правий край, а не лівий
 *
 * Плашок у рядку різна кількість — у когось і склад, і покази, у когось нічого,
 * — тож лівий край групи законно різний. Спільне в них одне: вони притиснуті
 * до правого краю рядка. Саме його збіг і означає «вирівняно».
 */

/** Сторінки, де перелік будується рядками й трапляються обидва види. */
const ПЕРЕЛІКИ = [
	{ name: 'фестивалі', url: '/projects/galaxy-graduates/festivals/' },
	{ name: 'вистави', url: '/projects/galaxy-graduates/plays/' }
] as const;

test.describe('рядки галактики', () => {
	for (const { name, url } of ПЕРЕЛІКИ) {
		test(`${name}: правий край плашок однаковий у всіх рядках`, async ({ page }) => {
			await gotoReady(page, url);

			const дані = await page.evaluate(() => {
				const rows = [...document.querySelectorAll('.grow')];
				const marks = [...document.querySelectorAll('.grow__marks')];
				return {
					рядків: rows.length,
					/* Скільки комірок у рядку: 4 зі складом, 3 без нього. Обидва види
					   мусять бути на сторінці, інакше перевірка нічого не доводить. */
					комірок: [...new Set(rows.map((r) => r.children.length))].sort(),
					краї: [...new Set(marks.map((m) => Math.round(m.getBoundingClientRect().right)))]
				};
			});

			expect(дані.рядків, `${name}: рядків не знайдено — перевірка мертва`).toBeGreaterThan(5);
			expect(
				дані.комірок.length,
				`${name}: усі рядки однакові за складом комірок (${дані.комірок.join(', ')}) — ` +
					'перевірка не бачить саме того випадку, проти якого написана'
			).toBeGreaterThan(1);
			expect(
				дані.краї,
				`${name}: плашки закінчуються на різних краях — рядок без складу з’їхав ` +
					'у чужу колонку сітки'
			).toHaveLength(1);
		});
	}
});

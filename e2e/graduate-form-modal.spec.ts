import { expect, test } from '@playwright/test';
import { gotoReady } from './ready';

/**
 * ВІКНО З АНКЕТОЮ GOOGLE — те, що в ньому належить НАМ.
 *
 * ## Звідки перевірка
 *
 * 2026-09-08 автор написав: «анкета google форми не скролиться у планшетному
 * режимі та не натискаються елементи в формі, хоча в звичайному desktop і в
 * телефонному режимі все працює». Відтворити це не вдалося: на п'яти ширинах,
 * у Chromium і в WebKit, з дотиком і без, у профілях iPad та Android-планшета
 * рамка лишалася зверху, прокручувалася й приймала натискання. Найімовірніше
 * винна емуляція пристрою в DevTools: синтетичний дотик і чужа (міжсайтова)
 * рамка там давно не дружать, і на живому планшеті цього немає.
 *
 * Але сама скарга показала, що це вікно НІЧИМ не було вкрите, хоч і має рівно
 * ті властивості, які роблять таку поразку можливою. Тому тут стережеться не
 * форма Google — її розмітка чужа й міняється без нас, — а три наші рішення,
 * кожне з яких поодинці дає той самий симптом «не скролиться й не натискається».
 *
 * ## Чому не чекаємо завантаження форми
 *
 * Перевірка не має залежати від того, чи відповів Google: усе, що тут
 * стережеться, — наше, і воно однакове з формою і без неї. Це навмисно: тест,
 * який червоніє від чужої мережі, перестають читати.
 */
const ПЛАНЕТА = '/projects/creativity-planet/';

/** Ширини, на яких автор бачив різницю. Планшетна — та сама, що в скарзі. */
const ШИРИНИ = [
	{ назва: 'десктоп', width: 1280, height: 900 },
	{ назва: 'планшет', width: 820, height: 1180 },
	{ назва: 'планшет-лежачи', width: 1180, height: 820 }
];

test.describe('вікно з анкетою', () => {
	for (const { назва, width, height } of ШИРИНИ) {
		test(`${назва}: вікно має справжню висоту, і рамка згори`, async ({ page }) => {
			await page.setViewportSize({ width, height });
			await gotoReady(page, ПЛАНЕТА);
			await page.getByTestId('creativity-planet-form-btn').click();

			const вікно = page.getByTestId('graduate-form-modal');
			await expect(вікно).toBeVisible();

			/*
			 * ВИСОТА. `height: min(90dvh, 880px)` — єдине місце в проєкті, де
			 * `dvh` стоїть у `height`, а не в `max-height`: якщо браузер не знає
			 * цієї одиниці, він викидає властивість цілком, і вікно складається
			 * до висоти шапки. Знадвору це виглядає рівно як скарга автора.
			 *
			 * Чесно про межу цієї перевірки: САМ ФОЛБЕК на `vh` вона не стереже —
			 * Chromium знає `dvh`, тож зняття фолбека тут нічого не зробить
			 * червоним. Стережеться наслідок: висота вікна, хай би що її забрало.
			 */
			const висота = (await вікно.boundingBox())?.height ?? 0;
			expect(висота, `вікно склалося до ${Math.round(висота)} px`).toBeGreaterThan(
				Math.min(height * 0.6, 500)
			);

			/*
			 * ХТО ЗВЕРХУ. Заставка «завантаження» лежить НА рамці й займає всю її
			 * площу. Без `pointer-events: none` вона перехоплює і дотики, і
			 * прокрутку — тобто поки вона видна, форма під нею мертва.
			 */
			const зверху = await page.evaluate(() => {
				const рамка = document.querySelector('[data-testid="graduate-form-frame-container"]');
				if (!рамка) return 'рамки немає';
				const r = рамка.getBoundingClientRect();
				const е = document.elementFromPoint(r.left + r.width / 2, r.top + r.height / 2);
				return е?.tagName ?? 'нічого';
			});
			expect(зверху, 'над анкетою лежить щось наше — крізь нього не натиснути').toBe('IFRAME');
		});
	}

	test('Tab доводить до самої анкети, а не крутиться по шапці вікна', async ({ page }) => {
		await gotoReady(page, ПЛАНЕТА);
		await page.getByTestId('creativity-planet-form-btn').click();
		await expect(page.getByTestId('graduate-form-modal')).toBeVisible();

		/*
		 * Пастка фокуса замикає Tab усередині вікна — і доти вважала рамку
		 * нефокусованою. Через це Tab ходив по двох кнопках шапки, НІКОЛИ не
		 * заходячи в анкету: усе, заради чого вікно відкривали, було недосяжне
		 * з клавіатури. Шість натискань — це більше, ніж кнопок у шапці, тобто
		 * коло вже мусило замкнутися.
		 *
		 * Ціна названа вголос: далі за рамкою пастка фокус НЕ тримає — Tab іде
		 * на сторінку під вікном. Інакше й бути не може, бо натискання клавіш
		 * усередині чужого документа до нас не долітають, а міжсайтову рамку
		 * ніхто нам не відкриє. Дійти до анкети важливіше, ніж замкнути коло
		 * навколо неї: доти форма була недосяжна взагалі.
		 */
		let дійшли = false;
		for (let i = 0; i < 6 && !дійшли; i += 1) {
			await page.keyboard.press('Tab');
			дійшли = await page.evaluate(() => document.activeElement?.tagName === 'IFRAME');
		}
		expect(дійшли, 'Tab не заходить в анкету — заповнити її з клавіатури неможливо').toBe(true);
	});
});

import { expect, test as setup } from '@playwright/test';
import { readFileSync } from 'node:fs';

/**
 * Перед першим тестом: на порту саме цей проєкт і саме щойно зібраний
 * (CI-CD-AND-TOOLS-v9, `CI-E2E-TARGET-IDENTITY`).
 *
 * ## Чому сетап-проєкт, а не перший тест у `smoke.spec.ts`
 *
 * Перевірка тотожності жила тут-таки, у `smoke.spec.ts`, і була написана
 * першою в файлі. Але «перший у файлі» не означає «перший у прогоні»:
 * `fullyParallel: true` і два проєкти-браузери запускають решту тридцяти
 * восьми файлів ОДНОЧАСНО з нею. Тобто на чужому сервері встигали відпрацювати
 * сотні перевірок, перш ніж хтось помічав, що сайт не той. Сетап-проєкт —
 * єдиний спосіб сказати «спершу це, потім усе інше»: решта проєктів оголошує
 * його в `dependencies`, і при червоному сетапі вони не стартують зовсім.
 *
 * ## Дві різні речі, які тут перевіряються
 *
 * 1. **Тотожність.** У цій екосистемі вже було: Playwright одного проєкту
 *    під'єднався до сервера іншого на спільному порту й пройшов повністю,
 *    перевіряючи чужий сайт. `strictPort` і `reuseExistingServer: false`
 *    зменшують шанс, але не знімають його: сервер міг піднятися й лишитися від
 *    попереднього прогону.
 *
 *    Маркер мусить бути в ПРЕРЕНДЕРЕНОМУ HTML, інакше перевіряється не
 *    тотожність сайту, а швидкість мережі. Раніше тут стояв `burger-menu-btn`,
 *    якого в `build/index.html` немає зовсім: уся шапка за `{#if headerReady}`,
 *    а прапорець вмикається лише після відповіді `getHeaderSettings()`. У
 *    тестовому середовищі Firestore віддає 400, прапорець виставляється у
 *    `.finally()` — і чекання в п'ять секунд цю гонку іноді втрачало. Кнопка
 *    піаніно в підвалі є в статиці й навряд чи трапиться на сусідньому проєкті.
 *
 * 2. **Штамп збірки.** Тотожність відповідає на «чий це сайт», але не на «яка
 *    це збірка». Сервер `vite preview` віддає те, що лежить у `build/`, а там
 *    може лежати вчорашнє: `npx playwright test` без збірки — звичайний рух,
 *    і саме він дає найгірший різновид зеленого прогону — правильний сайт,
 *    неправильний код. Тому звіряються три числа: версія, яку віддає сервер,
 *    версія у `build/app-version.json` на диску й версія в `package.json`.
 *
 *    Перше порівняння ловить чужий сервер, який випадково має ту саму кнопку;
 *    друге — стару збірку. Друге спрацьовує й тоді, коли після збірки був
 *    коміт: `.husky/pre-commit` кличе `bump-version`, тож версія в
 *    `package.json` іде вперед, а `build/` лишається позаду. Це не хибне
 *    спрацювання, а точний опис стану — прогін і справді перевіряв би не той
 *    код. Лікується `npm run test:e2e`, який збирає перед тестами.
 *
 * ## Зворотний експеримент (`PIT-REVERSE-EXPERIMENT`)
 *
 * Версію в `build/app-version.json` змінено на чужу — сетап упав і назвав
 * обидва числа, решта проєктів не стартувала. Після відкоту прогін іде далі.
 */

const прочитатиВерсію = (шлях: string) =>
	(JSON.parse(readFileSync(шлях, 'utf8')) as { version?: string }).version ?? '(немає поля)';

setup('на порту цей проєкт і саме щойно зібраний', async ({ page }) => {
	// --- 1. тотожність ---
	const відповідь = await page.goto('/');
	expect(відповідь?.status(), 'головна не віддала 200 — на порту не той сервер').toBe(200);
	// Обидві мови: desktop-проєкт ходить українською, mobile — англійською.
	await expect(page).toHaveTitle(/Одеська театральна школа|Odesa Theatre School/);
	await expect(page.getByTestId('footer-piano-btn').first()).toBeAttached();

	// --- 2. штамп збірки ---
	const наДиску = прочитатиВерсію('build/app-version.json');
	const уПакеті = прочитатиВерсію('package.json');

	const файлВерсії = await page.request.get('/app-version.json');
	expect(файлВерсії.ok(), '/app-version.json не віддається — сервер не з цієї збірки').toBe(true);
	const наПорту = ((await файлВерсії.json()) as { version?: string }).version ?? '(немає поля)';

	expect(
		наПорту,
		`сервер віддає версію ${наПорту}, а в build/ на диску лежить ${наДиску} — ` +
			'на порту чужий сервер або чужий каталог'
	).toBe(наДиску);

	expect(
		наДиску,
		`у build/ лежить версія ${наДиску}, а в package.json уже ${уПакеті} — ` +
			'збірка застаріла, прогін перевіряв би не той код. Зібрати: `npm run test:e2e`'
	).toBe(уПакеті);
});

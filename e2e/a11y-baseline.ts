/**
 * Базові числа для axe-обходу публічних сторінок.
 *
 * ЧОМУ НЕ `toEqual([])`. Нуль виглядає найсуворішим із можливих порогів, а
 * насправді він найкрихкіший: axe-core додає нові правила в **мінорних**
 * версіях, а Dependabot приносить такі оновлення щотижня. Гейт, який червоніє
 * від того, що зрушила залежність, — при незмінному нашому коді — це гейт, який
 * рано чи пізно вимикають. Поріг, який доводиться вимикати наступного дня,
 * гірший за відсутній (CODE-QUALITY-v8 § 6.4.1, ACCESSIBILITY-v8 § 10.1.1).
 *
 * Тому кількість — стеля, яка може лише **спадати**, а типи порушень, які ми
 * зараз терпимо, перелічені окремо. Друга половина важливіша за першу: вона
 * ловить порушення **нового типу** навіть коли загальна кількість лишилася в
 * межах ліміту. Голе число це сховало б — одне старе виправили, одне нове
 * привезли, у сумі нуль.
 *
 * Обидві таблиці порожні навмисно. Сьогодні всі сторінки чисті, тож гейт рівно
 * такий самий суворий, як був. Змінилося те, що станеться в день, коли axe
 * навчиться нового правила: тест назве це правило, а не покаже різницю двох
 * масивів.
 *
 * ПІДНЯТИ число можна лише разом із причиною в коментарі й номером задачі на
 * його зниження. Знизити — без нічого.
 */

/** Скільки порушень терпимо на сторінці. Відсутній шлях — нуль. */
export const A11Y_BASELINE: Record<string, number> = {};

/** Які типи порушень терпимо. Відсутній шлях — жодного; новий id валить прогін. */
export const A11Y_KNOWN: Record<string, string[]> = {};

export const baselineFor = (path: string): number => A11Y_BASELINE[path] ?? 0;
export const knownFor = (path: string): string[] => A11Y_KNOWN[path] ?? [];

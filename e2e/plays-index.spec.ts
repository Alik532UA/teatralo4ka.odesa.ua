import { expect, test } from '@playwright/test';
import { readFileSync } from 'node:fs';
import { gotoReady, openStageMenu } from './ready';

/**
 * Перелік усіх вистав — `/projects/galaxy-graduates/plays/`.
 *
 * ## Що саме тут стережеться
 *
 * Сторінки окремих вистав існували раніше за цей перелік, і дістатися до них
 * можна було лише збоку — з чужої анкети чи з репертуару групи. Сама адреса
 * `/plays/` віддавала 404, хоча під нею лежали 362 сторінки. Тобто розділ був,
 * а входу в нього не було.
 *
 * Тому перевіряється не «сторінка відкривається», а три речі, кожна з яких
 * ламається окремо:
 *
 *   1. У переліку РІВНО стільки карток, скільки вистав у реєстрі. Число
 *      береться з тих самих даних, що й сторінка, а не вписане сюди: інакше
 *      перевірка застаріє на першій же новій виставі й почне брехати.
 *   2. Вхід із галактики існує. Без нього сторінка знову стає недосяжною —
 *      пререндер її будує, бо на неї є посилання, і зникнення посилання
 *      прибрало б заразом і сторінку зі збірки.
 *   3. Дорога назад зі сторінки вистави веде В ПЕРЕЛІК, а не через голову в
 *      галактику.
 *
 * ## Типова область показу
 *
 * Сторінка типово показує НЕ всі 733 вистави, а 255 — ті, у яких «Хто грав»
 * непорожній. Тому перевірка «жодна вистава не лишилася недосяжною» тепер
 * робить один зайвий крок: тисне «Показати всі». Це навмисно: якби вона просто
 * порахувала те, що видно типово, то мовчала б і тоді, коли фільтр зламався і
 * ховає зайве.
 *
 * ## Три режими показу
 *
 * Сторінка вміє хронологію, список і плитку, і типовий режим — ХРОНОЛОГІЯ. Тому
 * перевірки більше не питають про «картки»: у двох режимах із трьох карток немає
 * взагалі. Питають про те, що є в кожному, — посилання на виставу.
 *
 * Заразом додана перевірка самого перемикача: він міняє розмітку, і зламатися в
 * ньому може як перехід (натиснув — нічого не сталося), так і вміст (перейшов, а
 * вистав у новому режимі менше).
 *
 * ## Зворотний експеримент (AI-AGENT-PITFALLS-v8 § 1.1)
 *
 * Прибрати кнопку «Вистави» на сторінці галактики — впаде друга перевірка, і
 * заразом (на наступній збірці) зникне сама сторінка. Показати в переліку лише
 * вистави з відомим складом — впаде перша й назве обидва числа. Зробити типовим
 * режимом плитку — впаде «типовий режим — хронологія». Прибрати фільтр із
 * типового стану — впаде «типово показані лише вистави з відомим складом».
 */

/*
 * Посилання на виставу в БУДЬ-ЯКОМУ режимі: у рядках це `-row-link-`, у плитці
 * `-card-`. Перевірки міряють досяжність вистав, а не обраний вигляд, тож і
 * добірка мусить бути спільною.
 */
const ПОСИЛАННЯ =
	'[data-testid^="galaxy-plays-row-link-"], [data-testid^="galaxy-plays-card-"]';

const ПЕРЕЛІК = '/projects/galaxy-graduates/plays';

/*
 * Дані читаються з ФАЙЛУ, а не імпортуються: Playwright виконує специфікації як
 * ESM, і статичний імпорт JSON вимагав би `with { type: 'json' }` — синтаксису,
 * якого решта проєкту не вживає. Читання дає той самий реєстр і не заводить
 * винятку в правилах збірки.
 */
const УСІ_ЗАПИСИ = JSON.parse(
	readFileSync('src/lib/data/plays.data.json', 'utf8')
) as ReadonlyArray<{ id: string; year: number; kind?: string }>;

/**
 * ЛИШЕ вистави курсів — без Посвят і новорічних показів.
 *
 * Перший розділ сторінки показує репертуар груп, а Посвята в Мистецтво й Новий
 * рік стоять окремими розділами нижче: Посвяту готують випускники різних років,
 * і «У репертуарі груп» для неї — брехня (розбір у `data/plays.ts`).
 *
 * Ця перевірка була написана ДО тих розділів і рахувала весь реєстр: 731 запис
 * проти 689 вистав курсів. Заміряно на живій сторінці — лічильник казав
 * «Показано 271 з 689», і перевірка чекала 731. Тобто вона впала не на дефекті
 * сторінки, а на власній застарілій арифметиці, і сорок два записи, які вона
 * «недорахувала», насправді просто показані в інших розділах.
 */
const ВИСТАВИ = УСІ_ЗАПИСИ.filter((play) => !play.kind);
const УСЬОГО = ВИСТАВИ.length;

test.describe('перелік вистав', () => {
	test('показує всі вистави реєстру, згруповані за роками', async ({ page }) => {
		await gotoReady(page, ПЕРЕЛІК);

		await expect(page.getByTestId('galaxy-plays-title')).toBeVisible();

		await expect(
			page.getByTestId('galaxy-plays-view-btn-timeline'),
			'типовий режим не хронологія — сторінка відкрилася іншим виглядом'
		).toHaveAttribute('aria-pressed', 'true');

		/* Типово видно менше, ніж є, — і сторінка мусить це САМА сказати. */
		const типово = await page.locator(ПОСИЛАННЯ).count();
		expect(типово, 'типово показані всі вистави — фільтр не діє').toBeLessThan(УСЬОГО);
		await expect(
			page.getByTestId('galaxy-plays-scope-count'),
			'сторінка показує не всі вистави й ніде про це не каже'
		).toContainText(String(УСЬОГО));

		/* Одне натискання — і досяжні всі: жодна сторінка не загубилася. */
		await page.getByTestId('galaxy-plays-scope-btn').click();
		const посилань = await page.locator(ПОСИЛАННЯ).count();
		expect(
			посилань,
			`після «Показати всі» у переліку ${посилань} вистав, а в реєстрі ${УСЬОГО} — ` +
				'частина сторінок лишилася недосяжною з переліку'
		).toBe(УСЬОГО);

		const років = new Set(ВИСТАВИ.map((play) => play.year)).size;
		expect(
			await page.locator('[data-testid^="galaxy-plays-year-section-"]').count(),
			'заголовків років менше, ніж років у реєстрі'
		).toBe(років);

		/*
		 * Плашка біля заголовка рахує ВСЕ, що є на сторінці, — разом із Посвятами
		 * й новорічними показами (731), а лічильник області показу — лише
		 * репертуар курсів (689). Числа різні НАВМИСНО: перше про сторінку, друге
		 * про її перший розділ, і саме тому тут стоять обидва.
		 */
		await expect(page.getByTestId('galaxy-plays-total-count')).toHaveText(
			String(УСІ_ЗАПИСИ.length)
		);
	});

	test('пошук звужує перелік і чесно каже, коли нічого немає', async ({ page }) => {
		await gotoReady(page, ПЕРЕЛІК);
		const пошук = page.getByTestId('galaxy-plays-search-input');

		await пошук.fill('Цибуліно');
		const знайдено = await page.locator(ПОСИЛАННЯ).count();
		expect(знайдено, 'пошук за відомою назвою не знайшов нічого').toBeGreaterThan(0);
		expect(знайдено, 'пошук нічого не звузив — фільтр не працює').toBeLessThan(УСЬОГО);
		/*
		 * `toContainText`, а не `toHaveText`: після переходу на спільний
		 * `SearchField` лічильник каже «Знайдено: N», а не саме число — те саме
		 * поле й той самий підпис, що на сторінках груп і фестивалів.
		 */
		await expect(page.getByTestId('galaxy-plays-search-count-text')).toContainText(
			String(знайдено)
		);

		await пошук.fill('такогонемаєточно');
		await expect(
			page.getByTestId('galaxy-plays-empty-text'),
			'порожній результат мовчить — читач не розуміє, це помилка чи справді нічого немає'
		).toBeVisible();
	});

	test('перемикач режимів міняє вигляд і не губить вистав', async ({ page }) => {
		await gotoReady(page, ПЕРЕЛІК);

		/* Знімаємо фільтр: перевіряються режими, а не область показу. */
		await page.getByTestId('galaxy-plays-scope-btn').click();

		const років = new Set(ВИСТАВИ.map((play) => play.year)).size;
		const заголовки = page.locator('[data-testid^="galaxy-plays-year-section-"]');

		/* Список: ті самі вистави, але БЕЗ заголовків років — інакше він нічим не
		   відрізняється від хронології, і два режими з трьох роблять те саме. */
		await page.getByTestId('galaxy-plays-view-btn-list').click();
		expect(await page.locator(ПОСИЛАННЯ).count(), 'у списку вистав менше, ніж у реєстрі').toBe(
			УСЬОГО
		);
		expect(await заголовки.count(), 'у списку лишилися заголовки років').toBe(0);

		/* Плитка: вистави повертаються картками, роки — заголовками. */
		await page.getByTestId('galaxy-plays-view-btn-tiles').click();
		expect(
			await page.locator('[data-testid^="galaxy-plays-card-"]').count(),
			'у плитці карток менше, ніж вистав у реєстрі'
		).toBe(УСЬОГО);

		await page.getByTestId('galaxy-plays-view-btn-timeline').click();
		expect(await заголовки.count(), 'у хронології заголовків років менше, ніж років').toBe(років);
	});

	test('типово показані лише вистави з відомим складом, і пошук цим не обмежений', async ({
		page
	}) => {
		await gotoReady(page, ПЕРЕЛІК);

		/*
		 * У кожної показаної вистави мусить бути хоч одне обличчя — у цьому й
		 * увесь сенс типової області показу. Рядок без облич тут означав би, що
		 * фільтр рахує не те, що обіцяє підпис.
		 */
		const рядків = await page.locator('[data-testid^="galaxy-plays-row-link-"]').count();
		expect(рядків, 'типово не показано жодної вистави').toBeGreaterThan(0);

		/* На кожен рядок — свій рядок облич. Менше означало б виставу без складу. */
		const зОбличчями = await page
			.locator('[data-testid^="galaxy-plays-cast-"][data-testid$="-list"]')
			.count();
		expect(
			зОбличчями,
			`показано ${рядків} вистав, а рядків облич ${зОбличчями} — серед показаних є вистава ` +
				'без жодного учасника'
		).toBe(рядків);

		/*
		 * Пошук шукає по ВСІХ виставах, тобто сам знімає фільтр. «Теремок» 2013
		 * року взятий навмисно: складу в нього немає, тож під фільтром він
		 * невидимий, а знайтися мусить.
		 */
		await page.getByTestId('galaxy-plays-search-input').fill('Теремок');
		await expect(
			page.getByTestId('galaxy-plays-search-count-text'),
			'пошук не знайшов виставу, бо про неї ще не заповнили анкету'
		).toContainText('Знайдено');
	});

	test('у перелік можна потрапити з галактики', async ({ page }) => {
		await gotoReady(page, '/projects/galaxy-graduates');
		// На телефоні кнопки сцени лежать за одним значком — див. `openStageMenu`.
		await openStageMenu(page);
		const вхід = page.getByTestId('galaxy-plays-link');
		await expect(вхід, 'на сторінці галактики немає входу в перелік вистав').toBeVisible();

		await вхід.click();
		await expect(page).toHaveURL(/\/projects\/galaxy-graduates\/plays\/?$/);
		await expect(page.getByTestId('galaxy-plays-title')).toBeVisible();
	});

	test('картка веде на виставу, а звідти є дорога назад у перелік', async ({ page }) => {
		await gotoReady(page, ПЕРЕЛІК);

		await page.locator(ПОСИЛАННЯ).first().click();
		await expect(page).toHaveURL(/\/projects\/galaxy-graduates\/plays\/[^/]+\/?$/);
		await expect(page.getByTestId('play-title')).toBeVisible();

		await page.getByTestId('play-back-link').click();
		await expect(
			page,
			'кнопка назад зі сторінки вистави веде не в перелік вистав'
		).toHaveURL(/\/projects\/galaxy-graduates\/plays\/?$/);
	});
});

import { expect, test } from '@playwright/test';
import { gotoReady } from './ready';

/**
 * Пошук по сайту: що він БАЧИТЬ і чого не бачить.
 *
 * ## Чому прогоном, а не гейтом
 *
 * Записи галактики довантажуються `import()`-ом у мить, коли накладку відкрили
 * (розбір — у `services/searchGalaxy`). Розбір джерел цього не перевіряє: там
 * видно імпорт, але не видно, чи модуль справді приїхав, чи потрапив у той
 * самий перелік, по якому шукають, і чи знайдеться людина за прізвищем.
 *
 * ## Що саме стережеться
 *
 * 1. Людина знаходиться за прізвищем. Саме з цього почалася робота: автор
 *    шукав «Тункевич» і не знаходив нічого — пошук знав лише markdown-сторінки
 *    та новини, а вся галактика лишалася поза ним.
 * 2. Знаходяться й інші реєстри: вистава, заклад освіти, курс.
 * 3. НЕ знаходиться той, кого приховали навмисно. Володимир Захарченко має
 *    рівень видимості `direct`: сторінка в нього є, але в переліках і в пошуку
 *    його немає — і це не випадковість, а вимога автора.
 * 4. Знаходиться те, що живе ГЛИБШЕ за шапку реєстру: викладач і роль з анкети.
 *    Обидва випадки заміряні 2026-09-05 і давали нуль.
 * 5. Знаходиться країна СЛОВОМ, а не кодом: у реєстрах лежить `BG`, а шукають
 *    «Болгарія». Той самий дефект автор знайшов і на сторінці фестивалів.
 * 6. Знаходиться той, чиє прізвище набрали НЕ ТАК, як воно в базі. Три випадки
 *    заміряні на живому пошуку 2026-09-05, і всі троє давали нуль: інша літера
 *    («Тункевіч»), справжня одруківка («Запальнов») та інший порядок слів
 *    («Тункевич Аліса»). Розбір шарів — у `utils/siteSearch`.
 */
const ЗАПИТИ: { запит: string; очікуємо: RegExp }[] = [
	{ запит: 'Тункевич', очікуємо: /Тункевич/ },
	{ запит: 'ОТХФК', очікуємо: /ОТХФК/ },
	{ запит: 'Резонанс', очікуємо: /Резонанс/ },
	{ запит: 'Тункевіч', очікуємо: /Тункевич/ },
	{ запит: 'Тункевич Аліса', очікуємо: /Тункевич/ },
	{ запит: 'Запальнов', очікуємо: /Запольнов/ },
	/*
	 * П'ятий і шостий рядки — те, чого пошук не бачив ЗОВСІМ, і причини в них
	 * різні.
	 *
	 * «Риськіна» — викладачка. Реєстр майстрів у пошук не додавали взагалі, коли
	 * навчали його галактиці: інший розділ сайту, про нього просто не згадали.
	 *
	 * «отримує ляпаса» — роль в анкеті. Такий текст лежить у файлі анкети, а не
	 * в бандлі, і приїжджає покажчиком `search/profiles.json` уже після
	 * відкриття накладки. Тобто цей рядок стереже ще й те, що покажчик справді
	 * довантажується й потрапляє в той самий перелік.
	 */
	{ запит: 'Риськіна', очікуємо: /Риськіна/ },
	/*
	 * Країна СЛОВОМ. У реєстрах вона лежить кодом (`BG`), і доти пошук по сайту
	 * її не бачив узагалі: «Болгарія» давала нуль, хоч фестиваль саме там і був.
	 * Той самий дефект автор знайшов на сторінці фестивалів — там поле обіцяло
	 * шукати «за країною» й не шукало.
	 */
	{ запит: 'Болгарія', очікуємо: /Слов’янський вінок|Слов'янський вінок/ }
];

async function відкритиПошук(page: import('@playwright/test').Page) {
	await page.getByTestId('header-search-btn').first().click();
	await expect(page.locator('.search__input')).toBeVisible();
}

test.describe('пошук по сайту', () => {
	test.skip(({ isMobile }) => !!isMobile, 'кнопка пошуку в шапці — на широкому екрані');

	for (const { запит, очікуємо } of ЗАПИТИ) {
		test(`знаходить «${запит}» у галактиці`, async ({ page }) => {
			await gotoReady(page, '/');
			await відкритиПошук(page);
			await page.locator('.search__input').fill(запит);

			/* Реєстри приїжджають окремим шматком, тож перший кадр може бути
			   порожній — чекаємо на появу, а не міряємо одразу. */
			await expect(page.locator('.search__hit').first()).toBeVisible({ timeout: 10_000 });
			await expect(page.locator('.search__hit').first()).toHaveText(очікуємо);
		});
	}

	/**
	 * Роль з анкети знаходить і виставу, і людину — і саме в такому порядку.
	 *
	 * Спершу цей запит перевірявся в спільному переліку й вимагав, щоб ПЕРВИМ
	 * був Запольнов. Так і було, поки анкета писала «Той, що отримує ляпаса», а
	 * реєстр — «ляпаси»: збігався лише один із двох. Після того, як написання
	 * вирівняли під реєстр, збігаються обидва, і вище стала ВИСТАВА — бо саме в
	 * її переліку номерів це й названо.
	 *
	 * Правильна вимога тому інша: знайтися мусять обоє. Порядок тут не помилка, а
	 * ранжування, яке працює як задумано.
	 */
	test('роль з анкети знаходить і виставу, і людину', async ({ page }) => {
		await gotoReady(page, '/');
		await відкритиПошук(page);
		await page.locator('.search__input').fill('отримує ляпаси');

		await expect(page.locator('.search__hit').first()).toBeVisible({ timeout: 10_000 });

		/*
		 * ЧЕКАЄМО, а не читаємо одразу: покажчик пошуку будується ДВІЧІ.
		 *
		 * Спершу — самі шапки з бандла (назви вистав, імена), і саме вони
		 * з'являються в ту мить, коли модуль приїхав. Текст анкет доїжджає
		 * окремим запитом, і роль «Той, хто отримує ляпаси» лежить саме в ньому —
		 * тобто Запольнов стає знаходимим на кілька сотень мілісекунд пізніше за
		 * виставу. Одноразове читання ловило то один стан, то другий: падало
		 * приблизно раз на три повні прогони й читалося як флак.
		 */
		const усі = async () => (await page.locator('.search__hit').allInnerTexts()).join(' | ');
		await expect
			.poll(усі, { timeout: 10_000, message: 'вистави з цим номером немає серед знайденого' })
			.toMatch(/Уривки з драматургії/);
		await expect
			.poll(усі, { timeout: 10_000, message: 'людини з цією роллю немає серед знайденого' })
			.toMatch(/Запольнов/);
	});

	test('не знаходить того, кого приховали навмисно', async ({ page }) => {
		await gotoReady(page, '/');
		await відкритиПошук(page);
		await page.locator('.search__input').fill('Захарченко');

		/* Реєстрам дається час приїхати — інакше «нічого не знайдено» означало б
		   лише те, що вони ще в дорозі. */
		await page.waitForTimeout(3000);
		await expect(page.locator('.search__hit')).toHaveCount(0);
	});

	test('поле пошуку без прямокутного кільця, а фокус видно межею рядка', async ({ page }) => {
		await gotoReady(page, '/');
		await відкритиПошук(page);

		/*
		 * 28 серпня я прибрав звідси `outline: none` заради видимого фокуса, і
		 * глобальне кільце намалювало прямокутник усередині круглої плашки —
		 * автор назвав це «старомодною обводою». Тепер межу підсвічує рядок, у
		 * якому лежить поле, а кільця на самому полі немає.
		 */
		const стан = await page.evaluate(() => {
			const поле = document.querySelector('.search__input') as HTMLElement;
			поле.focus();
			const рядок = document.querySelector('.search__field') as HTMLElement;
			return {
				кільце: getComputedStyle(поле).outlineStyle,
				межа: getComputedStyle(рядок).borderBottomColor,
				акцент: getComputedStyle(document.documentElement).getPropertyValue('--accent-primary').trim()
			};
		});
		expect(стан.кільце, 'на полі знову з’явилося кільце фокуса').toBe('none');
		expect(стан.межа, 'межа рядка не підсвічена акцентом теми').not.toBe('rgba(0, 0, 0, 0)');
	});
});

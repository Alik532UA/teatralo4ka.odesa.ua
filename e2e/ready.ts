import { expect, type Page } from '@playwright/test';

/**
 * Перейти на сторінку і дочекатися, поки застосунок справді готовий.
 *
 * Сама лише подія `load` тут не годиться: словники svelte-i18n вантажаться
 * асинхронно, і до їхнього приходу сторінка показує англійський фолбек та
 * «Loading…». Перша версія тестів саме на це й натрапила — і виглядало це як
 * поламані сторінки, хоча зламаними були очікування.
 *
 * `networkidle` теж не годиться у зворотний бік: Firebase тримає довге
 * з'єднання, тож мережа не затихає ніколи і чекання впирається в таймаут.
 *
 * Сигнал готовності — заголовок сторінки. Він є на кожній публічній сторінці
 * і з'являється рівно тоді, коли компонент отримав свій текст.
 */
export async function gotoReady(page: Page, path: string) {
	const response = await page.goto(path);
	await page.waitForLoadState('load');
	await expect(page.locator('h1, h2').first()).toBeVisible({ timeout: 15_000 });
	return response;
}

/**
 * Дочекатися, поки скінченні анімації добіжать до кінця.
 *
 * Потрібне перед axe. `.page-content` з'являється через
 * `animation: fadeInUp 0.6s`, а `fadeInUp` починається з `opacity: 0` — тож
 * поки анімація триває, увесь текст сторінки НАПІВПРОЗОРИЙ. axe рахує колір із
 * урахуванням прозорості й бачить те, чого на екрані вже за півсекунди немає.
 *
 * Це давало нестабільний тест: `/admission` і `/departments/music` падали з
 * «insufficient color contrast 3.18 (foreground #509ab1)», де #509ab1 — це
 * `--text-main` (#006c8d) під альфою 0.69, тобто кадр посеред появи. Різні
 * елементи давали різну альфу, бо анімації в них зміщені. Більшість прогонів
 * проходила, і саме тому дефект прожив довго: зелений тест читався як доказ.
 *
 * Нескінченні анімації (пульсація логотипа, фонові полотна) відкидаються —
 * їх чекати нема сенсу, вони не закінчаться ніколи.
 */
/**
 * Клік по елементу в ПІДВАЛІ.
 *
 * Підвал з'являється на прокрутці й робить це анімацією. Playwright сам
 * прокручує елемент у видиму частину — і тим САМИМ запускає ту анімацію, після
 * чого відмовляється клікати: «element is not stable». Кожен повтор знову
 * впирається в рух, і тест з'їдає свої 30 секунд на кнопці, яка ось вона.
 *
 * Падало це приблизно раз на прогін у мобільному проєкті й проходило з
 * ретраю — тобто читалося як флак і роками нічого не означало. Насправді це
 * той самий підвал, що вже описаний у PROJECT-CONTEXT: у момент заміру він має
 * `opacity: 0`, і `isVisible()` цього не вважає невидимістю.
 *
 * Тому: прокрутити СПЕРШУ, дочекатися, поки анімації добіжать, і аж тоді
 * клікати.
 */
export async function clickInFooter(page: Page, testId: string) {
	const target = page.getByTestId(testId).first();

	/*
	 * Спершу чекаємо на ВИДИМІСТЬ, і лише потім прокручуємо.
	 *
	 * Причина конкретна: підвал перемальовується після гідрації — на вузькому
	 * екрані кнопки стоять поруч, на широкому міняються місцями, тож розмітка
	 * після монтування інша. Якщо локатор розв'язався до перемальовування, вузол
	 * до моменту прокрутки вже від'єднаний, і `scrollIntoViewIfNeeded` падає з
	 * «Element is not attached to the DOM». Заміряно 2026-08-31: перевірка звуку
	 * піаніно так падала на мобільному проєкті і поодинці, і в повному наборі.
	 *
	 * `expect(...).toBeVisible()` розв'язує локатор наново на кожній спробі, тож
	 * чекання переживає перемальовування. Прокрутка після нього все одно
	 * страхується повтором: між нею й перевіркою лишається той самий проміжок,
	 * просто набагато вужчий.
	 */
	await expect(target).toBeVisible();
	await target.scrollIntoViewIfNeeded().catch(async () => {
		await expect(target).toBeVisible();
		await target.scrollIntoViewIfNeeded();
	});

	await waitForAnimations(page);
	await target.click();
}

export async function waitForAnimations(page: Page) {
	// Дірка в першій версії цієї функції: вона перевіряла лише «усі скінченні
	// анімації завершені» — і проходила МИТТЄВО, поки анімацій ще не створено
	// взагалі. Порожній `getAnimations()` дає `every() === true`. Тобто в
	// найгіршому випадку перевірка спрацьовувала ДО появи `.page-content`,
	// анімація починалася після неї, і axe знову мірив контраст напівпрозорого
	// тексту. Симптом лишався той самий, що й до появи цієї функції: раз на
	// прогін падала одна довільна сторінка, і щоразу інша.
	//
	// Тому спершу чекаємо, поки анімації з'являться, і лише потім — поки добіжать.
	await page
		.waitForFunction(
			() =>
				document.getAnimations().some((a) => (a.effect?.getTiming().iterations ?? 1) !== Infinity),
			undefined,
			{ timeout: 3000 }
		)
		// Сторінка справді може не мати жодної скінченної анімації — тоді чекати
		// нема чого, і це не помилка. Таймаут тут коротший за головний навмисно.
		.catch(() => {});

	// Умова — «жодна скінченна анімація не РУХАЄТЬСЯ», а не «всі завершені».
	// `paused` теж означає нерухомий кадр: так стоїть прогрес-бар тоста під
	// курсором. Поки `paused` не був у переліку, умова не виконувалася ніколи, і
	// перевірка падала таймаутом на головній під навантаженням — тобто одна
	// дірка (порожній `getAnimations()`) змінилася на іншу.
	const SETTLED = ['finished', 'idle', 'paused'];

	/**
	 * Довгі анімації не чекаються — і це третя дірка цієї функції, знайдена
	 * 2026-08-18 на сторінці галактики.
	 *
	 * Функція існує заради появи `.page-content` — це 600 мс. Але під фільтр
	 * «скінченна» потрапляв і індикатор тоста новин: `iterations: 1`,
	 * `duration: 30000`. Тост приходить із Firestore приблизно на четвертій
	 * секунді, тобто ГОНКОЮ з цією перевіркою — якщо він устигав, чекання
	 * гарантовано впиралося в свій десятисекундний таймаут, бо анімація триває
	 * тридцять.
	 *
	 * Саме це, найпевніше, і є причина «одного-двох плаваючих падінь за прогін,
	 * щоразу інших», які роками списувалися на паралельність: падала та сторінка,
	 * на якій тост випередив перевірку. Заміряно прямо — секунда за секундою: до
	 * 3 с незавершених нуль, з 4-ї й далі один і той самий `toast-progress` на
	 * 30000 мс.
	 *
	 * Поріг 2 с відділяє «сторінка ще з'являється» від «на сторінці живе елемент
	 * із власним таймером». Другого чекати не треба ніколи: він не завершиться до
	 * кінця й не заважає axe — тост не напівпрозорий.
	 */
	const SETTLE_LIMIT_MS = 2000;

	await page.waitForFunction(
		({ settled, limit }) =>
			document
				.getAnimations()
				.filter((a) => {
					const timing = a.effect?.getTiming();
					if ((timing?.iterations ?? 1) === Infinity) return false;
					return (Number(timing?.duration) || 0) <= limit;
				})
				.every((a) => settled.includes(a.playState)),
		{ settled: SETTLED, limit: SETTLE_LIMIT_MS },
		{ timeout: 10_000 }
	);

	// Один кадр після завершення: `finished` настає, коли анімація дограла, але
	// композитор ще не обов'язково намалював останній кадр — а axe читає саме
	// намальоване.
	await page.evaluate(() => new Promise((r) => requestAnimationFrame(() => r(null))));
}

/**
 * Відкриває меню керування сценою галактики — там, де воно є.
 *
 * На телефоні всі кнопки сцени (переліки груп, фестивалів, вистав, «Усі
 * випускники», плюс, повний екран) ховаються за одним значком: п'ять кнопок у
 * рядок займали чверть екрана. На широкому екрані значка немає — кнопки й так
 * у рядку, — тож помічник там нічого не робить.
 *
 * Без цього перевірки, написані до появи меню, падали на телефоні з
 * «unexpected value hidden»: `data-testid` знаходився, елемент існував, але
 * лежав у закритому меню. Заміряно: 10 таких падінь у чотирьох файлах.
 */
export async function openStageMenu(page: Page) {
	const кнопка = page.locator('[data-testid="galaxy-stage-menu-btn"]');
	if (!(await кнопка.isVisible().catch(() => false))) return;
	await кнопка.click();
	// Кнопки з'являються не в тому ж кадрі, що клік.
	await page.locator('[data-testid="galaxy-open-roster-btn"]').waitFor({ state: 'visible' });
}

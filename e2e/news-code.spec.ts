import { expect, test } from '@playwright/test';
import { gotoReady } from './ready';

/**
 * Новина, яка живе в КОДІ, а не в базі.
 *
 * ## Що саме тут стережеться
 *
 * Два твердження, які легко зламати непомітно, і жоден інший гейт їх не бачить.
 *
 * ПЕРШЕ — сторінка складається на збірці. Це і є причина, заради якої друге
 * джерело новин узагалі з'явилося: текст переживає збірку в HTML, тож його
 * бачить і краулер прев'ю, і читач без JavaScript. Досить комусь повернути
 * `prerender = false` у `news/[id]/+page.ts` — і сторінка стане порожньою
 * оболонкою, а прогін лишиться зеленим, бо з JavaScript усе працює.
 *
 * ДРУГЕ — ім'я випускника в тексті відкриває картку НА ЦІЙ сторінці. Автор
 * попросив саме цього: «при натисканні на випускників відкривається сторінка в
 * галактиці; очікуваний результат — у поточній сторінці». Тримається це на
 * делегованому обробнику `ProseGraduateLinks`, а той — на тому, що подію
 * побачить він, а не роутер SvelteKit.
 *
 * ## МЕЖА ЦЬОГО ТЕСТУ, названа вголос
 *
 * Він стереже ПОВЕДІНКУ, а не механізм. Зворотний експеримент проведено:
 * обробник переведено з фази перехоплення назад у фазу спливання — і тест
 * лишився ЗЕЛЕНИМ. Тобто на справжньому натисканні працюють обидві редакції, і
 * різницю між ними цей прогін не бачить.
 *
 * Це не привід його не мати: він падає на тому, що справді важливо — якщо
 * картка знову почне вести читача в галактику (наприклад, обробник зникне,
 * компонент перестане монтуватися або `findByAddress` розійдеться з адресами),
 * прогін це назве. А от вибір фази перехоплення лишається рішенням, яке тримає
 * докблок, а не гейт.
 */
/*
 * Адреса рядком, а не з `config/codeNews.ts`, — і це вимушено, а не з ліні:
 * реєстр імпортує `$app/paths` заради `asset()` у картці переліку, а в
 * node-контексті Playwright такого пакета немає («Cannot find package '$app'»).
 * Розділяти модуль надвоє заради одного рядка в тесті — дорожче за сам рядок.
 *
 * Дублювання тут безпечне: перейменують адресу — `goto` віддасть 404 і тест
 * упаде ГУЧНО, а зв'язки самого реєстру (markdown, знімки, мапа розмірів,
 * пошук) тримає `src/lib/config/codeNews.test.ts`.
 */
const АДРЕСА = '30-y-sezon-i-17-studentiv-2026';

test.describe('новина з коду', () => {
	test.describe('без JavaScript', () => {
		test.use({ javaScriptEnabled: false });

		test('текст і всі знімки вже в HTML', async ({ page }) => {
			await page.goto(`/news/${АДРЕСА}`);

			// Заголовок і перелік — із markdown, а не з клієнтського запиту.
			await expect(page.locator('h1')).toContainText('сезон');
			const пункти = page.locator('.prose ol li');
			expect(await пункти.count(), 'перелік студентів мусить бути в HTML').toBeGreaterThan(10);

			// Кожен знімок галереї — теж у HTML, а не домальований скриптом.
			const знімки = page.locator('[data-testid="article-gallery-list"] img');
			expect(
				await знімки.count(),
				'знімки мусять бути в HTML, а не домальовані скриптом'
			).toBeGreaterThan(9);
		});
	});

	test('ім’я в тексті відкриває картку ТУТ, а не веде в галактику', async ({ page }) => {
		await gotoReady(page, `/news/${АДРЕСА}`);

		const посилання = page.locator('.prose ol a').first();
		const адреса = (await посилання.getAttribute('href'))!;
		await посилання.click();

		/*
		 * Адреса СТАЄ адресою людини — так само, як при кліку на обличчя в складі
		 * вистави: у картки має бути власне посилання, щоб його можна було
		 * надіслати. Розбір у `services/graduateModal.svelte.ts`.
		 */
		await expect(page).toHaveURL(new RegExp(`${адреса.replace(/\//g, '\\/')}/?$`));

		// А сама новина НІКУДИ не поділася — саме це й просив автор.
		await expect(page.locator('[data-testid="article-gallery-list"]')).toBeVisible();
		await expect(page.locator('h1').first()).toContainText('сезон');

		// «Назад» закриває картку й лишає новину на місці.
		await page.goBack();
		await expect(page).toHaveURL(new RegExp(`/news/${АДРЕСА}/?$`));
		await expect(page.locator('[data-testid="article-gallery-list"]')).toBeVisible();
	});
});
